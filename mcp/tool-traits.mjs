/**
 * What each tool does to the world, in one place.
 *
 * These two sets lived in the test helpers, where they decide which tools an audit may call. The
 * server needs the same facts to tell a client -- `readOnlyHint`, `openWorldHint` -- and a second
 * copy here would be free to disagree with the first. So the server owns them and the audits
 * import them.
 *
 * They are hand-written on purpose. A name-pattern heuristic is quietly wrong the first time
 * someone names a tool badly, and the cost of a wrong answer is an audit calling something that
 * writes, or a client auto-approving it.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    MUTATES, REACHES_NETWORK, annotationsFor, withAnnotations
 * depends    —
 * used by    —
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */

/**
 * Tools that write: a file, a graph, a spreadsheet cell. An audit must never call one.
 *
 * `record_ep_relation` is listed despite being deprecated and returning only instructions: its
 * name says it records, and a classification that depends on reading the body rots when the body
 * changes. The Effective Paths names belong to a sibling server and are harmless here.
 */
export const MUTATES = new Set([
  'begin_mechanic_task',
  'record_mechanic_note',
  'record_work_status',
  'record_ep_relation',
  'sdk_graph_mutate',
  'ep_graph_mutate',
  'sdk_sandbox_run',
  'write_cells',
  'trust_drift_check',
  'sdk_docs_generate',
])

/** Tools that leave the process: the wiki fetchers, and the ones that spawn a repository script. */
export const REACHES_NETWORK = new Set([
  'wiki_page',
  'wiki_search',
  'sdk_graph_get',
  'sdk_graph_context',
  'sdk_graph_render',
  'sdk_graph_validate',
  'sdk_kernel_load',
  'sdk_registry_get',
  'sdk_save_graph_get',
  'sdk_debug_snapshot',
  'sdk_debug_watch',
  'sdk_debug_validate',
  'sdk_debug_trace',
  'sdk_lsp_diagnostics',
  'sdk_planner_compile',
  'trust_coverage_report',
])

/** Tools that reach a site this server does not control, as opposed to a local script. */
const OPEN_WORLD = new Set(['wiki_page', 'wiki_search', 'begin_mechanic_task'])

/**
 * The MCP annotations for one tool.
 *
 * Hints, not guarantees -- the specification says so, and a client must not treat them as a
 * security boundary. Nothing here is destructive: the tools that write only ever append.
 */
export function annotationsFor(name) {
  const readOnly = !MUTATES.has(name)
  return {
    readOnlyHint: readOnly,
    ...(readOnly ? {} : { destructiveHint: false }),
    openWorldHint: OPEN_WORLD.has(name),
  }
}

/** A registry with each tool's annotations attached, leaving any it already declares alone. */
export function withAnnotations(tools) {
  return Object.fromEntries(
    Object.entries(tools).map(([name, tool]) => [
      name,
      tool.annotations ? tool : { ...tool, annotations: annotationsFor(name) },
    ]),
  )
}
