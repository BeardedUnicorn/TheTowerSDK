/**
 * What each tool does to the world, in one place.
 *
 * These two sets lived in the test helpers, where they decide which tools an audit may call. The
 * server needs the same facts to tell a client -- `readOnlyHint`, `openWorldHint` -- and a second
 * copy here would be free to disagree with the first. So the server owns them and the audits
 * import them.
 *
 * They are hand-written on purpose. A name-pattern heuristic is quietly wrong the first time
 * someone names a tool badly, and the cost of a wrong answer is an audit calling something that
 * writes, or a client auto-approving it.
 */
