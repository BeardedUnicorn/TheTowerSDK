/**
 * Build the game pages of the GitHub wiki from the SDK's own data.
 *
 * Every value on these pages is read from the built package in `dist/` — the same thing a
 * consumer installs — so a page cannot say something the SDK does not. Nothing is fetched
 * from the community wikis and nothing is typed in here: prose comes from the description,
 * summary and fact fields the data already carries.
 *
 * This module returns pages; `scripts/build-wiki.mjs` writes them next to the SDK's docs.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    GAME_WIKI_HOME, buildGameWikiPages
 * depends    scripts/game-wiki/pages/cards.mjs, scripts/game-wiki/pages/companions.mjs, scripts/game-wiki/pages/economy.mjs, scripts/game-wiki/pages/history.mjs, scripts/game-wiki/pages/labs.mjs, scripts/game-wiki/pages/modules.mjs (+7 more)
 * used by    —
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { existsSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import * as cards from './pages/cards.mjs'
import * as companions from './pages/companions.mjs'
import * as economy from './pages/economy.mjs'
import * as history from './pages/history.mjs'
import * as labs from './pages/labs.mjs'
import * as modules from './pages/modules.mjs'
import * as progression from './pages/progression.mjs'
import * as reference from './pages/reference.mjs'
import * as relics from './pages/relics.mjs'
import * as weapons from './pages/weapons.mjs'
import * as workshop from './pages/workshop.mjs'
import * as world from './pages/world.mjs'
import { bullets, createFormat, heading, pageName, sections } from './render.mjs'

const PACKAGE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')

/** The landing page. Named so it cannot collide with a page made from a README section. */
export const GAME_WIKI_HOME = 'Game-Wiki'

/** Order here is the order of the landing page and the sidebar. */
const PAGE_MODULES = [workshop, labs, cards, modules, weapons, companions, relics, world, progression, economy, reference, history]

/** Systems the game has that the SDK holds no catalog for. Listed so their absence is not read as an oversight. */
const NOT_COVERED = ['Events (no event catalog, schedule or shop)', 'Season pass', 'Achievements', 'Shop and purchase packs']

function loadSdk() {
  const dist = path.join(PACKAGE_ROOT, 'dist')
  if (!existsSync(path.join(dist, 'data', 'index.js'))) {
    throw new Error('The game wiki is generated from the built package, and dist/ is missing. Run `pnpm build` first.')
  }
  const require = createRequire(import.meta.url)
  return {
    data: require(path.join(dist, 'data', 'index.js')),
    knowledge: require(path.join(dist, 'knowledge', 'index.js')),
    charts: require(path.join(dist, 'charts', 'index.js')),
    formatting: require(path.join(dist, 'formatting', 'index.js')),
  }
}

/**
 * @returns {{
 *   pages: Map<string, string>,
 *   nav: { group: string, entries: { title: string, name: string }[] }[],
 *   problems: string[],
 *   gameVersion: string,
 * }}
 */
export function buildGameWikiPages() {
  const sdk = loadSdk()
  const gameVersion = sdk.knowledge.CURRENT_GAME_VERSION
  const format = createFormat(sdk.formatting)

  const pages = new Map()
  const titles = new Map()
  const linked = []
  const problems = []
  const nav = []

  const context = {
    sdk,
    format,
    gameVersion,
    /** Add a page. `source` names the export(s) the page was read from. */
    page(title, body, { source, entry = '@beardedunicorn/thetowersdk/data' } = {}) {
      const name = pageName(title)
      if (pages.has(name)) problems.push(`game wiki: two pages are both named "${name}"`)
      const footer = source
        ? `\n\n---\n\n_Read from ${[].concat(source).map(item => `\`${item}\``).join(', ')} in \`${entry}\`. Game data as of ${gameVersion}._`
        : ''
      pages.set(name, `${heading(1, title)}\n\n${body.trim()}${footer}\n`)
      titles.set(name, title)
      return name
    },
    /** A link to another game page. Checked once every page exists. */
    link(title, label = title) {
      const name = pageName(title)
      linked.push(name)
      return `[${label.replace(/[[\]]/g, '')}](${name})`
    },
    /** One sidebar group and its index entries. */
    group(group, entryTitles) {
      nav.push({ group, entries: entryTitles.map(title => ({ title, name: pageName(title) })) })
    },
    /** What the knowledge layer says about a system, as an overview section. */
    overview(compartmentId) {
      const compartment = sdk.knowledge.GAME_KNOWLEDGE.compartments.find(item => item.id === compartmentId)
      return compartment ? compartment.summary : ''
    },
  }

  for (const module of PAGE_MODULES) module.build(context)

  context.page(
    'Game Wiki',
    sections(
      `Reference pages for The Tower – Idle Tower Defense, generated from the data in the SDK. Game data as of **${gameVersion}**.`,
      ...nav.map(({ group, entries }) =>
        sections(heading(2, group), bullets(entries.map(entry => `[${entry.title}](${entry.name})`))),
      ),
      heading(2, 'Not Covered Yet'),
      'The SDK has no data for these, so there are no pages for them:',
      bullets(NOT_COVERED),
    ),
  )

  for (const name of new Set(linked)) {
    if (!pages.has(name)) problems.push(`game wiki: a page links to "${name}", which was not generated`)
  }
  for (const { entries } of nav) {
    for (const entry of entries) {
      if (!pages.has(entry.name)) problems.push(`game wiki: the index lists "${entry.name}", which was not generated`)
    }
  }

  return { pages, nav, problems, gameVersion }
}
