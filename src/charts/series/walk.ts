/**
 * How a catalog's level table becomes series: which fields of a row can be plotted, and the
 * points each one gives. One implementation, so the count the docs publish and the series a
 * caller can fetch are the same walk rather than two that agree by coincidence.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    isPlottableValue, plottableFields, pointsOfField, pointsOfList, seriesSlug, fieldLabel, seriesOfLevelTable
 * depends    src/charts/series/types, src/data/charts/types
 * used by    src/calculators/specs.generated, src/charts/series/catalog-families, src/charts/series/cost-families
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import type { ChartSeriesFamily, ChartSeriesPoint } from '../../data/charts/types'
import type { ChartSeriesSource } from './types'

/** A finite number, or text that starts like one: `120s`, `x9.4`, `119:26:00`. `Unlock` is not. */
export function isPlottableValue(value: unknown): value is number | string {
  if (typeof value === 'number') return Number.isFinite(value)
  if (typeof value !== 'string') return false
  return /^[x×]?\s*-?\d/.test(value.trim())
}

/** Keys that identify a row rather than measure anything. */
const AXIS_KEYS: ReadonlySet<string> = new Set(['level', 'name', 'key', 'label', 'id', 'category'])

/** How many leading rows are searched for plottable fields. */
const SAMPLED_ROWS = 8

interface LevelEntry {
  x: number
  row: Record<string, unknown>
}

/** The rows of a level table, each with its level: the row's own `level`, else its key, else its position. */
function levelEntries(levels: unknown): LevelEntry[] {
  const pairs: [string, unknown][] = Array.isArray(levels)
    ? levels.map((row, index) => [String(index), row])
    : levels && typeof levels === 'object' ? Object.entries(levels as Record<string, unknown>) : []

  return pairs.flatMap(([key, row]) => {
    if (typeof row !== 'object' || row === null) return []
    const own = (row as Record<string, unknown>).level
    const x = typeof own === 'number' && Number.isFinite(own) ? own : Number(key)
    return Number.isFinite(x) ? [{ x, row: row as Record<string, unknown> }] : []
  })
}

/**
 * The fields of a level table that can be plotted, in the order they first appear.
 *
 * The union across the first few rows rather than the first alone: an ultimate weapon stat reads
 * `cost: "Unlock"` at level 0 and a real number from level 1 on, so sampling only row 0 drops
 * every one of those cost curves.
 */
export function plottableFields(levels: unknown): string[] {
  const fields: string[] = []
  for (const { row } of levelEntries(levels).slice(0, SAMPLED_ROWS)) {
    for (const [key, value] of Object.entries(row)) {
      if (!AXIS_KEYS.has(key) && isPlottableValue(value) && !fields.includes(key)) fields.push(key)
    }
  }
  return fields
}

/** The points of one field: every row where it holds something plottable, in level order. */
export function pointsOfField(levels: unknown, field: string): ChartSeriesPoint[] {
  return levelEntries(levels)
    .flatMap(({ x, row }) => {
      const value = row[field]
      return isPlottableValue(value) ? [{ x, y: value }] : []
    })
    .sort((left, right) => left.x - right.x)
}

/** A list of values, one per level starting at `firstLevel`. */
export function pointsOfList(values: readonly unknown[], firstLevel: number): ChartSeriesPoint[] {
  return values.flatMap((value, index) => (isPlottableValue(value) ? [{ x: firstLevel + index, y: value }] : []))
}

/** A name as an id segment: `Max Recovery` is `max-recovery`, `death_wave` is `death-wave`. */
export function seriesSlug(value: string): string {
  return value.trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')
}

/** A field name as a label: `coins` is `Coins`, `maxRecovery` is `Max Recovery`. */
export function fieldLabel(field: string): string {
  const spaced = field.replace(/([a-z0-9])([A-Z])/g, '$1 $2').replace(/[-_]+/g, ' ')
  return spaced.charAt(0).toUpperCase() + spaced.slice(1)
}

/** One series per plottable field of a level table. */
export function seriesOfLevelTable(
  family: ChartSeriesFamily,
  idPrefix: string,
  entity: string,
  entityTitle: string,
  levels: unknown,
): ChartSeriesSource[] {
  return plottableFields(levels).map(field => ({
    id: `${idPrefix}:${seriesSlug(field)}`,
    family,
    entity,
    metric: field,
    title: `${entityTitle}: ${fieldLabel(field)}`,
    xLabel: 'Level',
    yLabel: fieldLabel(field),
    read: () => pointsOfField(levels, field),
  }))
}
