/**
 * Every series the catalogs hold, by id: list them, count them, fetch one.
 *
 * A level table is already a chart — a lab's cost by level needs no hand-authored dataset. What
 * it lacked was a name. The count of these was published, but a count cannot be asked for: there
 * was no way to say "that one" and get its points.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    listChartSeries, getChartSeries, countChartSeriesByFamily
 * depends    src/charts/series/catalog-families, src/charts/series/types, src/data/charts/types
 * used by    src/calculators/specs.generated, src/charts/series/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import type { ChartSeries, ChartSeriesDescriptor, ChartSeriesFamily, ChartSeriesFilter } from '../../data/charts/types'
import { botSeries, cardSeries, guardianSeries, labSeries, ultimateWeaponSeries, workshopSeries } from './catalog-families'
import type { ChartSeriesSource } from './types'

interface IndexedSeries {
  source: ChartSeriesSource
  descriptor: ChartSeriesDescriptor
}

let cached: { list: readonly IndexedSeries[], byId: ReadonlyMap<string, IndexedSeries> } | null = null

/** Built on first use and kept: the catalogs are constants, and the walk reads all of them. */
function seriesIndex() {
  if (cached) return cached

  const sources = [
    ...labSeries(),
    ...workshopSeries(),
    ...cardSeries(),
    ...ultimateWeaponSeries(),
    ...botSeries(),
    ...guardianSeries(),
  ]
  const list = sources.map((source): IndexedSeries => {
    const { read, ...described } = source
    return { source, descriptor: { ...described, points: read().length } }
  })
  cached = { list, byId: new Map(list.map(entry => [entry.descriptor.id, entry])) }
  return cached
}

/**
 * Every series, or those a filter keeps.
 *
 * `entity` and `metric` match exactly, as the listing spells them. A filter that matches nothing
 * returns an empty list.
 */
export function listChartSeries(filter: ChartSeriesFilter = {}): readonly ChartSeriesDescriptor[] {
  const minPoints = filter.minPoints ?? 0
  return seriesIndex().list
    .map(entry => entry.descriptor)
    .filter(series =>
      (filter.family === undefined || series.family === filter.family)
      && (filter.entity === undefined || series.entity === filter.entity)
      && (filter.metric === undefined || series.metric === filter.metric)
      && series.points >= minPoints)
}

/** One series with its points, or `null` when no series has that id. */
export function getChartSeries(id: string): ChartSeries | null {
  const found = seriesIndex().byId.get(String(id ?? ''))
  if (!found) return null
  return { ...found.descriptor, data: found.source.read() }
}

/** How many series each family has, counted from the same list `listChartSeries` returns. */
export function countChartSeriesByFamily(filter: ChartSeriesFilter = {}): Readonly<Partial<Record<ChartSeriesFamily, number>>> {
  const counts: Partial<Record<ChartSeriesFamily, number>> = {}
  for (const series of listChartSeries(filter)) counts[series.family] = (counts[series.family] ?? 0) + 1
  return counts
}
