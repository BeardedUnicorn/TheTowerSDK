/**
 * The cost ladders that are not a field of a level table: what each module level costs, what each
 * workshop enhancement level costs, what each level of a vault upgrade costs, and what each ultimate
 * weapon unlock costs. They change with level like any other series; they were only stored
 * differently.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    moduleCostSeries, enhancementCostSeries, vaultCostSeries, vaultV29CostSeries, unlockLadderSeries
 * depends    src/charts/series/types, src/charts/series/walk, src/data, src/mechanics/effective-paths/enhancement-costs, src/mechanics/vault/keys
 * used by    src/calculators/specs.generated, src/charts/series/lookup
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import {
  DEFAULT_HARMONY_VAULT_NODES,
  DEFAULT_POWER_VAULT_NODES,
  MODULE_COIN_COSTS,
  MODULE_SHARD_COSTS,
  ULTIMATE_WEAPON_UNLOCK_STONE_COSTS_BY_OWNED,
  UW_PLUS_UNLOCK_STONE_COSTS_BY_OWNED,
  getModuleCoinUpgradeCost,
  getModuleShardUpgradeCost,
} from '../../data'
import { enhancementCoinCost, enhancementMaxLevel, enhancementStats } from '../../mechanics/effective-paths/enhancement-costs'
import { vaultV29KeyRows } from '../../mechanics/vault/keys'
import type { ChartSeriesSource } from './types'
import { seriesSlug } from './walk'

/**
 * Coins and shards for each module level. The first purchase is level 2, since a module starts at
 * level 1, and the price is the same for every rarity.
 */
export function moduleCostSeries(): ChartSeriesSource[] {
  const ladder = (
    metric: string,
    unit: string,
    count: number,
    priceAt: (level: number) => number,
  ): ChartSeriesSource => ({
    id: `module:upgrade:${seriesSlug(metric)}`,
    family: 'module',
    entity: 'upgrade',
    metric,
    title: `Module Upgrade: ${metric}`,
    xLabel: 'Level',
    yLabel: metric,
    unit,
    read: () => Array.from({ length: count }, (_, index) => ({ x: index + 2, y: priceAt(index + 2) })),
  })

  return [
    ladder('Coin Cost', 'coins', MODULE_COIN_COSTS.length, getModuleCoinUpgradeCost),
    ladder('Shard Cost', 'module shards', MODULE_SHARD_COSTS.length, getModuleShardUpgradeCost),
  ]
}

/** Coins for each level of a workshop enhancement, at list price, before any discount. */
export function enhancementCostSeries(): ChartSeriesSource[] {
  return enhancementStats().map(stat => ({
    id: `enhancement:${seriesSlug(stat)}:coin-cost`,
    family: 'enhancement',
    entity: stat,
    metric: 'Coin Cost',
    title: `${stat} Enhancement: Coin Cost`,
    xLabel: 'Level',
    yLabel: 'Coin Cost',
    unit: 'coins',
    read: () => Array.from({ length: enhancementMaxLevel(stat) ?? 0 }, (_, index) => index + 1)
      .flatMap(level => {
        const cost = enhancementCoinCost(stat, level)
        return cost === null ? [] : [{ x: level, y: cost }]
      }),
  }))
}

/**
 * Keys for each tier of a pre-v29 vault node that has more than one. Most nodes were bought once
 * and have no curve to plot, so they are not series. The current vault is `vaultV29CostSeries`.
 */
export function vaultCostSeries(): ChartSeriesSource[] {
  return [...DEFAULT_POWER_VAULT_NODES, ...DEFAULT_HARMONY_VAULT_NODES].flatMap((node): ChartSeriesSource[] => {
    const tiers = node.cost
    if (!Array.isArray(tiers) || tiers.length < 2) return []
    return [{
      id: `vault:${seriesSlug(node.id)}:keys`,
      family: 'vault',
      entity: node.id,
      metric: 'Keys',
      title: `${node.name}: Keys (pre-v29)`,
      xLabel: 'Level',
      yLabel: 'Keys',
      unit: 'keys',
      read: () => tiers.map((keys, index) => ({ x: index + 1, y: keys })),
    }]
  })
}

/**
 * Keys for each level of a v29 vault upgrade that has more than one. An upgrade bought once has no
 * curve to plot, so it is not a series; neither is a category unlock.
 */
export function vaultV29CostSeries(): ChartSeriesSource[] {
  return vaultV29KeyRows().flatMap((row): ChartSeriesSource[] => {
    if (row.levelCosts.length < 2) return []
    const name = row.tree === 'enemy' ? row.name.replace(':', ' ') : row.name
    const treeLabel = `${row.tree.charAt(0).toUpperCase()}${row.tree.slice(1)}`
    return [{
      id: `vault-v29:${row.tree}:${seriesSlug(`${row.category} ${name}`)}:keys`,
      family: 'vault-v29',
      entity: row.key,
      metric: 'Keys',
      title: `${treeLabel} ▸ ${row.category} ▸ ${name}: Keys`,
      xLabel: 'Level',
      yLabel: 'Keys',
      unit: 'keys',
      read: () => row.levelCosts.map((keys, index) => ({ x: index + 1, y: keys })),
    }]
  })
}

/**
 * Stones for the next ultimate weapon, and the next plus, by how many are already owned. The
 * x axis is the count owned, not a level: the price belongs to the purchase.
 */
export function unlockLadderSeries(): ChartSeriesSource[] {
  const ladder = (entity: string, title: string, prices: readonly number[]): ChartSeriesSource => ({
    id: `unlock-ladder:${entity}:stones`,
    family: 'unlock-ladder',
    entity,
    metric: 'Stones',
    title,
    xLabel: 'Already Owned',
    yLabel: 'Stones',
    unit: 'stones',
    read: () => prices.map((stones, owned) => ({ x: owned, y: stones })),
  })

  return [
    ladder('ultimate-weapon', 'Ultimate Weapon Unlock: Stones', ULTIMATE_WEAPON_UNLOCK_STONE_COSTS_BY_OWNED),
    ladder('ultimate-weapon-plus', 'Ultimate Weapon Plus Unlock: Stones', UW_PLUS_UNLOCK_STONE_COSTS_BY_OWNED),
  ]
}
