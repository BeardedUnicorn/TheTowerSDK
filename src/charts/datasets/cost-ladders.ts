/**
 * Cost ladders that had no chart: what each module level costs in coins and shards, what each
 * ultimate weapon and plus unlock costs, and what rushing a lab costs in gems.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    buildModuleUpgradeCostsDataset, buildUltimateWeaponUnlockLadderDataset, LAB_RUSH_CHART_HOURS, LAB_RUSH_CHART_MAXED_LAB_COUNTS, buildLabRushGemsDataset
 * depends    src/charts/tables/types, src/data
 * used by    src/calculators/specs.generated, src/charts/datasets/index, src/charts/index, src/charts/tables/lookup
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import {
  MODULE_COIN_COSTS,
  MODULE_SHARD_COSTS,
  ULTIMATE_WEAPON_UNLOCK_STONE_COSTS_BY_OWNED,
  UW_PLUS_UNLOCK_STONE_COSTS_BY_OWNED,
  buildModuleCostRows,
  computeLabRushGems,
  moduleCostMaxLevel,
  sumUltimateWeaponPlusUnlockStones,
  sumUltimateWeaponUnlockStones,
} from '../../data'
import type { SharedChartTableDataset } from '../tables/types'

type Dataset = SharedChartTableDataset<Record<string, unknown>>

/**
 * Coins and shards for every module level, with the running total of each.
 *
 * Undiscounted, and the same for every rarity: rarity decides how far a module may be levelled,
 * not what a level costs. Shards are of the module's own type.
 */
export function buildModuleUpgradeCostsDataset(): Dataset {
  const coins = buildModuleCostRows(MODULE_COIN_COSTS, 1, moduleCostMaxLevel(MODULE_COIN_COSTS), 0)
  const shards = new Map(
    buildModuleCostRows(MODULE_SHARD_COSTS, 1, moduleCostMaxLevel(MODULE_SHARD_COSTS), 0).map(row => [row.level, row]),
  )

  return {
    title: 'Module Upgrade Costs by Level',
    columns: [
      { key: 'level', label: 'Level' },
      { key: 'coins', label: 'Coins' },
      { key: 'totalCoins', label: 'Total Coins' },
      { key: 'shards', label: 'Shards' },
      { key: 'totalShards', label: 'Total Shards' },
    ],
    rows: coins.map(row => ({
      level: row.level,
      coins: row.baseCost,
      totalCoins: row.cumulativeCost,
      shards: shards.get(row.level)?.baseCost ?? '',
      totalShards: shards.get(row.level)?.cumulativeCost ?? '',
    })),
  }
}

/**
 * Stones for each ultimate weapon and each plus, by how many are already owned, with the running
 * total. The price belongs to the purchase, not the weapon, so the row is the count owned.
 */
export function buildUltimateWeaponUnlockLadderDataset(): Dataset {
  return {
    title: 'Ultimate Weapon Unlock Costs',
    columns: [
      { key: 'owned', label: 'Already Owned' },
      { key: 'weapon', label: 'Next Weapon' },
      { key: 'weaponTotal', label: 'Total' },
      { key: 'plus', label: 'Next Plus' },
      { key: 'plusTotal', label: 'Plus Total' },
    ],
    rows: ULTIMATE_WEAPON_UNLOCK_STONE_COSTS_BY_OWNED.map((weapon, owned) => ({
      owned,
      weapon,
      weaponTotal: sumUltimateWeaponUnlockStones(0, owned + 1) ?? '',
      plus: UW_PLUS_UNLOCK_STONE_COSTS_BY_OWNED[owned] ?? '',
      plusTotal: sumUltimateWeaponPlusUnlockStones(0, owned + 1) ?? '',
    })),
  }
}

/**
 * The times this chart samples. A choice of which rows to print, not game data: the gem curve is
 * straight lines between a minute, an hour, a day, a week, 30 days and 90 days, so those points
 * and a few between them show its whole shape.
 */
export const LAB_RUSH_CHART_HOURS: readonly number[] = [0.5, 1, 2, 4, 8, 12, 24, 48, 72, 168, 336, 720, 1440, 2160]

/** The counts of fully researched labs this chart prints a column for. Also a choice of columns. */
export const LAB_RUSH_CHART_MAXED_LAB_COUNTS: readonly number[] = [0, 10, 25, 50, 100]

const hoursLabel = (hours: number): string =>
  hours < 1 ? `${Math.round(hours * 60)}m` : hours < 48 ? `${hours}h` : `${hours / 24}d`

/**
 * Gems on a lab's Rush button, by the time left and how many labs are fully researched. Every
 * maxed lab makes each gem rush more, so the same wait costs an established account less.
 */
export function buildLabRushGemsDataset(): Dataset {
  return {
    title: 'Lab Rush Gems by Time Left',
    columns: [
      { key: 'timeLeft', label: 'Time Left' },
      ...LAB_RUSH_CHART_MAXED_LAB_COUNTS.map(count => ({ key: `maxed${count}`, label: `${count} Maxed Labs` })),
    ],
    rows: LAB_RUSH_CHART_HOURS.map(hours => {
      const row: Record<string, unknown> = { timeLeft: hoursLabel(hours) }
      for (const count of LAB_RUSH_CHART_MAXED_LAB_COUNTS) row[`maxed${count}`] = computeLabRushGems(hours, count)
      return row
    }),
  }
}
