/**
 * How enemy health and damage grow with the wave, on every tier. Built from the fitted scaling
 * model, so it shows the shape of the climb rather than a reading of the game.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    ENEMY_SCALING_CHART_WAVES, buildEnemyBaseStatsDataset
 * depends    src/charts/tables/types, src/data, src/formatting/numbers/game-notation, src/mechanics/waves/base-empirical-scaling
 * used by    src/calculators/specs.generated, src/charts/datasets/index, src/charts/index, src/charts/tables/lookup
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { TIERS } from '../../data'
import { formatGameNumber } from '../../formatting/numbers/game-notation'
import { computeWaveBaseDamage, computeWaveBaseHealth } from '../../mechanics/waves/base-empirical-scaling'
import type { SharedChartTableDataset } from '../tables/types'

/**
 * The waves this chart samples. A choice of which rows to print, not game data: dense where runs
 * start and sparser as the numbers get long.
 */
export const ENEMY_SCALING_CHART_WAVES: readonly number[] = [
  1, 10, 50, 100, 250, 500, 1000, 1500, 2000, 3000, 4000, 5000, 6000, 8000, 10000,
]

/**
 * Base enemy health or damage by wave, a column per tier, outside a tournament.
 *
 * `stat` is `base-health` or `base-damage`, as the chart id names it; `null` for anything else. The values are the base wave stat before enemy type, battle
 * conditions and labs, and come from a model fitted to observed runs: it drifts at very high
 * waves and tiers, so read the shape, not the last digit.
 */
export function buildEnemyBaseStatsDataset(
  stat: string,
): SharedChartTableDataset<Record<string, unknown>> | null {
  const compute = stat === 'base-health' ? computeWaveBaseHealth : stat === 'base-damage' ? computeWaveBaseDamage : null
  if (!compute) return null

  return {
    title: `Enemy Base ${stat === 'base-health' ? 'Health' : 'Damage'} by Wave and Tier (fitted model)`,
    columns: [
      { key: 'wave', label: 'Wave' },
      ...TIERS.map(tier => ({ key: `t${tier}`, label: `T${tier}` })),
    ],
    rows: ENEMY_SCALING_CHART_WAVES.map(wave => {
      const row: Record<string, unknown> = { wave }
      for (const tier of TIERS) row[`t${tier}`] = formatGameNumber(compute({ wave, tier }))
      return row
    }),
  }
}
