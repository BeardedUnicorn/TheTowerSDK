/**
 * Relics by save index: the relic a saved index names, its label, and a lookup over the whole
 * catalog.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    findRelicCatalogRow, countRelicCatalogSlots, findRelicLabel, listRelicCatalogRows, isRelicCatalogPopulated, buildRelicCatalogLookup
 * depends    src/save/catalogs/indexes.data, src/save/catalogs/types
 * used by    src/calculators/specs.generated, src/save/catalogs/index, src/save/catalogs/relic-template-match, src/save/relics/read
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import {
  IMPORT_CATALOG_META,
  RELIC_IMPORT_CATALOG,
} from './indexes.data'
import type { RelicCatalogRow } from './types'

const relicRows = (): readonly RelicCatalogRow[] =>
  RELIC_IMPORT_CATALOG as unknown as readonly RelicCatalogRow[]

let relicRowsByIndex: ReadonlyMap<number, RelicCatalogRow> | null = null

/**
 * The relic a save index names, found by the row's own `index`.
 *
 * Not by array position: the catalog can have gaps where the game defines a slot whose relic is
 * not out yet (325 and 330-333 at v29.2.0), and a positional read shifted every later relic onto
 * its neighbour's name.
 */
export function findRelicCatalogRow(index: number): RelicCatalogRow | null {
  relicRowsByIndex ??= buildRelicCatalogLookup()
  return relicRowsByIndex.get(index) ?? null
}

/** How many save slots the catalog spans: its highest index plus one, gaps included. */
export function countRelicCatalogSlots(): number {
  return relicRows().reduce((max, row) => Math.max(max, row.index + 1), 0)
}

export function findRelicLabel(index: number): string | null {
  return findRelicCatalogRow(index)?.label ?? null
}

export function listRelicCatalogRows(): readonly RelicCatalogRow[] {
  return relicRows()
}

export function isRelicCatalogPopulated(): boolean {
  return IMPORT_CATALOG_META.populated.relics && relicRows().length > 0
}

export function buildRelicCatalogLookup(): ReadonlyMap<number, RelicCatalogRow> {
  return new Map(relicRows().map(row => [row.index, row]))
}
