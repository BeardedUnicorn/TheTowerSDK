/**
 * Derives what happened to an account from a series of its exports.
 *
 * No export says "a pack was bought" or "a lab was stopped": each only says what is true now.
 * Two of them in a row say what changed in between, and this names the changes a plan depends
 * on — purchases, labs, workshop levels, boosts, presets, spending and runs — each placed
 * between the two exports that bracket it.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    resolveExportRunModes, buildExportTimeline
 * depends    src/formatting/numbers/compute, src/formatting/numbers/game-notation, src/save/current-run/in-run-levels, src/save/current-run/types, src/save/history/access, src/save/history/snapshot (+1 more)
 * used by    src/calculators/run-planning, src/calculators/specs.generated, src/save/history/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { formatGameNumber } from '../../formatting/numbers/game-notation'
import { parseSaveDateTimeToMs } from '../../formatting/numbers/compute'
import { resolveInRunLevels } from '../current-run/in-run-levels'
import type { CurrentRunSaveExtract } from '../current-run/types'
import {
  snapshotBalances,
  snapshotCurrentRun,
  snapshotEnhancementLevels,
  snapshotLabLevels,
  snapshotLabSlots,
  snapshotLifetimeFree,
  snapshotPurchases,
  snapshotTimeMs,
  snapshotWorkshopLevels,
  snapshotWorkshopPreset,
} from './access'
import { orderExportSnapshots } from './snapshot'
import type { ExportEvent, ExportEventKind, ExportRunMode, ExportSnapshot, ExportTimelineOptions } from './types'

const PURCHASE_NAMES: Record<string, string> = {
  hasStarterPack: 'Starter Pack',
  hasEpicPack: 'Epic Pack',
  hasDisableAds: 'No Ads',
}

function runEndMs(run: Record<string, unknown>): number {
  const ms = parseSaveDateTimeToMs(run.battleDate ?? run.runDate)
  return ms == null ? Number.NaN : ms
}

function runKey(run: Record<string, unknown>): string {
  return String(run.battleDate ?? run.runDate ?? '')
}

function between(earlier: ExportSnapshot, later: ExportSnapshot, add: (kind: ExportEventKind, detail: string, data: Record<string, unknown>) => void): void {
  const owned = snapshotPurchases(earlier)
  for (const [flag, now] of Object.entries(snapshotPurchases(later))) {
    if (now && owned[flag] === false) add('purchase', `${PURCHASE_NAMES[flag] ?? flag} bought`, { purchase: flag })
  }

  const labsBefore = snapshotLabLevels(earlier)
  const labsAfter = snapshotLabLevels(later)
  const finished = new Set<string>()
  for (const [slug, lab] of Object.entries(labsAfter)) {
    const from = labsBefore[slug]?.level ?? 0
    if (lab.level > from) {
      finished.add(slug)
      add('lab', `${lab.name} finished level ${lab.level}`, { lab: lab.name, slug, change: 'finished', fromLevel: from, toLevel: lab.level })
    }
  }
  const slotsBefore = snapshotLabSlots(earlier)
  for (const slot of snapshotLabSlots(later)) {
    const was = slotsBefore.find(row => row.slot === slot.slot)
    if (!was) continue
    if (was.slug && was.slug !== slot.slug && !finished.has(was.slug)) {
      add('lab', `${was.name} stopped in slot ${slot.slot + 1}`, { lab: was.name, slug: was.slug, change: 'stopped', slot: slot.slot })
    }
    if (slot.slug && (was.slug !== slot.slug || slot.level > was.level)) {
      add('lab', `${slot.name} ${slot.level + 1} started in slot ${slot.slot + 1}`, {
        lab: slot.name, slug: slot.slug, change: 'started', slot: slot.slot, toLevel: slot.level + 1,
      })
    }
    if (was.boost !== slot.boost) {
      add('boost', `slot ${slot.slot + 1} boost ${was.boost}x → ${slot.boost}x`, { slot: slot.slot, from: was.boost, to: slot.boost })
    }
    else if (slot.boost > 1 && slot.boostRemainingSeconds > was.boostRemainingSeconds) {
      add('boost', `slot ${slot.slot + 1} boost ${slot.boost}x renewed`, { slot: slot.slot, from: was.boost, to: slot.boost, renewed: true })
    }
  }

  const presetBefore = snapshotWorkshopPreset(earlier)
  const presetAfter = snapshotWorkshopPreset(later)
  const switched = presetBefore != null && presetAfter != null && presetBefore !== presetAfter
  if (switched) add('preset', `workshop preset ${presetBefore + 1} → ${presetAfter + 1}`, { from: presetBefore, to: presetAfter })
  /* After a preset switch the levels differ because the preset does, not because any were bought. */
  if (!switched) {
    const levelsBefore = snapshotWorkshopLevels(earlier)
    for (const [stat, level] of Object.entries(snapshotWorkshopLevels(later))) {
      const from = levelsBefore[stat]
      if (from != null && level > from) add('workshop', `${stat} ${from} → ${level}`, { stat, fromLevel: from, toLevel: level })
    }
    const enhancementsBefore = snapshotEnhancementLevels(earlier)
    for (const [stat, level] of Object.entries(snapshotEnhancementLevels(later))) {
      const from = enhancementsBefore[stat]
      if (from != null && level > from) {
        add('workshop', `${stat} enhancement ${from} → ${level}`, { stat, enhancement: true, fromLevel: from, toLevel: level })
      }
    }
  }

  const balancesBefore = snapshotBalances(earlier)
  for (const [currency, balance] of Object.entries(snapshotBalances(later))) {
    const from = balancesBefore[currency]
    if (from != null && balance < from) {
      add('currency', `${currency} ${formatGameNumber(from)} → ${formatGameNumber(balance)}`, { currency, from, to: balance, spentAtLeast: from - balance })
    }
  }
}

/**
 * How each stored run was played, from the exports taken while it was in progress.
 *
 * An export belongs to a run when it was taken after the previous run ended and before this one
 * did, with a wave above zero on the run's tier. `active` when any such export shows levels
 * bought with cash; `afk` when the last one shows none — as far as that export, since cash can
 * be spent after it; `unknown` when no export was taken during the run or none could tell.
 */
export function resolveExportRunModes(sources: readonly unknown[]): ExportRunMode[] {
  const snapshots = orderExportSnapshots(sources)
  const runs = new Map<string, Record<string, unknown>>()
  for (const snapshot of snapshots) for (const run of snapshot.runs) if (runKey(run)) runs.set(runKey(run), run)
  const ordered = [...runs.values()].filter(run => Number.isFinite(runEndMs(run))).sort((a, b) => runEndMs(a) - runEndMs(b))

  const out: ExportRunMode[] = []
  ordered.forEach((run, index) => {
    const end = runEndMs(run)
    const previousEnd = index > 0 ? runEndMs(ordered[index - 1]) : Number.NEGATIVE_INFINITY
    const during = snapshots.filter((snapshot) => {
      const at = snapshotTimeMs(snapshot)
      const current = snapshotCurrentRun(snapshot)
      return at > previousEnd && at < end && current != null && Number(current.currentWave) > 0
        && Number(current.currentTier) === Number(run.tier) && Number(current.currentWave) <= Number(run.wave)
    })
    let mode: ExportRunMode['mode'] = 'unknown'
    for (const snapshot of during) {
      const at = snapshotTimeMs(snapshot)
      /* The newest export before this one: at the run's start when it shows wave 0 after the previous run ended. */
      const prior = snapshots.filter(other => snapshotTimeMs(other) < at).at(-1)
      const priorFree = prior ? snapshotLifetimeFree(prior) : null
      const priorRun = prior ? snapshotCurrentRun(prior) : null
      const levels = resolveInRunLevels({
        currentRun: snapshotCurrentRun(snapshot) as unknown as CurrentRunSaveExtract,
        workshopLevels: snapshotWorkshopLevels(snapshot),
        lifetimeFree: snapshotLifetimeFree(snapshot),
        earlier: prior && priorFree
          ? { lifetimeFree: priorFree, atRunStart: snapshotTimeMs(prior) > previousEnd && Number(priorRun?.currentWave) === 0 }
          : null,
      })
      if (levels.mode === 'active') { mode = 'active'; break }
      mode = levels.mode
    }
    out.push({ runDate: new Date(end).toISOString(), mode, exportsDuringRun: during.length })
  })
  return out
}

/**
 * Everything that happened across a series of exports, oldest first. Each source is a stored
 * snapshot or a decoded save; fewer than two give only the runs of the one.
 *
 * A run is dated by its own end time. Every other event is dated by the later of the two exports
 * around it, with the earlier one in `after`: it happened somewhere in between. A run's `data`
 * carries its mode from `resolveExportRunModes`.
 */
export function buildExportTimeline(sources: readonly unknown[], options: ExportTimelineOptions = {}): ExportEvent[] {
  const snapshots = orderExportSnapshots(sources)
  const events: ExportEvent[] = []
  for (let index = 1; index < snapshots.length; index += 1) {
    const earlier = snapshots[index - 1]
    const later = snapshots[index]
    if (!later.meta.exportedAt) continue
    between(earlier, later, (kind, detail, data) => {
      events.push({ at: later.meta.exportedAt as string, after: earlier.meta.exportedAt, kind, detail, data })
    })
  }

  const modes = new Map(resolveExportRunModes(snapshots).map(mode => [mode.runDate, mode]))
  const seen = new Set<string>()
  for (const snapshot of snapshots) {
    for (const run of snapshot.runs) {
      const end = runEndMs(run)
      if (!Number.isFinite(end) || seen.has(runKey(run))) continue
      seen.add(runKey(run))
      const at = new Date(end).toISOString()
      const coins = Number(run.coinsEarned)
      events.push({
        at,
        after: null,
        kind: 'run',
        detail: `tier ${Number(run.tier)} run ended at wave ${Number(run.wave)}${Number.isFinite(coins) ? ` with ${formatGameNumber(coins)} coins` : ''}`,
        data: { tier: Number(run.tier), wave: Number(run.wave), coins: Number.isFinite(coins) ? coins : null, mode: modes.get(at)?.mode ?? 'unknown' },
      })
    }
  }

  const since = options.since ? Date.parse(options.since) : Number.NEGATIVE_INFINITY
  const kinds = options.kinds ? new Set(options.kinds) : null
  return events
    .filter(event => Date.parse(event.at) >= since && (!kinds || kinds.has(event.kind)))
    .sort((a, b) => Date.parse(a.at) - Date.parse(b.at))
}
