/**
 * Compares two exports reader by reader and lists every value that differs.
 *
 * Two exports an hour apart differ in a few dozen places, and those places are the account's
 * history: a level bought, a lab finished, coins spent. Listing them by reader and path lets a
 * person read what happened, and lets the timeline pick out the kinds it knows how to name.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    diffExportSnapshots
 * depends    src/save/history/snapshot, src/save/history/types
 * used by    src/calculators/run-planning, src/save/history/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { toExportSnapshot } from './snapshot'
import type { ExportDiff, ExportDiffOptions, ExportDifference } from './types'

const DEFAULT_LIMIT = 500

function isObject(value: unknown): value is Record<string, unknown> {
  return value != null && typeof value === 'object' && !Array.isArray(value)
}

function walk(before: unknown, after: unknown, path: string, visit: (path: string, before: unknown, after: unknown) => void): void {
  if (Array.isArray(before) && Array.isArray(after)) {
    const length = Math.max(before.length, after.length)
    for (let index = 0; index < length; index += 1) walk(before[index], after[index], `${path}[${index}]`, visit)
    return
  }
  if (isObject(before) && isObject(after)) {
    for (const key of new Set([...Object.keys(before), ...Object.keys(after)])) {
      walk(before[key], after[key], path ? `${path}.${key}` : key, visit)
    }
    return
  }
  if (before === after) return
  if (typeof before === 'number' && typeof after === 'number' && Number.isNaN(before) && Number.isNaN(after)) return
  visit(path, before, after)
}

/**
 * Every value that differs between two exports. Each of `from` and `to` is a stored snapshot or
 * a decoded save. A reader present in only one of them is one difference at the reader's root,
 * not one per field. Returns `null` when either is neither.
 */
export function diffExportSnapshots(from: unknown, to: unknown, options: ExportDiffOptions = {}): ExportDiff | null {
  const earlier = toExportSnapshot(from)
  const later = toExportSnapshot(to)
  if (!earlier || !later) return null
  const limit = Math.max(0, Math.floor(options.limit ?? DEFAULT_LIMIT))
  const names = options.readers ?? [...new Set([...Object.keys(earlier.readers), ...Object.keys(later.readers)])].sort()

  const differences: ExportDifference[] = []
  const countsByReader: Record<string, number> = {}
  let total = 0
  for (const reader of names) {
    const before = earlier.readers[reader]
    const after = later.readers[reader]
    const record = (path: string, was: unknown, now: unknown) => {
      total += 1
      countsByReader[reader] = (countsByReader[reader] ?? 0) + 1
      if (differences.length >= limit) return
      differences.push({
        reader,
        path,
        before: was,
        after: now,
        change: typeof was === 'number' && typeof now === 'number' ? now - was : null,
      })
    }
    if (before == null || after == null) {
      if (before != null || after != null) record('', before == null ? undefined : '(present)', after == null ? undefined : '(present)')
      continue
    }
    walk(before, after, '', record)
  }
  return {
    from: earlier.meta.exportedAt,
    to: later.meta.exportedAt,
    differences,
    countsByReader,
    omitted: total - differences.length,
  }
}
