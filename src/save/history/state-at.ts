/**
 * Finds the account as it stood at a moment, from the exports kept around it.
 *
 * A past run was played with the workshop, labs and purchases of its own day, not today's. The
 * nearest export taken before a moment is the best record of that state, and whether anything a
 * model reads changed while a run was being played decides whether the run can be trusted as
 * evidence at all.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    exportStateAt, exportChangesDuring
 * depends    src/save/history/access, src/save/history/snapshot, src/save/history/types
 * used by    src/calculators/run-planning, src/calculators/specs.generated, src/save/history/index, src/save/planning/coin-check
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { snapshotLabLevels, snapshotPurchases, snapshotTimeMs, snapshotWorkshopLevels } from './access'
import { orderExportSnapshots } from './snapshot'
import type { ExportSnapshot, ExportStateAt } from './types'

/**
 * The account at `at` (an ISO date): the newest export taken at or before it, or — when every
 * export is later — the oldest one, marked `after`. Returns `null` with no dated exports or an
 * unreadable date.
 */
export function exportStateAt(sources: readonly unknown[], at: string): ExportStateAt | null {
  const moment = Date.parse(at)
  const snapshots = orderExportSnapshots(sources).filter(snapshot => Number.isFinite(snapshotTimeMs(snapshot)))
  if (!Number.isFinite(moment) || snapshots.length === 0) return null
  let index = -1
  for (let i = 0; i < snapshots.length; i += 1) if (snapshotTimeMs(snapshots[i]) <= moment) index = i
  const side = index >= 0 ? 'before' : 'after'
  const chosen = snapshots[Math.max(0, index)]
  return {
    snapshot: chosen,
    takenAt: chosen.meta.exportedAt,
    side,
    nextTakenAt: snapshots[Math.max(0, index) + 1]?.meta.exportedAt ?? null,
  }
}

function changedBetween(earlier: ExportSnapshot, later: ExportSnapshot): string[] {
  const changes: string[] = []
  const owned = snapshotPurchases(earlier)
  for (const [flag, now] of Object.entries(snapshotPurchases(later))) if (now !== owned[flag] && owned[flag] != null) changes.push(flag)
  const levels = snapshotWorkshopLevels(earlier)
  for (const [stat, level] of Object.entries(snapshotWorkshopLevels(later))) if (levels[stat] != null && levels[stat] !== level) changes.push(stat)
  const labs = snapshotLabLevels(earlier)
  for (const [slug, lab] of Object.entries(snapshotLabLevels(later))) if ((labs[slug]?.level ?? 0) !== lab.level) changes.push(lab.name)
  return changes
}

/**
 * What changed on the account while a run was played: purchases, workshop levels and lab levels
 * that differ between the last export before the run began and the first one after it ended.
 *
 * `startedAt` and `endedAt` are ISO dates. Returns `null` when the exports do not bracket the
 * run, which leaves the question open; an empty list means the bracketing exports agree.
 */
export function exportChangesDuring(sources: readonly unknown[], startedAt: string, endedAt: string): string[] | null {
  const start = Date.parse(startedAt)
  const end = Date.parse(endedAt)
  const snapshots = orderExportSnapshots(sources).filter(snapshot => Number.isFinite(snapshotTimeMs(snapshot)))
  const before = snapshots.filter(snapshot => snapshotTimeMs(snapshot) <= start).at(-1)
  const after = snapshots.find(snapshot => snapshotTimeMs(snapshot) >= end)
  if (!before || !after || !Number.isFinite(start) || !Number.isFinite(end)) return null
  return changedBetween(before, after)
}
