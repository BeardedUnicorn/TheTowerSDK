/** What an export says about itself, kept beside its reader output. Never the player's id or name. */
export interface ExportSnapshotMeta {
  /** When the game wrote the export, as an ISO date, or `null` when it does not say. */
  exportedAt: string | null
  /** The game build number, such as 1301. */
  gameBuild: number | null
  dataVersion: number | null
  /** Readers that returned nothing for this export, by name. */
  readersAbsent: string[]
  /** Readers that threw, by name. Their output is left out. */
  readersFailed: string[]
}

/**
 * One export as the save readers saw it: each reader's output under the reader's own name, and
 * the stored runs. A snapshot can be kept and read back later without the export it came from.
 */
export interface ExportSnapshot {
  meta: ExportSnapshotMeta
  /** Reader output keyed by reader name, such as `readLabsFromSaveRoot`. */
  readers: Record<string, unknown>
  /** Raw run records, as `listImportableBattleRuns` returns them. */
  runs: Record<string, unknown>[]
}

/** One value that differs between two exports. */
export interface ExportDifference {
  /** The reader whose output holds the value. */
  reader: string
  /** Where in that output, as a dotted path with list positions in brackets. */
  path: string
  /** The value in the earlier export, `undefined` when it was not there. */
  before: unknown
  after: unknown
  /** `after - before` when both are numbers. */
  change: number | null
}

/** What `diffExportSnapshots` takes besides the two exports. */
export interface ExportDiffOptions {
  /** Readers to compare, by name. Every reader in either export when omitted. */
  readers?: readonly string[]
  /** The most differences to return. 500 when omitted. */
  limit?: number
}

/** Every value that differs between two exports, reader by reader. */
export interface ExportDiff {
  /** The earlier export's time, as an ISO date. */
  from: string | null
  to: string | null
  differences: ExportDifference[]
  /** How many differences each reader has, including any past `limit`. */
  countsByReader: Record<string, number>
  /** How many differences were left out because of `limit`. */
  omitted: number
}

/** What kind of thing happened between two exports. */
export type ExportEventKind = 'purchase' | 'lab' | 'workshop' | 'boost' | 'preset' | 'currency' | 'run'

/** One thing that happened to the account, placed between the two exports that bracket it. */
export interface ExportEvent {
  /**
   * When it happened, as an ISO date. A run carries its own end time. Anything else is known
   * only to lie between two exports, and this is the later one.
   */
  at: string
  /** The earlier export, or `null` for a run, whose time is its own. */
  after: string | null
  kind: ExportEventKind
  /** What happened, in a sentence. */
  detail: string
  /** The values behind `detail`, for a caller that computes with them. */
  data: Record<string, unknown>
}

/** What `buildExportTimeline` takes besides the exports. */
export interface ExportTimelineOptions {
  /** Leave out events before this ISO date. */
  since?: string
  /** Kinds to keep. All of them when omitted. */
  kinds?: readonly ExportEventKind[]
}

/** The account as it stood at a moment. */
export interface ExportStateAt {
  snapshot: ExportSnapshot
  /** When that export was taken, as an ISO date. */
  takenAt: string | null
  /**
   * `before` when the export was taken at or before the moment asked for, which is the state the
   * account had. `after` when only later exports exist, so the state may already have changed.
   */
  side: 'before' | 'after'
  /** The next export's time, or `null` when this is the newest. */
  nextTakenAt: string | null
}

/** How one stored run was played, as far as the exports taken during it can tell. */
export interface ExportRunMode {
  /** The run's end, as an ISO date. */
  runDate: string
  mode: 'afk' | 'active' | 'unknown'
  /** How many exports were taken while the run was in progress. */
  exportsDuringRun: number
}

/** One lab slot as a snapshot recorded it. */
export interface SnapshotLabSlot {
  slot: number
  /** The lab being researched, or `null` for an empty slot. */
  slug: string | null
  name: string | null
  /** The level already held; the research in the slot is for the next one. */
  level: number
  /** Seconds left at the unboosted rate the save recorded. */
  remainingSeconds: number
  /** The cell boost multiplier on the slot; 1 when none. */
  boost: number
  boostRemainingSeconds: number
}
