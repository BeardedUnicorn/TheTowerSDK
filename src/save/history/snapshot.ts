/**
 * Turns one export into a snapshot: what each save reader returned, and the stored runs.
 *
 * A save holds only the present. What the account looked like when a past run was played — its
 * workshop, its labs, whether a pack was owned — survives only if a reading was kept at the time.
 * This is the reading worth keeping: reader output, so it can be compared with any later one, and
 * neither the player's id nor name, so it can be kept anywhere.
 */
