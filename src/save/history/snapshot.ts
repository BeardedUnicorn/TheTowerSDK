import type { ExportSnapshot } from './types'

type Json = Record<string, unknown>

function isObject(value: unknown): value is Json {
  return value != null && typeof value === 'object' && !Array.isArray(value)
}

/** The readers a snapshot holds, under the names their output is stored by. */
export const EXPORT_SNAPSHOT_READERS: Readonly<Record<string, (root: Json) => unknown>> = {
  readBotsFromSaveRoot,
  readCardsFromSaveRoot,
  readCurrenciesFromSaveRoot,
  readCurrentRunFromSaveRoot,
  readExportInfoFromSaveRoot,
  readGlobalPresetsFromSaveRoot,
  readLabsFromSaveRoot,
  readLifetimeBreakdownFromSaveRoot,
  readModuleEconomyFromSaveRoot,
  readModulesFromSaveRoot,
  readPurchasesFromSaveRoot,
  readRelicsFromSaveRoot,
  readTierRecordsFromSaveRoot,
  readTotalCoinBonusFromSaveRoot: root => readTotalCoinBonusFromSaveRoot(root),
  readUltimateWeaponsFromSaveRoot,
  readWorkshopFromSaveRoot,
  readWorkshopUnlocksFromSaveRoot,
}

/** Whether a value is a stored snapshot — reader output plus runs — and not a decoded save. */
export function isExportSnapshot(value: unknown): value is ExportSnapshot {
  return isObject(value) && isObject(value.readers) && isObject(value.meta)
}

/**
 * One decoded save as a snapshot. Each reader runs on its own: one that throws is named in
 * `meta.readersFailed` and one that returns nothing in `meta.readersAbsent`, and the rest are
 * kept. Returns `null` for something that is not a save root.
 */
export function buildExportSnapshot(root: unknown): ExportSnapshot | null {
  if (!isObject(root)) return null
  const readers: Json = {}
  const readersAbsent: string[] = []
  const readersFailed: string[] = []
  for (const [name, read] of Object.entries(EXPORT_SNAPSHOT_READERS)) {
    try {
      const output = read(root)
      if (output == null) readersAbsent.push(name)
      else readers[name] = output
    }
    catch {
      readersFailed.push(name)
    }
  }
  const info = isObject(readers.readExportInfoFromSaveRoot) ? readers.readExportInfoFromSaveRoot : {}
  let runs: Json[] = []
  try { runs = listImportableBattleRuns(root) } catch { readersFailed.push('listImportableBattleRuns') }
  return {
    meta: {
      exportedAt: typeof info.exportedAt === 'string' ? info.exportedAt : null,
      gameBuild: typeof info.versionNumber === 'number' ? info.versionNumber : null,
      dataVersion: typeof info.dataVersion === 'number' ? info.dataVersion : null,
      readersAbsent,
      readersFailed,
    },
    readers,
    runs,
  }
}

/**
 * A snapshot from whichever of the two a caller holds: a stored snapshot is returned as it is
 * (with missing parts filled in as empty), a decoded save is read. `null` for neither.
 */
export function toExportSnapshot(source: unknown): ExportSnapshot | null {
  if (!isObject(source)) return null
  if (!isObject(source.readers)) return buildExportSnapshot(source)
  const meta = isObject(source.meta) ? source.meta : {}
  const exportedAt = typeof meta.exportedAt === 'string'
    ? meta.exportedAt
    : typeof meta.snapshotAt === 'string' ? meta.snapshotAt : null
  return {
    meta: {
      exportedAt,
      gameBuild: typeof meta.gameBuild === 'number' ? meta.gameBuild : null,
      dataVersion: typeof meta.dataVersion === 'number' ? meta.dataVersion : null,
      readersAbsent: Array.isArray(meta.readersAbsent) ? meta.readersAbsent.filter(name => typeof name === 'string') : [],
      readersFailed: Array.isArray(meta.readersFailed) ? meta.readersFailed.filter(name => typeof name === 'string') : [],
    },
    readers: source.readers,
    runs: Array.isArray(source.runs) ? source.runs.filter(isObject) : [],
  }
}

/** Snapshots from a mixed list of stored snapshots and decoded saves, oldest first; undated ones last. */
export function orderExportSnapshots(sources: readonly unknown[]): ExportSnapshot[] {
  const out: ExportSnapshot[] = []
  for (const source of sources) {
    const snapshot = toExportSnapshot(source)
    if (snapshot) out.push(snapshot)
  }
  const at = (snapshot: ExportSnapshot) => {
    const ms = snapshot.meta.exportedAt ? Date.parse(snapshot.meta.exportedAt) : Number.NaN
    return Number.isFinite(ms) ? ms : Number.POSITIVE_INFINITY
  }
  return out.sort((a, b) => at(a) - at(b))
}
