/** How many lab slots the account owns, or `null` when the labs reading does not say. */
export function snapshotLabSlotCount(snapshot: ExportSnapshot): number | null {
  const unlocked = reader(snapshot, 'readLabsFromSaveRoot').labsUnlocked
  return typeof unlocked === 'number' && Number.isFinite(unlocked) ? unlocked + 1 : null
}

/** The save positions of the relics the account has unlocked. */
export function snapshotUnlockedRelicIndices(snapshot: ExportSnapshot): number[] {
  const relics = reader(snapshot, 'readRelicsFromSaveRoot').relics
  if (!Array.isArray(relics)) return []
  const out: number[] = []
  for (const relic of relics) if (isObject(relic) && relic.unlocked === true && typeof relic.index === 'number') out.push(relic.index)
  return out
}

/** The highest wave reached on each tier, by tier number. */
export function snapshotBestWaveByTier(snapshot: ExportSnapshot): Record<number, number> {
  const out: Record<number, number> = {}
  const tiers = reader(snapshot, 'readTierRecordsFromSaveRoot').tiers
  if (!Array.isArray(tiers)) return out
  for (const row of tiers) {
    if (isObject(row) && typeof row.tier === 'number' && typeof row.highestWave === 'number') out[row.tier] = row.highestWave
  }
  return out
}
