/**
 * Reads the handful of values the history modules compare out of a snapshot's reader output.
 *
 * A stored snapshot is JSON written by an earlier version of the readers, so nothing in it can
 * be assumed to be there or to have today's shape. Each accessor here returns a plain value and
 * an empty one when the reader, or the field, is missing.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    snapshotTimeMs, snapshotWorkshopLevels, snapshotEnhancementLevels, snapshotWorkshopPreset, snapshotLifetimeFree, snapshotLabLevels, snapshotLabSlots, snapshotPurchases (+7 more)
 * depends    src/save/current-run/types, src/save/history/types
 * used by    src/calculators/specs.generated, src/save/history/index, src/save/history/state-at, src/save/history/timeline, src/save/planning/candidates, src/save/planning/cells (+6 more)
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import type { LifetimeFreeUpgradeCounts } from '../current-run/types'
import type { ExportSnapshot, SnapshotLabSlot } from './types'

type Json = Record<string, unknown>

function isObject(value: unknown): value is Json {
  return value != null && typeof value === 'object' && !Array.isArray(value)
}

function reader(snapshot: ExportSnapshot, name: string): Json {
  const output = snapshot.readers[name]
  return isObject(output) ? output : {}
}

function numbers(value: unknown): Record<string, number> {
  const out: Record<string, number> = {}
  if (!isObject(value)) return out
  for (const [key, entry] of Object.entries(value)) {
    if (typeof entry === 'number' && Number.isFinite(entry)) out[key] = entry
  }
  return out
}

/** When a snapshot was taken, in milliseconds, or `NaN` when it does not say. */
export function snapshotTimeMs(snapshot: ExportSnapshot): number {
  return snapshot.meta.exportedAt ? Date.parse(snapshot.meta.exportedAt) : Number.NaN
}

/** Workshop levels of the active preset, by workshop table name. */
export function snapshotWorkshopLevels(snapshot: ExportSnapshot): Record<string, number> {
  const active = reader(snapshot, 'readWorkshopFromSaveRoot').active
  return numbers(isObject(active) ? active.levels : undefined)
}

/** Workshop enhancement levels of the active preset, by enhancement key. */
export function snapshotEnhancementLevels(snapshot: ExportSnapshot): Record<string, number> {
  const active = reader(snapshot, 'readWorkshopFromSaveRoot').active
  return numbers(isObject(active) ? active.enhancementLevels : undefined)
}

/**
 * The workshop preset in use, counted from 0, or `null`.
 *
 * @unit preset
 */
export function snapshotWorkshopPreset(snapshot: ExportSnapshot): number | null {
  const meta = reader(snapshot, 'readWorkshopFromSaveRoot').meta
  return isObject(meta) && typeof meta.currentPreset === 'number' ? meta.currentPreset : null
}

/** Lifetime free-upgrade counters, or `null` when the workshop reading lacks any of them. */
export function snapshotLifetimeFree(snapshot: ExportSnapshot): LifetimeFreeUpgradeCounts | null {
  const meta = reader(snapshot, 'readWorkshopFromSaveRoot').meta
  if (!isObject(meta)) return null
  const attack = Number(meta.totalFreeAttackUpgrades)
  const defense = Number(meta.totalFreeDefenseUpgrades)
  const utility = Number(meta.totalFreeUtilityUpgrades)
  return [attack, defense, utility].every(Number.isFinite) && meta.totalFreeAttackUpgrades != null
    ? { attack, defense, utility }
    : null
}

/** Lab levels by slug, with each lab's display name. A lab not researched is absent. */
export function snapshotLabLevels(snapshot: ExportSnapshot): Record<string, { level: number, name: string }> {
  const out: Record<string, { level: number, name: string }> = {}
  const researches = reader(snapshot, 'readLabsFromSaveRoot').researches
  if (!Array.isArray(researches)) return out
  for (const lab of researches) {
    if (!isObject(lab) || typeof lab.slug !== 'string') continue
    const level = Number(lab.level)
    if (Number.isFinite(level) && level > 0) out[lab.slug] = { level, name: typeof lab.displayName === 'string' ? lab.displayName : lab.slug }
  }
  return out
}

/** The lab slots a snapshot recorded, in slot order. */
export function snapshotLabSlots(snapshot: ExportSnapshot): SnapshotLabSlot[] {
  const queue = reader(snapshot, 'readLabsFromSaveRoot').activeQueue
  if (!Array.isArray(queue)) return []
  const out: SnapshotLabSlot[] = []
  for (const row of queue) {
    if (!isObject(row)) continue
    const research = isObject(row.research) && row.active !== false ? row.research : null
    const boost = Number(row.speedUp)
    out.push({
      slot: Number(row.slotIndex) || out.length,
      slug: research && typeof research.slug === 'string' ? research.slug : null,
      name: research && typeof research.displayName === 'string' ? research.displayName : null,
      level: research ? Number(research.level) || 0 : 0,
      remainingSeconds: research ? Math.max(0, Number(research.remainingSeconds) || 0) : 0,
      boost: Number.isFinite(boost) && boost > 1 ? boost : 1,
      boostRemainingSeconds: Math.max(0, Number(row.speedUpRemainingSeconds) || 0),
    })
  }
  return out
}

/** The paid purchases a snapshot recorded as owned, by reader flag name. */
export function snapshotPurchases(snapshot: ExportSnapshot): Record<string, boolean> {
  const out: Record<string, boolean> = {}
  for (const [key, value] of Object.entries(reader(snapshot, 'readPurchasesFromSaveRoot'))) {
    if (typeof value === 'boolean') out[key] = value
  }
  return out
}

