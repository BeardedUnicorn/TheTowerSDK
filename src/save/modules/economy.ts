/**
 * Module economy beyond what is equipped: pity counters, what each slot cost, presets, reroll
 * settings and lifetime counters.
 *
 * v29 moved module levels onto the slot (patch note 1541918023470940302), so slot levels and slot
 * spend live in their own lists and a module's own `coinsSpent` reads 0. Lifetime shard counts
 * use the `_v2` keys the game moved its balances to (patch note 1571908572156272841).
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    readModuleEconomyFromSaveRoot
 * depends    src/data/modules/types, src/save/access/values, src/save/modules/read, src/save/modules/types
 * used by    src/calculators/specs.generated, src/save/history/snapshot, src/save/modules/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { coerceSaveNumber, readSaveBoolean, readSaveListItems } from '../access/values'
import { MODULE_SAVE_ASSIST_TYPE_TO_CATEGORY, MODULE_SAVE_PRIMARY_CATEGORY_ORDER } from './read'
import type { ModuleCategory } from '../../data/modules/types'
import type { AssistSlotInvestmentSaveRow, ModuleEconomySaveExtract, ModulePresetSaveRow } from './types'

const CATEGORY_PREFIX: Record<ModuleCategory, string> = {
  Cannon: 'cannon',
  Armor: 'armor',
  Generator: 'generator',
  Core: 'core',
}

function readNumbers(raw: unknown): (number | null)[] {
  return readSaveListItems(raw).map(value => coerceSaveNumber(value))
}

function readIds(raw: unknown): number[] {
  return readNumbers(raw).filter((value): value is number => value !== null)
}

function readGuids(raw: unknown): (string | null)[] {
  return readSaveListItems(raw).map(value => (typeof value === 'string' && value ? value : null))
}

function readPresets(raw: unknown): ModulePresetSaveRow[] {
  return readSaveListItems(raw).flatMap((entry, index) => {
    if (!entry || typeof entry !== 'object') return []
    const row = entry as Record<string, unknown>
    return [{
      index,
      name: typeof row.presetName === 'string' ? row.presetName : `Preset ${index + 1}`,
      primaryModuleGuids: readGuids(row.primaryModuleGuids),
      assistModuleGuids: readGuids(row.assistModuleGuids),
    }]
  })
}

function readAssistSlots(raw: unknown, warnings: string[]): AssistSlotInvestmentSaveRow[] {
  return readSaveListItems(raw).flatMap((entry, index) => {
    const slot = entry && typeof entry === 'object' ? entry as Record<string, unknown> : null
    const type = coerceSaveNumber(slot?.type)
    const category = type === null ? undefined : MODULE_SAVE_ASSIST_TYPE_TO_CATEGORY[type]
    if (!slot || !category) {
      warnings.push(`assistModuleSlots[${index}] has no known category.`)
      return []
    }
    return [{
      category,
      unlocked: readSaveBoolean(slot.unlocked),
      level: coerceSaveNumber(slot.level),
      mainEffectEfficiencyLevel: coerceSaveNumber(slot.mainEffectEfficiencyLevel),
      substatEfficiencyLevel: coerceSaveNumber(slot.substatEfficiencyLevel),
      uniqueEffectEfficiencyLevel: coerceSaveNumber(slot.uniqueEffectEfficiencyLevel),
      coinsSpent: coerceSaveNumber(slot.coinsSpent),
      shardsSpent: coerceSaveNumber(slot.shardsSpent),
    }]
  })
}

function byCategory(root: Record<string, unknown>, suffix: string): Record<ModuleCategory, number[]> {
  return Object.fromEntries(MODULE_SAVE_PRIMARY_CATEGORY_ORDER.map(category => (
    [category, readIds(root[`${CATEGORY_PREFIX[category]}${suffix}`])]
  ))) as Record<ModuleCategory, number[]>
}

function lifetime(root: Record<string, unknown>, key: string): number | null {
  return coerceSaveNumber(root[`${key}_v2`]) ?? coerceSaveNumber(root[key])
}

/** Module economy, or null for a save from before modules. */
export function readModuleEconomyFromSaveRoot(root: Record<string, unknown> | null): ModuleEconomySaveExtract | null {
  if (!root || !['modulePity', 'slotLevels', 'assistModuleSlots', 'modulePresets'].some(key => key in root)) return null
  const warnings: string[] = []
  return {
    pity: coerceSaveNumber(root.modulePity),
    rarePity: coerceSaveNumber(root.moduleRarePity),
    slotLevels: readNumbers(root.slotLevels),
    slotCoinsSpent: readNumbers(root.slotCoinsSpent),
    slotShardsSpent: readNumbers(root.slotShardsSpent),
    assistModulesAvailable: typeof root.assistModulesAvailable === 'boolean' ? root.assistModulesAvailable : null,
    assistSlots: readAssistSlots(root.assistModuleSlots, warnings),
    presets: readPresets(root.modulePresets),
    currentPreset: coerceSaveNumber(root.currentModulePreset),
    substatBans: byCategory(root, 'SubstatBans'),
    autoRerollSubstats: byCategory(root, 'AutoRerollSubstats'),
    lifetimeShards: {
      cannon: lifetime(root, 'moduleCannonShardsLifetime'),
      armor: lifetime(root, 'moduleArmorShardsLifetime'),
      generator: lifetime(root, 'moduleGeneratorShardsLifetime'),
      core: lifetime(root, 'moduleCoreShardsLifetime'),
      reroll: lifetime(root, 'moduleRerollCurrencyLifetime'),
    },
    gemsSpent: coerceSaveNumber(root.totalGemsSpentOnModules),
    commonObtained: coerceSaveNumber(root.commonModulesObtained),
    rareObtained: coerceSaveNumber(root.rareModulesObtained),
    epicObtained: coerceSaveNumber(root.epicModulesObtained),
    shattered: coerceSaveNumber(root.totalModulesShattered),
    merges: coerceSaveNumber(root.totalMergesDone),
    warnings,
  }
}
