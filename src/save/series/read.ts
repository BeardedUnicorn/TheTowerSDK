/**
 * A player's history as series: what each run earned over time, how each tournament went, and
 * the best result on every tier. The catalog series say what an upgrade costs; these say what a
 * specific account has done, in the same shape, so one chart draws either.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    readBattleHistorySeriesFromSaveRoot, readTournamentSeriesFromSaveRoot, readTierRecordSeriesFromSaveRoot, readSaveSeriesFromSaveRoot
 * depends    src/data/charts/types, src/formatting/numbers/compute, src/save/access/values, src/save/battle/history, src/save/series/types, src/save/tier-records/read (+1 more)
 * used by    src/calculators/specs.generated, src/save/series/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import type { ChartSeries, ChartSeriesPoint } from '../../data/charts/types'
import { parseSaveDateTimeToMs } from '../../formatting/numbers/compute'
import { coerceSaveNumber } from '../access/values'
import { battleRunCoinsPerHour, listImportableBattleRuns } from '../battle/history'
import { readTierRecordsFromSaveRoot } from '../tier-records/read'
import { readTournamentsFromSaveRoot } from '../tournaments/read'
import type { SaveSeriesExtract } from './types'

/** A series over time puts the moment on the x axis, as milliseconds since the epoch. */
const TIME_AXIS = { xLabel: 'Date (ms since epoch)' } as const

function series(
  id: string,
  entity: string,
  metric: string,
  title: string,
  xLabel: string,
  yLabel: string,
  data: ChartSeriesPoint[],
  unit?: string,
): ChartSeries {
  const ordered = [...data].sort((left, right) => left.x - right.x)
  return { id, family: 'save', entity, metric, title, xLabel, yLabel, ...(unit ? { unit } : {}), points: ordered.length, data: ordered }
}

/** Only series with something in them: an empty one says nothing a missing one does not. */
const nonEmpty = (list: ChartSeries[]): ChartSeries[] => list.filter(entry => entry.points > 0)

const asRoot = (root: unknown): Record<string, unknown> | null =>
  root && typeof root === 'object' && !Array.isArray(root) ? root as Record<string, unknown> : null

/**
 * Coins per hour, wave reached, coins and cells for every run in battle history, by the run's
 * date.
 *
 * `null` for a save with no battle history. A run with no readable date cannot be placed on a
 * time axis and is left out of every series; a run missing one value is left out of that series
 * only. Both are counted in `warnings`.
 */
export function readBattleHistorySeriesFromSaveRoot(root: unknown): SaveSeriesExtract | null {
  const runs = listImportableBattleRuns(root)
  if (runs.length === 0) return null

  const warnings: string[] = []
  const points: Record<'rate' | 'wave' | 'coins' | 'cells', ChartSeriesPoint[]> = { rate: [], wave: [], coins: [], cells: [] }
  let undated = 0
  const missing = { rate: 0, wave: 0, coins: 0, cells: 0 }

  for (const run of runs) {
    const x = parseSaveDateTimeToMs(run.battleDate ?? run.runDate)
    if (x === null) {
      undated += 1
      continue
    }
    const values = {
      rate: battleRunCoinsPerHour(run),
      wave: coerceSaveNumber(run.wave),
      coins: coerceSaveNumber(run.coinsEarned),
      cells: coerceSaveNumber(run.cellsEarned),
    }
    for (const key of ['rate', 'wave', 'coins', 'cells'] as const) {
      const y = values[key]
      if (y === null) missing[key] += 1
      else points[key].push({ x, y })
    }
  }

  if (undated > 0) warnings.push(`${undated} of ${runs.length} runs have no readable date and are left out.`)
  for (const [key, label] of [['rate', 'coins per hour'], ['wave', 'wave'], ['coins', 'coins earned'], ['cells', 'cells earned']] as const) {
    if (missing[key] > 0) warnings.push(`${missing[key]} dated runs have no ${label} and are left out of that series.`)
  }

  return {
    series: nonEmpty([
      series('save:battle:coins-per-hour', 'battle', 'coinsPerHour', 'Coins per Hour by Run', TIME_AXIS.xLabel, 'Coins per Hour', points.rate, 'coins per hour'),
      series('save:battle:wave', 'battle', 'wave', 'Wave Reached by Run', TIME_AXIS.xLabel, 'Wave', points.wave),
      series('save:battle:coins', 'battle', 'coinsEarned', 'Coins Earned by Run', TIME_AXIS.xLabel, 'Coins', points.coins, 'coins'),
      series('save:battle:cells', 'battle', 'cellsEarned', 'Cells Earned by Run', TIME_AXIS.xLabel, 'Cells', points.cells, 'cells'),
    ]),
    warnings,
  }
}

/**
 * Wave reached and final rank for every tournament entered, by the tournament's date.
 *
 * `null` for a save with no tournament data. A tournament still running has rank 0, which is not
 * a placing, so it has a wave point and no rank point. Rank 1 is first place, so a lower rank is
 * a better result.
 */
export function readTournamentSeriesFromSaveRoot(root: unknown): SaveSeriesExtract | null {
  const tournaments = readTournamentsFromSaveRoot(asRoot(root))
  if (!tournaments) return null

  const warnings = [...tournaments.warnings]
  const wave: ChartSeriesPoint[] = []
  const rank: ChartSeriesPoint[] = []
  let undated = 0
  let unranked = 0

  for (const record of tournaments.records) {
    const x = parseSaveDateTimeToMs(record.date)
    if (x === null) {
      undated += 1
      continue
    }
    if (record.wave !== null) wave.push({ x, y: record.wave })
    if (record.rank !== null && record.rank > 0) rank.push({ x, y: record.rank })
    else unranked += 1
  }

  if (undated > 0) warnings.push(`${undated} of ${tournaments.records.length} tournaments have no readable date and are left out.`)
  if (unranked > 0) warnings.push(`${unranked} tournaments have no final rank yet and are left out of the rank series.`)

  return {
    series: nonEmpty([
      series('save:tournament:wave', 'tournament', 'wave', 'Tournament Wave by Date', TIME_AXIS.xLabel, 'Wave', wave),
      series('save:tournament:rank', 'tournament', 'rank', 'Tournament Rank by Date', TIME_AXIS.xLabel, 'Rank', rank),
    ]),
    warnings,
  }
}

/**
 * The best wave, coins and cells on each tier, by tier.
 *
 * `null` for a save with no per-tier records. A tier with no value for a field is absent from
 * that series rather than plotted at zero: the save does not say it was played.
 */
export function readTierRecordSeriesFromSaveRoot(root: unknown): SaveSeriesExtract | null {
  const records = readTierRecordsFromSaveRoot(asRoot(root))
  if (!records) return null

  const column = (field: 'highestWave' | 'highestCoinsEarned' | 'highestCellsEarned'): ChartSeriesPoint[] =>
    records.tiers.flatMap(row => {
      const y = row[field]
      return y === null ? [] : [{ x: row.tier, y }]
    })

  return {
    series: nonEmpty([
      series('save:tier:highest-wave', 'tier', 'highestWave', 'Highest Wave by Tier', 'Tier', 'Wave', column('highestWave')),
      series('save:tier:highest-coins', 'tier', 'highestCoinsEarned', 'Most Coins in a Run by Tier', 'Tier', 'Coins', column('highestCoinsEarned'), 'coins'),
      series('save:tier:highest-cells', 'tier', 'highestCellsEarned', 'Most Cells in a Run by Tier', 'Tier', 'Cells', column('highestCellsEarned'), 'cells'),
    ]),
    warnings: [],
  }
}

/**
 * Every series a save holds: battle history, tournaments and per-tier records together.
 *
 * `null` only when the save has none of the three. Each warning says which part it came from.
 */
export function readSaveSeriesFromSaveRoot(root: unknown): SaveSeriesExtract | null {
  const parts: [string, SaveSeriesExtract | null][] = [
    ['battle history', readBattleHistorySeriesFromSaveRoot(root)],
    ['tournaments', readTournamentSeriesFromSaveRoot(root)],
    ['tier records', readTierRecordSeriesFromSaveRoot(root)],
  ]
  if (parts.every(([, part]) => part === null)) return null

  return {
    series: parts.flatMap(([, part]) => part?.series ?? []),
    warnings: parts.flatMap(([label, part]) => (part?.warnings ?? []).map(warning => `${label}: ${warning}`)),
  }
}
