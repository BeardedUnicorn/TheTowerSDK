/**
 * What a card pull can land on for the account in a save.
 *
 * Decides the pool from the save — which cards are maxed, which milestone cards have been claimed —
 * and hands it to `computeCardDrawOdds`. Reproduces the Card Chances panel of a v29.2.2 account on
 * 2026-11-24 to the hundredth of a percent (facts/v29.2.2/live-ui-check.json, `cardChances`).
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    readCardDrawOddsFromSaveRoot
 * depends    src/data/cards/data, src/data/cards/milestone-unlocks, src/mechanics/cards/draw-odds, src/save/cards/read, src/save/cards/types, src/save/milestones/read
 * used by    src/calculators/specs.generated, src/save/cards/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { CARD_TEMPLATES } from '../../data/cards/data'
import { CARD_MILESTONE_UNLOCK_REWARDS } from '../../data/cards/milestone-unlocks'
import { computeCardDrawOdds } from '../../mechanics/cards/draw-odds'
import { readMilestonesFromSaveRoot } from '../milestones/read'
import { readCardsFromSaveRoot } from './read'
import type { CardDrawOddsSaveExtract, CardDrawPoolSaveRow } from './types'

/** The level at which a card leaves the pool. */
const CARD_MAX_LEVEL = 7

/**
 * Draw odds for every card, or null for a save with no card data.
 *
 * A milestone card counts as in the pool once its milestone slot is claimed, or once it is owned
 * (a save older than the claim lists can still show it owned). Without milestone data, gated cards
 * that are not owned are left out and a warning says so.
 */
export function readCardDrawOddsFromSaveRoot(root: Record<string, unknown> | null): CardDrawOddsSaveExtract | null {
  const cards = readCardsFromSaveRoot(root)
  if (!cards) return null
  const milestones = readMilestonesFromSaveRoot(root)
  const warnings = [...cards.warnings, ...(milestones?.warnings ?? [])]
  if (!milestones) {
    warnings.push('No milestone claims in the save: milestone cards count as in the pool only once owned.')
  }

  const claimed = (tier: number, slot: number) =>
    milestones?.tiers.find(row => row.tier === tier)?.claimedSlots.includes(slot) ?? false

  const pool: CardDrawPoolSaveRow[] = CARD_TEMPLATES.map(template => {
    const saved = cards.cards.find(row => row.slug === template.id)
    const level = saved?.level ?? 1
    const gate = CARD_MILESTONE_UNLOCK_REWARDS.find(unlock => unlock.card === template.id) ?? null
    const inPool = !gate || claimed(gate.tier, gate.slot) || Boolean(saved?.unlocked)
    return {
      card: template.id,
      name: template.name,
      rarity: template.rarity,
      level,
      inPool,
      drawable: inPool && level < CARD_MAX_LEVEL,
      gatedBy: gate ? { tier: gate.tier, wave: gate.wave } : null,
    }
  })

  const odds = computeCardDrawOdds(pool.map(({ card, rarity, drawable }) => ({ card, rarity, drawable })))
  return { pool, odds, warnings }
}
