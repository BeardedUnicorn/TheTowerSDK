/**
 * Reads what changes a lab's price and speed on one account: the Labs Coin Discount level, the
 * Labs Speed level and the lab speed its relics add.
 *
 * The lab cost and duration formulas take these as arguments and no reader assembled them, so
 * every caller looked three things up by hand. This is that lookup, from a save or from lab
 * levels and relics already read.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    labSpeedRelicFractionFromIndices, labCostModifiersFromLevels, readLabCostModifiersFromSaveRoot
 * depends    src/data/relics/data, src/mechanics/effective-paths/common/types, src/save/labs/read, src/save/relics/read
 * used by    src/calculators/specs.generated, src/save/labs/index, src/save/planning/candidates, src/save/planning/lab-queue
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { computeLabSpeedRelicBonusPercent } from '../../data/relics/data'
import type { LabCostModifiers } from '../../mechanics/effective-paths/common/types'
import { findRelicTemplateIdForSaveIndex, readRelicsFromSaveRoot } from '../relics/read'
import { readLabsFromSaveRoot } from './read'

/**
 * Lab speed from relics as a fraction, 0.035 for +3.5%, from the save positions of the relics
 * the account has unlocked.
 */
export function labSpeedRelicFractionFromIndices(unlockedRelicIndices: readonly number[]): number {
  const owned: Record<string, boolean> = {}
  for (const index of unlockedRelicIndices) {
    const templateId = findRelicTemplateIdForSaveIndex(index)
    if (templateId) owned[templateId] = true
  }
  return computeLabSpeedRelicBonusPercent(owned) / 100
}

/**
 * The modifiers the lab cost and duration formulas take, from lab levels by slug and the relic
 * lab speed fraction. The cell boost is per slot, not per account, so `labSpeedMultiplier` is
 * left for the caller.
 */
export function labCostModifiersFromLevels(labLevels: Readonly<Record<string, number>>, labSpeedRelicFraction = 0): LabCostModifiers {
  return {
    coinDiscountLabLevel: labLevels.labs_coin_discount ?? 0,
    labSpeedLabLevel: labLevels.labs_speed ?? 0,
    labSpeedRelicPct: Math.max(0, labSpeedRelicFraction),
  }
}

/** The lab cost modifiers of a save's account, or `null` when its labs cannot be read. */
export function readLabCostModifiersFromSaveRoot(root: Record<string, unknown> | null): LabCostModifiers | null {
  const labs = readLabsFromSaveRoot(root)
  if (!labs) return null
  const levels: Record<string, number> = {}
  for (const lab of labs.researches) if (lab.slug && lab.level > 0) levels[lab.slug] = lab.level
  const relics = readRelicsFromSaveRoot(root)
  const unlocked = relics ? relics.relics.filter(relic => relic.unlocked).map(relic => relic.index) : []
  return labCostModifiersFromLevels(levels, labSpeedRelicFractionFromIndices(unlocked))
}
