/**
 * Which milestone rewards a player has claimed, tier by tier.
 *
 * The claim lists are indexed by tier like the save's other per-tier lists: a v29.2 export holds
 * 575 flags, 25 blocks of 23 reward slots, block 0 always empty and block 13 holding tier 13's
 * claims. The premium pass list has one flag per three tiers (index 0 covers tiers 1-3).
 *
 * Slots are reported as the game numbers them within a tier, not as rewards: which reward a slot
 * pays is game data, not save data.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    MILESTONE_PREMIUM_PASS_TIERS, readMilestonesFromSaveRoot
 * depends    src/data/tiers/campaign, src/save/access/values, src/save/milestones/types
 * used by    src/save/milestones/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { MAX_CAMPAIGN_TIER } from '../../data/tiers/campaign'
import { readSaveBoolean, readSaveListItems } from '../access/values'
import type { MilestoneTierClaimsSaveRow, MilestonesSaveExtract } from './types'

/** Tiers covered by one premium pass. */
export const MILESTONE_PREMIUM_PASS_TIERS = 3

function claimedSlotsByTier(flags: unknown[], slotsPerTier: number): Map<number, number[]> {
  const byTier = new Map<number, number[]>()
  flags.forEach((flag, index) => {
    if (!readSaveBoolean(flag)) return
    const tier = Math.floor(index / slotsPerTier)
    const slots = byTier.get(tier) ?? []
    slots.push(index % slotsPerTier)
    byTier.set(tier, slots)
  })
  return byTier
}

/** Milestone claims per tier, or null for a save with no milestone data. */
export function readMilestonesFromSaveRoot(root: Record<string, unknown> | null): MilestonesSaveExtract | null {
  if (!root || !('milestonesRewardClaimed' in root)) return null
  const warnings: string[] = []
  const free = readSaveListItems(root.milestonesRewardClaimed)
  const premium = readSaveListItems(root.milestonesRewardPremiumClaimed)
  const passes = readSaveListItems(root.milestonesPremiumUnlocked).map(readSaveBoolean)

  // One block per tier plus the empty block 0.
  const blocks = MAX_CAMPAIGN_TIER + 1
  if (free.length % blocks !== 0) {
    warnings.push(`milestonesRewardClaimed has ${free.length} flags, not a whole number of ${blocks} tier blocks.`)
  }
  const slotsPerTier = Math.max(1, Math.round(free.length / blocks))
  const freeByTier = claimedSlotsByTier(free, slotsPerTier)
  const premiumByTier = claimedSlotsByTier(premium, slotsPerTier)
  if (freeByTier.has(0) || premiumByTier.has(0)) warnings.push('Milestone claims found in block 0, which no tier uses.')

  const tiers: MilestoneTierClaimsSaveRow[] = []
  for (let tier = 1; tier <= MAX_CAMPAIGN_TIER; tier += 1) {
    const premiumUnlocked = passes[Math.floor((tier - 1) / MILESTONE_PREMIUM_PASS_TIERS)] ?? false
    const claimedSlots = freeByTier.get(tier) ?? []
    const premiumClaimedSlots = premiumByTier.get(tier) ?? []
    if (claimedSlots.length || premiumClaimedSlots.length || premiumUnlocked) {
      tiers.push({ tier, claimedSlots, premiumClaimedSlots, premiumUnlocked })
    }
  }
  return { slotsPerTier, tiers, warnings }
}
