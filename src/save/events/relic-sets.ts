/**
 * The relics each event awards, joined from the relic catalog: which event a relic belongs to, and
 * how many medals it takes.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    normalizeEventName, EVENT_RELIC_SETS, findEventRelicSet, findThemeSourceEvent, selectEventRelicEdition
 * depends    src/data/events/shop, src/data/generated/relic-game-table.generated, src/data/themes/bonus-catalog, src/save/catalogs/relics, src/save/events/types, src/save/relics/read
 * used by    src/calculators/run, src/calculators/specs.generated, src/save/events/index, src/save/events/read, src/save/events/shop
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { findEventShopPrice } from '../../data/events/shop'
import { BACKGROUND, TOWER } from '../../data/themes/bonus-catalog'
import { RELIC_GAME_TABLE_BY_INDEX } from '../../data/generated/relic-game-table.generated'
import { listRelicCatalogRows } from '../catalogs/relics'
import { readRelicEventFromUnlockText } from '../relics/read'
import type { EventRelicRow, EventRelicSet } from './types'

/** Medal thresholds of the two relics every player can earn; the other two need the event pass. */
const FREE_TRACK_MEDALS: ReadonlySet<number> = new Set([350, 700])

/** The threshold of the first relic of every run of an event. */
const FIRST_RELIC_MEDALS = 350

/**
 * One key for an event however it is spelled: the save writes `RAINFALL` and `SANDS_OF_TIME` for
 * recent events and `What time is it?` for older ones, where the relic text says `Rainfall`,
 * `Sands of Time` and `What Time Is It`.
 */
export function normalizeEventName(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '')
}

function buildEventRelicSets(): EventRelicSet[] {
  const sets = new Map<string, EventRelicSet>()
  for (const row of listRelicCatalogRows()) {
    const event = readRelicEventFromUnlockText(row.unlockDescription)
    if (!event) continue
    const game = RELIC_GAME_TABLE_BY_INDEX.get(row.index)
    const medals = game?.unlockType === 'Medals' ? game.unlockCost : null
    const key = normalizeEventName(event)
    const set = sets.get(key) ?? { event, key, relics: [], editions: 0 }
    // Each run of an event opens with its 350-medal relic, so that relic starts a new edition.
    if (medals === FIRST_RELIC_MEDALS || set.editions === 0) set.editions += 1
    set.relics.push({
      index: row.index,
      label: row.label,
      rarity: game?.rarity ?? null,
      stat: game?.stat ?? null,
      benefit: game?.benefit ?? null,
      medals,
      needsEventPass: medals === null ? null : !FREE_TRACK_MEDALS.has(medals),
      shopPrice: findEventShopPrice('relic', game?.rarity ?? null),
      rotatingShopPrice: findEventShopPrice('rotatingRelic', game?.rarity ?? null),
      edition: set.editions,
      releaseDate: game?.releaseDate ?? null,
    })
    sets.set(key, set)
  }
  return [...sets.values()]
}

/**
 * Every event the relic catalog names, in the order its first relic appears, with its relics.
 *
 * Built from the game's own unlock text, so it holds only relics whose text names an event. A set
 * holds the relics of EVERY run of its event (Cherry Blossom has four runs' worth); `edition`
 * tells them apart and `selectEventRelicEdition` picks the run an event record belongs to.
 */
export const EVENT_RELIC_SETS: readonly EventRelicSet[] = buildEventRelicSets()

const EVENT_RELIC_SETS_BY_KEY: ReadonlyMap<string, EventRelicSet> = new Map(
  EVENT_RELIC_SETS.map(set => [set.key, set]),
)

/**
 * The event each event theme belongs to, by the theme's normalized name.
 *
 * An event that returns under a new name keeps its old themes: the Howling Wolf event sells the
 * Howling Wolf tower theme and the Mountain Night background, which the theme catalog files under
 * Full Moon. Its shop also sells Full Moon's relics. The relics EARNED in it are its own.
 */
const EVENT_BY_THEME_KEY: ReadonlyMap<string, string> = new Map(
  [...BACKGROUND, ...TOWER]
    .filter(theme => typeof theme.event === 'string')
    .map(theme => [normalizeEventName(theme.name), theme.event as string]),
)

/**
 * The relics an event awards, by any spelling of its name, or null when no relic names that event.
 *
 * Matches the event's own name only. It used to fall back to a theme of the same name, which
 * answered the Howling Wolf event with Full Moon's Dreamcatcher and Spirit Wolf where the game
 * awards Wolf Paw and Midnight Forest. Use `findThemeSourceEvent` for the event a theme came from.
 */
export function findEventRelicSet(name: string | null | undefined): EventRelicSet | null {
  if (!name) return null
  return EVENT_RELIC_SETS_BY_KEY.get(normalizeEventName(name)) ?? null
}

/**
 * The past event whose themes share this name ("Howling Wolf" gives "Full Moon"), or null. That
 * event's themes and relics are what a shop sells when an event returns under its theme's name.
 */
export function findThemeSourceEvent(name: string | null | undefined): string | null {
  return name ? EVENT_BY_THEME_KEY.get(normalizeEventName(name)) ?? null : null
}

/**
 * The relics of one run of an event: the newest edition released on or before `date`, or the
 * newest of all when no edition is that old or no date is given.
 *
 * A save bears this out: each of its event records unlocked relics of the newest edition only
 * (Rainfall on 2026-11-24 unlocked 326 and 327, never 72 or 73).
 */
export function selectEventRelicEdition(set: EventRelicSet, date?: string | null): EventRelicRow[] {
  const day = typeof date === 'string' ? date.slice(0, 10) : null
  let edition = set.editions
  if (day) {
    const released = set.relics.filter(relic => relic.releaseDate !== null && relic.releaseDate <= day)
    if (released.length > 0) edition = Math.max(...released.map(relic => relic.edition))
  }
  return set.relics.filter(relic => relic.edition === edition)
}
