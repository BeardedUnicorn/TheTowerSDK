/**
 * Prices a range of workshop or enhancement levels the way one account pays for it.
 *
 * The price tables hold list prices. What an account pays depends on its discount labs — a
 * different lab for each workshop tab, and a different family of labs again for enhancements —
 * and the game rounds each workshop level on its own, so list price times one minus the discount
 * is close but not what the Workshop shows. This reads the right lab for the stat and applies it
 * level by level, and returns the stat's value before and after so one call gives cost and effect.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    workshopTabOfStat, priceWorkshopLevelsForAccount, priceEnhancementLevelsForAccount, readLabLevelsBySlugFromSaveRoot, readWorkshopCoinCostBetweenFromSaveRoot, readEnhancementCoinCostBetweenFromSaveRoot
 * depends    src/data/workshop/cost-ranges, src/data/workshop/discount-normalize, src/data/workshop/upgrade-price, src/mechanics/effective-paths/enhancement-costs, src/mechanics/effective-paths/workshop-values, src/save/labs/read (+2 more)
 * used by    src/calculators/run-planning, src/calculators/specs.generated, src/save/planning/candidates, src/save/workshop/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { enhancementLabLevelToSectionDiscountPercent, workshopLabLevelToSectionDiscountPercent } from '../../data/workshop/discount-normalize'
import { workshopCoinCostBetween } from '../../data/workshop/cost-ranges'
import { computeWorkshopUpgradePrice } from '../../data/workshop/upgrade-price'
import { WORKSHOP_ENHANCEMENT_CATEGORIES, enhancementCoinCostBetween } from '../../mechanics/effective-paths/enhancement-costs'
import { workshopStatValue } from '../../mechanics/effective-paths/workshop-values'
import { readLabsFromSaveRoot } from '../labs/read'
import { workshopStatOrder } from './read'
import type { AccountLevelPrice, AccountLevelPriceInput } from './types'

type Tab = 'attack' | 'defense' | 'utility'

/** The workshop tab a stat is on, or `null` for a stat the workshop does not have. */
export function workshopTabOfStat(stat: string): Tab | null {
  const order = workshopStatOrder()
  for (const tab of ['attack', 'defense', 'utility'] as const) if (order[tab].includes(stat)) return tab
  return null
}

function whole(level: number): boolean {
  return Number.isInteger(level) && level >= 0
}

/**
 * A range of regular workshop levels at the account's price: the tab's Workshop Discount lab,
 * 0.5% a level, applied to each level and rounded as the Workshop screen does.
 *
 * Returns `null` for a stat the workshop does not have, levels that are not whole numbers,
 * `toLevel` below `fromLevel`, or a level past the stat's last row. Unlock prices are not
 * discounted and are not priced here.
 */
export function priceWorkshopLevelsForAccount(input: AccountLevelPriceInput): AccountLevelPrice | null {
  const { stat, fromLevel, toLevel } = input
  const tab = workshopTabOfStat(stat)
  if (!tab || !whole(fromLevel) || !whole(toLevel) || toLevel < fromLevel) return null
  const listCoins = workshopCoinCostBetween(stat, fromLevel, toLevel)
  if (listCoins == null) return null
  const discountPct = workshopLabLevelToSectionDiscountPercent(input.labLevels[`workshop_${tab}_discount`] ?? 0)
  const priced = toLevel === fromLevel ? { coins: 0, toLevel } : computeWorkshopUpgradePrice(stat, fromLevel, toLevel - fromLevel, discountPct)
  if (!priced || priced.toLevel !== toLevel) return null
  return {
    stat,
    fromLevel,
    toLevel,
    coins: priced.coins,
    listCoins,
    discountPct,
    valueBefore: workshopStatValue(stat, fromLevel)?.value ?? null,
    valueAfter: workshopStatValue(stat, toLevel)?.value ?? null,
  }
}

/**
 * A range of workshop enhancement levels at the account's price: the tab's Enhancement Coin
 * Discount lab, 0.3% a level, and the Vault's discount where the caller supplies it. `stat` is
 * the enhancement's own name, such as `Coin Bonus` or `Recovery Package`.
 *
 * Enhancement values are multipliers the price table does not hold, so `valueBefore` and
 * `valueAfter` are `null`. Returns `null` for an unknown enhancement or a level past its table.
 * Whether the account has enhancements open at all is not checked here.
 */
export function priceEnhancementLevelsForAccount(input: AccountLevelPriceInput): AccountLevelPrice | null {
  const { stat, fromLevel, toLevel } = input
  const tab = WORKSHOP_ENHANCEMENT_CATEGORIES[stat]
  if (!tab) return null
  const labLevel = input.labLevels[`enhancement_${tab}_coin_discount`] ?? 0
  const vault = Math.max(0, input.vaultDiscountPct ?? 0) / 100
  const listCoins = enhancementCoinCostBetween(stat, fromLevel, toLevel)
  const coins = enhancementCoinCostBetween(stat, fromLevel, toLevel, {
    [`${tab}DiscountLabLevel`]: labLevel,
    globalDiscountPct: vault,
  })
  if (listCoins == null || coins == null) return null
  const section = enhancementLabLevelToSectionDiscountPercent(labLevel)
  return {
    stat,
    fromLevel,
    toLevel,
    coins,
    listCoins,
    discountPct: (1 - (1 - section / 100) * (1 - vault)) * 100,
    valueBefore: null,
    valueAfter: null,
  }
}

/** Lab levels by slug from a save. A lab not researched is absent; an unreadable save gives none. */
export function readLabLevelsBySlugFromSaveRoot(root: Record<string, unknown> | null): Record<string, number> {
  const out: Record<string, number> = {}
  for (const lab of readLabsFromSaveRoot(root)?.researches ?? []) {
    if (lab.slug && lab.level > 0) out[lab.slug] = lab.level
  }
  return out
}

/**
 * Coins to take a workshop upgrade from one level to another on this save's account, with the
 * stat's value before and after. `null` when the range cannot be priced; see
 * `priceWorkshopLevelsForAccount`.
 */
export function readWorkshopCoinCostBetweenFromSaveRoot(
  root: Record<string, unknown> | null,
  stat: string,
  fromLevel: number,
  toLevel: number,
): AccountLevelPrice | null {
  if (!root) return null
  return priceWorkshopLevelsForAccount({ stat, fromLevel, toLevel, labLevels: readLabLevelsBySlugFromSaveRoot(root) })
}

/**
 * Coins to take a workshop enhancement from one level to another on this save's account.
 * `vaultDiscountPct` is the Vault's enhancement discount as a percentage, which the save readers
 * do not supply. `null` when the range cannot be priced.
 */
export function readEnhancementCoinCostBetweenFromSaveRoot(
  root: Record<string, unknown> | null,
  stat: string,
  fromLevel: number,
  toLevel: number,
  vaultDiscountPct = 0,
): AccountLevelPrice | null {
  if (!root) return null
  return priceEnhancementLevelsForAccount({ stat, fromLevel, toLevel, labLevels: readLabLevelsBySlugFromSaveRoot(root), vaultDiscountPct })
}
