/**
 * Which workshop rows a save has unlocked, and which stats are locked against free upgrades.
 *
 * The row lists are flags, one per row, counted here: a v29.2 export has 5 attack, 8 defense and
 * 6 utility rows unlocked. Which stats each row opens, and its coin price, is `WORKSHOP_UNLOCK_ROWS`
 * in `data/workshop/unlocks` — slot N there is flag N here, and a count is the `unlocked`
 * argument of `getNextWorkshopUnlock`, which `nextUnlock` here already applies. The free-upgrade
 * locks run parallel to the per-category level lists, so they are mapped onto stats here.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    readWorkshopUnlocksFromSaveRoot
 * depends    src/data/workshop/unlocks, src/save/access/values, src/save/workshop/read, src/save/workshop/types
 * used by    src/calculators/specs.generated, src/save/history/snapshot, src/save/survival/reading, src/save/workshop/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { getNextWorkshopUnlock } from '../../data/workshop/unlocks'
import { readSaveBoolean, readSaveListItems } from '../access/values'
import { workshopStatOrder } from './read'
import type { WorkshopCategoryCounts, WorkshopUnlocksSaveExtract } from './types'

const CATEGORY_KEYS = {
  upgradeTiersUnlocked: ['upgradeTierUnlocked', 'upgradeDefenseTierUnlocked', 'upgradeUtilityTierUnlocked'],
  upgradeTiersEverUnlocked: ['upgradeAttackTierEverUnlocked', 'upgradeDefenseTierEverUnlocked', 'upgradeUtilityTierEverUnlocked'],
  enhancementTiersUnlocked: ['enhancementTierUnlocked', 'enhancementDefenseTierUnlocked', 'enhancementUtilityTierUnlocked'],
  freeUpgradeLocked: ['upgradesLockedFreeUpgrades', 'upgradesDefenseLockedFreeUpgrades', 'upgradesUtilityLockedFreeUpgrades'],
} as const

function count(root: Record<string, unknown>, keys: readonly [string, string, string]): WorkshopCategoryCounts {
  const [attack, defense, utility] = keys.map(key => readSaveListItems(root[key]).filter(readSaveBoolean).length)
  return { attack, defense, utility }
}

/** Workshop unlocks, or null for a save with none of the unlock lists. */
export function readWorkshopUnlocksFromSaveRoot(root: Record<string, unknown> | null): WorkshopUnlocksSaveExtract | null {
  if (!root || !Object.values(CATEGORY_KEYS).flat().some(key => key in root)) return null
  const warnings: string[] = []
  const order = workshopStatOrder()
  const freeUpgradeLocked: string[] = []
  ;(['attack', 'defense', 'utility'] as const).forEach((category, categoryIndex) => {
    readSaveListItems(root[CATEGORY_KEYS.freeUpgradeLocked[categoryIndex]]).forEach((flag, index) => {
      if (!readSaveBoolean(flag)) return
      const name = order[category][index]
      if (name) freeUpgradeLocked.push(name)
      else warnings.push(`${CATEGORY_KEYS.freeUpgradeLocked[categoryIndex]}[${index}] names no known ${category} stat.`)
    })
  })
  const upgradeTiersUnlocked = count(root, CATEGORY_KEYS.upgradeTiersUnlocked)
  return {
    upgradeTiersUnlocked,
    nextUnlock: {
      attack: getNextWorkshopUnlock('attack', upgradeTiersUnlocked.attack),
      defense: getNextWorkshopUnlock('defense', upgradeTiersUnlocked.defense),
      utility: getNextWorkshopUnlock('utility', upgradeTiersUnlocked.utility),
    },
    upgradeTiersEverUnlocked: count(root, CATEGORY_KEYS.upgradeTiersEverUnlocked),
    enhancementTiersUnlocked: count(root, CATEGORY_KEYS.enhancementTiersUnlocked),
    freeUpgradeLocked,
    warnings,
  }
}
