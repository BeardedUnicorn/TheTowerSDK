import type { WorkshopCategory, WorkshopUnlock } from '../../data/workshop/types'

// from read.ts

export interface WorkshopSaveMeta {
  currentPreset: number
  presetNames: string[]
  totalUpgradesBought: unknown
  totalCoinsSpentWorkshop: unknown
  totalCoinsSpentEnhancements: unknown
  totalCoinsSpentAttackEnhancements: unknown
  totalCoinsSpentDefenseEnhancements: unknown
  totalCoinsSpentUtilityEnhancements: unknown
  totalFreeAttackUpgrades: unknown
  totalFreeDefenseUpgrades: unknown
  totalFreeUtilityUpgrades: unknown
}

export interface WorkshopSavePresetSnapshot {
  levels: Record<string, number>
  enhancementLevels: Record<string, number>
}

export interface WorkshopSaveExtract {
  meta: WorkshopSaveMeta
  active: WorkshopSavePresetSnapshot
  presets: WorkshopSavePresetSnapshot[]
  workshopStatCount: number
  enhancementStatCount: number
  warnings: string[]
}

// from unlocks.ts

/** A count per workshop category. */
export interface WorkshopCategoryCounts {
  attack: number
  defense: number
  utility: number
}

/** What a save says is unlocked in the workshop, beyond upgrade levels. */
export interface WorkshopUnlocksSaveExtract {
  /** Workshop upgrade rows unlocked, per category. */
  upgradeTiersUnlocked: WorkshopCategoryCounts
  /**
   * The "Unlock…" button each tab offers next, with its price in coins; null once a tab has
   * nothing left to unlock. The full price: the workshop discount labs do not reduce it.
   */
  nextUnlock: Record<WorkshopCategory, WorkshopUnlock | null>
  /** Rows ever unlocked, which can exceed the current count. */
  upgradeTiersEverUnlocked: WorkshopCategoryCounts
  /** Enhancement rows unlocked, per category. */
  enhancementTiersUnlocked: WorkshopCategoryCounts
  /** Stats the player has locked against free upgrades, by stat name. */
  freeUpgradeLocked: string[]
  warnings: string[]
}

// from account-prices.ts

/** A range of levels priced for one account: what it costs there, and what it changes. */
export interface AccountLevelPrice {
  stat: string
  fromLevel: number
  toLevel: number
  /** Coins with the account's discounts applied the way the game applies them. */
  coins: number
  /** Coins at list price, with no discount. */
  listCoins: number
  /** The discount applied, as a percentage: 15 for 15%. */
  discountPct: number
  /** The stat's value at `fromLevel` in the game's unit, or `null` when the table has none. */
  valueBefore: number | null
  valueAfter: number | null
}

/** What pricing a workshop or enhancement range for an account reads. */
export interface AccountLevelPriceInput {
  stat: string
  fromLevel: number
  toLevel: number
  /** Lab levels by slug, as the labs reader names them. A lab not researched is absent. */
  labLevels: Readonly<Record<string, number>>
  /**
   * The Vault's discount on every enhancement, as a percentage. Enhancements only; no save
   * reader supplies it yet, so it is 0 unless the caller knows it.
   */
  vaultDiscountPct?: number
}
