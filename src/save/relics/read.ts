import type { RelicSaveRow, RelicSaveState, RelicsSaveExtract } from './types'
export const RELICS_SAVE_PROFILE_KEY = 'profileRelics'
export const RELICS_SAVE_UNLOCKED_KEY = 'relicsUnlocked'

/** The game's relic state: 0 locked, 1 mailed (held, not yet claimed), 2 unlocked. 1 and above is held. */
export const RELIC_STATE_UNLOCKED_VALUE = 1

function isRelicStateUnlocked(value: unknown): boolean {
  if (typeof value === 'boolean') return value
  const state = readSaveEnumValue(value)
  return state != null && state >= RELIC_STATE_UNLOCKED_VALUE
}

const RELIC_STATE_NAMES: readonly RelicSaveState[] = ['locked', 'mailed', 'unlocked']

/** The state each slot stores, or null where the save holds a plain flag instead of a state. */
function readRelicStates(raw: unknown): (RelicSaveState | null)[] {
  return coerceSaveArray(raw).map(item => {
    if (typeof item === 'boolean') return null
    if (item && typeof item === 'object' && 'unlocked' in item) return null
    const state = readSaveEnumValue(item)
    return state != null && Number.isInteger(state) ? RELIC_STATE_NAMES[state] ?? null : null
  })
}

/** The event an unlock text names: "Earn 350 medals during the Rainfall event" gives "Rainfall". */
export function readRelicEventFromUnlockText(unlockDescription: string | null | undefined): string | null {
  return unlockDescription?.match(/ during the (.+) event$/)?.[1] ?? null
}

function readRelicUnlockedFlags(raw: unknown, catalogLength: number): boolean[] {
  const source = coerceSaveArray(raw)
  if (source.length === 0 && !Array.isArray(raw)) return []

  if (source.every(value => typeof value === 'boolean')) {
    return source.map(readSaveBoolean)
  }

  const flags = Array.from({ length: Math.max(catalogLength, source.length) }, () => false)
  for (let index = 0; index < source.length; index += 1) {
    const item = source[index]
    if (typeof item === 'boolean') {
      flags[index] = item
      continue
    }
    if (typeof item === 'number') {
      flags[index] = isRelicStateUnlocked(item)
      continue
    }
    if (item && typeof item === 'object') {
      const record = item as Record<string, unknown>
      if ('unlocked' in record) {
        flags[index] = readSaveBoolean(record.unlocked)
        continue
      }
      if ('typeName' in record && String(record.typeName).includes('RelicState')) {
        flags[index] = isRelicStateUnlocked(item)
        continue
      }
      if ('value__' in record) {
        flags[index] = isRelicStateUnlocked(item)
      }
    }
  }
  return flags
}

function buildUnlockedSet(profileIndices: number[], unlockedFlags: boolean[]): Set<number> {
  const unlocked = new Set<number>()
  for (const index of profileIndices) {
    if (index >= 0) unlocked.add(index)
  }
  unlockedFlags.forEach((flag, index) => {
    if (flag) unlocked.add(index)
  })
  return unlocked
}

export function readRelicsFromSaveRoot(root: Record<string, unknown> | null): RelicsSaveExtract | null {
  if (!root) return null

  const warnings: string[] = []
  const catalogLength = countRelicCatalogSlots()

  if (catalogLength === 0) {
    warnings.push('Relic catalog is not imported from game data yet.')
  }

  // A list of relic indices, not slots, so an unreadable entry is dropped. Reading it as 0 would
  // claim relic 0.
  const profileRelicIndices = toNumberArray(readSaveListItems(root[RELICS_SAVE_PROFILE_KEY]))
    .filter(index => index >= 0)
  const unlockedFlags = readRelicUnlockedFlags(root[RELICS_SAVE_UNLOCKED_KEY], catalogLength)
  const unlockedSet = buildUnlockedSet(profileRelicIndices, unlockedFlags)

  if (profileRelicIndices.length === 0 && unlockedFlags.length === 0) {
    warnings.push('No relic unlock arrays found (profileRelics, relicsUnlocked).')
  }

  if (!IMPORT_CATALOG_META.populated.relics) {
    warnings.push('Relic names are not mapped yet; showing index labels only.')
  }

  // A save written by an older game version has fewer relic slots than the
  // catalog. Those trailing relics are absent from the save, not locked — say so,
  // otherwise the result looks like the player is missing relics they never had
  // the chance to earn. The labs extractor reports the same situation.
  const savedSlotCount = coerceSaveArray(root[RELICS_SAVE_UNLOCKED_KEY]).length
  if (savedSlotCount > 0 && savedSlotCount < catalogLength) {
    warnings.push(
      `relicsUnlocked has ${savedSlotCount} entries; catalog has ${catalogLength}. `
      + `Relics ${savedSlotCount}-${catalogLength - 1} are absent from this save, not locked.`,
    )
  }

  // The other direction: a save from a newer game version than this catalog. Those slots are real
  // relics this package cannot name yet, so say which ones instead of returning bare numbers.
  if (catalogLength > 0 && savedSlotCount > catalogLength) {
    warnings.push(
      `relicsUnlocked has ${savedSlotCount} entries; catalog has ${catalogLength}. `
      + `Relics ${catalogLength}-${savedSlotCount - 1} are newer than this catalog and have no name here.`,
    )
  }

  const states = readRelicStates(root[RELICS_SAVE_UNLOCKED_KEY])
  const slotCount = Math.max(catalogLength, profileRelicIndices.length, unlockedFlags.length)
  const relics: RelicSaveRow[] = Array.from({ length: slotCount }, (_, index) => {
    const catalog = findRelicCatalogRow(index)
    const game = RELIC_GAME_TABLE_BY_INDEX.get(index)
    return {
      index,
      name: catalog?.name ?? null,
      label: findRelicLabel(index) ?? `Relic ${index + 1}`,
      description: catalog?.description ?? null,
      unlocked: unlockedSet.has(index),
      state: states[index] ?? null,
      onProfile: profileRelicIndices.includes(index),
      rarity: game?.rarity ?? null,
      benefit: game?.benefit ?? null,
      stat: game?.stat ?? null,
      unlockType: game?.unlockType ?? null,
      unlockCost: game?.unlockCost ?? null,
      unlockDescription: catalog?.unlockDescription ?? null,
      event: readRelicEventFromUnlockText(catalog?.unlockDescription),
      releaseDate: game?.releaseDate ?? null,
    }
  })

  const mailedCount = relics.filter(relic => relic.state === 'mailed').length
  if (mailedCount > 0) {
    warnings.push(
      `${mailedCount} relic(s) are mailed and not yet claimed. They count as held here, `
      + 'and the game adds no bonus for them until they are claimed.',
    )
  }

  return {
    relics,
    profileRelicIndices,
    unlockedCount: relics.filter(relic => relic.unlocked).length,
    mailedCount,
    warnings,
  }
}

export function listUnlockedRelics(extract: RelicsSaveExtract): RelicSaveRow[] {
  return extract.relics.filter(relic => relic.unlocked)
}

const RELIC_TEMPLATE_ID_LOOKUP = buildRelicTemplateIdLookup(RELIC_TEMPLATES)

export function findRelicTemplateIdForSaveIndex(saveIndex: number): string | null {
  return findRelicTemplateIdFromSaveIndex(saveIndex, RELIC_TEMPLATES, RELIC_TEMPLATE_ID_LOOKUP)
}
