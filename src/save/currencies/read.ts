/**
 * The currencies a player holds, and what they earned and spent this cycle.
 *
 * Balances are top-level fields. The shard and reroll balances moved to `_v2` keys when they
 * outgrew 32 bits (patch note 1571908572156272841, v29.2: reroll shards no longer show negative
 * above 2.1B), so those are read from `_v2` first and the old name second.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    CURRENCY_SAVE_KEY_BY_BALANCE, readCurrenciesFromSaveRoot
 * depends    src/save/access/values, src/save/currencies/types
 * used by    src/save/currencies/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { coerceSaveNumber } from '../access/values'
import type { CurrenciesSaveExtract, CurrencyBalancesSaveRow } from './types'

/** Save key for each balance. A pair is `[current, older]`. */
export const CURRENCY_SAVE_KEY_BY_BALANCE: Readonly<Record<keyof CurrencyBalancesSaveRow, string | readonly [string, string]>> = {
  coins: 'coins',
  gems: 'gems',
  stones: 'stones',
  medals: 'medals',
  cells: 'cells',
  keys: 'keys',
  tokens: 'tokens',
  bits: 'bits',
  rerollShards: ['moduleRerollCurrency_v2', 'moduleRerollCurrency'],
  cannonShards: ['moduleCannonShards_v2', 'moduleCannonShards'],
  armorShards: ['moduleArmorShards_v2', 'moduleArmorShards'],
  generatorShards: ['moduleGeneratorShards_v2', 'moduleGeneratorShards'],
  coreShards: ['moduleCoreShards_v2', 'moduleCoreShards'],
  moduleTickets: 'moduleTickets',
}

function readBalance(root: Record<string, unknown>, key: string | readonly [string, string]): number | null {
  if (typeof key === 'string') return coerceSaveNumber(root[key])
  return coerceSaveNumber(root[key[0]]) ?? coerceSaveNumber(root[key[1]])
}

function readCycleCurrencies(raw: unknown, label: string, warnings: string[]): Record<string, number> {
  const container = raw && typeof raw === 'object' ? (raw as Record<string, unknown>).currencies : undefined
  if (!container || typeof container !== 'object') return {}
  const result: Record<string, number> = {}
  for (const [name, value] of Object.entries(container as Record<string, unknown>)) {
    const amount = coerceSaveNumber(value)
    if (amount === null) warnings.push(`${label}.${name} is unreadable.`)
    else result[name] = amount
  }
  return result
}

/** Balances and this cycle's flows, or null for a save that records no balance at all. */
export function readCurrenciesFromSaveRoot(root: Record<string, unknown> | null): CurrenciesSaveExtract | null {
  if (!root) return null
  const warnings: string[] = []
  const balances = Object.fromEntries(
    Object.entries(CURRENCY_SAVE_KEY_BY_BALANCE).map(([field, key]) => [field, readBalance(root, key)]),
  ) as unknown as CurrencyBalancesSaveRow
  if (Object.values(balances).every(value => value === null)) return null

  return {
    balances,
    earnedThisCycle: readCycleCurrencies(root.currencyEarnedThisCycle, 'currencyEarnedThisCycle', warnings),
    spentThisCycle: readCycleCurrencies(root.currencySpentThisCycle, 'currencySpentThisCycle', warnings),
    warnings,
  }
}
