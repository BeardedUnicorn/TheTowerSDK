/**
 * Names the levels of the run in progress and says how the run is being played.
 *
 * The save stores a run's levels as three positional arrays, in the workshop's own order, and
 * says nothing about which levels were bought. Setting each against its workshop level, and the
 * tab's total against the free upgrades that landed, separates a run left alone from one where
 * cash was spent — which is what a forecast or a survival fit needs to know about a run.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    resolveInRunLevels, readLifetimeFreeUpgradesFromSaveRoot, readInRunLevelsFromSaveRoot
 * depends    src/save/access/values, src/save/current-run/read, src/save/current-run/types, src/save/workshop/read
 * used by    src/calculators/run-planning, src/calculators/specs.generated, src/save/current-run/index, src/save/history/timeline
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { coerceSaveNumber } from '../access/values'
import { readWorkshopFromSaveRoot, workshopStatOrder } from '../workshop/read'
import { readCurrentRunFromSaveRoot } from './read'
import type {
  CurrentRunCategory,
  CurrentRunMode,
  InRunCategoryTotals,
  InRunLevelRow,
  InRunLevels,
  InRunLevelsInput,
  LifetimeFreeUpgradeCounts,
} from './types'

const CATEGORIES: readonly CurrentRunCategory[] = ['attack', 'defense', 'utility']

/*
 * Free upgrades landed in one tab this run, and how far the count can be trusted. The save's own
 * per-run counter is exact. Without it, the lifetime counter's growth since an earlier export
 * stands in: exact when that export was taken at the run's start, an upper bound otherwise.
 */
function freeCountFor(
  input: InRunLevelsInput,
  category: CurrentRunCategory,
): { fromFree: number | null, freeCount: InRunCategoryTotals['freeCount'] } {
  const own = input.currentRun.freeUpgrades?.[category]
  if (own != null) return { fromFree: own, freeCount: 'exact' }
  if (input.lifetimeFree && input.earlier) {
    const grown = input.lifetimeFree[category] - input.earlier.lifetimeFree[category]
    if (Number.isFinite(grown) && grown >= 0) {
      return { fromFree: grown, freeCount: input.earlier.atRunStart ? 'exact' : 'upper-bound' }
    }
  }
  return { fromFree: null, freeCount: 'missing' }
}

/**
 * The run in progress as one row per stat, with each tab's gained levels split into free and
 * bought, and the run's mode.
 *
 * Within a tab, levels bought = levels above the workshop − free upgrades landed. The mode is
 * `active` when any tab bought a level, `afk` when every tab's count is exact and none did, and
 * `unknown` otherwise: no run in progress, no free-upgrade count, or only an upper bound that
 * the gained levels do not exceed.
 */
export function resolveInRunLevels(input: InRunLevelsInput): InRunLevels {
  const warnings: string[] = []
  const order = workshopStatOrder()
  const arrays: Record<CurrentRunCategory, (number | null)[] | null> = {
    attack: input.currentRun.upgradeLevel,
    defense: input.currentRun.upgradeDefenseLevel,
    utility: input.currentRun.upgradeUtilityLevel,
  }

  const rows: InRunLevelRow[] = []
  const categories: InRunCategoryTotals[] = []
  for (const category of CATEGORIES) {
    const levels = arrays[category]
    if (!levels) {
      warnings.push(`${category} levels of the run are not in the save`)
      categories.push({ category, gained: 0, fromFree: null, bought: null, freeCount: 'missing' })
      continue
    }
    let gained = 0
    const own: InRunLevelRow[] = []
    order[category].forEach((stat, index) => {
      if (!stat) return
      const inRun = levels[index]
      if (inRun == null) return
      const workshop = input.workshopLevels[stat] ?? 0
      const above = Math.max(0, inRun - workshop)
      gained += above
      own.push({ category, stat, workshop, inRun, gained: above, fromFree: null, bought: null })
    })

    const { fromFree, freeCount } = freeCountFor(input, category)
    /* Free upgrades can outnumber the gained levels: one that lands on a maxed stat adds none. */
    const bought = fromFree == null ? null : Math.max(0, gained - fromFree)
    if (freeCount === 'exact' && bought === 0) for (const row of own) { row.fromFree = row.gained; row.bought = 0 }
    if (fromFree === 0) for (const row of own) { row.fromFree = 0; row.bought = row.gained }
    rows.push(...own)
    categories.push({ category, gained, fromFree, bought, freeCount })
  }

  let mode: CurrentRunMode = 'unknown'
  const started = (input.currentRun.currentWave ?? 0) > 0 && input.currentRun.roundActive !== false
  if (!started) {
    warnings.push('no run in progress: the levels are those of the last run or of none')
  }
  else if (categories.some(tab => tab.freeCount !== 'missing' && (tab.bought ?? 0) > 0)) {
    mode = 'active'
  }
  else if (categories.every(tab => tab.freeCount === 'exact')) {
    mode = 'afk'
  }
  else {
    warnings.push('free upgrades this run are not known exactly, so levels bought with cash cannot be ruled out')
  }
  return { rows, categories, mode, warnings }
}

/** Lifetime free-upgrade counters from a save, or `null` when any of the three is missing. */
export function readLifetimeFreeUpgradesFromSaveRoot(root: Record<string, unknown> | null): LifetimeFreeUpgradeCounts | null {
  if (!root) return null
  const attack = coerceSaveNumber(root.totalFreeAttackUpgrades)
  const defense = coerceSaveNumber(root.totalFreeDefenseUpgrades)
  const utility = coerceSaveNumber(root.totalFreeUtilityUpgrades)
  return attack == null || defense == null || utility == null ? null : { attack, defense, utility }
}

/**
 * The run in progress in a save, named and split. `earlier` passes an earlier export's lifetime
 * counters for saves that carry no per-run free-upgrade count.
 *
 * Returns `null` when the save has no current-run fields or no workshop to compare with.
 */
export function readInRunLevelsFromSaveRoot(
  root: Record<string, unknown> | null,
  earlier: InRunLevelsInput['earlier'] = null,
): InRunLevels | null {
  const currentRun = readCurrentRunFromSaveRoot(root)
  const workshop = readWorkshopFromSaveRoot(root)
  if (!currentRun || !workshop) return null
  return resolveInRunLevels({
    currentRun,
    workshopLevels: workshop.active.levels,
    lifetimeFree: readLifetimeFreeUpgradesFromSaveRoot(root),
    earlier,
  })
}
