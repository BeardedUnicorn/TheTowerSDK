/** Current-run fields listed as int/int[] in data/player-stats field catalog.
 * They are distinct from purchased upgradeWorkshop* arrays. No stat-index or
 * active-session inference is made here: the three level arrays stay positional, and the run's
 * own counters (time played, coins and cells so far, free upgrades landed) are read as stored.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    readCurrentRunFromSaveRoot
 * depends    src/save/access/values, src/save/current-run/types
 * used by    src/calculators/specs.generated, src/save/current-run/in-run-levels, src/save/current-run/index, src/save/current-run/progress, src/save/history/snapshot
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { coerceSaveNumber, readSaveBoolean } from '../access/values'
import type { CurrentRunSaveExtract } from './types'

export function readCurrentRunFromSaveRoot(root: Record<string, unknown> | null): CurrentRunSaveExtract | null {
  if (!root) return null
  const unreadableKeys: string[] = []
  const integer = (value: unknown, key: string): number | null => {
    if (typeof value === 'number' && Number.isSafeInteger(value) && value >= 0) return value
    unreadableKeys.push(key)
    return null
  }
  const levels = (key: string): (number | null)[] | null => {
    const value = root[key]
    if (!Array.isArray(value)) { unreadableKeys.push(key); return null }
    return value.map((entry, index) => integer(entry, `${key}[${index}]`))
  }
  /* The run's own counters are absent from older exports, so a missing one is `null`, not unreadable. */
  const amount = (value: unknown): number | null => {
    const parsed = coerceSaveNumber(value)
    return parsed != null && parsed >= 0 ? parsed : null
  }
  return {
    currentWave: integer(root.currentWave, 'currentWave'),
    currentTier: integer(root.currentTier, 'currentTier'),
    upgradeLevel: levels('upgradeLevel'),
    upgradeDefenseLevel: levels('upgradeDefenseLevel'),
    upgradeUtilityLevel: levels('upgradeUtilityLevel'),
    roundActive: root.roundActiveBool == null ? null : readSaveBoolean(root.roundActiveBool),
    realSeconds: amount(root.realTimeThisRound),
    gameSeconds: amount(root.gameplayTimeThisRound),
    coinsSoFar: amount(root.coinsEarnedThisRound),
    cellsSoFar: amount(root.cellsEarnedThisRound),
    freeUpgrades: {
      attack: amount(root.freeAttackUpgradesThisRound),
      defense: amount(root.freeDefenseUpgradesThisRound),
      utility: amount(root.freeUtilityUpgradesThisRound),
    },
    unreadableKeys,
  }
}
