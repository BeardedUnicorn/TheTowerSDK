/**
 * Says how long the run in progress has been going and what it has earned.
 *
 * The save has no start timestamp. It does count the real seconds played this run, so the start
 * is the export time less that — the latest it can be, since time paused in the background is
 * not counted. An export too old to carry the counter falls back to lifetime play time across
 * two exports, which is why this takes an earlier reading.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    resolveCurrentRunProgress, readCurrentRunProgressFromSaveRoot
 * depends    src/save/access/values, src/save/current-run/read, src/save/current-run/types, src/save/export-info/read
 * used by    src/calculators/run-planning, src/calculators/specs.generated, src/save/current-run/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { coerceSaveNumber } from '../access/values'
import { readExportInfoFromSaveRoot } from '../export-info/read'
import { readCurrentRunFromSaveRoot } from './read'
import type { CurrentRunProgress, CurrentRunProgressInput } from './types'

function startBefore(exportedAt: string | null, seconds: number | null): string | null {
  if (!exportedAt || seconds == null) return null
  const at = Date.parse(exportedAt)
  return Number.isFinite(at) ? new Date(at - seconds * 1000).toISOString() : null
}

/**
 * Where the run in progress stands.
 *
 * `source` is `save` when the run's own counters gave the time. It is `history` when they are
 * missing and `beforeRun` supplied the play time at the last export before the run began: the
 * elapsed time is then the growth in lifetime play time, which also holds whatever of the
 * previous run was played after that export, so it is an upper bound and coins and cells so far
 * stay `null`.
 */
export function resolveCurrentRunProgress(input: CurrentRunProgressInput): CurrentRunProgress {
  const { currentRun } = input
  const warnings: string[] = []
  const base = { tier: currentRun.currentTier, wave: currentRun.currentWave }
  if (currentRun.realSeconds != null) {
    return {
      ...base,
      startedAt: startBefore(input.exportedAt, currentRun.realSeconds),
      realSeconds: currentRun.realSeconds,
      gameSeconds: currentRun.gameSeconds,
      coinsSoFar: currentRun.coinsSoFar,
      cellsSoFar: currentRun.cellsSoFar,
      source: 'save',
      warnings: input.exportedAt ? warnings : ['the save has no export time, so the start cannot be dated'],
    }
  }
  if (input.beforeRun && input.playTimeSeconds != null) {
    const realSeconds = Math.max(0, input.playTimeSeconds - input.beforeRun.playTimeSeconds)
    warnings.push('elapsed time is lifetime play time since the last export before this run; it may include the end of the previous run')
    return {
      ...base,
      startedAt: startBefore(input.exportedAt, realSeconds),
      realSeconds,
      gameSeconds: null,
      coinsSoFar: null,
      cellsSoFar: null,
      source: 'history',
      warnings,
    }
  }
  warnings.push('the save does not count this run\'s time, and no earlier export was given to derive it')
  return { ...base, startedAt: null, realSeconds: null, gameSeconds: null, coinsSoFar: null, cellsSoFar: null, source: null, warnings }
}

/**
 * The run in progress in a save. `beforeRun` passes the last export taken before the run began,
 * for saves that do not count the run's own time.
 *
 * Returns `null` when the save has no current-run fields.
 */
export function readCurrentRunProgressFromSaveRoot(
  root: Record<string, unknown> | null,
  beforeRun: CurrentRunProgressInput['beforeRun'] = null,
): CurrentRunProgress | null {
  const currentRun = readCurrentRunFromSaveRoot(root)
  if (!currentRun || !root) return null
  return resolveCurrentRunProgress({
    currentRun,
    exportedAt: readExportInfoFromSaveRoot(root)?.exportedAt ?? null,
    playTimeSeconds: coerceSaveNumber(root.playTime),
    beforeRun,
  })
}
