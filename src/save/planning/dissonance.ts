/**
 * Prices a Dissonant run for a save's account: the gain at several waves against the farm run
 * it replaces.
 *
 * Everything the payback model needs is already known about the account — its coin bonus
 * inputs, its coins per day, what a farm run earns, what its past Dissonant runs earned — and
 * this collects it, measuring the pass-through from the runs unless the caller supplies one.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    priceDissonancePaybackFromSave
 * depends    src/mechanics/coin-bonus/types, src/mechanics/planning/dissonance-payback, src/mechanics/planning/income, src/save/planning/coin-check, src/save/planning/forecast, src/save/planning/sources (+1 more)
 * used by    src/calculators/run-planning, src/save/planning/index, src/save/planning/plan, src/save/planning/rank
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import type { TotalCoinBonusInput } from '../../mechanics/coin-bonus/types'
import { priceDissonancePayback } from '../../mechanics/planning/dissonance-payback'
import { quantileBand } from '../../mechanics/planning/income'
import { checkCoinModelFromSave } from './coin-check'
import { forecastIncomeFromSave } from './forecast'
import { readPlanningAccount } from './sources'
import type { DissonancePaybackOptions, SaveDissonancePayback } from './types'

const DEFAULT_WAVE_STEP = 200
const DEFAULT_WAVE_COUNT = 5

/**
 * What a Dissonant run on `tier` is worth at each wave, for a save's account.
 *
 * The cost is the median farm run's coins and cells, less the median of what the account's own
 * past Dissonant runs earned. Returns `null` when the save cannot be read, has no Total Coin
 * Bonus reading, or has no farm run to price the cost and income from.
 */
export function priceDissonancePaybackFromSave(options: DissonancePaybackOptions): SaveDissonancePayback | null {
  const account = readPlanningAccount(options)
  const forecast = options.forecast ?? forecastIncomeFromSave(options)
  const reading = account?.current.readers.readTotalCoinBonusFromSaveRoot as { input?: TotalCoinBonusInput } | undefined
  if (!account || !forecast || !forecast.coinsPerDay || !forecast.coinsPerRun || !reading?.input) return null
  const tier = options.tier ?? forecast.tier ?? reading.input.tier
  const passThrough = options.passThrough ?? checkCoinModelFromSave(options)?.passThrough ?? 1

  const used = forecast.runs.filter(run => run.used)
  const dissonant = forecast.runs.filter(run => run.kind === 'dissonant' && run.tier === tier)
  const best = reading.input.dissonance.coinBoostWaves[tier] ?? 0
  const first = Math.ceil((best + 1) / 100) * 100
  const waves = options.waves ?? Array.from({ length: DEFAULT_WAVE_COUNT }, (_, index) => first + index * DEFAULT_WAVE_STEP)

  const farmRunCoins = forecast.coinsPerRun.median
  const farmRunCells = quantileBand(used.map(run => run.cells))?.median ?? 0
  const payback = priceDissonancePayback({
    coinBonus: reading.input,
    tier,
    waves,
    coinsPerDay: forecast.coinsPerDay.median,
    passThrough,
    farmRunCoins,
    farmRunCells,
    dissonantRunCoins: quantileBand(dissonant.map(run => run.coins))?.median ?? 0,
    dissonantRunCells: quantileBand(dissonant.map(run => run.cells))?.median ?? 0,
    paybackLimitDays: options.paybackLimitDays,
  })
  const warnings = [...payback.warnings]
  if (forecast.tier != null && forecast.tier !== tier) {
    warnings.push(`the account farms tier ${forecast.tier}; a Dissonant boost on tier ${tier} reaches those runs only through the echo, which is not priced here`)
  }
  if (options.waves == null) warnings.push('the waves are a table, not a prediction: the wave a Dissonant run reaches with a tab disabled is the player\'s estimate to make')
  return { ...payback, warnings, coinsPerDay: forecast.coinsPerDay.median, passThrough, farmRunCoins, farmRunCells }
}
