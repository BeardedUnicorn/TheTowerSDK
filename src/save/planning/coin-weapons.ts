/**
 * Reads the ultimate weapons that pay coins out of one export, as the coin simulation takes them.
 *
 * Half of a farming run's coins come from kills inside a Golden Tower, Spotlight or Death Wave
 * window, and the simulation counts none of them without the weapons' levels and how often each
 * window is open. The export stores those levels by slot and position; the weapon catalog names
 * them. This puts the two together, for the weapons the account owns and no others.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    readCoinWeaponInputsFromSnapshot, readCoinModuleBonusesFromSnapshot
 * depends    src/data/bots/data, src/data/enemies/data, src/data/modules/effect-resolver, src/mechanics/resource-drops/types, src/mechanics/uptime/types, src/save/history/access (+4 more)
 * used by    src/calculators/specs.generated, src/save/planning/coin-inputs, src/save/planning/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { BOT_UPGRADES_DATA } from '../../data/bots/data'
import { bossWaveIntervalForTier } from '../../data/enemies/data'
import { findModuleEffect } from '../../data/modules/effect-resolver'
import type { ResourceDropsCoinUwLevels } from '../../mechanics/resource-drops/types'
import type { UptimeCoreState } from '../../mechanics/uptime/types'
import { snapshotLabLevels } from '../history/access'
import type { ExportSnapshot } from '../history/types'
import { buildUltimateWeaponSaveRows } from '../ultimate-weapons/read'
import type { UltimateWeaponsSaveExtract } from '../ultimate-weapons/types'
import type { CoinModuleBonuses, CoinWeaponInputs } from './types'

const fold = (value: string): string => value.toLowerCase().replace(/[^a-z0-9]+/g, '')

function isObject(value: unknown): value is Record<string, unknown> {
  return value != null && typeof value === 'object' && !Array.isArray(value)
}

/**
 * The coin simulation's ultimate weapon levels and uptime state from an export, or `null` when
 * the export has no ultimate weapon reading.
 *
 * A weapon the account does not own gets no levels, so its window is never open. Module
 * sub-effects, the Multiverse Nexus, the Galaxy Compressor, perks and the Golden Bot are not
 * read: every one of them is left off, which can only shorten the windows.
 */
export function readCoinWeaponInputsFromSnapshot(snapshot: ExportSnapshot, tier: number): CoinWeaponInputs | null {
  const extract = snapshot.readers.readUltimateWeaponsFromSaveRoot
  if (!isObject(extract) || !Array.isArray(extract.slots)) return null
  const owned = new Map<string, Map<string, number>>()
  for (const row of buildUltimateWeaponSaveRows(extract as unknown as UltimateWeaponsSaveExtract)) {
    if (!row.unlocked) continue
    const stats = new Map<string, number>()
    for (const stat of row.stats) if (typeof stat.level === 'number') stats.set(fold(stat.name), stat.level)
    owned.set(fold(row.name), stats)
  }
  const level = (weapon: string, stat: string): number | null => owned.get(fold(weapon))?.get(fold(stat)) ?? null
  const labs = snapshotLabLevels(snapshot)
  const lab = (slug: string) => labs[slug]?.level ?? 0
  const cards = snapshot.readers.readCardsFromSaveRoot
  const equipped = isObject(cards) && Array.isArray(cards.equippedCards) ? cards.equippedCards : []
  const waveAccelerator = equipped.find(card => isObject(card) && card.slug === 'wa')

  const uwLevels: ResourceDropsCoinUwLevels = {
    gtMultiplierLevel: level('Golden Tower', 'Multiplier') ?? 0,
    gtCdLevel: level('Golden Tower', 'Cooldown') ?? 0,
    gtDurLevel: level('Golden Tower', 'Duration') ?? 0,
    gtCdLab: 0,
    gtDurLab: lab('golden_tower_duration'),
    bhCdLevel: level('Black Hole', 'Cooldown') ?? 0,
    bhDurLevel: level('Black Hole', 'Duration') ?? 0,
    bhCdLab: 0,
    bhDurLab: 0,
    dwCdLevel: level('Death Wave', 'Cooldown') ?? 0,
    dwQtyLevel: level('Death Wave', 'Quantity') ?? 0,
    slCdLevel: 0,
    slQtyLevel: level('Spotlight', 'Quantity') ?? 0,
    slAngleLevel: level('Spotlight', 'Angle') ?? 0,
  }
  const uptime: UptimeCoreState = {
    mvnRarity: 'Disabled', mvnGt: false, mvnDw: false, mvnBh: false,
    gtCdLevel: level('Golden Tower', 'Cooldown'), gtDurLevel: level('Golden Tower', 'Duration'), gtDurLab: lab('golden_tower_duration'),
    gtCdStat: 'None', gtCdAssist: 'None', gtDurStat: 'None', gtDurAssist: 'None',
    bhCdLevel: level('Black Hole', 'Cooldown'), bhDurLevel: level('Black Hole', 'Duration'),
    bhCdStat: 'None', bhCdAssist: 'None', bhDurStat: 'None', bhDurAssist: 'None',
    dwCdLevel: level('Death Wave', 'Cooldown'), dwBaseWavesLevel: level('Death Wave', 'Quantity') ?? 0,
    dwCdStat: 'None', dwCdAssist: 'None', dwQtyStat: 'None', dwQtyAssist: 'None',
    slAngleLevel: level('Spotlight', 'Angle'), slQtyLevel: level('Spotlight', 'Quantity'), slAngleStat: 'None', slAngleAssist: 'None',
    psCdLevel: null, psDurLevel: null, psCdStat: 'None', psCdAssist: 'None', psDurStat: 'None', psDurAssist: 'None',
    cfCdLevel: null, cfDurLevel: null, cfDurLab: 0, cfCdStat: 'None', cfCdAssist: 'None', cfDurStat: 'None', cfDurAssist: 'None',
    smCdLevel: null, smQtyLevel: null, smCdStat: 'None', smCdAssist: 'None', smQtyStat: 'None', smQtyAssist: 'None',
    ilmCdLevel: null, ilmCdStat: 'None', ilmCdAssist: 'None',
    gbCdLevel: null, gbDurLevel: null, gbCdLab: 0, gbDurLab: 0,
    abCdLevel: null, abDurLevel: null, abCdLab: 0, abDurLab: 0,
    bbCdLevel: null, bbDurLevel: null, bbCdLab: 0, bbDurLab: 0,
    fbCdLevel: null, fbDurLevel: null, fbCdLab: 0, tbCdLevel: null, tbDurLevel: null, tbCdLab: 0,
    wavesPerBoss: bossWaveIntervalForTier(tier), compressor: 'Disabled',
    waLevel: isObject(waveAccelerator) ? Number(waveAccelerator.level) || 0 : 0, pkgChance: 0,
    assistEffPct: 0, tournament: false, bhPerk: false, cfDurPerk: false, dwPerk: false, smQtyPerk: false,
    uwBc: false, bcLabLevel: 0, summonCooldownLevel: null, summonDurationLevel: null,
    attackCooldownLevel: null, allyCooldownLevel: null, bountyCooldownLevel: null, fetchCooldownLevel: null,
    scoutCooldownLevel: null, scoutDurationLevel: null,
  }
  return { uwLevels, uptime, owned: [...owned.keys()] }
}

/**
 * What the equipped modules and the Golden Bot add to coins from kills.
 *
 * A module stores its sub-effects as indexes into the game's effect table; the resolver names
 * them. Two matter here: Coins / Kill Bonus on the Generator, which is added inside Coins / Kill,
 * and Golden Tower - Bonus on the Core, which is added to the Golden Tower multiplier. Only
 * primary modules are read: an assist module's sub-effects apply at an efficiency this does not
 * resolve.
 */
export function readCoinModuleBonusesFromSnapshot(snapshot: ExportSnapshot): CoinModuleBonuses {
  const out: CoinModuleBonuses = { coinsKillBonus: 0, goldenTowerBonus: 0, goldenBotBonusLevel: null }
  const modules = snapshot.readers.readModulesFromSaveRoot
  for (const module of isObject(modules) && Array.isArray(modules.equipped) ? modules.equipped : []) {
    if (!isObject(module) || module.role !== 'primary' || !Array.isArray(module.effects)) continue
    for (const index of module.effects) {
      const effect = typeof index === 'number' && index > 0 ? findModuleEffect(index) : null
      if (!effect || !Number.isFinite(effect.benefitValue)) continue
      if (effect.label === 'Coins / Kill Bonus') out.coinsKillBonus += effect.benefitValue
      if (effect.label === 'Golden Tower - Bonus') out.goldenTowerBonus += effect.benefitValue
    }
  }
  const bots = snapshot.readers.readBotsFromSaveRoot
  const order = BOT_UPGRADES_DATA.find(bot => bot.name === 'Golden Bot')?.statOrder ?? []
  for (const bot of isObject(bots) && Array.isArray(bots.bots) ? bots.bots : []) {
    if (!isObject(bot) || bot.name !== 'Golden Bot' || bot.unlocked !== true || !Array.isArray(bot.statLevels)) continue
    const level = bot.statLevels[order.indexOf('Bonus')]
    if (typeof level === 'number') out.goldenBotBonusLevel = level
  }
  return out
}
