/**
 * Builds the coin model's input for a run from one export of the account.
 *
 * The coin simulation takes some seventy inputs and nothing assembled them from a save. A stored
 * export supplies the ones that decide how much a run earns — purchases, the Coins card, themes,
 * relics, the Generator, Dissonance, the coin labs, workshop levels and the ultimate weapons —
 * and the account's run records supply the enemy mix. What is still left out is named, so a
 * prediction is read knowing what it lacks.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    COIN_SIMULATION_INPUTS_NOT_READ, measureOrdinaryCoinWeights, ordinaryCoinWeightAtWave, measureOrdinaryKills, ordinaryKillScaleAtWave, measureCoinShares, buildCoinSimulationInputFromSnapshot
 * depends    src/data/enemies/data, src/mechanics/planning/income, src/save/history/access, src/save/history/types, src/save/planning/coin-weapons, src/save/planning/types
 * used by    src/calculators/specs.generated, src/save/planning/candidates, src/save/planning/coin-check, src/save/planning/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { bossWaveIntervalForTier } from '../../data/enemies/data'
import { snapshotLabLevels, snapshotWorkshopLevels } from '../history/access'
import type { ExportSnapshot } from '../history/types'
import { quantileBand } from '../../mechanics/planning/income'
import { readCoinModuleBonusesFromSnapshot, readCoinWeaponInputsFromSnapshot } from './coin-weapons'
import type { CoinSimulationInputs, MeasuredCoinInputs, MeasuredCoinShares } from './types'

type Json = Record<string, unknown>

function isObject(value: unknown): value is Json {
  return value != null && typeof value === 'object' && !Array.isArray(value)
}

/** Inputs the stored readings do not supply. Each is left at the value that changes nothing. */
export const COIN_SIMULATION_INPUTS_NOT_READ: readonly string[] = [
  'perks (coin perks, the coin trade-off, and the perks that raise a weapon\'s coin bonus or lengthen its window)',
  'assist modules\' sub-effects, and module sub-effects on weapon cooldowns and durations',
  'the Multiverse Nexus and the Galaxy Compressor',
  'vaultCoinskillLevel',
  'card masteries (Coins, Enemy Balance, Wave Skip, Wave Accelerator)',
  'Fetch (Guardian) levels',
]

const ORDINARY_COINS = { totalFast: 2, totalTank: 4, totalRanged: 2, totalProtector: 3, totalBasic: 0 } as const

/**
 * Base coins an ordinary kill paid on average in each of an account's runs, by the wave the run
 * reached: (2 x Fast + 4 x Tank + 2 x Ranged + 3 x Protector) / ordinary kills, from the run
 * records' own kill counts. Runs on another tier, tournaments and runs with too few kills to
 * mean anything are left out. Sorted by wave.
 */
export function measureOrdinaryCoinWeights(runs: readonly Json[], tier: number): { wave: number, weight: number }[] {
  const out: { wave: number, weight: number }[] = []
  for (const run of runs) {
    if (Number(run.tier) !== tier || run.isTournament === true) continue
    let kills = 0
    let coins = 0
    for (const [field, value] of Object.entries(ORDINARY_COINS)) {
      const count = Number(run[field])
      if (!Number.isFinite(count)) { kills = 0; break }
      kills += count
      coins += count * value
    }
    if (kills >= 1000 && Number(run.wave) > 0) out.push({ wave: Number(run.wave), weight: coins / kills })
  }
  return out.sort((a, b) => a.wave - b.wave)
}

/*
 * A measured figure for a run that reaches `wave`: interpolated between the two measured runs
 * either side of it, and held at the nearest one beyond either end.
 */
function atWave(measured: readonly { wave: number, value: number }[], wave: number): number | null {
  if (measured.length === 0) return null
  if (wave <= measured[0].wave) return measured[0].value
  for (let index = 1; index < measured.length; index += 1) {
    const [low, high] = [measured[index - 1], measured[index]]
    if (wave > high.wave) continue
    return high.wave === low.wave ? high.value : low.value + (high.value - low.value) * ((wave - low.wave) / (high.wave - low.wave))
  }
  return measured[measured.length - 1].value
}

/**
 * The measured coin weight for a run that reaches `wave`: interpolated between the two measured
 * runs either side of it, and held at the nearest one beyond either end. The share of Fast, Tank
 * and Ranged enemies grows through a run, so a run's average depends on how far it went; no
 * source gives the game's rule for that, and this reads it off the account instead. `null` with
 * nothing measured.
 */
export function ordinaryCoinWeightAtWave(measured: readonly { wave: number, weight: number }[], wave: number): number | null {
  return atWave(measured.map(row => ({ wave: row.wave, value: row.weight })), wave)
}

/**
 * How many ordinary enemies each of an account's runs recorded, by the wave it reached: Basic,
 * Fast, Tank, Ranged and Protector together. Tournaments, other tiers and runs with too few
 * kills to mean anything are left out. Sorted by wave.
 */
export function measureOrdinaryKills(runs: readonly Json[], tier: number): { wave: number, kills: number }[] {
  const out: { wave: number, kills: number }[] = []
  for (const run of runs) {
    if (Number(run.tier) !== tier || run.isTournament === true) continue
    let kills = 0
    for (const field of Object.keys(ORDINARY_COINS)) {
      const count = Number(run[field])
      if (!Number.isFinite(count)) { kills = 0; break }
      kills += count
    }
    if (kills >= 1000 && Number(run.wave) > 0) out.push({ wave: Number(run.wave), kills })
  }
  return out.sort((a, b) => a.wave - b.wave)
}

/**
 * The measured kill scale for a run that reaches `wave`: recorded over modelled kills,
 * interpolated between the measured runs either side of it. The model's enemies per wave follow
 * the spawn chance chart and the records do not, so the ratio changes with depth. `null` with
 * nothing measured.
 */
export function ordinaryKillScaleAtWave(measured: readonly { wave: number, scale: number }[], wave: number): number | null {
  return atWave(measured.map(row => ({ wave: row.wave, value: row.scale })), wave)
}

const WINDOW_COUNTS = {
  goldenTower: 'destroyedInGoldenTower',
  spotlight: 'destroyedInSpotlight',
  deathWave: 'taggedByDeathwave',
  goldenBot: 'destroyedInGoldenBot',
} as const

function medianOf(values: readonly number[]): number {
  return quantileBand(values)?.median ?? 0
}

/**
 * The share of enemies destroyed inside each coin window, and Critical Coin's share of kill
 * coins, each a median across a tier's farming runs. They are steady from run to run on one
 * account — Golden Tower within half a point — so one figure stands for any depth.
 *
 * Death Wave is counted by the enemies it tagged, since its bonus stays on an enemy until it
 * dies. A run with no enemy count is skipped, and a counter a run does not carry is left out of
 * that window's median. `null` with no run to measure.
 */
export function measureCoinShares(runs: readonly Json[], tier: number): MeasuredCoinShares | null {
  const shares: Record<string, number[]> = { goldenTower: [], spotlight: [], deathWave: [], goldenBot: [], criticalCoin: [] }
  let counted = 0
  for (const run of runs) {
    const enemies = Number(run.totalEnemies)
    if (Number(run.tier) !== tier || run.isTournament === true || !(enemies >= 1000)) continue
    counted += 1
    for (const [window, field] of Object.entries(WINDOW_COUNTS)) {
      const count = Number(run[field])
      if (Number.isFinite(count) && run[field] != null) shares[window].push(count / enemies)
    }
    const killCoins = Number(run.coinsEarned) - Number(run.coinsEarnedCPW)
    const critical = Number(run.coinsFromCritCoin)
    if (killCoins > 0 && Number.isFinite(critical) && run.coinsFromCritCoin != null) shares.criticalCoin.push(critical / killCoins)
  }
  if (counted === 0) return null
  const windowShares: Record<string, number> = {}
  for (const window of Object.keys(WINDOW_COUNTS)) if (shares[window].length > 0) windowShares[window] = medianOf(shares[window])
  return { windowShares, criticalCoinShare: Math.min(0.9, medianOf(shares.criticalCoin)), runs: counted }
}

function card(cards: unknown, slug: string): { level: number, equipped: boolean } {
  const equipped = isObject(cards) && Array.isArray(cards.equippedCards) ? cards.equippedCards : []
  for (const entry of equipped) {
    if (isObject(entry) && entry.slug === slug) return { level: Math.max(1, Number(entry.level) || 1), equipped: true }
  }
  return { level: 1, equipped: false }
}

/**
 * The coin simulation's input for a run to `wave` on `tier`, with the account as `snapshot`
 * recorded it. Returns `null` when the snapshot has no Total Coin Bonus reading, which carries
 * the purchases, card, cosmetics, relics, Generator and Dissonance the model multiplies by.
 *
 * `averageWaveSeconds` is the run's own game time per wave when the caller has it, and
 * `measured` what the run records give in place of the model's own estimates.
 */
export function buildCoinSimulationInputFromSnapshot(
  snapshot: ExportSnapshot,
  tier: number,
  wave: number,
  averageWaveSeconds = 26,
  measured: MeasuredCoinInputs = {},
): CoinSimulationInputs | null {
  const { ordinaryKillScale } = measured
  /*
   * Basic enemies pay nothing but through Critical Coin, which the run records count as a share
   * of kill coins; raising the weight by that share is the same coins by another route.
   */
  const ordinaryCoinWeight = measured.ordinaryCoinWeight == null
    ? null
    : measured.ordinaryCoinWeight / (1 - Math.min(0.9, Math.max(0, measured.criticalCoinShare ?? 0)))
  const windowShares = measured.windowShares ?? null
  const reading = snapshot.readers.readTotalCoinBonusFromSaveRoot
  if (!isObject(reading) || !isObject(reading.input) || !isObject(reading.bonus)) return null
  const total = reading.input
  const rows = reading.bonus
  const purchases = isObject(total.purchases) ? total.purchases : {}
  const coinsCard = isObject(total.coinsCard) ? total.coinsCard : {}
  const labs = snapshotLabLevels(snapshot)
  const lab = (...slugs: string[]) => slugs.map(slug => labs[slug]?.level).find(level => level != null) ?? 0
  const workshop = snapshotWorkshopLevels(snapshot)
  const cards = snapshot.readers.readCardsFromSaveRoot
  const enemyBalance = card(cards, 'eb')
  const waveSkip = card(cards, 'ws')
  const atLeastOne = (value: unknown) => Math.max(1, Number(value) || 1)
  const weapons = readCoinWeaponInputsFromSnapshot(snapshot, tier)
  const modules = readCoinModuleBonusesFromSnapshot(snapshot)
  /* The bot's coin bonus counts only with a measured share of kills inside its range: its range against the tower's is not read. */
  const goldenBot = modules.goldenBotBonusLevel != null && (windowShares?.goldenBot ?? 0) > 0
  const unfilled = [...COIN_SIMULATION_INPUTS_NOT_READ]
  if (!weapons) unfilled.unshift('ultimate weapon levels and how often each coin window is open (no reading in this export)')
  if (!windowShares) unfilled.unshift('the share of kills inside each coin window (no run records to measure it from; the uptime model stands in, and Critical Coin and the Golden Bot are left out)')
  if (ordinaryKillScale == null) unfilled.unshift('enemies per wave (no kill counts to measure them from; the spawn chance chart stands in)')
  if (ordinaryCoinWeight == null) unfilled.unshift('the enemy mix by wave (no kill counts to measure it from; the tier\'s spawn chances stand in)')

  return {
    unfilled,
    input: {
      ...(ordinaryCoinWeight == null ? {} : { ordinaryCoinWeight }),
      ...(ordinaryKillScale == null ? {} : { ordinaryKillScale }),
      ...(windowShares ? { coinWindowShares: windowShares } : {}),
      goldenTowerBonusSubstat: modules.goldenTowerBonus,
      tier,
      targetWave: Math.max(1, Math.floor(wave)),
      enemyBalanceActive: enemyBalance.equipped,
      enemyBalanceCardLevel: enemyBalance.level,
      enemyBalanceMasteryLevel: 0,
      waveSkipActive: waveSkip.equipped,
      waveSkipCardLevel: waveSkip.level,
      waveSkipMasteryLevel: 0,
      waveAcceleratorMasteryLevel: -1,
      fetchActive: false,
      commonDropLabLevel: 0,
      rareDropLabLevel: 0,
      rerollShardsLabLevel: 0,
      shatterShardsLabLevel: 0,
      deathWaveCellsBonusLevel: lab('death_wave_cells_bonus'),
      cellsPerKillBonusLevel: lab('cells_kill_bonus', 'cells_per_kill_bonus'),
      shatterCommonModules: true,
      shatterRareModules: false,
      fetchCooldownLevel: 1,
      fetchFindChanceLevel: 1,
      fetchDoubleFindLevel: 1,
      wavesPerBoss: bossWaveIntervalForTier(tier),
      averageWaveSeconds,
      coinsKillWorkshopLevel: workshop['Coins / Kill Bonus'] ?? 0,
      coinsWaveWorkshopLevel: workshop['Coins / Wave'] ?? 0,
      coinBonusEnhancementLevel: Number(total.coinBonusEnhancementLevel) || 0,
      coinsKillLabLevel: lab('coins_kill_bonus'),
      coinsWaveLabLevel: lab('coins_per_wave', 'coins_wave'),
      gtBonusLabLevel: lab('golden_tower_bonus'),
      bhCoinLabLevel: lab('black_hole_coin_bonus'),
      dwCoinLabLevel: lab('death_wave_coin_bonus'),
      slCoinLabLevel: lab('spotlight_coin_bonus'),
      coinsCardActive: coinsCard.equipped === true,
      coinsCardLevel: Math.max(1, Number(coinsCard.level) || 1),
      coinsCardMastery: coinsCard.masteryUnlocked === true ? Number(coinsCard.masteryLevel) || 0 : -1,
      themeCoinBonusPct: (atLeastOne(rows.themes) - 1) * 100,
      relicCoinBonusPct: (Number(total.relicCoinBonus) || 0) * 100,
      iapToggles: {
        hasStarterPack: purchases.hasStarterPack === true,
        hasEpicPack: purchases.hasEpicPack === true,
        hasDisableAds: purchases.hasDisableAds === true,
      },
      generatorCoinMultiplier: atLeastOne(rows.modules),
      dissonanceCoinMultiplier: atLeastOne(rows.dissonance),
      moduleCoinsKillBonus: modules.coinsKillBonus,
      vaultCoinskillLevel: 0,
      allCoinPerkLevel: 0,
      standardPerkBonusPct: 0,
      hasCoinTradeOffPerk: false,
      improveTradeOffLabPct: 0,
      introSprintZeroCoinWaveCap: 0,
      bhdCpkBonusPct: 0,
      gtPlusLevel: 0,
      goldenBotCoverageFraction: 1,
      goldenBotBonusLevel: modules.goldenBotBonusLevel ?? 0,
      useGoldenBotCoinBonus: goldenBot,
      assumeSyncedUwCoinWindows: true,
      uwLevels: weapons?.uwLevels ?? {
        gtMultiplierLevel: 0, gtCdLevel: 0, gtDurLevel: 0, gtCdLab: 0, gtDurLab: 0,
        bhCdLevel: 0, bhDurLevel: 0, bhCdLab: 0, bhDurLab: 0,
        dwCdLevel: 0, dwQtyLevel: 0, slCdLevel: 0, slQtyLevel: 0, slAngleLevel: 0,
      },
      botLevels: { gbBonusLevel: 0, gbCdLevel: 0, gbDurLevel: 0, gbCdLab: 0, gbDurLab: 0 },
      uptime: weapons?.uptime ?? null,
    },
  }
}
