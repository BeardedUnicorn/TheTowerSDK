/**
 * Schedules a save's lab slots: the labs it has running, played forward against its income.
 *
 * The scheduler needs the slots as the save has them — what is researching, how long is left,
 * what boost is on — along with the account's lab speed, lab discount, coins on hand and coins
 * per day. Each comes from a different reader; this gathers them and runs the schedule.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    readLabSlotStates, scheduleLabsFromSave
 * depends    src/mechanics/effective-paths/lab-costs, src/mechanics/planning/lab-schedule, src/mechanics/planning/types, src/save/history/access, src/save/history/types, src/save/labs/cost-modifiers (+3 more)
 * used by    src/calculators/run-planning, src/calculators/specs.generated, src/save/planning/index, src/save/planning/plan
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { labSpeedTotal } from '../../mechanics/effective-paths/lab-costs'
import { scheduleLabs } from '../../mechanics/planning/lab-schedule'
import type { LabSlotState } from '../../mechanics/planning/types'
import {
  snapshotBalances,
  snapshotLabLevels,
  snapshotLabSlotCount,
  snapshotLabSlots,
  snapshotUnlockedRelicIndices,
} from '../history/access'
import type { ExportSnapshot } from '../history/types'
import { labSpeedRelicFractionFromIndices } from '../labs/cost-modifiers'
import { forecastIncomeFromSave } from './forecast'
import { readPlanningAccount } from './sources'
import type { LabScheduleOptions, SaveLabSchedule } from './types'

/**
 * The lab slots an export recorded, as the scheduler reads them: only the slots the account
 * owns, each with its running lab's slug, the level being researched and the seconds left.
 */
export function readLabSlotStates(snapshot: ExportSnapshot, gainPerSlotHour: Readonly<Record<string, number>> = {}): LabSlotState[] {
  const owned = snapshotLabSlotCount(snapshot)
  return snapshotLabSlots(snapshot)
    .filter(slot => owned == null || slot.slot < owned)
    .map(slot => ({
      slot: slot.slot,
      running: slot.slug
        ? {
            lab: slot.slug,
            name: slot.name ?? slot.slug,
            toLevel: slot.level + 1,
            remainingSeconds: slot.remainingSeconds,
            gainPerSlotHour: gainPerSlotHour[slot.slug],
          }
        : null,
      boost: slot.boost,
      boostRemainingSeconds: slot.boostRemainingSeconds,
    }))
}

/**
 * The lab schedule for a save's account over the next `horizonDays`.
 *
 * Coins per day is the forecast's median; a start the forecast balance does not cover waits and
 * says so. With no `labQueue`, each slot goes on with the next level of its own lab. Local times
 * are in `timeZone`, UTC when none is given, since the export does not carry the player's.
 * Returns `null` when the save cannot be read, has no export time, no lab slots or no coin
 * balance.
 */
export function scheduleLabsFromSave(options: LabScheduleOptions): SaveLabSchedule | null {
  const account = readPlanningAccount(options)
  if (!account || !account.now) return null
  const slots = readLabSlotStates(account.current, options.runningGainPerSlotHour)
  const balance = snapshotBalances(account.current).coins
  if (slots.length === 0 || balance == null) return null
  const forecast = options.forecast ?? forecastIncomeFromSave(options)
  const coinsPerDay = forecast?.coinsPerDay?.median ?? 0

  const labs = snapshotLabLevels(account.current)
  const labLevels: Record<string, number> = {}
  for (const [slug, lab] of Object.entries(labs)) labLevels[slug] = lab.level
  const labSpeedLevel = labLevels.labs_speed ?? 0
  const labSpeedRelicFraction = labSpeedRelicFractionFromIndices(snapshotUnlockedRelicIndices(account.current))

  const schedule = scheduleLabs({
    now: account.now,
    slots,
    queue: options.labQueue ?? [],
    labLevels,
    labSpeedLevel,
    labSpeedRelicFraction,
    coinDiscountLevel: labLevels.labs_coin_discount ?? 0,
    balance,
    coinsPerDay,
    boostPolicy: options.boostPolicy,
    horizonDays: options.horizonDays,
    timeZone: options.timeZone,
  })
  const warnings = [...schedule.warnings]
  if (!forecast?.coinsPerDay) warnings.push('no income could be forecast, so the schedule assumes no coins come in')
  return { ...schedule, warnings, now: account.now, balance, coinsPerDay, labSpeed: labSpeedTotal(labSpeedLevel, labSpeedRelicFraction) }
}
