/** What every planning function reads an account from. */
export interface PlanningSources {
  /** The account now: a decoded save, or a stored snapshot of reader output. */
  save: unknown
  /**
   * Earlier exports of the same account, as stored snapshots or decoded saves, in any order.
   * They supply runs older than the save's own thirty, the state each past run was played with,
   * and the moments that state changed.
   */
  snapshots?: readonly unknown[]
}

