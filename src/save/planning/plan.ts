/**
 * Answers the whole question at once for a save's account: what should the next coins buy, and
 * when will each buy be affordable.
 *
 * Each planning tool answers a part and needs another's output: the ranker needs the forecast
 * and the pass-through, the scheduler needs the ranker's lab queue and the boost policy, the
 * cell budget needs to know which slots matter. Run by hand that is a dozen calls in the right
 * order; this is the order.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    planSpendingFromSave
 * depends    src/save/planning/cells, src/save/planning/coin-check, src/save/planning/dissonance, src/save/planning/forecast, src/save/planning/lab-queue, src/save/planning/rank (+1 more)
 * used by    src/calculators/run-planning, src/save/planning/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { planCellBudgetFromSave } from './cells'
import { checkCoinModelFromSave } from './coin-check'
import { priceDissonancePaybackFromSave } from './dissonance'
import { affordableByFromSave, forecastIncomeFromSave } from './forecast'
import { scheduleLabsFromSave } from './lab-queue'
import { rankSpendsFromSave } from './rank'
import type { SpendingPlan, SpendingPlanOptions } from './types'

const DEFAULT_HORIZON_DAYS = 3

/**
 * The forecast, the coin check, both spend queues, the lab schedule, the boost policy and the
 * Dissonance table for a save's account.
 *
 * The lab schedule is given only the queued labs the forecast can pay for within the horizon;
 * a lab that costs more would hold a slot empty while it waited, and a warning names each one
 * left out. The buy list dates the coin queue alone and does not set coins aside for lab starts,
 * which the schedule shows. Returns `null` when the save cannot be read or has no export time.
 */
export function planSpendingFromSave(options: SpendingPlanOptions): SpendingPlan | null {
  const sources = { save: options.save, snapshots: options.snapshots }
  const forecast = forecastIncomeFromSave(sources)
  if (!forecast) return null
  const warnings: string[] = []
  const horizonDays = options.horizonDays ?? DEFAULT_HORIZON_DAYS
  const check = checkCoinModelFromSave(sources)
  const passThrough = check?.passThrough ?? 1

  const ranking = rankSpendsFromSave({
    ...sources,
    forecast,
    passThrough,
    coinModel: check,
    dissonantWave: options.dissonantWave,
    workshopTargets: options.workshopTargets,
    survivalFit: options.survivalFit,
    survivalSeeds: options.survivalSeeds,
    ...(options.includeSurvival === false ? { include: ['lab', 'enhancement', 'module', 'unlock', 'dissonant-run'] as const } : {}),
  })
  if (!ranking) warnings.push('nothing was ranked: the account has no full farm run to forecast income from')
  if (options.includeSurvival === false) warnings.push('workshop levels were not ranked: the wave survival model was switched off for this plan')

  const boostPolicy = planCellBudgetFromSave({
    ...sources,
    forecast,
    floor: options.cellFloor,
    labValues: ranking?.runningGainPerSlotHour,
    cellsPerHourByMultiplier: options.cellsPerHourByMultiplier,
    maxMultiplier: options.maxBoostMultiplier,
  })

  const reach = (forecast.coins ?? 0) + (forecast.coinsPerDay?.median ?? 0) * horizonDays
  const queue = []
  for (const row of ranking?.labQueue ?? []) {
    if (!row.lab || row.toLevel == null || !(row.gainPerDay.likely > 0)) continue
    if (row.totalCoins > reach) {
      warnings.push(`${row.candidate} is not scheduled: it costs more coins than the forecast brings in within ${horizonDays} days`)
      continue
    }
    queue.push({ lab: row.lab, name: row.lab, toLevel: row.toLevel, gainPerSlotHour: row.gainPerSlotHour ?? undefined })
  }
  const labSchedule = scheduleLabsFromSave({
    ...sources,
    forecast,
    labQueue: queue,
    boostPolicy: boostPolicy?.policy.map(slot => ({ slot: slot.slot, multiplier: slot.multiplier })),
    horizonDays,
    timeZone: options.timeZone,
    runningGainPerSlotHour: ranking?.runningGainPerSlotHour,
  })

  const worthwhile = (ranking?.coinQueue ?? []).filter(row => row.gainPerDay.likely > 0 && row.kind !== 'dissonant-run')
  const buyList = worthwhile.length > 0
    ? affordableByFromSave({ ...sources, forecast, list: worthwhile.map(row => ({ name: row.candidate, coins: row.totalCoins })) })
    : null

  const { runs: _runs, ...forecastSummary } = forecast
  void _runs
  let coinModel: SpendingPlan['coinModel'] = null
  if (check) {
    const { perRun: _perRun, ...rest } = check
    void _perRun
    coinModel = rest
  }
  return {
    now: forecast.now,
    coins: forecast.coins,
    cells: forecast.cells,
    forecast: forecastSummary,
    coinModel,
    labQueue: ranking?.labQueue ?? [],
    coinQueue: ranking?.coinQueue ?? [],
    notRanked: ranking?.notRanked ?? [],
    buyList,
    labSchedule,
    boostPolicy,
    dissonance: priceDissonancePaybackFromSave({ ...sources, forecast, passThrough }),
    warnings: [...warnings, ...(ranking?.warnings ?? [])],
  }
}
