/**
 * Lists what a save's account could buy next, each priced in coins per day by the model that
 * understands it.
 *
 * Two models can put a figure on a spend. The economy planner knows what a coin lab or the Coin
 * Bonus enhancement adds to income; the wave survival model knows how many more waves a workshop
 * level buys. This asks each for its candidates and converts both to one unit, and names what
 * neither can price so that nothing is silently left out.
 */
