const HOURS_PER_DAY = 24
const fold = (value: string): string => value.toLowerCase().replace(/[^a-z0-9]+/g, '')

interface Priced { id: string, name: string, level: number, gain: number, days: number, coins: number | null }

/*
 * Every candidate the economy planner prices at its first step: its gain in effective economy,
 * its research days at the account's lab speed, and its coins. Two passes, because the planner
 * prices in one currency at a time.
 */
function economyCandidates(
  root: Record<string, unknown>,
  bumped: ReadonlySet<string>,
): { start: number, priced: Priced[], excluded: { name: string, reason: string }[] } {
  const inputs = buildEffectiveEconomyInputsFromSave(root)
  const time: Record<string, number> = { ...(inputs.levels as unknown as { time: Record<string, number> }).time }
  for (const key of Object.keys(time)) if (bumped.has(fold(key))) time[key] += 1
  const levels = { ...inputs.levels, time } as unknown as typeof inputs.levels
  const shared = {
    config: inputs.config,
    levels,
    steps: 1,
    labModifiers: readLabCostModifiersFromSaveRoot(root) ?? {},
    enhancementLevels: readWorkshopFromSaveRoot(root)?.active.enhancementLevels ?? {},
    workshopEnhancementsUnlocked: (time.enhancementCoinBonus ?? 0) > 0,
  }
  const byId = new Map<string, Priced>()
  const days = planEffectiveEconomyPath({
    ...shared, variant: 'time', daysOnly: true,
    onCandidateRoi: (entry) => {
      if (entry.step === 1) byId.set(entry.id, { id: entry.id, name: entry.name, level: entry.nextLevel, gain: entry.gain, days: entry.price, coins: null })
    },
  })
  planEffectiveEconomyPath({
    ...shared, variant: 'coin',
    onCandidateRoi: (entry) => {
      const row = byId.get(entry.id)
      if (entry.step === 1 && row) row.coins = entry.price
    },
  })
  return {
    start: days.startingEffectiveEconomy,
    priced: [...byId.values()],
    excluded: days.excluded.map(row => ({ name: row.sheetName, reason: row.reason })),
  }
}

/**
 * The economy planner's candidates as spends: coin labs for the lab queue, and the Coin Bonus
 * enhancement, gates included, for the coin queue.
 *
 * A lab's gain is its share of effective economy times coins per day times the pass-through. A
 * lab already researching is priced one level on, since that is the level that can be started,
 * and its current level's worth is returned for the scheduler's swap test. `root` must be a
 * decoded save: the planner's inputs are not kept in a stored snapshot.
 */
export function listEconomySpendCandidates(
  root: Record<string, unknown>,
  current: ExportSnapshot,
  coinsPerDay: number,
  passThrough: number,
): SpendCandidateList {
  const warnings: string[] = []
  const candidates: SpendCandidate[] = []
  const runningGainPerSlotHour: Record<string, number> = {}
  const running = snapshotLabSlots(current).filter(slot => slot.slug)
  const runningKeys = new Set(running.map(slot => fold(slot.slug as string)))

  const now = economyCandidates(root, new Set())
  const perDay = (gain: number, start: number) => (start > 0 ? (gain / start) * coinsPerDay * passThrough : 0)
  for (const row of now.priced) {
    const slot = running.find(entry => fold(entry.name ?? '') === fold(row.name) || fold(entry.slug as string) === fold(row.name))
    if (slot && row.days > 0) runningGainPerSlotHour[slot.slug as string] = perDay(row.gain, now.start) / (row.days * HOURS_PER_DAY)
  }
  const next = runningKeys.size > 0
    ? economyCandidates(root, new Set(now.priced.filter(row => running.some(slot => fold(slot.name ?? '') === fold(row.name))).map(row => fold(row.id.replace(/^time\./, '')))))
    : now
  const bestWaves = snapshotBestWaveByTier(current)
  const unlocks = new Map(Object.entries(LAB_UNLOCKS).map(([name, unlock]) => [fold(name), unlock]))
  const locked: { candidate: string, reason: string }[] = []
  for (const row of next.priced) {
    if (!(row.days > 0)) continue
    /*
     * Being modelled is not being available: most labs sit behind a tier milestone. A lab with a
     * level already held is open whatever the tier records say.
     */
    const unlock = unlocks.get(fold(row.name))
    if (row.level <= 1 && unlock && typeof unlock === 'object' && (bestWaves[unlock.tier] ?? 0) < unlock.wave) {
      locked.push({
        candidate: `${row.name} ${row.level}`,
        reason: `the lab unlocks at the tier ${unlock.tier} wave ${unlock.wave} milestone; the best wave on that tier is ${bestWaves[unlock.tier] ?? 0}`,
      })
      continue
    }
    const schedulable = labDurationDaysToReachLevel(row.name, row.level, {}) != null && labCoinCostToReachLevel(row.name, row.level, {}) != null
    const likely = perDay(row.gain, next.start)
    candidates.push({
      candidate: `${row.name} ${row.level}`,
      kind: 'lab',
      coins: row.coins ?? 0,
      slotHours: row.days * HOURS_PER_DAY,
      gainPerDay: { low: likely, likely, high: likely },
      permanent: true,
      confidence: null,
      model: 'economy planner',
      ...(schedulable ? { lab: row.name, toLevel: row.level } : {}),
    })
    if (row.coins == null) warnings.push(`${row.name} ${row.level} has research time but no coin price from the planner; its coins are shown as 0`)
  }

  /* The Coin Bonus enhancement: +1% a level on the coin bonus, which kill coins take twice. */
  const labs = snapshotLabLevels(current)
  const labLevels: Record<string, number> = {}
  for (const [slug, lab] of Object.entries(labs)) labLevels[slug] = lab.level
  const enhancement = readWorkshopFromSaveRoot(root)
  const level = enhancement?.active.enhancementLevels['Coin Bonus'] ?? 0
  const price = priceEnhancementLevelsForAccount({ stat: 'Coin Bonus', fromLevel: level, toLevel: level + 1, labLevels })
  if (price) {
    const gates: SpendGate[] = []
    if (!labLevels.workshop_enhancements) {
      const modifiers = readLabCostModifiersFromSaveRoot(root) ?? {}
      gates.push({
        name: 'Workshop Enhancements lab',
        coins: labCoinCostToReachLevel('workshop_enhancements', 1, modifiers) ?? 0,
        slotHours: (labDurationDaysToReachLevel('workshop_enhancements', 1, modifiers) ?? 0) * HOURS_PER_DAY,
      })
    }
    const spent = coerceSaveNumber(enhancement?.meta.totalCoinsSpentUtilityEnhancements) ?? 0
    const threshold = UTILITY_ENHANCEMENT_SPEND_UNLOCKS['Coin Bonus']
    if (spent <= threshold) gates.push({ name: `more than ${threshold / 1e9}B spent on other Utility enhancements`, coins: threshold - spent })
    const one = ((1 + (level + 1) * 0.01) / (1 + level * 0.01)) - 1
    candidates.push({
      candidate: `Coin Bonus enhancement ${level} → ${level + 1}`,
      kind: 'enhancement',
      coins: price.coins,
      gainPerDay: { low: one * coinsPerDay * passThrough, likely: ((1 + one) ** 2 - 1) * coinsPerDay * passThrough, high: ((1 + one) ** 2 - 1) * coinsPerDay * passThrough },
      permanent: false,
      confidence: null,
      model: 'coin bonus row',
      gates,
    })
    if (gates.length > 0) warnings.push('the Coin Bonus enhancement also needs the Tier 12 wave 60 milestone claimed, which costs no coins and is not checked here')
  }

  return {
    candidates,
    notRanked: [...locked, ...next.excluded.filter(row => !/costs coins rather than research time/.test(row.reason)).map(row => ({ candidate: row.name, reason: row.reason }))],
    runningGainPerSlotHour,
    warnings,
  }
}

function defaultWorkshopTargets(levels: Readonly<Record<string, number>>): WorkshopSpendTarget[] {
  const out: WorkshopSpendTarget[] = []
  for (const stat of SURVIVAL_STATS) {
    const level = levels[stat]
    const max = workshopStatMaxLevel(stat)
    if (level == null || max == null || level >= max) continue
    out.push({ stat, toLevel: Math.min(max, (Math.floor(level / 100) + 1) * 100) })
  }
  return out
}

/**
 * Workshop levels as spends, priced through the wave survival model: the extra waves an away-run
 * survives, turned into coins per day.
 *
 * A run that goes Δ waves deeper earns more by the coin model's ratio between the two waves, with
 * kill coins at the scale fitted to the account's runs.
 * `high` assumes the account plays as many runs a day as before, each longer; `low` assumes it
 * plays the same hours, so only the richer waves count; `likely` is halfway. Fitting the model
 * takes tens of seconds, so pass a calibration when one is at hand. Workshop levels can be
 * moved by Workshop Respec, so none is permanent.
 */
export function listSurvivalSpendCandidates(options: SpendRankOptions, current: ExportSnapshot, forecast: SaveIncomeForecast): SpendCandidateList {
  const warnings: string[] = []
  const empty = { candidates: [], runningGainPerSlotHour: {} }
  const tier = forecast.tier
  const coinsPerDay = forecast.coinsPerDay?.median ?? 0
  const levels = snapshotWorkshopLevels(current)
  const targets = (options.workshopTargets ?? defaultWorkshopTargets(levels))
    .filter(target => (SURVIVAL_STATS as readonly string[]).includes(target.stat))
  const skipped = (options.workshopTargets ?? []).filter(target => !(SURVIVAL_STATS as readonly string[]).includes(target.stat))
    .map(target => ({ candidate: `${target.stat} → ${target.toLevel}`, reason: 'not a stat the wave survival model reads, so no coins-per-day figure can be put on it' }))
  if (tier == null || targets.length === 0) return { ...empty, notRanked: skipped, warnings }

  let calibration = options.survivalCalibration
  let error = options.survivalError ?? null
  if (!calibration) {
    const fit = calibrateSurvivalFromHistory({ save: options.save, snapshots: options.snapshots, tier, maxRuns: 6, seeds: 8, passes: 2, ...options.survivalFit })
    if (!fit || fit.runsUsed === 0) {
      return { ...empty, notRanked: [...skipped, ...targets.map(target => ({ candidate: `${target.stat} → ${target.toLevel}`, reason: 'the survival model could not be fitted to this account\'s runs' }))], warnings }
    }
    calibration = fit.calibration
    error = fit.leaveOneOutError
    warnings.push(...fit.warnings.slice(0, 3))
  }
  const rank = rankSurvivalUpgradesFromSave({
    save: options.save, tier, mode: 'afk', calibration,
    candidates: targets.map(target => ({ stat: target.stat as SurvivalStat, toLevel: target.toLevel })),
    seeds: options.survivalSeeds ?? 100,
  })
  if (!rank) return { ...empty, notRanked: [...skipped, ...targets.map(target => ({ candidate: `${target.stat} → ${target.toLevel}`, reason: 'the survival model could not read this account' }))], warnings }

  const labs = snapshotLabLevels(current)
  const labLevels: Record<string, number> = {}
  for (const [slug, lab] of Object.entries(labs)) labLevels[slug] = lab.level
  const wave = rank.baseline.median
  /* Kill coins at the account's own fitted scale, so the wave payout and the kills are weighed as the records weigh them. */
  const killScale = options.coinModel?.calibration ?? null
  if (!killScale) warnings.push('no kill-coin scale could be fitted, so the coins of a deeper run come from the model as it is')
  const coinsAt = (target: number): number | null => {
    const model = predictRunCoinsFromSnapshot(current, tier, target, undefined, {
      ordinaryCoinWeight: ordinaryCoinWeightAtWave(options.coinModel?.coinWeights ?? [], target),
      ordinaryKillScale: ordinaryKillScaleAtWave(options.coinModel?.killScales ?? [], target),
      windowShares: options.coinModel?.measuredShares?.windowShares,
      criticalCoinShare: options.coinModel?.measuredShares?.criticalCoinShare,
    })
    return model ? model.waveCoins + model.killCoins * (killScale ? killCoinScaleAtWave(killScale, target) : 1) : null
  }
  const base = coinsAt(wave)
  const candidates: SpendCandidate[] = []
  const notRanked = [...skipped]
  for (const row of rank.ranked) {
    const name = `${row.stat} ${row.fromLevel} → ${row.toLevel}`
    const price = priceWorkshopLevelsForAccount({ stat: row.stat, fromLevel: row.fromLevel, toLevel: row.toLevel, labLevels })
    const deeper = coinsAt(wave + row.medianWavesGained)
    if (!price || base == null || deeper == null || !(base > 0) || !(wave > 0)) {
      notRanked.push({ candidate: name, reason: 'its price or the coins at the deeper wave could not be worked out' })
      continue
    }
    const ratio = deeper / base
    const high = Math.max(0, ratio - 1) * coinsPerDay
    const low = Math.max(0, ratio / ((wave + row.medianWavesGained) / wave) - 1) * coinsPerDay
    candidates.push({
      candidate: name,
      kind: 'workshop',
      coins: price.coins,
      gainPerDay: { low, likely: (low + high) / 2, high },
      permanent: false,
      confidence: error,
      model: `wave survival (+${Math.round(row.medianWavesGained)} waves from ${Math.round(wave)})`,
    })
  }
  if (error != null) warnings.push(`the survival fit misses a held-out run's wave by ${(error * 100).toFixed(0)}% on average: a gain smaller than that is within the noise`)
  warnings.push(...rank.warnings.slice(0, 3))
  return { candidates, notRanked, runningGainPerSlotHour: {}, warnings }
}

/** Whether a planning source is a decoded save, which the economy planner needs, and not a stored snapshot. */
export function isDecodedSave(source: unknown): source is Record<string, unknown> {
  return source != null && typeof source === 'object' && !Array.isArray(source) && !isExportSnapshot(source)
    && !('readers' in (source as Record<string, unknown>))
}
