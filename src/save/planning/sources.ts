/**
 * Gathers what the planning models read from an account's save and the exports kept before it.
 *
 * Every planning tool starts from the same three things: the account now, every run on record
 * and the moment the save was written. A save holds thirty runs; the exports kept before it hold
 * older ones and show which run was in progress when. This assembles them once, so the tools
 * agree on what the account's history is.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    readPlanningAccount, listPlanningRuns, listCoinBonusReadings
 * depends    src/formatting/numbers/compute, src/mechanics/planning/types, src/save/access/values, src/save/history/access, src/save/history/snapshot, src/save/killed-by/read (+1 more)
 * used by    src/calculators/specs.generated, src/save/planning/cells, src/save/planning/coin-check, src/save/planning/dissonance, src/save/planning/forecast, src/save/planning/index (+2 more)
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { parseSaveDateTimeToMs } from '../../formatting/numbers/compute'
import type { CoinBonusReading, PlanningRun } from '../../mechanics/planning/types'
import { coerceSaveNumber, readSaveBoolean } from '../access/values'
import { snapshotCurrentRun, snapshotTimeMs } from '../history/access'
import { orderExportSnapshots, toExportSnapshot } from '../history/snapshot'
import { SAVE_FILE_KILLED_BY_APATHY_INDICES } from '../killed-by/read'
import type { PlanningAccount, PlanningSources } from './types'

type Json = Record<string, unknown>

function isObject(value: unknown): value is Json {
  return value != null && typeof value === 'object' && !Array.isArray(value)
}

/**
 * The account behind a set of planning sources, or `null` when `save` is neither a decoded save
 * nor a stored snapshot.
 */
export function readPlanningAccount(sources: PlanningSources): PlanningAccount | null {
  const current = toExportSnapshot(sources.save)
  if (!current) return null
  const now = current.meta.exportedAt
  const nowMs = snapshotTimeMs(current)
  /* An export from after the save says nothing about the account the save describes. */
  const earlier = orderExportSnapshots(sources.snapshots ?? [])
    .filter(snapshot => !Number.isFinite(nowMs) || !(snapshotTimeMs(snapshot) >= nowMs))
  const history = [...earlier, current]

  const byDate = new Map<string, Json>()
  for (const snapshot of history) {
    for (const run of snapshot.runs) {
      const ms = parseSaveDateTimeToMs(run.battleDate ?? run.runDate)
      if (ms != null && Number.isFinite(ms)) byDate.set(new Date(ms).toISOString(), run)
    }
  }
  const runs = [...byDate.keys()].sort().map(key => byDate.get(key) as Json)
  return { current, history, now, runs }
}

function runEndIso(run: Json): string | null {
  const ms = parseSaveDateTimeToMs(run.battleDate ?? run.runDate)
  return ms == null || !Number.isFinite(ms) ? null : new Date(ms).toISOString()
}

/**
 * The account's runs as the income models read them, oldest first.
 *
 * A run is `endedByPlayer` when its killed-by code is one the game writes for a run nobody
 * killed. `firstSeenAt` is the earliest kept export that shows the run in progress: taken after
 * the previous run ended, on the run's tier, at a wave above zero and no higher than the run's.
 */
export function listPlanningRuns(account: PlanningAccount): PlanningRun[] {
  const out: PlanningRun[] = []
  let previousEnd = Number.NEGATIVE_INFINITY
  for (const run of account.runs) {
    const endedAt = runEndIso(run)
    if (!endedAt) continue
    const end = Date.parse(endedAt)
    const tier = coerceSaveNumber(run.tier) ?? 0
    const wave = coerceSaveNumber(run.wave) ?? 0
    const killedBy = coerceSaveNumber(run.killedBy)
    const seen = account.history.find((snapshot) => {
      const at = snapshotTimeMs(snapshot)
      const current = snapshotCurrentRun(snapshot)
      const currentWave = Number(current?.currentWave)
      return at > previousEnd && at < end && current != null && Number(current.currentTier) === tier
        && currentWave > 0 && currentWave <= wave
    })
    out.push({
      endedAt,
      tier,
      wave,
      realSeconds: Math.max(0, coerceSaveNumber(run.realTime) ?? 0),
      coins: Math.max(0, coerceSaveNumber(run.coinsEarned) ?? 0),
      cells: Math.max(0, coerceSaveNumber(run.cellsEarned) ?? 0),
      tournament: readSaveBoolean(run.isTournament),
      dissonant: (coerceSaveNumber(run.dissonanceType) ?? 0) > 0,
      endedByPlayer: killedBy == null ? null : SAVE_FILE_KILLED_BY_APATHY_INDICES.has(killedBy),
      firstSeenAt: seen?.meta.exportedAt ?? null,
    })
    previousEnd = end
  }
  return out
}

/** The Total Coin Bonus each kept export recorded, oldest first, for finding breaks in income. */
export function listCoinBonusReadings(account: PlanningAccount): CoinBonusReading[] {
  const out: CoinBonusReading[] = []
  for (const snapshot of account.history) {
    const reading = snapshot.readers.readTotalCoinBonusFromSaveRoot
    if (!snapshot.meta.exportedAt || !isObject(reading) || !isObject(reading.bonus) || !isObject(reading.input)) continue
    const total = Number(reading.bonus.total)
    const tier = Number(reading.input.tier)
    if (Number.isFinite(total) && Number.isFinite(tier)) out.push({ at: snapshot.meta.exportedAt, tier, total })
  }
  return out
}
