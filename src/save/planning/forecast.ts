/**
 * Forecasts a save's coins and cells per day, and dates a shopping list against that income.
 *
 * The forecast model takes runs and readings; this supplies them from the account's own save
 * and whatever exports were kept before it, and adds the one thing only a save knows: how many
 * coins and cells are on hand now.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    forecastIncomeFromSave, affordableByFromSave
 * depends    src/mechanics/planning/income, src/save/history/access, src/save/planning/sources, src/save/planning/types
 * used by    src/calculators/run-planning, src/save/planning/cells, src/save/planning/coin-check, src/save/planning/dissonance, src/save/planning/index, src/save/planning/lab-queue (+2 more)
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { affordableBy, forecastIncome } from '../../mechanics/planning/income'
import { snapshotBalances, snapshotCurrentRun } from '../history/access'
import { listCoinBonusReadings, listPlanningRuns, readPlanningAccount } from './sources'
import type { AffordableBy, AffordableByOptions, IncomeForecastOptions, SaveIncomeForecast } from './types'

/**
 * Coins and cells per day for a save's account, from its full farm runs since income last
 * changed and the hours it runs.
 *
 * `snapshots` are earlier exports of the account. They add runs older than the save's thirty,
 * show a run that sat paused, and date a change in income by the Total Coin Bonus; without them
 * a change is found only as a step in the runs themselves. Returns `null` when `save` cannot be
 * read or carries no export time to forecast from.
 */
export function forecastIncomeFromSave(options: IncomeForecastOptions): SaveIncomeForecast | null {
  const account = readPlanningAccount(options)
  if (!account || !account.now) return null
  const current = snapshotCurrentRun(account.current)
  const running = current && Number(current.currentWave) > 0 && current.roundActive !== false
    ? Number(current.realSeconds)
    : 0
  const forecast = forecastIncome({
    runs: listPlanningRuns(account),
    now: account.now,
    tier: options.tier,
    since: options.since,
    coinBonusReadings: listCoinBonusReadings(account),
    currentRunRealSeconds: Number.isFinite(running) ? running : 0,
    uptimeDays: options.uptimeDays,
    hoursPerDay: options.hoursPerDay,
  })
  const balances = snapshotBalances(account.current)
  const warnings = [...forecast.warnings]
  if ((options.snapshots ?? []).length === 0) {
    warnings.push('no earlier exports were given: a paused run cannot be seen, and a change in income is found only from the runs')
  }
  return { ...forecast, warnings, now: account.now, coins: balances.coins ?? null, cells: balances.cells ?? null }
}

/**
 * When each item on an ordered shopping list becomes affordable for a save's account: an early,
 * likely and late date from the forecast's income band, starting from the coins on hand.
 *
 * Returns `null` when the save cannot be read, carries no coin balance, or has no farm run to
 * forecast income from.
 */
export function affordableByFromSave(options: AffordableByOptions): AffordableBy | null {
  const forecast = options.forecast ?? forecastIncomeFromSave(options)
  if (!forecast || forecast.coins == null || !forecast.coinsPerDay) return null
  return {
    now: forecast.now,
    balance: forecast.coins,
    items: affordableBy(options.list, forecast.coins, forecast.coinsPerDay, forecast.now),
    warnings: forecast.warnings,
  }
}
