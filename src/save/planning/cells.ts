/**
 * Budgets a save's cells for lab boosts: the multiplier each slot can be kept at on what the
 * account's runs bring in.
 *
 * The budget needs the slots and their boosts, the cells on hand and the cells per day; this
 * reads them from the save and its forecast, and takes the price table from the caller when the
 * player has read the prices in game, falling back to the wiki's and saying so.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    planCellBudgetFromSave
 * depends    src/data/labs/boost-prices, src/mechanics/planning/cell-budget, src/save/history/access, src/save/planning/forecast, src/save/planning/sources, src/save/planning/types
 * used by    src/calculators/run-planning, src/save/planning/index, src/save/planning/plan
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { LAB_BOOST_CELLS_PER_HOUR, LAB_BOOST_PRICES_VERIFIED_IN_GAME } from '../../data/labs/boost-prices'
import { planCellBudget } from '../../mechanics/planning/cell-budget'
import { snapshotBalances, snapshotLabSlotCount, snapshotLabSlots } from '../history/access'
import { forecastIncomeFromSave } from './forecast'
import { readPlanningAccount } from './sources'
import type { CellBudgetOptions, SaveCellBudget } from './types'

/**
 * A boost multiplier per lab slot that the save's cell income sustains, with the days the bank
 * lasts and when each boost needs renewing.
 *
 * Returns `null` when the save cannot be read, carries no cell balance or lab slots, or has no
 * farm run to forecast cells from.
 */
export function planCellBudgetFromSave(options: CellBudgetOptions): SaveCellBudget | null {
  const account = readPlanningAccount(options)
  if (!account || !account.now) return null
  const forecast = options.forecast ?? forecastIncomeFromSave(options)
  const bank = snapshotBalances(account.current).cells
  const owned = snapshotLabSlotCount(account.current)
  const slots = snapshotLabSlots(account.current).filter(slot => owned == null || slot.slot < owned)
  if (!forecast?.cellsPerDay || bank == null || slots.length === 0) return null
  const budget = planCellBudget({
    now: account.now,
    cellsPerDay: forecast.cellsPerDay,
    bank,
    floor: options.floor,
    slots: slots.map(slot => ({
      slot: slot.slot,
      occupied: slot.slug != null,
      value: slot.slug ? options.labValues?.[slot.slug] : undefined,
      boost: slot.boost,
      boostRemainingSeconds: slot.boostRemainingSeconds,
    })),
    cellsPerHourByMultiplier: options.cellsPerHourByMultiplier ?? LAB_BOOST_CELLS_PER_HOUR,
    pricesVerified: options.cellsPerHourByMultiplier != null || LAB_BOOST_PRICES_VERIFIED_IN_GAME,
    maxMultiplier: options.maxMultiplier,
  })
  return { ...budget, now: account.now, bank, income: forecast.cellsPerDay }
}
