/**
 * A run's coin counters, by the names the run record uses. They overlap — a Golden Tower coin is
 * also a kill coin — so each is compared with itself across runs and they are never added up.
 */
export const RUN_COIN_SOURCE_FIELDS: readonly string[] = [
  'coinsFromGoldenTower',
  'coinsFromCoinUpgrade',
  'coinsFromCoinBonuses',
  'coinsEarnedWaveSkip',
  'coinsEarnedCPW',
  'coinsFromSpotlight',
  'coinsFromCritCoin',
  'coinsFromDeathWave',
  'coinsFromBlackHole',
  'goldenBotCoinsEarned',
]

/**
 * The coin model's wave payout and kill coins for a run to `wave`, with the account as an export
 * recorded it. The two are returned apart because they are not equally good: the wave payout
 * follows from the coin bonus alone, while kill coins rest on inputs the export does not carry
 * and need the fitted scale from `checkCoinModelFromSave`. `null` when the model cannot be run.
 */
export function predictRunCoinsFromSnapshot(
  snapshot: ExportSnapshot,
  tier: number,
  wave: number,
  averageWaveSeconds?: number,
  measured: MeasuredCoinInputs = {},
): { waveCoins: number, killCoins: number, kills: number } | null {
  const built = buildCoinSimulationInputFromSnapshot(snapshot, tier, wave, averageWaveSeconds, measured)
  if (!built) return null
  try {
    const result = simulateResourceDropsCoins(built.input)
    return {
      waveCoins: result.coins.coinsFromWavePayout + result.coins.coinsFromWavePayoutWaveSkipBonus,
      killCoins: result.coins.coinsFromKills + result.coins.coinsFromKillsWaveSkipBonus,
      kills: result.totalKillsEstimated,
    }
  }
  catch {
    return null
  }
}

/**
 * Predicted against recorded coins for every full farm run on a tier, and the drift across the
 * last change in income.
 *
 * A run with no export at or before its start is predicted from the oldest export on hand, and a
 * warning counts such runs. Kill coins are brought to the account's own level by a fitted scale,
 * since the model leaves out the inputs in `unfilled`; wave coins need none. Returns `null` when
 * `save` cannot be read or carries no export time.
 */
export function checkCoinModelFromSave(options: CoinModelCheckOptions): SaveCoinModelCheck | null {
  const account = readPlanningAccount(options)
  const forecast = forecastIncomeFromSave(options)
  if (!account || !forecast) return null
  const tier = options.tier ?? forecast.tier
  const farmDates = new Set(forecast.runs.filter(run => run.kind === 'farm' && run.tier === tier).map(run => run.endedAt))

  const firstSeen = new Map(forecast.runs.map(run => [run.endedAt, run.firstSeenAt ?? null]))

  const weights = tier == null ? [] : measureOrdinaryCoinWeights(account.runs, tier)
  const measuredShares = tier == null ? null : measureCoinShares(account.runs, tier)
  /*
   * Recorded kills over the model's, run by run, with the account as it stands now: the cards that
   * set how many enemies a wave spawns rarely change, and the ratio is what carries the shape the
   * spawn chance chart gets wrong.
   */
  const killScales: { wave: number, scale: number }[] = []
  if (tier != null) {
    for (const measured of measureOrdinaryKills(account.runs, tier)) {
      const modelled = predictRunCoinsFromSnapshot(account.current, tier, measured.wave)
      if (modelled && modelled.kills > 0) killScales.push({ wave: measured.wave, scale: measured.kills / modelled.kills })
    }
  }
  const perRun: CoinModelRunInput[] = []
  let undated = 0
  let unsettled = 0
  for (const run of account.runs) {
    const end = parseSaveDateTimeToMs(run.battleDate ?? run.runDate)
    if (end == null || !farmDates.has(new Date(end).toISOString())) continue
    const wave = coerceSaveNumber(run.wave) ?? 0
    const realSeconds = coerceSaveNumber(run.realTime) ?? 0
    const gameSeconds = coerceSaveNumber(run.gameTime) ?? 0
    /*
     * An export taken during the run shows the loadout it was played with. One taken before it
     * may show another: a tournament preset, a card swapped out between runs.
     */
    const seen = firstSeen.get(new Date(end).toISOString())
    const nearest = exportStateAt(account.history, seen ?? new Date(end - realSeconds * 1000).toISOString())
    /*
     * An export written before the coin bonus was read holds nothing to predict from. The oldest
     * one that does stands in, as an assumption: which runs can be predicted must not depend on
     * when a reader was added, or the runs left are whichever happen to be recent.
     */
    const readable = nearest && snapshotTotalCoinBonus(nearest.snapshot) == null
      ? account.history.find(snapshot => snapshotTotalCoinBonus(snapshot) != null)
      : null
    const found = readable ? { ...nearest, snapshot: readable, takenAt: readable.meta.exportedAt, side: 'after' as const } : nearest
    /*
     * The state is known when an export shows the run in progress, or when the exports on either
     * side of it agree on the coin bonus. Where they disagree, something changed between them and
     * nothing says whether before or during the run. A run older than every export is predicted
     * from the oldest, which is an assumption and is counted as one.
     */
    let state: CoinRunState = found?.side === 'before' ? 'known' : 'assumed'
    if (state === 'known' && !seen && found) {
      const after = account.history.find(snapshot => snapshotTimeMs(snapshot) >= end)
      const was = snapshotTotalCoinBonus(found.snapshot)
      const became = after ? snapshotTotalCoinBonus(after) : null
      if (was != null && became != null && Math.abs(became / was - 1) > 0.01) state = 'unsettled'
    }
    /* Assumed from an export on the far side of a change in income is not an assumption worth making. */
    const exportedAt = found ? snapshotTimeMs(found.snapshot) : Number.NaN
    if (state === 'assumed' && forecast.regimeBreaks.some(change => end <= Date.parse(change.after) && exportedAt >= Date.parse(change.before))) {
      state = 'unsettled'
    }
    if (state === 'assumed') undated += 1
    if (state === 'unsettled') unsettled += 1
    const model = found && tier != null && wave > 0
      ? predictRunCoinsFromSnapshot(found.snapshot, tier, wave, gameSeconds > 0 ? gameSeconds / wave : undefined, {
        ordinaryCoinWeight: ordinaryCoinWeightAtWave(weights, wave),
        ordinaryKillScale: ordinaryKillScaleAtWave(killScales, wave),
        windowShares: measuredShares?.windowShares,
        criticalCoinShare: measuredShares?.criticalCoinShare,
      })
      : null
    const sources: Record<string, number> = {}
    for (const field of RUN_COIN_SOURCE_FIELDS) {
      const value = coerceSaveNumber(run[field])
      if (value != null) sources[field] = value
    }
    perRun.push({
      runDate: new Date(end).toISOString(),
      wave,
      actual: coerceSaveNumber(run.coinsEarned) ?? 0,
      actualWaveCoins: coerceSaveNumber(run.coinsEarnedCPW),
      predictedWaveCoins: model?.waveCoins ?? null,
      predictedKillCoins: model?.killCoins ?? null,
      sources,
      state,
    })
  }

  /*
   * Breaks with no farm run finished between them are one change as far as the runs can tell:
   * two packs bought an hour apart are measured together, from before the first to after the last.
   */
  const breaks = forecast.regimeBreaks
  let lastBreak = breaks.at(-1) ?? null
  for (let index = breaks.length - 2; index >= 0 && lastBreak; index -= 1) {
    const earlier = breaks[index]
    const from = Date.parse(earlier.before)
    const to = Date.parse(lastBreak.after)
    if (perRun.some(run => Date.parse(run.runDate) > from && Date.parse(run.runDate) <= to)) break
    lastBreak = { after: earlier.after, before: lastBreak.before, reason: lastBreak.reason, ratio: earlier.ratio * lastBreak.ratio }
  }
  const check = measureCoinDrift({ runs: perRun, changedBetween: lastBreak })
  const warnings = [...check.warnings]
  if (undated > 0) warnings.push(`${undated} run${undated === 1 ? ' was' : 's were'} played before the oldest export on hand and predicted from it: the account then is assumed to be the account at that export`)
  if (unsettled > 0) warnings.push(`${unsettled} run${unsettled === 1 ? '' : 's'} had no export that shows the account as ${unsettled === 1 ? 'it was' : 'they were'} played: the coin bonus differs in the nearest one. Left out of the drift`)
  if (perRun.some(run => run.predictedWaveCoins == null)) warnings.push('some runs could not be predicted: the export nearest them has no Total Coin Bonus reading')
  return { ...check, warnings, tier, changedBetween: lastBreak, unfilled: [...COIN_SIMULATION_INPUTS_NOT_READ], coinWeights: weights, killScales, measuredShares }
}
