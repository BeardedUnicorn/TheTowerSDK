/**
 * Sets a save's recorded coins against what the coin model predicts, run by run.
 *
 * Each past run is predicted with the account as it stood when the run was played, taken from an
 * export kept at the time — today's state would credit an old run with a pack bought since. The
 * wave payout needs nothing more; kill coins are brought to the account's own level by a scale
 * fitted to its runs. Where income changed at once, the change is read against how much the
 * account's runs differ with nothing changed, which decides whether coin-bonus gains are discounted.
 */
