/**
 * Ranks what a save's account should buy next, across labs, workshop levels, enhancements and a
 * Dissonant run.
 *
 * The candidates come from the models that can price them; the income, the pass-through and the
 * Dissonance figures come from the account's own runs. This puts them together and hands the
 * pure ranker one list, so a coach asks once instead of once per kind of spend.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    SPENDS_WITHOUT_A_MODEL, rankSpendsFromSave
 * depends    src/mechanics/planning/spend-rank, src/mechanics/planning/types, src/save/planning/candidates, src/save/planning/coin-check, src/save/planning/dissonance, src/save/planning/forecast (+2 more)
 * used by    src/calculators/run-planning, src/save/planning/index, src/save/planning/plan
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { rankSpends } from '../../mechanics/planning/spend-rank'
import type { SpendCandidate, SpendKind, UnrankedSpend } from '../../mechanics/planning/types'
import { isDecodedSave, listEconomySpendCandidates, listSurvivalSpendCandidates } from './candidates'
import { checkCoinModelFromSave } from './coin-check'
import { priceDissonancePaybackFromSave } from './dissonance'
import { forecastIncomeFromSave } from './forecast'
import { readPlanningAccount } from './sources'
import type { SaveSpendRanking, SpendRankOptions } from './types'

/** Spends no model here can put a coins-per-day figure on, and why each is left unranked. */
export const SPENDS_WITHOUT_A_MODEL: readonly UnrankedSpend[] = [
  { candidate: 'Labs Speed and Labs Coin Discount', reason: 'they make every other lab faster or cheaper; no model here turns that into coins per day' },
  { candidate: 'Module slot levels', reason: 'no model here turns a module slot level into coins per day' },
  { candidate: 'Workshop unlocks, such as the Wall', reason: 'the wave survival model does not read the Wall, so its extra waves cannot be priced' },
  { candidate: 'Recovery Package enhancement', reason: 'the wave survival model reads workshop levels, not enhancements; the wiki says it multiplies both Max Recovery and Recovery Amount' },
  { candidate: 'Attack workshop levels', reason: 'the wave survival model fits incoming damage and healing, not how fast enemies die' },
  { candidate: 'In-run upgrades bought with cash', reason: 'they cost cash, not coins, and reset each run, so they are in neither queue; workshop.cashCostBetween prices a run of them' },
]

/**
 * The lab queue and the coin queue for a save's account.
 *
 * Economy candidates need `save` to be a decoded save; with a stored snapshot they are left out
 * and a warning says so. Survival candidates fit the wave survival model unless a calibration is
 * passed, which takes tens of seconds. A Dissonant run is ranked only when `dissonantWave` says
 * how far it is expected to go. Returns `null` when the save cannot be read or has no farm run
 * to forecast income from.
 */
export function rankSpendsFromSave(options: SpendRankOptions): SaveSpendRanking | null {
  const account = readPlanningAccount(options)
  const forecast = options.forecast ?? forecastIncomeFromSave(options)
  if (!account || !forecast || !forecast.coinsPerDay) return null
  const coinsPerDay = forecast.coinsPerDay.median
  const coinModel = options.coinModel === undefined ? checkCoinModelFromSave(options) : options.coinModel
  const passThrough = options.passThrough ?? coinModel?.passThrough ?? 1
  const wants = (kind: SpendKind) => !options.include || options.include.includes(kind)

  const candidates: SpendCandidate[] = []
  const notRanked: UnrankedSpend[] = []
  const warnings: string[] = []
  let runningGainPerSlotHour: Record<string, number> = {}

  if (wants('lab') || wants('enhancement')) {
    if (isDecodedSave(options.save)) {
      const economy = listEconomySpendCandidates(options.save, account.current, coinsPerDay, passThrough)
      candidates.push(...economy.candidates.filter(candidate => wants(candidate.kind)))
      notRanked.push(...economy.notRanked)
      warnings.push(...economy.warnings)
      runningGainPerSlotHour = economy.runningGainPerSlotHour
    }
    else {
      warnings.push('labs and enhancements were not ranked: the economy planner reads a decoded save, and a stored snapshot was given')
    }
  }
  if (wants('workshop')) {
    const survival = listSurvivalSpendCandidates({ ...options, coinModel }, account.current, forecast)
    candidates.push(...survival.candidates)
    notRanked.push(...survival.notRanked)
    warnings.push(...survival.warnings)
  }
  if (wants('dissonant-run')) {
    const payback = options.dissonantWave != null
      ? priceDissonancePaybackFromSave({ ...options, forecast, passThrough, waves: [options.dissonantWave] })
      : null
    const row = payback?.rows[0]
    if (payback && row) {
      candidates.push({
        candidate: `Dissonant run on tier ${payback.tier} to wave ${row.wave}`,
        kind: 'dissonant-run',
        coins: row.cost,
        cells: row.cellsCost,
        gainPerDay: { low: row.gainPerDay, likely: row.gainPerDay, high: row.gainPerDay },
        permanent: true,
        confidence: null,
        model: 'coin bonus row',
      })
    }
    else {
      notRanked.push({ candidate: 'Dissonant run', reason: 'its gain depends on the wave it reaches: pass the wave you expect, or see the Dissonance payback table' })
    }
  }
  if (wants('module') || wants('unlock') || wants('enhancement') || wants('workshop')) notRanked.push(...SPENDS_WITHOUT_A_MODEL)

  const ranking = rankSpends(candidates, notRanked)
  if (passThrough < 1) warnings.push(`coin-bonus gains are multiplied by a pass-through of ${passThrough.toFixed(2)}, measured from this account's runs`)
  return { ...ranking, warnings: [...ranking.warnings, ...warnings], coinsPerDay, passThrough, runningGainPerSlotHour }
}
