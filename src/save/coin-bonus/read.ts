/**
 * A save's Total Coin Bonus at a chosen tier — the x30.07 the Battle tab shows — row by row.
 *
 * The formula is `computeTotalCoinBonus`; this reads its inputs from the save so a caller with
 * an export and a tier gets the number the game shows without assembling ten readers.
 *
 * Which cosmetics pay is the part only a save can answer, and the part checked against the game
 * (game v29.2.2, 2026-11-24): the guild and event stores print +0.4% per tower, +0.8% per
 * background, +0.6% per menu, profile banner, guardian skin and event song, and the account's
 * Theme & Song Coin Bonus read x1.316. Its purchased cosmetics sum to exactly that, so slot 0 of
 * each kind (the default every account has, Orbie among guardians) and the six songs every
 * account plays pay nothing. Milestone tower themes sit in the tower slots and pay the tower rate.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    readTotalCoinBonusFromSaveRoot
 * depends    src/data, src/mechanics/coin-bonus/compute, src/mechanics/coin-bonus/types, src/save/access/values, src/save/cards/read, src/save/catalogs/themes (+9 more)
 * used by    src/save/coin-bonus/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { getTierData, SONGS } from '../../data'
import { computeTotalCoinBonus } from '../../mechanics/coin-bonus/compute'
import type { PaidCosmeticCounts, TotalCoinBonusInput } from '../../mechanics/coin-bonus/types'
import { coerceSaveNumber } from '../access/values'
import { listThemeCatalogRowsByCategory } from '../catalogs/themes'
import type { ThemeCatalogCategory } from '../catalogs/types'
import { readCardsFromSaveRoot } from '../cards/read'
import { readDissonanceBoostWavesByType } from '../dissonance/waves'
import { readLabsFromSaveRoot } from '../labs/read'
import { readModulesFromSaveRoot } from '../modules/read'
import { readPurchasesFromSaveRoot } from '../purchases/read'
import { readRelicsFromSaveRoot } from '../relics/read'
import { readThemesFromSaveRoot } from '../themes/read'
import { readWorkshopFromSaveRoot } from '../workshop/read'
import type { TotalCoinBonusSaveExtract } from './types'

const COIN_BONUS_ENHANCEMENT_KEY = 'WSP_COIN_BONUS'
const COIN_BONUS_RELIC_STAT = 'CoinBonus'

/** Research slugs this reads a level from. */
const LAB = {
  coinsMastery: 'coins_mastery',
  dissonantEcho: 'dissonant_echo_utility',
  primaryGenerator: 'primary_module_bonus_generator',
} as const

/** Song tracks sold in the event store: the bonus catalog's event songs, found in the save catalog by name. */
const EVENT_SONG_TRACKS: ReadonlySet<number> = (() => {
  const eventSongs = new Set(SONGS.filter(song => song.event === 'Event Store').map(song => song.name))
  return new Set(listThemeCatalogRowsByCategory('song')
    .filter(row => eventSongs.has(row.name))
    .map(row => row.catalogIndex))
})()

const COSMETIC_COUNT_KEYS: Readonly<Record<ThemeCatalogCategory, keyof PaidCosmeticCounts>> = {
  tower: 'tower',
  background: 'background',
  menu: 'menu',
  profileBanner: 'profileBanner',
  guardian: 'guardian',
  song: 'song',
}

function paysCoinBonus(category: ThemeCatalogCategory, index: number): boolean {
  return category === 'song' ? EVENT_SONG_TRACKS.has(index) : index >= 1
}

function countPaidCosmetics(root: Record<string, unknown>, warnings: string[]): PaidCosmeticCounts {
  const counts: PaidCosmeticCounts = { tower: 0, background: 0, menu: 0, profileBanner: 0, guardian: 0, song: 0 }
  const themes = readThemesFromSaveRoot(root)
  if (!themes) {
    warnings.push('No themes in the save; the Themes Bonus is 1.')
    return counts
  }
  warnings.push(...themes.warnings)
  for (const item of themes.unlocked) {
    if (paysCoinBonus(item.category, item.index)) counts[COSMETIC_COUNT_KEYS[item.category]] += 1
  }
  return counts
}

function researchLevel(levels: ReadonlyMap<string, number>, slug: string, warnings: string[]): number {
  const level = levels.get(slug)
  if (level !== undefined) return level
  warnings.push(`Research ${slug} is not in the save; read as level 0.`)
  return 0
}

function readPurchases(root: Record<string, unknown>, warnings: string[]): TotalCoinBonusInput['purchases'] {
  const purchases = readPurchasesFromSaveRoot(root)
  const owned = (flag: boolean | null | undefined, name: string): boolean => {
    if (flag == null) warnings.push(`The save does not say whether the ${name} was bought; read as not bought.`)
    return flag === true
  }
  const result = {
    hasDisableAds: owned(purchases?.hasDisableAds, 'No Ads purchase'),
    hasStarterPack: owned(purchases?.hasStarterPack, 'Starter Pack'),
    hasEpicPack: owned(purchases?.hasEpicPack, 'Epic Pack'),
  }
  if (!result.hasDisableAds) {
    warnings.push('The x1.5 from watching ads is timed and the export does not record it; Disable ads is 1.')
  }
  return result
}

function readCoinsCard(
  root: Record<string, unknown>,
  labLevels: ReadonlyMap<string, number>,
  warnings: string[],
): TotalCoinBonusInput['coinsCard'] {
  const coins = readCardsFromSaveRoot(root)?.cards.find(card => card.slug === 'coins')
  if (!coins) {
    warnings.push('No Coins card in the save; Active cards is 1.')
    return { equipped: false, level: 1, masteryUnlocked: false, masteryLevel: 0 }
  }
  return {
    equipped: coins.unlocked && coins.active,
    level: coins.level,
    masteryUnlocked: coins.masteryUnlocked,
    masteryLevel: coins.masteryUnlocked ? researchLevel(labLevels, LAB.coinsMastery, warnings) : 0,
  }
}

function readGenerator(
  root: Record<string, unknown>,
  labLevels: ReadonlyMap<string, number>,
  warnings: string[],
): TotalCoinBonusInput['generator'] {
  const equipped = readModulesFromSaveRoot(root)?.equipped ?? []
  if (equipped.some(module => module.role === 'assist' && module.category === 'Generator')) {
    warnings.push('An assist Generator is equipped. Modules counts the primary Generator only; '
      + 'how the game adds an assist to this row has not been checked.')
  }
  const primary = equipped.find(module => module.role === 'primary' && module.category === 'Generator')
  if (!primary) return null
  if (!primary.rarityLabel || !primary.level) {
    warnings.push('The equipped Generator has no readable rarity or level; Modules is 1.')
    return null
  }
  return {
    rarityLabel: primary.rarityLabel,
    level: primary.level,
    primaryLabLevel: labLevels.get(LAB.primaryGenerator) ?? 0,
  }
}

function readRelicCoinBonus(root: Record<string, unknown>, warnings: string[]): number {
  const relics = readRelicsFromSaveRoot(root)
  if (!relics) return 0
  warnings.push(...relics.warnings)
  // A mailed relic is held but pays nothing until claimed.
  return relics.relics
    .filter(relic => relic.unlocked && relic.state !== 'mailed' && relic.stat === COIN_BONUS_RELIC_STAT)
    .reduce((total, relic) => total + (relic.benefit ?? 0), 0)
}

/**
 * The Total Coin Bonus a save shows with `tier` selected, with every row of the All Coins
 * Bonuses panel.
 *
 * Without `tier`, the save's own `currentTier` — the tier selected on the Battle tab when the
 * export was written. Null for no save, or for no tier given and none this SDK knows in the
 * save; throws `RangeError` for a `tier` argument the game does not have.
 */
export function readTotalCoinBonusFromSaveRoot(
  root: Record<string, unknown> | null,
  tier?: number,
): TotalCoinBonusSaveExtract | null {
  if (!root) return null
  if (tier === undefined) {
    const saved = coerceSaveNumber(root.currentTier)
    if (saved === null || !getTierData(saved)) return null
    tier = saved
  }
  const warnings: string[] = []
  const labLevels = new Map<string, number>()
  for (const row of readLabsFromSaveRoot(root)?.researches ?? []) {
    if (row.slug) labLevels.set(row.slug, row.level)
  }

  const input: TotalCoinBonusInput = {
    tier,
    purchases: readPurchases(root, warnings),
    coinsCard: readCoinsCard(root, labLevels, warnings),
    generator: readGenerator(root, labLevels, warnings),
    paidCosmetics: countPaidCosmetics(root, warnings),
    relicCoinBonus: readRelicCoinBonus(root, warnings),
    coinBonusEnhancementLevel: readWorkshopFromSaveRoot(root)?.active.enhancementLevels[COIN_BONUS_ENHANCEMENT_KEY] ?? 0,
    dissonance: {
      coinBoostWaves: readDissonanceBoostWavesByType(root).utility,
      echoLevel: researchLevel(labLevels, LAB.dissonantEcho, warnings),
    },
  }
  return { input, bonus: computeTotalCoinBonus(input), warnings }
}
