/**
 * The player's tournament league and their record of past tournaments.
 *
 * `leagueID` counts leagues from 0 in the game's own order, Copper first, the order
 * `TOURNAMENT_LEAGUES` lists them in: a v29.2 export from a Gold-league account stores 2.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    tournamentLeagueForSaveId, readTournamentsFromSaveRoot
 * depends    src/data/tournaments/data, src/data/tournaments/types, src/save/access/values, src/save/tournaments/types
 * used by    src/calculators/specs.generated, src/save/tournaments/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { TOURNAMENT_LEAGUES } from '../../data/tournaments/data'
import type { TournamentLeague } from '../../data/tournaments/types'
import { coerceSaveNumber, readSaveListItems } from '../access/values'
import type { TournamentRecordSaveRow, TournamentsSaveExtract } from './types'

/** The league a save's 0-based league id names, or null for an id outside the known leagues. */
export function tournamentLeagueForSaveId(id: number | null): TournamentLeague | null {
  if (id === null || !Number.isInteger(id)) return null
  return TOURNAMENT_LEAGUES[id]?.league ?? null
}

function readBoolean(value: unknown): boolean | null {
  return typeof value === 'boolean' ? value : null
}

function readRecord(raw: unknown, warnings: string[], index: number): TournamentRecordSaveRow | null {
  if (!raw || typeof raw !== 'object') {
    warnings.push(`tournamentRecords[${index}] is not a record.`)
    return null
  }
  const row = raw as Record<string, unknown>
  const leagueId = coerceSaveNumber(row.leagueID)
  const league = tournamentLeagueForSaveId(leagueId)
  if (leagueId !== null && league === null) warnings.push(`tournamentRecords[${index}] names unknown league ${leagueId}.`)
  return {
    number: coerceSaveNumber(row.tournamentNumber),
    date: typeof row.date === 'string' ? row.date : null,
    league,
    leagueId,
    wave: coerceSaveNumber(row.wave),
    rank: coerceSaveNumber(row.rank),
  }
}

/** League and tournament history, or null for a save with no tournament data. */
export function readTournamentsFromSaveRoot(root: Record<string, unknown> | null): TournamentsSaveExtract | null {
  if (!root || !['leagueID', 'highestLeague', 'tournamentRecords'].some(key => key in root)) return null
  const warnings: string[] = []
  const leagueId = coerceSaveNumber(root.leagueID)
  const highestLeagueId = coerceSaveNumber(root.highestLeague)
  const records = readSaveListItems(root.tournamentRecords)
    .map((raw, index) => readRecord(raw, warnings, index))
    .filter((row): row is TournamentRecordSaveRow => row !== null)

  const league = tournamentLeagueForSaveId(leagueId)
  if (leagueId !== null && league === null) warnings.push(`leagueID ${leagueId} names no known league.`)
  return {
    league,
    leagueId,
    highestLeague: tournamentLeagueForSaveId(highestLeagueId),
    highestLeagueId,
    joined: readBoolean(root.tournamentJoined),
    playing: readBoolean(root.playing),
    records,
    warnings,
  }
}
