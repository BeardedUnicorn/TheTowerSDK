/** One equipped card: its slug and level. */
export interface SurvivalCardReading {
  slug: string
  level: number
}

/**
 * What the survival model needs from an account at one moment: workshop levels, equipped cards,
 * lab levels and the stored runs.
 *
 * Both a decoded save and a stored snapshot reduce to this, so the model reads either the same way.
 */
export interface SurvivalAccountReading {
  /** When the account was read, as an ISO date, or `null` when the source does not say. */
  takenAt: string | null
  /** Workshop levels of the active preset, by workshop table name. */
  workshopLevels: Record<string, number>
  equippedCards: SurvivalCardReading[]
  /** Lab levels by slug. A lab not researched is absent. */
  labLevels: Record<string, number>
  /** How many unlock groups each workshop tab has bought, or `null` when unknown. */
  unlockedGroups: { defense: number, utility: number } | null
  /** Raw run records, as `listImportableBattleRuns` returns them. */
  runs: Record<string, unknown>[]
  warnings: string[]
}

/** One real run, reduced to the totals the model reads. */
export interface SurvivalRunFacts {
  /** The run's `battleDate`, as an ISO date. */
  runDate: string
  tier: number
  wave: number
  /** Real seconds the run took. */
  realSeconds: number
  damageTaken: number
  /** Damage before mitigation: taken plus everything the defenses blocked. */
  damageBeforeMitigation: number
  /** Defense % blocked, as a share of blocked plus taken. */
  defensePercentShare: number
  /** Share of a hit still taken after the layers outside Defense %. */
  otherDamageTakenMultiplier: number
  packageHeal: number
  packages: number
  lifestealHeal: number
  regenHeal: number
  deathWaveHealth: number
  deathDefies: number
  wavesSkipped: number
  attackLevelSkips: number
  healthLevelSkips: number
  freeDefenseUpgrades: number
  freeUtilityUpgrades: number
  spawned: {
    basic: number, fast: number, tank: number, ranged: number, protector: number, boss: number,
    vampire: number, ray: number, scatter: number,
  }
  /** Share of all kills made by tower projectiles. */
  projectileKillShare: number
}

/** The rates a set of runs measured, each a median across them. */
export interface SurvivalMeasuredProfile {
  runs: number
  defensePercent: number
  otherDamageTakenMultiplier: number
  /** Chance of a package on a played wave, with the after-boss packages taken out. */
  packageChance: number
  waveSkipChance: number
  freeDefenseChance: number
  freeUtilityChance: number
  /** Real ordinary spawns over what the SDK's spawn model expects. */
  spawnCountScale: number
  spawnShares: { basic: number, fast: number, tank: number, ranged: number, protector: number }
  eliteScale: number
  eliteShares: { vampire: number, ray: number, scatter: number }
  projectileKillShare: number
  /** Share of the runs in which lifesteal healed anything. */
  lifestealActiveShare: number
}

export interface SurvivalStateOptions {
  /** Which runs to measure the account's rates from. Defaults to every farming run on the tier. */
  measureFrom?: readonly SurvivalRunFacts[]
}

/** A state built from an account, with what it could not resolve said out loud. */
export interface SurvivalStateReading {
  state: SurvivalState
  /** What the runs measured, or `null` when there were none and the state is derived alone. */
  measured: SurvivalMeasuredProfile | null
  assumptions: Partial<SurvivalAssumptions>
  /** Workshop tab discounts, in percent, for pricing. */
  discountPercent: { defense: number, utility: number }
  warnings: string[]
}

/** Why a stored run was left out of a fit. */
export interface SurvivalSkippedRun {
  runDate: string
  wave: number
  reason: string
}

export interface SurvivalHistoryOptions extends SurvivalFitOptions {
  /** The decoded save, or a stored snapshot. */
  save: unknown
  /** Earlier readings of the same account, any order: decoded saves or stored snapshots. */
  snapshots?: readonly unknown[]
  /** The tier to fit. Defaults to the tier of the most recent farming run. */
  tier?: number
  /**
   * How each run was played, by its `battleDate`. Run records do not say, so a run not named here
   * is taken as AFK.
   */
  runModes?: Readonly<Record<string, SurvivalMode | 'exclude'>>
  /** What a run `runModes` does not name is taken as. Defaults to `afk`. */
  unlabelledRuns?: SurvivalMode | 'exclude'
  /**
   * What to do with a run no pair of unchanged readings brackets. `skip`, the default, leaves it
   * out. `nearest` fits it against the reading taken closest to it — during it if there is one —
   * and says so in `warnings`.
   */
  unbracketedRuns?: 'skip' | 'nearest'
  /** The in-run levels an active run bought, by its `battleDate`. An active run without one is left out. */
  cashPolicies?: Readonly<Record<string, SurvivalCashPolicy>>
  /** Leave out runs shorter than this. Defaults to 100 waves. */
  minWave?: number
  /** Use at most this many of the most recent runs. Defaults to all of them. */
  maxRuns?: number
}

export interface SurvivalHistoryFit extends SurvivalFitResult {
  tier: number
  /** Runs that went into the fit. */
  runsUsed: number
  skipped: SurvivalSkippedRun[]
  warnings: string[]
}

