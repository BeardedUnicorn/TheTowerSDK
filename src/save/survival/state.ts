/**
 * Builds the simulator's starting state from an account.
 *
 * Two kinds of input meet here and they are kept apart. Workshop levels, equipped cards and labs
 * come from the reading. The account's rates — how much Defense % blocks, how often a package
 * arrives, what a wave spawns — come from what its runs measured, because the game has already
 * counted them. Without runs the rates fall back to the cards and say so in `warnings`.
 *
 * Not resolved, and reported: lab and perk multipliers on max health, and the Death Wave health
 * bonus. Both scale the health pool as a whole, which the fitted hit curves absorb.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    survivalRunsOnTier, survivalDefaultTier, buildSurvivalState, survivalReadingsMatch
 * depends    src/data/workshop/discount-normalize, src/data/workshop/progress-definitions, src/data/workshop/unlocks, src/mechanics/cards/effect-lookup, src/mechanics/effective-paths/eecon-stats, src/mechanics/effective-paths/workshop-values (+5 more)
 * used by    src/calculators/specs.generated, src/save/survival/from-save, src/save/survival/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { WORKSHOP_STATS_OPEN_FROM_START, WORKSHOP_UNLOCK_ROWS } from '../../data/workshop/unlocks'
import { getWorkshopStatDefinitions } from '../../data/workshop/progress-definitions'
import { workshopLabLevelToSectionDiscountPercent } from '../../data/workshop/discount-normalize'
import { cardLevelMultiplier, cardLevelPercentFraction, enemyBalanceSpawnMultiplier } from '../../mechanics/cards/effect-lookup'
import { waveSkipChance } from '../../mechanics/effective-paths/eecon-stats'
import { workshopStatValue } from '../../mechanics/effective-paths/workshop-values'
import { SURVIVAL_STATS } from '../../mechanics/survival/constants'
import type { SurvivalLevels, SurvivalStat, SurvivalState } from '../../mechanics/survival/types'
import { ordinarySpawnChancesForCoinMix } from '../../mechanics/waves/spawn-type-chances-coin-mix'
import { listSurvivalRunFacts, measureSurvivalProfile } from './history'
import type { SurvivalAccountReading, SurvivalRunFacts, SurvivalStateOptions, SurvivalStateReading } from './types'

const MODELLED = new Set<string>(SURVIVAL_STATS)

function cardLevel(reading: SurvivalAccountReading, slug: string): number {
  return reading.equippedCards.find(card => card.slug === slug)?.level ?? 0
}

function tableValue(stat: string, level: number): number {
  return workshopStatValue(stat, Math.max(0, Math.floor(level)))?.value ?? 0
}

/* A workshop upgrade takes free upgrades once its unlock group is bought and until it is maxed. */
function otherOpenTargets(reading: SurvivalAccountReading, tab: 'defense' | 'utility'): number {
  const unlocked = reading.unlockedGroups?.[tab]
  const open = new Set<string>(WORKSHOP_STATS_OPEN_FROM_START)
  for (const row of WORKSHOP_UNLOCK_ROWS) {
    if (row.category !== tab) continue
    /* With no unlock reading, an upgrade the player has levels in is taken as unlocked. */
    const bought = unlocked == null
      ? row.stats.some(stat => (reading.workshopLevels[stat] ?? 0) > 0)
      : row.order < unlocked
    if (bought) for (const stat of row.stats) open.add(stat)
  }
  let count = 0
  for (const definition of getWorkshopStatDefinitions()) {
    if (definition.category !== tab) continue
    const name = definition.label in reading.workshopLevels ? definition.label : definition.key
    if (MODELLED.has(name) || !open.has(name)) continue
    if ((reading.workshopLevels[name] ?? 0) < definition.maxLevel) count += 1
  }
  return count
}

/**
 * The runs of a reading that were finished farming runs on one tier, oldest first.
 *
 * `minWave` leaves out runs too short to say anything about survival.
 */
export function survivalRunsOnTier(reading: SurvivalAccountReading, tier: number, minWave = 100): SurvivalRunFacts[] {
  return listSurvivalRunFacts(reading.runs).filter(run => run.tier === tier && run.wave >= minWave)
}

/** The tier of the most recent finished farming run, or `null` with none. */
export function survivalDefaultTier(reading: SurvivalAccountReading): number | null {
  return listSurvivalRunFacts(reading.runs).at(-1)?.tier ?? null
}

/**
 * The state a run on `tier` would start from, for this account.
 *
 * Rates are measured from `options.measureFrom`, or from every finished farming run on the tier.
 * `warnings` names everything left at a default; a state with warnings still simulates, and the
 * calibration is what makes its predictions mean something.
 */
export function buildSurvivalState(
  reading: SurvivalAccountReading,
  tier: number,
  options: SurvivalStateOptions = {},
): SurvivalStateReading {
  const warnings = [...reading.warnings]
  const levels = {} as SurvivalLevels
  for (const stat of SURVIVAL_STATS) levels[stat] = Math.max(0, Math.floor(reading.workshopLevels[stat] ?? 0))

  const enemyBalance = cardLevel(reading, 'eb')
  const enemyBalanceMultiplier = enemyBalance > 0 ? enemyBalanceSpawnMultiplier(enemyBalance) : 1
  const packageAfterBoss = (reading.labLevels.package_after_boss ?? 0) >= 1
  const runs = options.measureFrom ?? survivalRunsOnTier(reading, tier)
  const measured = measureSurvivalProfile(runs, enemyBalanceMultiplier, packageAfterBoss)

  const card = (slug: string) => {
    const level = cardLevel(reading, slug)
    return level > 0 ? cardLevelPercentFraction(slug, level) : 0
  }
  const healthCard = cardLevel(reading, 'hp')
  const workshop = (stat: SurvivalStat | string) => tableValue(stat, reading.workshopLevels[stat] ?? 0)

  let defensePercentAdd = card('def')
  let packageChanceAdd = card('rpc')
  let waveSkip = 0
  const waveSkipCard = cardLevel(reading, 'ws')
  if (waveSkipCard > 0) for (let skips = 1; skips <= 8; skips += 1) waveSkip += skips * waveSkipChance(skips, true, waveSkipCard, false, 0)
  let freeDefense = workshop('Free Defense Upgrade') + card('freeups')
  let freeUtility = workshop('Free Utility Upgrade') + card('freeups')
  const coinMix = ordinarySpawnChancesForCoinMix(tier)
  let shares = {
    basic: coinMix.Basic / 100, fast: coinMix.Fast / 100, tank: coinMix.Tank / 100,
    ranged: coinMix.Ranged / 100, protector: coinMix.Protector / 100,
  }
  let eliteShares = { vampire: 1 / 3, ray: 1 / 3, scatter: 1 / 3 }
  let countScale = 1
  let eliteScale = 1
  let otherDamageTakenMultiplier = 1
  let projectileKillShare = 1

  if (measured) {
    defensePercentAdd = measured.defensePercent - workshop('Defense Percent')
    packageChanceAdd = measured.packageChance - workshop('Package Chance')
    waveSkip = measured.waveSkipChance
    freeDefense = measured.freeDefenseChance
    freeUtility = measured.freeUtilityChance
    shares = measured.spawnShares
    eliteShares = measured.eliteShares
    countScale = measured.spawnCountScale
    eliteScale = measured.eliteScale
    otherDamageTakenMultiplier = measured.otherDamageTakenMultiplier
    projectileKillShare = measured.projectileKillShare
  } else {
    warnings.push(
      `no finished farming runs on tier ${tier}: Defense %, package chance, wave skips, free upgrades and spawns `
      + 'come from the workshop and cards alone, and labs, perks and modules are left out of them',
    )
  }
  warnings.push('max health uses the workshop and the Health card only: lab, perk, relic and module multipliers are left to the calibration')
  warnings.push('the Death Wave health bonus is not read from the account and is left to the calibration')
  warnings.push('kill speed is the workshop Damage value, not the full eDamage model: a damage upgrade is not ranked reliably')

  const state: SurvivalState = {
    tier,
    levels,
    bonuses: {
      healthMultiplier: healthCard > 0 ? cardLevelMultiplier('hp', healthCard) : 1,
      healthRegenMultiplier: 1,
      defenseAbsoluteMultiplier: 1,
      defensePercentAdd,
      recoveryAmountAdd: 0,
      maxRecoveryAdd: 0,
      packageChanceAdd,
      lifestealMultiplier: 1,
      otherDamageTakenMultiplier,
    },
    spawn: { countScale, enemyBalanceMultiplier, shares, eliteScale, eliteShares },
    freeUpgrades: {
      defenseChance: freeDefense,
      utilityChance: freeUtility,
      otherDefenseTargets: otherOpenTargets(reading, 'defense'),
      otherUtilityTargets: otherOpenTargets(reading, 'utility'),
    },
    deathWave: { maxHealthFractionPerWave: 0, maxHealthFractionCap: 0 },
    packageAfterBoss,
    waveSkipChance: Math.min(0.95, Math.max(0, waveSkip)),
    effectiveDamage: Math.max(1, workshop('Damage')),
    effectiveDamageGrowthPerWave: 1,
    projectileKillShare,
  }

  const discount = (slug: string) => workshopLabLevelToSectionDiscountPercent(reading.labLevels[slug] ?? 0)
  return {
    state,
    measured,
    assumptions: measured ? { lifestealActive: measured.lifestealActiveShare >= 0.5 } : {},
    discountPercent: {
      defense: discount('workshop_defense_discount'),
      utility: discount('workshop_utility_discount'),
    },
    warnings,
  }
}

/** Whether two readings would start a run from the same modelled state: same levels, same cards. */
export function survivalReadingsMatch(a: SurvivalAccountReading, b: SurvivalAccountReading): boolean {
  for (const stat of SURVIVAL_STATS) {
    if ((a.workshopLevels[stat] ?? 0) !== (b.workshopLevels[stat] ?? 0)) return false
  }
  for (const stat of ['Damage', 'Free Defense Upgrade', 'Free Utility Upgrade']) {
    if ((a.workshopLevels[stat] ?? 0) !== (b.workshopLevels[stat] ?? 0)) return false
  }
  const cards = (reading: SurvivalAccountReading) =>
    reading.equippedCards.map(card => `${card.slug}:${card.level}`).sort().join(',')
  return cards(a) === cards(b)
}
