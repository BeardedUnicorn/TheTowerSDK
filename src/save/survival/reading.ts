/**
 * Reduces an account to what the survival model reads, from either source that holds one: a
 * decoded save, or a stored snapshot of reader output.
 *
 * A save keeps only today's workshop, labs and cards, but its run history reaches back thirty
 * runs. Fitting those runs needs the state each was played with, and the only record of that is a
 * snapshot taken at the time — so this reads snapshots as first-class input, not as an afterthought.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    isSurvivalSnapshot, readSurvivalAccountFromSnapshot, readSurvivalAccountFromSaveRoot, readSurvivalAccount
 * depends    src/save/battle/history, src/save/cards/read, src/save/export-info/read, src/save/labs/read, src/save/survival/types, src/save/workshop/read (+1 more)
 * used by    src/calculators/specs.generated, src/node/survival-snapshots, src/save/survival/from-save, src/save/survival/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { listImportableBattleRuns } from '../battle/history'
import { readCardsFromSaveRoot } from '../cards/read'
import { readExportInfoFromSaveRoot } from '../export-info/read'
import { readLabsFromSaveRoot } from '../labs/read'
import { readWorkshopFromSaveRoot } from '../workshop/read'
import { readWorkshopUnlocksFromSaveRoot } from '../workshop/unlocks'
import type { SurvivalAccountReading, SurvivalCardReading } from './types'

type Json = Record<string, unknown>

function isObject(value: unknown): value is Json {
  return value != null && typeof value === 'object' && !Array.isArray(value)
}

function levelsFrom(value: unknown): Record<string, number> {
  const out: Record<string, number> = {}
  if (!isObject(value)) return out
  for (const [key, level] of Object.entries(value)) {
    if (typeof level === 'number' && Number.isFinite(level)) out[key] = level
  }
  return out
}

function cardsFrom(value: unknown): SurvivalCardReading[] {
  if (!Array.isArray(value)) return []
  const out: SurvivalCardReading[] = []
  for (const card of value) {
    if (!isObject(card) || typeof card.slug !== 'string') continue
    const level = Number(card.level)
    if (Number.isFinite(level) && level > 0) out.push({ slug: card.slug, level })
  }
  return out
}

function labsFrom(value: unknown): Record<string, number> {
  const out: Record<string, number> = {}
  if (!Array.isArray(value)) return out
  for (const lab of value) {
    if (!isObject(lab) || typeof lab.slug !== 'string') continue
    const level = Number(lab.level)
    if (Number.isFinite(level) && level > 0) out[lab.slug] = level
  }
  return out
}

function unlockedFrom(value: unknown): { defense: number, utility: number } | null {
  if (!isObject(value) || !isObject(value.upgradeTiersUnlocked)) return null
  const defense = Number(value.upgradeTiersUnlocked.defense)
  const utility = Number(value.upgradeTiersUnlocked.utility)
  return Number.isFinite(defense) && Number.isFinite(utility) ? { defense, utility } : null
}

function assemble(
  takenAt: string | null,
  workshop: unknown,
  cards: unknown,
  labs: unknown,
  unlocks: unknown,
  runs: unknown,
): SurvivalAccountReading | null {
  const warnings: string[] = []
  const active = isObject(workshop) && isObject(workshop.active) ? workshop.active.levels : undefined
  const workshopLevels = levelsFrom(active)
  if (Object.keys(workshopLevels).length === 0) return null
  if (!isObject(cards)) warnings.push('cards not readable: card bonuses left out')
  if (!isObject(labs)) warnings.push('labs not readable: lab bonuses and workshop discounts left out')
  return {
    takenAt,
    workshopLevels,
    equippedCards: cardsFrom(isObject(cards) ? cards.equippedCards : undefined),
    labLevels: labsFrom(isObject(labs) ? labs.researches : undefined),
    unlockedGroups: unlockedFrom(unlocks),
    runs: Array.isArray(runs) ? runs.filter(isObject) : [],
    warnings,
  }
}

/** Whether a value is a stored snapshot — reader output plus runs — and not a decoded save. */
export function isSurvivalSnapshot(value: unknown): boolean {
  return isObject(value) && isObject(value.readers) && isObject(value.readers.readWorkshopFromSaveRoot)
}

/**
 * Read the account out of a stored snapshot: `{ meta, readers, runs }`, where `readers` holds the
 * output of the SDK's own save readers keyed by reader name. This is the shape the coaching skill
 * stores under `~/.tower-coach/snapshots`.
 *
 * Returns `null` when the snapshot has no workshop reading.
 */
export function readSurvivalAccountFromSnapshot(snapshot: unknown): SurvivalAccountReading | null {
  if (!isObject(snapshot) || !isObject(snapshot.readers)) return null
  const readers = snapshot.readers
  const meta = isObject(snapshot.meta) ? snapshot.meta : {}
  const takenAt = typeof meta.exportedAt === 'string'
    ? meta.exportedAt
    : typeof meta.snapshotAt === 'string' ? meta.snapshotAt : null
  return assemble(
    takenAt,
    readers.readWorkshopFromSaveRoot,
    readers.readCardsFromSaveRoot,
    readers.readLabsFromSaveRoot,
    readers.readWorkshopUnlocksFromSaveRoot,
    snapshot.runs,
  )
}

/**
 * Read the account out of a decoded save, through the save readers.
 *
 * Returns `null` when the save has no workshop to read. `takenAt` is the export's own timestamp,
 * and `null` for a save that does not carry one.
 */
export function readSurvivalAccountFromSaveRoot(root: unknown): SurvivalAccountReading | null {
  if (!isObject(root)) return null
  const quiet = <T>(read: () => T): T | null => {
    try { return read() } catch { return null }
  }
  return assemble(
    quiet(() => readExportInfoFromSaveRoot(root))?.exportedAt ?? null,
    quiet(() => readWorkshopFromSaveRoot(root)),
    quiet(() => readCardsFromSaveRoot(root)),
    quiet(() => readLabsFromSaveRoot(root)),
    quiet(() => readWorkshopUnlocksFromSaveRoot(root)),
    quiet(() => listImportableBattleRuns(root)),
  )
}

/** Read the account from whichever of the two a caller holds. */
export function readSurvivalAccount(source: unknown): SurvivalAccountReading | null {
  return isSurvivalSnapshot(source) ? readSurvivalAccountFromSnapshot(source) : readSurvivalAccountFromSaveRoot(source)
}
