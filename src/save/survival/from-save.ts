/**
 * The survival model as a caller with a save meets it: fit the account's own runs, predict a
 * death wave, rank upgrades.
 *
 * The mechanics take plain numbers; this is where a save, its stored snapshots and its run
 * history become those numbers. A run is fitted with the state it was played with, which only a
 * snapshot taken around it records — so a run whose state changed mid-run, or that no snapshot
 * brackets, is left out and named rather than fitted against the wrong account.
 */
