const DEFAULT_MIN_WAVE = 100

function timeOf(reading: SurvivalAccountReading): number | null {
  if (!reading.takenAt) return null
  const ms = Date.parse(reading.takenAt)
  return Number.isFinite(ms) ? ms : null
}

/**
 * The reading a run was played with, or why there is none.
 *
 * A run is bracketed by the last reading before it started and the first one after it ended. When
 * both exist and agree, that is the state. When they disagree the state changed mid-run. With no
 * dated readings at all — a lone save — the current reading is used and the caller is warned.
 */
export function survivalReadingForRun(
  run: SurvivalRunFacts,
  readings: readonly SurvivalAccountReading[],
): { reading: SurvivalAccountReading | null, reason: string | null } {
  const end = Date.parse(run.runDate)
  const start = end - run.realSeconds * 1000
  let before: SurvivalAccountReading | null = null
  let after: SurvivalAccountReading | null = null
  for (const reading of readings) {
    const at = timeOf(reading)
    if (at == null) continue
    if (at <= start && (!before || at > (timeOf(before) ?? 0))) before = reading
    if (at >= end && (!after || at < (timeOf(after) ?? Number.POSITIVE_INFINITY))) after = reading
  }
  if (before && after) {
    return survivalReadingsMatch(before, after)
      ? { reading: before, reason: null }
      : { reading: null, reason: 'workshop or cards changed between the readings around this run' }
  }
  if (!before && !after) return { reading: null, reason: 'no dated reading of the account' }
  return { reading: null, reason: before ? 'no reading after this run ended' : 'no reading before this run started' }
}

/**
 * The dated reading taken closest to a run: one taken during it if there is any, else the nearest
 * in time. Weaker evidence than a bracketing pair — it cannot show the state held for the whole run.
 */
export function survivalNearestReadingForRun(
  run: SurvivalRunFacts,
  readings: readonly SurvivalAccountReading[],
): SurvivalAccountReading | null {
  const end = Date.parse(run.runDate)
  const start = end - run.realSeconds * 1000
  let best: SurvivalAccountReading | null = null
  let bestDistance = Number.POSITIVE_INFINITY
  for (const reading of readings) {
    const at = timeOf(reading)
    if (at == null) continue
    const distance = at < start ? start - at : at > end ? at - end : 0
    if (distance < bestDistance) {
      best = reading
      bestDistance = distance
    }
  }
  return best
}

function readAll(save: unknown, snapshots: readonly unknown[] | undefined): { current: SurvivalAccountReading | null, readings: SurvivalAccountReading[] } {
  const current = readSurvivalAccount(save)
  const readings: SurvivalAccountReading[] = []
  for (const snapshot of snapshots ?? []) {
    const reading = readSurvivalAccount(snapshot)
    if (reading) readings.push(reading)
  }
  if (current) readings.push(current)
  return { current, readings }
}

/**
 * Fit the hit curves to the account's stored runs, each with the state it was played with.
 *
 * Returns `null` when the save has no workshop to read. With `snapshots`, only runs a pair of
 * readings brackets unchanged are fitted. Without any, every run is fitted against today's state
 * and `warnings` says so. Run records do not say whether a run was AFK or active: name the active
 * ones in `runModes` and give their bought levels in `cashPolicies`, or they are fitted as AFK.
 */
export function calibrateSurvivalFromHistory(options: SurvivalHistoryOptions): SurvivalHistoryFit | null {
  const { current, readings } = readAll(options.save, options.snapshots)
  if (!current) return null
  const tier = options.tier ?? survivalDefaultTier(current)
  const warnings: string[] = []
  if (tier == null) {
    return {
      calibration: fitSurvivalCalibration([]).calibration, perRun: [], leaveOneOutError: null, loss: 0,
      tier: 0, runsUsed: 0, skipped: [], warnings: ['no finished farming runs in this save: nothing to fit'],
    }
  }

  /* Runs live in every reading; the newest reading holds the most recent thirty. */
  const byDate = new Map<string, SurvivalRunFacts>()
  for (const reading of readings) {
    for (const run of survivalRunsOnTier(reading, tier, options.minWave ?? DEFAULT_MIN_WAVE)) byDate.set(run.runDate, run)
  }
  let runs = [...byDate.values()].sort((a, b) => a.runDate.localeCompare(b.runDate))
  if (options.maxRuns != null) runs = runs.slice(-Math.max(0, Math.floor(options.maxRuns)))

  const dated = readings.some(reading => timeOf(reading) != null) && (options.snapshots?.length ?? 0) > 0
  if (!dated) warnings.push('no stored snapshots: every run is fitted against the state in this save, which may not be the state it was played with')
  if (!options.runModes && !options.unlabelledRuns) warnings.push('run records do not say AFK or active: every run is fitted as AFK')

  const targets: SurvivalRunTarget[] = []
  const skipped: SurvivalSkippedRun[] = []
  for (const run of runs) {
    const mode = options.runModes?.[run.runDate] ?? options.unlabelledRuns ?? 'afk'
    if (mode === 'exclude') {
      skipped.push({ runDate: run.runDate, wave: run.wave, reason: 'excluded by the caller' })
      continue
    }
    const cashPolicy = options.cashPolicies?.[run.runDate]
    if (mode === 'active' && !cashPolicy) {
      skipped.push({ runDate: run.runDate, wave: run.wave, reason: 'active run with no bought levels given' })
      continue
    }
    let reading = current
    if (dated) {
      const paired = survivalReadingForRun(run, readings)
      const nearest = paired.reading || options.unbracketedRuns !== 'nearest' ? null : survivalNearestReadingForRun(run, readings)
      if (!paired.reading && !nearest) {
        skipped.push({ runDate: run.runDate, wave: run.wave, reason: paired.reason ?? 'no reading for this run' })
        continue
      }
      if (!paired.reading) warnings.push(`run ${run.runDate}: ${paired.reason}; fitted against the nearest reading instead`)
      reading = paired.reading ?? nearest ?? current
    }
    /* Account rates from every run but this one where there are others, so a run does not predict itself. */
    const others = runs.filter(other => other.runDate !== run.runDate)
    const built = buildSurvivalState(reading, tier, { measureFrom: others.length > 0 ? others : [run] })
    targets.push({
      runDate: run.runDate,
      wave: run.wave,
      damageTaken: run.damageTaken,
      packageHeal: run.packageHeal,
      packages: run.packages,
      state: {
        ...built.state,
        /* What this run itself recorded about how it was played, which no reading holds. */
        bonuses: {
          ...built.state.bonuses,
          defensePercentAdd: built.state.bonuses.defensePercentAdd
            + run.defensePercentShare - (built.measured?.defensePercent ?? run.defensePercentShare),
        },
      },
      mode,
      cashPolicy,
      assumptions: { lifestealActive: run.lifestealHeal > 0 },
    })
  }

  const fit = fitSurvivalCalibration(targets, options)
  return { ...fit, tier, runsUsed: targets.length, skipped, warnings }
}

/**
 * Predict the death wave of the account in a save: many seeded runs from its current state.
 *
 * Returns `null` when the save has no workshop to read or no tier can be chosen. Pass the
 * calibration from `calibrateSurvivalFromHistory`; without one the result rests on a placeholder
 * and `warnings` says so.
 */
export function simulateSurvivalRunFromSave(options: SurvivalSaveSimulationOptions): SurvivalSaveSimulation | null {
  const reading = readSurvivalAccount(options.save)
  if (!reading) return null
  const tier = options.tier ?? survivalDefaultTier(reading)
  if (tier == null) return null
  const built = buildSurvivalState(reading, tier)
  const warnings = [...built.warnings]
  if (!options.calibration) warnings.push('no calibration given: the death wave rests on a placeholder hit curve')
  const result = simulateSurvivalRun({
    state: built.state,
    mode: options.mode,
    calibration: options.calibration,
    seeds: options.seeds,
    baseSeed: options.baseSeed,
    rows: options.rows,
    cashPolicy: options.cashPolicy,
    assumptions: { ...built.assumptions, ...options.assumptions },
  })
  return { ...result, tier, warnings }
}

/**
 * Rank workshop purchases for the account in a save by waves gained per billion coins.
 *
 * Coins carry the account's Workshop Defense and Utility Discount labs, so they match the
 * Workshop screen. Returns `null` when the save has no workshop to read or no tier can be chosen.
 */
export function rankSurvivalUpgradesFromSave(options: SurvivalSaveRankOptions): SurvivalSaveRank | null {
  const reading = readSurvivalAccount(options.save)
  if (!reading) return null
  const tier = options.tier ?? survivalDefaultTier(reading)
  if (tier == null) return null
  const built = buildSurvivalState(reading, tier)
  const warnings = [...built.warnings]
  if (!options.calibration) warnings.push('no calibration given: the ranking rests on a placeholder hit curve')
  const result = rankSurvivalUpgrades({
    state: built.state,
    mode: options.mode,
    calibration: options.calibration,
    candidates: options.candidates,
    discountPercent: built.discountPercent,
    seeds: options.seeds,
    baseSeed: options.baseSeed,
    cashPolicy: options.cashPolicy,
    assumptions: { ...built.assumptions, ...options.assumptions },
  })
  return { ...result, tier, warnings }
}
