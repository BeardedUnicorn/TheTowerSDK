/**
 * What the stored runs measured.
 *
 * Every run record carries totals the model would otherwise have to derive: how much the defenses
 * blocked, how many packages arrived, how many waves were skipped, how many of each enemy
 * spawned. Where the game has already counted something, this reads the count instead of
 * modelling it — the account's own runs are better evidence than a formula for its rates.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    survivalRunDate, readSurvivalRunFacts, listSurvivalRunFacts, measureSurvivalProfile
 * depends    src/data/enemies/data, src/formatting/numbers/compute, src/mechanics/enemies/elite-spawn-chance, src/mechanics/waves/resolve-wave-spawn-yield, src/save/access/values, src/save/survival/types
 * used by    src/calculators/specs.generated, src/save/survival/index, src/save/survival/state
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { bossWaveIntervalForTier } from '../../data/enemies/data'
import { parseSaveDateTimeToMs } from '../../formatting/numbers/compute'
import { expectedEliteKillsPerWave } from '../../mechanics/enemies/elite-spawn-chance'
import { expectedEnemiesPerWaveFromAccount } from '../../mechanics/waves/resolve-wave-spawn-yield'
import { coerceSaveNumber, readSaveBoolean } from '../access/values'
import type { SurvivalMeasuredProfile, SurvivalRunFacts } from './types'

/*
 * A run field under any of the spellings an export has used: camelCase, PascalCase, and either
 * with the newer `ThisRound` suffix.
 */
function field(record: Record<string, unknown>, key: string): unknown {
  const pascal = key[0].toUpperCase() + key.slice(1)
  for (const name of [key, pascal, `${key}ThisRound`, `${pascal}ThisRound`]) {
    if (record[name] != null) return record[name]
  }
  return undefined
}

function num(record: Record<string, unknown>, key: string): number {
  return coerceSaveNumber(field(record, key)) ?? 0
}

function median(values: readonly number[]): number {
  const usable = values.filter(Number.isFinite).sort((a, b) => a - b)
  if (usable.length === 0) return 0
  const mid = Math.floor(usable.length / 2)
  return usable.length % 2 === 1 ? usable[mid] : (usable[mid - 1] + usable[mid]) / 2
}

/** A run's end as an ISO date, or `null` when its `battleDate` cannot be read. */
export function survivalRunDate(record: Record<string, unknown>): string | null {
  const ms = parseSaveDateTimeToMs(field(record, 'battleDate') ?? field(record, 'runDate'))
  return ms == null || !Number.isFinite(ms) ? null : new Date(ms).toISOString()
}

/**
 * One stored run as the totals the model reads, or `null` for a record that is not a finished
 * farming run: a tournament, a run with no date or wave, or one that took no damage — abandoned
 * rather than lost.
 */
export function readSurvivalRunFacts(record: Record<string, unknown>): SurvivalRunFacts | null {
  if (readSaveBoolean(field(record, 'isTournament'))) return null
  const runDate = survivalRunDate(record)
  const wave = num(record, 'wave')
  const damageTaken = num(record, 'damageTaken')
  if (!runDate || wave < 1 || damageTaken <= 0) return null

  const defenseBlocked = num(record, 'defensePercentBlocked')
  const otherBlocked = num(record, 'flameBotBlocked') + num(record, 'chronoFieldBlocked')
    + num(record, 'chainThunderBlocked') + num(record, 'primordialCollapseBlocked')
  const before = damageTaken + defenseBlocked + num(record, 'defenseAbsoluteBlocked') + otherBlocked
  const total = num(record, 'totalEnemies')
  return {
    runDate,
    tier: num(record, 'tier'),
    wave,
    realSeconds: num(record, 'realTime'),
    damageTaken,
    damageBeforeMitigation: before,
    defensePercentShare: defenseBlocked + damageTaken > 0 ? defenseBlocked / (defenseBlocked + damageTaken) : 0,
    otherDamageTakenMultiplier: before > 0 ? 1 - otherBlocked / before : 1,
    packageHeal: num(record, 'recoveryPackagesRegen'),
    packages: num(record, 'recoveryPackages'),
    lifestealHeal: num(record, 'lifesteal'),
    regenHeal: num(record, 'towerHealthRegen'),
    deathWaveHealth: num(record, 'healthFromDeathWaveThisRound'),
    deathDefies: num(record, 'deathDefy'),
    wavesSkipped: num(record, 'wavesSkipped'),
    attackLevelSkips: num(record, 'attackLevelSkips'),
    healthLevelSkips: num(record, 'healthLevelSkips'),
    freeDefenseUpgrades: num(record, 'freeDefenseUpgrades'),
    freeUtilityUpgrades: num(record, 'freeUtilityUpgrades'),
    spawned: {
      basic: num(record, 'totalBasic'),
      fast: num(record, 'totalFast'),
      tank: num(record, 'totalTank'),
      ranged: num(record, 'totalRanged'),
      protector: num(record, 'totalProtector'),
      boss: num(record, 'totalBoss'),
      vampire: num(record, 'totalVampires'),
      ray: num(record, 'totalRays'),
      scatter: num(record, 'totalScatters'),
    },
    projectileKillShare: total > 0 ? Math.min(1, num(record, 'destroyedByProjectiles') / total) : 0,
  }
}

/** Every finished farming run in a list of raw records, oldest first. */
export function listSurvivalRunFacts(records: readonly Record<string, unknown>[]): SurvivalRunFacts[] {
  const out: SurvivalRunFacts[] = []
  for (const record of records) {
    const facts = readSurvivalRunFacts(record)
    if (facts) out.push(facts)
  }
  return out.sort((a, b) => a.runDate.localeCompare(b.runDate))
}

/* What the SDK's spawn model expects over a run's waves, so a real count can be set against it. */
const EXPECTED_BY_KEY = new Map<string, { ordinary: number[], elite: number[] }>()

function expectedThrough(tier: number, enemyBalanceMultiplier: number, wave: number): { ordinary: number, elite: number } {
  const key = `${tier}|${enemyBalanceMultiplier}`
  let sums = EXPECTED_BY_KEY.get(key)
  if (!sums) {
    sums = { ordinary: [0], elite: [0] }
    EXPECTED_BY_KEY.set(key, sums)
  }
  for (let w = sums.ordinary.length; w <= wave; w += 1) {
    sums.ordinary[w] = sums.ordinary[w - 1]
      + expectedEnemiesPerWaveFromAccount({ wave: w, tier, enemyBalanceMult: enemyBalanceMultiplier })
    sums.elite[w] = sums.elite[w - 1] + expectedEliteKillsPerWave(tier, w)
  }
  return { ordinary: sums.ordinary[wave], elite: sums.elite[wave] }
}

/**
 * The account's rates as its runs measured them, each a median across the runs.
 *
 * `enemyBalanceMultiplier` is the Enemy Balance card's spawn multiplier, which the spawn model
 * needs before a real count can be compared with it. `packageAfterBoss` takes one package per
 * boss out of the package count, so what is left is the per-wave chance. Returns `null` with no
 * runs.
 */
export function measureSurvivalProfile(
  runs: readonly SurvivalRunFacts[],
  enemyBalanceMultiplier: number,
  packageAfterBoss: boolean,
): SurvivalMeasuredProfile | null {
  if (runs.length === 0) return null
  const share = (pick: (run: SurvivalRunFacts) => number, of: (run: SurvivalRunFacts) => number) =>
    median(runs.map((run) => { const whole = of(run); return whole > 0 ? pick(run) / whole : Number.NaN }))
  const ordinary = (run: SurvivalRunFacts) =>
    run.spawned.basic + run.spawned.fast + run.spawned.tank + run.spawned.ranged + run.spawned.protector
  const elites = (run: SurvivalRunFacts) => run.spawned.vampire + run.spawned.ray + run.spawned.scatter
  const played = (run: SurvivalRunFacts) => Math.max(1, run.wave - run.wavesSkipped)
  const playedShare = (run: SurvivalRunFacts) => played(run) / run.wave

  const shares = {
    basic: share(run => run.spawned.basic, ordinary),
    fast: share(run => run.spawned.fast, ordinary),
    tank: share(run => run.spawned.tank, ordinary),
    ranged: share(run => run.spawned.ranged, ordinary),
    protector: share(run => run.spawned.protector, ordinary),
  }
  const shareSum = shares.basic + shares.fast + shares.tank + shares.ranged + shares.protector || 1
  const eliteShares = {
    vampire: share(run => run.spawned.vampire, elites),
    ray: share(run => run.spawned.ray, elites),
    scatter: share(run => run.spawned.scatter, elites),
  }
  const eliteSum = eliteShares.vampire + eliteShares.ray + eliteShares.scatter || 1

  return {
    runs: runs.length,
    defensePercent: median(runs.map(run => run.defensePercentShare)),
    otherDamageTakenMultiplier: median(runs.map(run => run.otherDamageTakenMultiplier)),
    packageChance: Math.min(1, Math.max(0, median(runs.map((run) => {
      /* A boss is spawned only on a played boss wave, so the boss count is the after-boss packages. */
      const afterBoss = packageAfterBoss ? Math.min(run.spawned.boss, run.wave / bossWaveIntervalForTier(run.tier)) : 0
      return (run.packages - afterBoss) / played(run)
    })))),
    waveSkipChance: Math.min(0.95, share(run => run.wavesSkipped, run => run.wave)),
    freeDefenseChance: share(run => run.freeDefenseUpgrades, run => run.wave),
    freeUtilityChance: share(run => run.freeUtilityUpgrades, run => run.wave),
    spawnCountScale: median(runs.map((run) => {
      const expected = expectedThrough(run.tier, enemyBalanceMultiplier, run.wave).ordinary * playedShare(run)
      return expected > 0 ? ordinary(run) / expected : Number.NaN
    })) || 1,
    spawnShares: {
      basic: shares.basic / shareSum,
      fast: shares.fast / shareSum,
      tank: shares.tank / shareSum,
      ranged: shares.ranged / shareSum,
      protector: shares.protector / shareSum,
    },
    eliteScale: median(runs.map((run) => {
      const expected = expectedThrough(run.tier, enemyBalanceMultiplier, run.wave).elite * playedShare(run)
      return expected > 0 ? elites(run) / expected : Number.NaN
    })) || 1,
    eliteShares: {
      vampire: eliteShares.vampire / eliteSum,
      ray: eliteShares.ray / eliteSum,
      scatter: eliteShares.scatter / eliteSum,
    },
    projectileKillShare: median(runs.map(run => run.projectileKillShare)),
    lifestealActiveShare: runs.filter(run => run.lifestealHeal > 0).length / runs.length,
  }
}
