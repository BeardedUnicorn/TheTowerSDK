/**
 * Global Presets: the v29 feature that switches workshop, card, bot, module and guardian presets
 * together for a kind of battle (patch note 1541918021939892245; unlocked by a lab at T11 W60).
 *
 * The battle assignments (`tierPreset`, `tournamentPreset`, `dissonantPreset`) are reported as
 * stored. What a value outside `presets` means (no Global Preset selected, most likely) is not
 * established, so it is not interpreted here.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    readGlobalPresetsFromSaveRoot
 * depends    src/save/access/values, src/save/presets/types
 * used by    src/calculators/specs.generated, src/save/history/snapshot, src/save/presets/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { coerceSaveNumber, readSaveListItems } from '../access/values'
import type { GlobalPresetSaveRow, GlobalPresetsSaveExtract } from './types'

function readPreset(raw: unknown, index: number): GlobalPresetSaveRow | null {
  if (!raw || typeof raw !== 'object') return null
  const row = raw as Record<string, unknown>
  return {
    index,
    name: typeof row.presetName === 'string' ? row.presetName : `Preset ${index + 1}`,
    workshop: coerceSaveNumber(row.workshopIndex),
    cards: coerceSaveNumber(row.cardsIndex),
    bots: coerceSaveNumber(row.botsIndex),
    modules: coerceSaveNumber(row.modulesIndex),
    guardians: coerceSaveNumber(row.guardiansIndex),
  }
}

/** Global Presets and their battle assignments, or null for a save from before v29. */
export function readGlobalPresetsFromSaveRoot(root: Record<string, unknown> | null): GlobalPresetsSaveExtract | null {
  if (!root || !('globalPresets' in root)) return null
  const warnings: string[] = []
  const presets = readSaveListItems(root.globalPresets).flatMap((raw, index) => {
    const preset = readPreset(raw, index)
    if (!preset) warnings.push(`globalPresets[${index}] is not a record.`)
    return preset ? [preset] : []
  })
  return {
    presets,
    currentPreset: coerceSaveNumber(root.currentGlobalPreset),
    tierPreset: coerceSaveNumber(root.tierPreset),
    tournamentPreset: coerceSaveNumber(root.tournamentPreset),
    dissonantPreset: coerceSaveNumber(root.dissonantPreset),
    warnings,
  }
}
