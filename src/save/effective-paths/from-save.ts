/**
 * A save file to Effective Paths planner inputs.
 *
 * The planner takes two things: a `levels` record — what the player has bought
 * — and a `config` — what they own, have unlocked and have equipped. Both were
 * left to the caller, and the only worked example filled `levels` from labs
 * alone against a zero config. On a real account that mapped 31 of 48
 * candidates, gated every ultimate-weapon upgrade behind "the weapon is not
 * unlocked" on a save with all nine unlocked, and returned an empty plan.
 *
 * The eleven stone-band candidates are ultimate-weapon stat levels and the six
 * remaining time-band ones are bot, workshop-enhancement and module levels.
 * None are labs, which is why a labs-only pass could never reach them.
 *
 * What a save cannot answer stays the caller's to supply — `estimates` is what
 * the sheet asks a player for directly (kills a second, Black Hole kill share)
 * and no save records it. Those keep their model defaults. A candidate this
 * function could not fill is returned in `unmapped`, and a `config` input it
 * left at its default in `unfilledConfig`, rather than either being left as a
 * zero that reads like a real answer.
 *
 * The config matters as much as the levels. On a real v29.2.1 export this
 * returned a config whose economy came to exactly 0, so every step of the plan
 * had a gain and an ROI of 0 and the "plan" was the first candidate bought to
 * its cap. Two inputs did it: the Coins / Kill Bonus workshop VALUE was never
 * filled, and the Golden Bot was given its stat LEVELS where the model reads
 * VALUES — a Bonus of level 0 is 2.0x in the game and was a multiplier of 0
 * here.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    buildEffectiveEconomyInputsFromSave
 * depends    src/data/bots/data, src/data/workshop/enhancement-progress-definitions, src/mechanics/effective-paths/eecon-compute, src/mechanics/effective-paths/eecon-levels, src/mechanics/effective-paths/eecon-plan, src/mechanics/effective-paths/eecon-stats (+8 more)
 * used by    src/calculators/specs.generated, src/save/effective-paths/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
