/**
 * What an official export says about itself: its format, the build that wrote it, and its
 * save-data version.
 *
 * Read so a newer export can be flagged instead of read silently. The v29.2 export renamed the
 * module shard balances to `_v2` keys, and nothing noticed: every reader returned data, none
 * warned, and the shard balances were null. A data version newer than any this SDK has been
 * checked against is the earliest warning a caller can get that this may happen again.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    NEWEST_CHECKED_EXPORT, readExportInfoFromSaveRoot
 * depends    src/data/player-stats/fields.data, src/save/access/values, src/save/export-info/types
 * used by    src/calculators/specs.generated, src/save/export-info/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { PLAYER_DATA_FIELDS_BY_DOMAIN } from '../../data/player-stats/fields.data'
import { coerceSaveNumber } from '../access/values'
import type { ExportInfoSaveExtract } from './types'

/** Every save field the catalog names, as a decoded root spells it. */
const KNOWN_SAVE_FIELDS: ReadonlySet<string> = new Set(
  Object.values(PLAYER_DATA_FIELDS_BY_DOMAIN).flat().map(field => field.name),
)
/** Keys the decoder renames, which the catalog lists under the binary save's name. */
const DECODER_RENAMED_KEYS: ReadonlySet<string> = new Set(['inventory'])

/**
 * The newest official export this SDK has been checked against, field by field.
 *
 * v29.2.1 (build 1294, patch note 1572999340027420755) changed no save field, constant or game
 * table the SDK reads; the v29.2.0 facts hold for it unchanged.
 *
 * v29.2.2 (build 1296) was announced as a fix to tournament reward validation and nothing else. A
 * build 1296 export has the same 456 fields at data version 35, every reader returns without a
 * warning, and the game still defines the same 350 relics. Of the game tables, the vault upgrades
 * and card values were read again from build 1296 and match; the others were not read again.
 *
 * On 2026-11-24 the running build 1296 game was read screen by screen against a paired export
 * (facts/v29.2.2/live-ui-check.json): workshop costs, ultimate weapon costs and values, running
 * labs, card copies, equipped modules, perks, bots, relic totals, dissonant boosts and tier records.
 * The milestone tracks of tiers 1-15 were read the same day (facts/v29.2.2/milestone-screen.json).
 *
 * v29.2.3 (build 1301, patch note 1574821572844200137) was announced as a fix to new players being
 * shown the login screen, and nothing else. A build 1301 export written 2026-11-25 has the same 456
 * fields at data version 35, none the catalog does not name, the same 350 relics, and every reader
 * returns as it did for build 1296. The game's English text table is unchanged, all 4,515 entries.
 * Of the game tables, the vault upgrades, card values, daily mission goals and bot formulas were
 * read again from build 1301 and match; the others were not read again, and no screen was.
 */
export const NEWEST_CHECKED_EXPORT = {
  exportVersion: 1,
  versionNumber: 1301,
  dataVersion: 35,
  gameVersion: 'v29.2.3',
} as const

const EXPORT_INFO_KEYS = ['exportVersion', 'exportedAt', 'versionNumber', 'dataVersion'] as const

/** The export's own metadata, or null for a save that carries none of it. */
export function readExportInfoFromSaveRoot(root: Record<string, unknown> | null): ExportInfoSaveExtract | null {
  if (!root || !EXPORT_INFO_KEYS.some(key => key in root)) return null

  const warnings: string[] = []
  const exportVersion = coerceSaveNumber(root.exportVersion)
  const versionNumber = coerceSaveNumber(root.versionNumber)
  const dataVersion = coerceSaveNumber(root.dataVersion)
  const exportedAt = typeof root.exportedAt === 'string' && root.exportedAt.trim() ? root.exportedAt : null

  const newerFormat = exportVersion !== null && exportVersion > NEWEST_CHECKED_EXPORT.exportVersion
  const newerData = dataVersion !== null && dataVersion > NEWEST_CHECKED_EXPORT.dataVersion
  const newerBuild = versionNumber !== null && versionNumber > NEWEST_CHECKED_EXPORT.versionNumber
  if (newerFormat) {
    warnings.push(`Export format ${exportVersion} is newer than ${NEWEST_CHECKED_EXPORT.exportVersion}, the newest this SDK reads.`)
  }
  if (newerData) {
    warnings.push(
      `Save data version ${dataVersion} is newer than ${NEWEST_CHECKED_EXPORT.dataVersion} `
      + `(${NEWEST_CHECKED_EXPORT.gameVersion}); renamed fields may read as missing.`,
    )
  } else if (newerBuild) {
    warnings.push(
      `Game build ${versionNumber} is newer than ${NEWEST_CHECKED_EXPORT.versionNumber} `
      + `(${NEWEST_CHECKED_EXPORT.gameVersion}), the newest this SDK was checked against.`,
    )
  }

  // A top-level key the catalog does not name is a field this SDK has never seen: a new feature,
  // or a rename like the `_v2` shard balances, which read as missing until someone looks.
  const unknownKeys = Object.keys(root).filter(key => !KNOWN_SAVE_FIELDS.has(key) && !DECODER_RENAMED_KEYS.has(key))
  if (unknownKeys.length) warnings.push(`Fields this SDK does not know: ${unknownKeys.sort().join(', ')}.`)

  return {
    exportVersion,
    exportedAt,
    versionNumber,
    dataVersion,
    checked: !newerFormat && !newerData && !newerBuild,
    unknownKeys,
    warnings,
  }
}
