/**
 * Reads a folder of stored account readings for the wave survival model.
 *
 * A save keeps only today's workshop and cards, so fitting past runs needs the readings taken
 * around them. Those live on disk as one JSON file each — a stored snapshot of reader output, or
 * a kept `tool_export.json`. This is the one place the model touches the file system, which is
 * why it sits with the Node adapters and not with the save readers.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    readSurvivalSnapshotDirectory
 * depends    src/node/decode-save, src/node/types, src/save/survival/reading
 * used by    src/calculators/specs.generated, src/node/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import * as nodeFs from 'node:fs'
import * as path from 'node:path'

import { isSurvivalSnapshot, readSurvivalAccount } from '../save/survival/reading'
import { decodePlayerInfoSaveBytes } from './decode-save'
import type { SurvivalSnapshotDirectory, SurvivalSnapshotDirectoryOptions } from './types'

const DEFAULT_LIMIT = 60
const MAX_BYTES = 32 * 1024 * 1024

/**
 * Every reading in a folder that the survival model can use, newest files last.
 *
 * Takes `.json` files only, the `limit` most recently written. A stored snapshot is parsed as it
 * is; anything else is decoded as a game export. A file that is neither, is too large or cannot
 * be read is skipped and named in `warnings`. Never throws: a folder that cannot be listed
 * returns no readings and says why.
 */
export function readSurvivalSnapshotDirectory(
  directory: string,
  options: SurvivalSnapshotDirectoryOptions = {},
): SurvivalSnapshotDirectory {
  const fs = options.fs ?? nodeFs
  const warnings: string[] = []
  let names: string[]
  try {
    names = fs.readdirSync(directory).filter(name => name.toLowerCase().endsWith('.json'))
  }
  catch (error) {
    return { snapshots: [], files: [], warnings: [`could not list ${directory}: ${error instanceof Error ? error.message : String(error)}`] }
  }

  const dated: { name: string, at: number }[] = []
  for (const name of names) {
    try {
      const stats = fs.statSync(path.join(directory, name))
      if (!stats.isFile()) continue
      if (stats.size > MAX_BYTES) {
        warnings.push(`${name}: larger than ${MAX_BYTES} bytes, skipped`)
        continue
      }
      dated.push({ name, at: stats.mtimeMs })
    }
    catch {
      warnings.push(`${name}: could not be read, skipped`)
    }
  }
  dated.sort((a, b) => a.at - b.at || a.name.localeCompare(b.name))
  const limit = Math.max(1, Math.floor(options.limit ?? DEFAULT_LIMIT))
  if (dated.length > limit) warnings.push(`${dated.length} files; only the ${limit} most recent were read`)

  const snapshots: unknown[] = []
  const files: string[] = []
  for (const { name } of dated.slice(-limit)) {
    try {
      const bytes = fs.readFileSync(path.join(directory, name))
      let value: unknown = JSON.parse(Buffer.from(bytes).toString('utf8'))
      if (!isSurvivalSnapshot(value)) value = decodePlayerInfoSaveBytes(bytes).parsedRoot
      if (!readSurvivalAccount(value)) {
        warnings.push(`${name}: no workshop reading in it, skipped`)
        continue
      }
      snapshots.push(value)
      files.push(name)
    }
    catch (error) {
      warnings.push(`${name}: ${error instanceof Error ? error.message : String(error)}`)
    }
  }
  return { snapshots, files, warnings }
}
