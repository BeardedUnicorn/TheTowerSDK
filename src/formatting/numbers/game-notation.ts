/**
 * The game's suffix ladder, and a number written exactly as the game writes it on screen.
 *
 * `formatNumberForDisplay` and the `formatCompact` family round to the nearest hundredth and drop
 * trailing zeros, which suits a table of figures read side by side. The game does neither. Read off
 * v29.2.2 on 2026-11-24 (facts/v29.2.2/live-ui-check.json), every abbreviated amount on the
 * workshop, module, stats and tier screens is CUT to two decimals and keeps them: a Damage upgrade
 * costing 12,228,041 coins shows as 12.22M, not 12.23M; 25,200 shows as 25.20K, not 25.2K. A
 * tool that prints the SDK's number beside the game's had no way to make the two agree.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    COMPACT_NUMBER_SUFFIX_ORDER, compactNotationStep, formatGameNumber
 * depends    —
 * used by    src/formatting/numbers/compute, src/formatting/numbers/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */

/** The notations in order: `K` is 1e3 through `D` at 1e33, then `AA` (1e36) to `AZ` (1e111). */
export const COMPACT_NUMBER_SUFFIX_ORDER = [
  'K',
  'M',
  'B',
  'T',
  'q',
  'Q',
  's',
  'S',
  'O',
  'N',
  'D',
  ...Array.from({ length: 26 }, (_, tier) => `A${String.fromCharCode(65 + tier)}`),
] as const

/** The multiplier a notation stands for: `K` is 1e3, `D` is 1e33, `AZ` is 1e111. */
export function compactNotationStep(tier: number): number {
  return 10 ** (3 * (tier + 1))
}

/** Digits kept after the point in an abbreviated amount. */
const GAME_NOTATION_DECIMALS = 2

/**
 * A number as the game prints an amount: below 1000 a whole number, from 1000 the suffix ladder
 * with exactly two decimals, cut rather than rounded.
 *
 * - 12,228,041 is `12.22M`; 606,369,524,124,622,800,000 is `606.36Q`; 25,200 is `25.20K`.
 * - Below 1000 the game rounds to a whole number: a cost of 25.5 shows as `26`, 778.6 cells as `779`.
 *   Only from 1000 does the ladder start, so 999.6 is `1000`, as a whole number.
 * - Cutting never carries, so 999,999 is `999.99K`, never `1000.00K` or `1.00M`.
 *
 * This is for the amounts the game abbreviates: coins, cash, cells, damage and costs. Counts it
 * keeps as whole numbers — stones, shards, waves, waves skipped — it prints in full (`12000`,
 * `73783`), so pass those through `String()` instead. Non-finite input gives `'0'`, as
 * `formatCompact` does, and a number past `AZ` falls back to exponential.
 */
export function formatGameNumber(value: number): string {
  if (!Number.isFinite(value)) return '0'
  const sign = value < 0 ? '-' : ''
  const magnitude = Math.abs(value)
  if (magnitude < 1000) {
    const whole = Math.round(magnitude)
    return whole === 0 ? '0' : `${sign}${whole}`
  }

  const maxTier = COMPACT_NUMBER_SUFFIX_ORDER.length - 1
  if (magnitude >= compactNotationStep(maxTier + 1)) return `${sign}${magnitude.toExponential(GAME_NOTATION_DECIMALS)}`
  // log10 is inexact at the boundaries, so the tier it suggests is settled by comparison.
  let tier = Math.min(maxTier, Math.max(0, Math.floor(Math.log10(magnitude) / 3) - 1))
  while (tier < maxTier && magnitude >= compactNotationStep(tier + 1)) tier += 1
  while (tier > 0 && magnitude < compactNotationStep(tier)) tier -= 1

  const scale = 10 ** GAME_NOTATION_DECIMALS
  const scaled = (magnitude / compactNotationStep(tier)) * scale
  // Settle binary error before cutting: 25,200 / 1000 * 100 is 2519.9999999999995, which is 2520.
  const hundredths = Math.floor(Number(scaled.toFixed(6)))
  return `${sign}${(hundredths / scale).toFixed(GAME_NOTATION_DECIMALS)}${COMPACT_NUMBER_SUFFIX_ORDER[tier]}`
}
