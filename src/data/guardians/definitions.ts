/**
 * Guardian definitions built from the upgrade ladders: each guardian's stat names, values and
 * costs by level, and the bounds a level may take.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    getGuardianStatNames, getGuardianStatValues, getGuardianCostValues, getGuardianBaseValues, getGuardianStatBounds, getGuardianStatValueAt, getGuardianStatCostAt, buildGuardianDefinitions (+4 more)
 * depends    src/data/guardians/types, src/data/guardians/upgrades.data
 * used by    src/calculators/run, src/calculators/run-costs, src/calculators/specs.generated, src/data/guardians/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { guardianUpgrades } from './upgrades.data'
import type { GuardianDefinition } from './types'

function getNormalizedGuardianLevelInfo(upgrades: Array<{ level?: number | null }>): { sourceMinLevel: number; normalizedMaxLevel: number } {
  const sourceLevels = upgrades
    .map(upgrade => Number(upgrade.level))
    .filter(level => Number.isFinite(level))

  if (sourceLevels.length === 0) {
    return { sourceMinLevel: 0, normalizedMaxLevel: 0 }
  }

  const sourceMinLevel = Math.min(...sourceLevels)
  const sourceMaxLevel = Math.max(...sourceLevels)

  return {
    sourceMinLevel,
    normalizedMaxLevel: Math.max(0, sourceMaxLevel - sourceMinLevel),
  }
}

export function getGuardianStatNames(guardian: GuardianDefinition): string[] {
  return guardian.statOrder
}

function getGuardianLevelKeys(guardian: GuardianDefinition, statName: string): number[] {
  const stat = guardian.stats[statName]
  if (!stat) return []

  return Object.keys(stat.levels)
    .map(level => Number(level))
    .filter(level => Number.isFinite(level))
    .sort((a, b) => a - b)
}

export function getGuardianStatValues(guardian: GuardianDefinition): (string | number | null)[][] {
  return guardian.statOrder.map(statName => {
    const stat = guardian.stats[statName]
    if (!stat) return []

    const levelKeys = getGuardianLevelKeys(guardian, statName)
    const maxLevel = levelKeys.length > 0 ? Math.max(...levelKeys) : 0
    return Array.from({ length: maxLevel + 1 }, (_, level) => stat.levels[level]?.value ?? null)
  })
}

export function getGuardianCostValues(guardian: GuardianDefinition): (number | null)[][] {
  return guardian.statOrder.map(statName => {
    const stat = guardian.stats[statName]
    if (!stat) return []

    const levelKeys = getGuardianLevelKeys(guardian, statName)
    const maxLevel = levelKeys.length > 0 ? Math.max(...levelKeys) : 0
    return Array.from({ length: maxLevel + 1 }, (_, level) => stat.levels[level]?.cost ?? null)
  })
}

export function getGuardianBaseValues(guardian: GuardianDefinition): (string | number | null)[] {
  return guardian.statOrder.map(statName => guardian.stats[statName]?.base ?? null)
}

export function getGuardianStatBounds(guardian: GuardianDefinition, statIndex: number): { min: number; max: number } {
  const statName = guardian.statOrder[statIndex]
  if (!statName) return { min: 0, max: 0 }

  const stat = guardian.stats[statName]
  if (!stat) return { min: 0, max: 0 }

  const validLevels = Object.entries(stat.levels)
    .map(([level, entry]) => ({ level: Number(level), value: String(entry.value || '').trim() }))
    .filter(item => Number.isFinite(item.level) && item.value.length > 0)
    .map(item => item.level)

  if (validLevels.length === 0) return { min: 0, max: 0 }
  return { min: Math.min(...validLevels), max: Math.max(...validLevels) }
}

export function getGuardianStatValueAt(guardian: GuardianDefinition, statIndex: number, level: number): string | number | null {
  const statName = guardian.statOrder[statIndex]
  if (!statName) return null
  return guardian.stats[statName]?.levels[level]?.value ?? null
}

export function getGuardianStatCostAt(guardian: GuardianDefinition, statIndex: number, level: number): number | null {
  const statName = guardian.statOrder[statIndex]
  if (!statName) return null
  return guardian.stats[statName]?.levels[level]?.cost ?? null
}

const SPECIAL_STAT_COST_KEY_MAP: Record<string, Record<string, string>> = {
  attack: { percentage: 'attackCost' },
  ally: { recoveryAmount: 'recoveryCost' },
}

function formatGuardianStatName(name: string): string {
  return name.charAt(0).toUpperCase() + name.slice(1).replace(/([A-Z])/g, ' $1')
}

function formatGuardianLabel(key: string): string {
  return key.charAt(0).toUpperCase() + key.slice(1)
}

export function buildGuardianDefinitions(): GuardianDefinition[] {
  return Object.keys(guardianUpgrades).map(key => {
    const upgrades = guardianUpgrades[key as keyof typeof guardianUpgrades]
    const allKeys = Object.keys(upgrades[0])
    const statNames = allKeys.filter(name => name !== 'level' && !name.endsWith('Cost'))
    const specialMap = SPECIAL_STAT_COST_KEY_MAP[key] || {}
    const statToCostMap = Object.fromEntries(
      statNames.map(stat => [stat, specialMap[stat] || `${stat}Cost`]),
    )

    const { sourceMinLevel, normalizedMaxLevel } = getNormalizedGuardianLevelInfo(upgrades)
    const normalizedStatNames = statNames.map(formatGuardianStatName)
    const stats: Record<string, { base: string | number | null; levels: Record<number, { value: string | number | null; cost: number | null }> }> = {}

    statNames.forEach((rawStatName, index) => {
      const normalizedName = normalizedStatNames[index]
      const costKey = statToCostMap[rawStatName]
      const levels: Record<number, { value: string | number | null; cost: number | null }> = {}

      for (let level = 0; level <= normalizedMaxLevel; level += 1) {
        const sourceLevel = level + sourceMinLevel
        const upgrade = upgrades.find(item => item.level === sourceLevel)
        const value = upgrade ? (upgrade[rawStatName as keyof typeof upgrade] as string | number | null) : null
        const cost = upgrade ? (upgrade[costKey as keyof typeof upgrade] as number | null) : null
        levels[level] = { value, cost }
      }

      stats[normalizedName] = {
        base: levels[0]?.value ?? null,
        levels,
      }
    })

    return {
      key,
      label: formatGuardianLabel(key),
      statOrder: normalizedStatNames,
      stats,
    }
  })
}

const GUARDIAN_DEFINITIONS = buildGuardianDefinitions()

/** Letters and digits only, so `Max Recovery`, `maxRecovery` and `max-recovery` all match. */
const guardianNameKey = (value: string): string => value.toLowerCase().replace(/[^a-z0-9]+/g, '')

/**
 * A guardian chip's definition by its key or label — `attack`, `Attack` — or `null` when no chip
 * has that name. The functions above take the definition object; this is how a caller holding
 * only a name gets one.
 */
export function findGuardianDefinition(guardianKey: string): GuardianDefinition | null {
  const wanted = guardianNameKey(String(guardianKey ?? ''))
  if (!wanted) return null
  return GUARDIAN_DEFINITIONS.find(
    guardian => guardianNameKey(guardian.key) === wanted || guardianNameKey(guardian.label) === wanted,
  ) ?? null
}

function findGuardianStatIndex(guardian: GuardianDefinition, statName: string): number {
  const wanted = guardianNameKey(String(statName ?? ''))
  if (!wanted) return -1
  return guardian.statOrder.findIndex(name => guardianNameKey(name) === wanted)
}

/**
 * What one level of a guardian chip stat costs, by name.
 *
 * Levels count from 0: level 0 is the stat as the chip starts, and costs nothing. `level` is the
 * level being bought, so `guardianStatCost('attack', 'Percentage', 1)` is the first upgrade.
 * `null` for an unknown chip or stat, and for a level the ladder does not price — several stats
 * stop well before their chip's longest one.
 */
export function guardianStatCost(guardianKey: string, statName: string, level: number): number | null {
  const guardian = findGuardianDefinition(guardianKey)
  if (!guardian || !Number.isInteger(level) || level < 0) return null
  const statIndex = findGuardianStatIndex(guardian, statName)
  if (statIndex < 0) return null
  return getGuardianStatCostAt(guardian, statIndex, level)
}

/**
 * What it costs to take a guardian chip stat from `fromLevel` to `toLevel`.
 *
 * Sums the levels bought, `fromLevel + 1` through `toLevel`; `0` when the two are equal. `null`
 * for an unknown chip or stat, a level that is not a whole number, `toLevel` below `fromLevel`,
 * or any level past the stat's last — never a total that quietly stops at the cap.
 */
export function sumGuardianStatCostsBetween(
  guardianKey: string,
  statName: string,
  fromLevel: number,
  toLevel: number,
): number | null {
  if (!Number.isInteger(fromLevel) || !Number.isInteger(toLevel)) return null
  if (fromLevel < 0 || toLevel < fromLevel) return null
  // The starting level has to exist too, or a range from past the cap would total 0.
  if (guardianStatCost(guardianKey, statName, fromLevel) === null) return null

  let total = 0
  for (let level = fromLevel + 1; level <= toLevel; level += 1) {
    const step = guardianStatCost(guardianKey, statName, level)
    if (step === null) return null
    total += step
  }
  return total
}

/**
 * What it costs to finish a guardian chip: every stat taken from where it is to its last level.
 *
 * `fromLevels` is in the chip's stat order; a stat left out starts from level 0. `null` for an
 * unknown chip, or a starting level a stat does not have.
 */
export function sumGuardianAllStatCosts(guardianKey: string, fromLevels: readonly number[] = []): number | null {
  const guardian = findGuardianDefinition(guardianKey)
  if (!guardian) return null

  let total = 0
  for (const [statIndex, statName] of guardian.statOrder.entries()) {
    const { max } = getGuardianStatBounds(guardian, statIndex)
    const part = sumGuardianStatCostsBetween(guardianKey, statName, fromLevels[statIndex] ?? 0, max)
    if (part === null) return null
    total += part
  }
  return total
}
