/**
 * What a lab speed boost costs in cells, by multiplier.
 *
 * A boost is bought for one slot, for 1, 8 or 24 hours, and the price is the same per hour at
 * every length. These are the prices the Fandom wiki lists for a single lab ("Lab Upgrades",
 * read 2026-11-26), which since v25.5 is also the price of each further lab: that patch removed
 * the rule that every lab already boosted added 20% of the base price.
 *
 * NOT VERIFIED IN GAME. The game reads boost prices from remote config, so they can change
 * without a client update, and a second source (Game Vault) lists lower prices, a top multiplier
 * of 5 and the 20% rule still in force. Anything computed from this table should say so until a
 * player confirms the prices on their own screen.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    LAB_BOOST_CELLS_PER_HOUR, LAB_BOOST_MULTIPLIERS, LAB_BOOST_DURATION_HOURS, LAB_BOOST_PRICES_VERIFIED_IN_GAME, labBoostCellsPerHour
 * depends    src/support/own-lookup
 * used by    src/calculators/specs.generated, src/data/labs/index, src/save/planning/cells
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { ownLookup } from '../../support/own-lookup'

/** Cells for one hour of boost on one slot, by multiplier. */
export const LAB_BOOST_CELLS_PER_HOUR: Readonly<Record<string, number>> = {
  '1.5': 15,
  '2': 100,
  '3': 840,
  '4': 3_360,
  '5': 11_900,
  '6': 60_000,
  '7': 250_000,
  '8': 1_000_000,
}

/** The boost multipliers the table prices, lowest first. */
export const LAB_BOOST_MULTIPLIERS: readonly number[] = Object.keys(LAB_BOOST_CELLS_PER_HOUR).map(Number).sort((a, b) => a - b)

/** The lengths a boost is sold in, in hours. */
export const LAB_BOOST_DURATION_HOURS: readonly number[] = [1, 8, 24]

/** Whether the prices above have been confirmed on a game screen. They have not. */
export const LAB_BOOST_PRICES_VERIFIED_IN_GAME = false

/**
 * Cells per hour to hold one slot at `multiplier`, or `null` for a multiplier the table does not
 * price. 1x is no boost and costs nothing.
 */
export function labBoostCellsPerHour(multiplier: number): number | null {
  if (multiplier === 1) return 0
  return ownLookup(LAB_BOOST_CELLS_PER_HOUR, String(multiplier)) ?? null
}
