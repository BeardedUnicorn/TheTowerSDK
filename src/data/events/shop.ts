/**
 * What the event shop charges for themes, songs and relics.
 *
 * These are PRICES, and they are not the numbers on a relic. A relic's `unlockCost` (350, 700, 550,
 * 1100) is how many medals to EARN during its event to be given it; the shop sells the same relic
 * on a rerun for 200 or 500 medals, and sells rotating relics for gems. Reading the earn threshold
 * as the price answered "Dreamcatcher costs 350 medals" when the shop showed 200.
 *
 * Source: wiki "Events" → Event Shop and "Currency/Medals", and the game's own shop screen in
 * v29.2.2 (Howling Wolf event, 2026-11-24), which agree on every row except the song price, which
 * only the wiki states.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    EVENT_SHOP_PRICES, findEventShopPrice
 * depends    src/data/events/types
 * used by    src/calculators/run, src/data/events/index, src/knowledge/compartments/meta-game, src/save/events/relic-sets, src/save/events/shop
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import type { EventShopItemKind, EventShopPrice, EventShopPriceRow } from './types'

/**
 * Every fixed price in the event shop, one row per item kind and rarity.
 *
 * `relic` is the current event's own relics, sold for medals when the event is a rerun.
 * `rotatingRelic` is the "Rotating Relics" shelf: relics from other events, sold for gems for a
 * limited time. Bots, Bot+ and the gem, stone and shard trades are priced elsewhere
 * (`BOT_BASE_UNLOCK_COSTS`, `BOT_UPGRADES_DATA`).
 */
export const EVENT_SHOP_PRICES: readonly EventShopPriceRow[] = [
  { item: 'towerTheme', rarity: null, price: 150, currency: 'medals' },
  { item: 'backgroundTheme', rarity: null, price: 250, currency: 'medals' },
  { item: 'song', rarity: null, price: 200, currency: 'medals' },
  { item: 'relic', rarity: 'Rare', price: 200, currency: 'medals' },
  { item: 'relic', rarity: 'Epic', price: 500, currency: 'medals' },
  { item: 'rotatingRelic', rarity: 'Rare', price: 600, currency: 'gems' },
  { item: 'rotatingRelic', rarity: 'Epic', price: 1200, currency: 'gems' },
]

/**
 * The shop price of one kind of item, or null where the shop has no price for it.
 *
 * A relic kind needs its rarity; a rarity the shop does not sell (anything but Rare and Epic)
 * returns null rather than a guess.
 */
export function findEventShopPrice(item: EventShopItemKind, rarity: string | null = null): EventShopPrice | null {
  const row = EVENT_SHOP_PRICES.find(entry => entry.item === item && entry.rarity === rarity)
  return row ? { price: row.price, currency: row.currency } : null
}
