/**
 * What each gated workshop group costs to unlock, and in what order, so a calculator can price
 * the next "Unlock …" button rather than treat a locked upgrade as merely unbought.
 *
 * Most workshop upgrades are hidden behind a button that replaces the group until it is bought:
 * "Unlock Rend Armor 500.00B", "Unlock The Wall 500.00M". Each tab is one chain. A group is
 * offered only after the one before it, so how many groups a tab has unlocked says which
 * button it shows next.
 *
 * ## Where the numbers come from
 *
 * Every price is from the upgrade's own wiki page, read 2026-11-24 ("Unlocked in workshop for
 * 5000 coins after Lifesteal"). Two were also read off v29.2.2 on screen the same day, and both
 * agreed with the wiki (facts/v29.2.2/live-ui-check.json). All 21 gated groups have a wiki
 * price, so none is left out.
 *
 * The groups and their order match the save's own layout: `upgradeUnlockIndices` in
 * fixtures/data/save-format/workshop_save_format.json lists the same groups at the same slots,
 * and the 2026-11-24 export had attack flags 0-4 and defense flags 0-7 set, which is exactly
 * where the screen offered Rend Armor and The Wall.
 *
 * ## What this does not say
 *
 * - **The discount labs do not apply.** With the attack discount lab at 32 and the defense one at
 *   30, the buttons showed the full 500.00B and 500.00M. Do not run these through
 *   `computeDiscountedWorkshopCost`.
 * - **Button names were read for two groups only** ("Rend Armor", "The Wall"), so rows name the
 *   stats a button opens rather than the button.
 * - **Presets and respecs are not modelled.** The same export had The Wall unlocked at some time
 *   (`UpgradeDefenseTierEverUnlocked`) but not now. Whether a second workshop preset, or a respec,
 *   asks for the price again is not established.
 */
