/**
 * The workshop upgrades no button gates: open from the start of the game, per the wiki's
 * "Damage/Description", "Attack Speed", "Critical Hits", "Health" and "Health Regen" pages.
 * Every other `WORKSHOP_DATA` key is in exactly one `WORKSHOP_UNLOCK_ROWS` row.
 */
