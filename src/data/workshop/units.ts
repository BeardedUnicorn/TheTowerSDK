/**
 * A workshop upgrade's value at a level, in the game's unit, with the unit named.
 *
 * This is the workshop's own contribution: labs, relics, cards and modules are not in it (for the
 * number a Workshop row shows with those folded in, use `computeWorkshopScreenValue`). A `fraction`
 * is a chance where 1 is 100%, so Enemy Attack Level Skip at level 0 is 0.0005, the game's 0.05%.
 *
 * Returns `null` for an upgrade the table does not have or a level it has no row for.
 *
 * @unit named in the result: fraction, multiplier, count, seconds, meters, amount or unitless
 */
export function workshopGameValueAtLevel(
  stat: string,
  level: number,
): { value: number, unit: WorkshopValueUnit } | null {
  if (!Number.isInteger(level) || level < 0) return null
  const statUnit = ownLookup(WORKSHOP_STAT_UNITS, stat)
  const rows = ownLookup(WORKSHOP_DATA, stat)
  const row = rows && ownLookup(rows, String(level))
  if (!statUnit || !row) return null
  const { unit, tableDivisor, offset } = statUnit
  return { value: offset + row.value / tableDivisor, unit }
}
