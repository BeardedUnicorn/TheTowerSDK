/** One "Unlock …" button: the group of upgrades it opens on a workshop tab, and its coin price. */
export interface WorkshopUnlock {
  category: WorkshopCategory
  /**
   * Position in the tab's unlock chain, from 0. Each group is offered only once the one before it
   * is bought. The same number is the group's slot in the save's unlock flags
   * (`UpgradeTierUnlocked`, `UpgradeDefenseTierUnlocked`, `UpgradeUtilityTierUnlocked`).
   */
  order: number
  /** The upgrades the button opens, by their `WORKSHOP_DATA` key, in the game's own order. */
  stats: readonly string[]
  /** The price in coins, as a plain number. The workshop discount labs do not reduce it. */
  coins: number
  /** Where the price was read. */
  source: string
}

// from units.ts

/**
 * What a workshop value is, once it is out of the table's own storage unit.
 *
 * `fraction` is a chance or share where 1 is 100%: the screen prints it times 100 with a `%`.
 * `multiplier` is printed with an `x`. `amount` is a plain quantity (health, damage, cash, a size).
 * `unitless` is Knockback Force, which the game gives no unit for.
 */
export type WorkshopValueUnit = 'fraction' | 'multiplier' | 'count' | 'seconds' | 'meters' | 'amount' | 'unitless'

export interface WorkshopStatUnit {
  unit: WorkshopValueUnit
  /** Game value = `offset + tableValue / tableDivisor`. */
  tableDivisor: number
  /** Only Damage / Meter has one: the table holds thousandths over a multiplier of 1. */
  offset: number
  /** `screen`: read off the Workshop screen. `wiki`: the upgrade was locked, so the wiki's unit is used. */
  source: 'screen' | 'wiki'
}

