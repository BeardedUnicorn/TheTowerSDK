/** One "Unlock …" button: the group of upgrades it opens on a workshop tab, and its coin price. */
export interface WorkshopUnlock {
  category: WorkshopCategory
  /**
   * Position in the tab's unlock chain, from 0. Each group is offered only once the one before it
   * is bought. The same number is the group's slot in the save's unlock flags
   * (`UpgradeTierUnlocked`, `UpgradeDefenseTierUnlocked`, `UpgradeUtilityTierUnlocked`).
   */
  order: number
  /** The upgrades the button opens, by their `WORKSHOP_DATA` key, in the game's own order. */
  stats: readonly string[]
  /** The price in coins, as a plain number. The workshop discount labs do not reduce it. */
  coins: number
  /** Where the price was read. */
  source: string
}
