/**
 * The workshop cost curves: the price of every level of every workshop stat, and each stat's
 * maximum level.
 *
 * Read from `enhancement-costs.json`, the full ladder for every enhancement. This file used to hold
 * hand-typed copies of those ladders cut short at the pre-v28.3 caps (Damage at 400, Cash Bonus at
 * 300, Attack Speed at 75, ...). Game data v29.2.0 caps twelve enhancements at 600, Coin Bonus and
 * Cells / Kill at 300, Orb Size at 250, Free Upgrades at 150, Attack Speed at 100 and Enemy Level
 * Skips at 60, and every one of the JSON ladders is exactly that long
 * (`workshop-enhancement-caps.test.ts`).
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    WSP_ATTACK_COSTS, WSP_ATTACK_SPEED_COSTS, WSP_DEFENSE_COSTS, WSP_ORB_SIZE_COSTS, WSP_CASH_COSTS, WSP_COIN_CELL_COSTS, WSP_FREEUP_COSTS, WSP_RECOVERY_COSTS (+8 more)
 * depends    src/data/workshop/enhancement-costs.json, src/data/workshop/types
 * used by    src/calculators/specs.generated, src/data/workshop/compute, src/data/workshop/enhancement-progress-definitions, src/data/workshop/index, src/knowledge/compartments/workshop, src/mechanics/modules/els-upgrade-path
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import enhancementCosts from './enhancement-costs.json'
import type { WorkshopCostLevels } from './types'

const LADDER_BY_CURVE = new Map<string, WorkshopCostLevels>()

/**
 * A ladder from the JSON as `{ level: cost }`, where the cost at `level` buys level + 1.
 *
 * Identical curves come back as the same object, as the hand-typed tables were: twelve of the
 * eighteen enhancements share one curve, and the knowledge layer reads that sharing.
 */
function ladder(name: keyof typeof enhancementCosts.costs): WorkshopCostLevels {
  const costs = enhancementCosts.costs[name]
  const signature = costs.join(',')
  let table = LADDER_BY_CURVE.get(signature)
  if (!table) {
    table = Object.fromEntries(costs.map((cost, level) => [level, cost]))
    LADDER_BY_CURVE.set(signature, table)
  }
  return table
}

