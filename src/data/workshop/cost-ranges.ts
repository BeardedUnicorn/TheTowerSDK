/**
 * What a run of workshop upgrades costs, asked for by the stat's name and two levels: in coins for
 * the levels bought between runs, in cash for the levels bought inside one. The table prices one
 * level at a time, and a row's price is for the level after it.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    workshopCoinCostBetween, workshopCashCostBetween
 * depends    src/data/workshop/table, src/support/own-lookup
 * used by    src/calculators/run-costs, src/data/workshop/index, src/save/workshop/account-prices
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { ownLookup } from '../../support/own-lookup'
import { WORKSHOP_DATA } from './table'

/* Sums one price column over rows `fromLevel` up to, not including, `toLevel`; `null` as the callers document. */
function costBetween(stat: string, fromLevel: number, toLevel: number, column: 'coins' | 'cash'): number | null {
  const rows = ownLookup(WORKSHOP_DATA, stat)
  if (!rows) return null
  if (!Number.isInteger(fromLevel) || !Number.isInteger(toLevel)) return null
  if (fromLevel < 0 || toLevel < fromLevel) return null
  if (!ownLookup(rows, String(toLevel))) return null

  let total = 0
  for (let level = fromLevel; level < toLevel; level += 1) {
    const row = ownLookup(rows, String(level))
    if (!row) return null
    total += row[column]
  }
  return total
}

/**
 * Coins, at list price, to take a workshop upgrade from `fromLevel` to `toLevel`.
 *
 * A row's `coins` buys the NEXT level, so the sum runs over rows `fromLevel` up to, not including,
 * `toLevel`. List price: the workshop discount labs are not applied, and the rows are summed as
 * stored, unrounded. For the price the Workshop shows, with the tab's discount applied to each
 * level and rounded as the game does, use `computeWorkshopUpgradePrice`. `0` when the two levels are
 * equal; `null` for a stat the table does not have, a level that is not a whole number, `toLevel`
 * below `fromLevel`, or a level past the stat's last row.
 */
export function workshopCoinCostBetween(stat: string, fromLevel: number, toLevel: number): number | null {
  return costBetween(stat, fromLevel, toLevel, 'coins')
}

/**
 * Cash, at the table's price, to take an upgrade from `fromLevel` to `toLevel` inside a run.
 *
 * The levels are the run's own: a run starts each upgrade at its workshop level, and free upgrades
 * and cash raise it from there, so `fromLevel` is the level the upgrade stands at in the run, not
 * how many levels were bought. A row's `cash` buys the NEXT level, so the sum runs over rows
 * `fromLevel` up to, not including, `toLevel`. The rows are the game's base cash costs, summed as
 * stored; nothing here lowers them, and no source read so far names an effect that does. The
 * workshop discount labs are coin discounts and are not applied. `0` when the two levels are
 * equal; `null` for a stat the table does not have, a level that is not a whole number, `toLevel`
 * below `fromLevel`, or a level past the stat's last row. The last row's own `cash` is never
 * summed: it is above zero on most upgrades, and there is no level after it to buy.
 */
export function workshopCashCostBetween(stat: string, fromLevel: number, toLevel: number): number | null {
  return costBetween(stat, fromLevel, toLevel, 'cash')
}
