/**
 * What the Workshop charges for one or several levels of a regular upgrade.
 *
 * The buy multiplier (x1, x5, x10, x100) is not a discount and not a separate table. The game
 * prices each level as it would alone, section discount applied and rounded, and adds them up;
 * when fewer levels are left than the multiplier asks for, it sells what is left. All 60 prices
 * read off the Workshop screen on 2026-11-25 are that sum. Discounting the total once instead is
 * a coin or more out at low levels: Health Regen from level 0 at x5 is 405, not 404.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    computeWorkshopUpgradePrice
 * depends    src/data/workshop/discounted-costs, src/data/workshop/table, src/data/workshop/types, src/support/own-lookup
 * used by    src/calculators/run, src/data/workshop/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { ownLookup } from '../../support/own-lookup'
import { computeDiscountedWorkshopCost } from './discounted-costs'
import { WORKSHOP_DATA } from './table'
import type { WorkshopUpgradePrice } from './types'

/**
 * Coins to buy `count` levels of a regular workshop upgrade from `fromLevel`.
 *
 * `sectionDiscountPercent` is the tab's discount as a percentage, 15 for 15%: the Workshop Attack,
 * Defense or Utility Discount lab, through `workshopLabLevelToSectionDiscountPercent`. A row's
 * `coins` buys the next level, so level L is paid for on row L.
 *
 * Returns `null` for an upgrade the table does not have, a level it has no row for, or a count
 * below 1. At the last level `levels` and `coins` are 0. Unlock prices and enhancements are not
 * priced here. For the undiscounted list price between two named levels, see
 * `workshopCoinCostBetween`.
 */
export function computeWorkshopUpgradePrice(
  stat: string,
  fromLevel: number,
  count = 1,
  sectionDiscountPercent = 0,
): WorkshopUpgradePrice | null {
  if (!Number.isInteger(fromLevel) || fromLevel < 0 || !Number.isInteger(count) || count < 1) return null
  const rows = ownLookup(WORKSHOP_DATA, stat)
  if (!rows || !ownLookup(rows, String(fromLevel))) return null

  let coins = 0
  let level = fromLevel
  // The last row has no next level to sell, and is the only one without a price.
  while (level - fromLevel < count && ownLookup(rows, String(level + 1))) {
    coins += computeDiscountedWorkshopCost(rows[String(level)].coins, sectionDiscountPercent)
    level += 1
  }
  return { stat, fromLevel, toLevel: level, levels: level - fromLevel, coins }
}
