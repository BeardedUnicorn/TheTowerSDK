/** Which catalog a series is drawn from. */
export type ChartSeriesFamily =
  | 'lab' | 'workshop' | 'card' | 'ultimate-weapon' | 'bot' | 'guardian'
  | 'module' | 'enhancement' | 'vault' | 'unlock-ladder'

/** One point of a series: a level, and the value the catalog holds at it. */
export interface ChartSeriesPoint {
  x: number
  /** A number where the catalog stores one; otherwise the catalog's own text, such as `x9.4` or `119:26:00`. */
  y: number | string
}

/** What a series is, without its points. */
export interface ChartSeriesDescriptor {
  /** Stable address: `family:entity:metric`, with a stat between where an entity has several. */
  id: string
  family: ChartSeriesFamily
  /** The thing the series belongs to, as its catalog keys it: a lab slug, a bot name. */
  entity: string
  /** The field plotted: `cost`, `duration`, `value`. */
  metric: string
  /** A name for a chart heading. */
  title: string
  xLabel: string
  yLabel: string
  /** The unit, only where the catalog states one. */
  unit?: string
  /** How many points the series has. */
  points: number
}

/** A series with its points. */
export interface ChartSeries extends ChartSeriesDescriptor {
  data: readonly ChartSeriesPoint[]
}

/** Narrows a listing of series. Every field left out matches everything. */
export interface ChartSeriesFilter {
  family?: ChartSeriesFamily
  entity?: string
  metric?: string
  /** Leave out series with fewer points than this; 2 drops the single-point ones. */
  minPoints?: number
}
