/**
 * What the next ultimate weapon costs to unlock, so a calculator can price it.
 *
 * The price belongs to the purchase, not the weapon: the wiki's "Ultimate Weapons" page (Buying)
 * says it is set by how many weapons are already owned, and each purchase offers three weapons
 * at random. So the ladder is indexed by the count owned, and there is no per-weapon price to
 * look up.
 *
 * The ladder lived only in the knowledge entry point, which nothing may import, so no calculator
 * could reach it. It lives here now. `@beardedunicorn/thetowersdk/knowledge` still exports it as
 * `ULTIMATE_WEAPON_STONE_COST`, its released name, and that is this same array rather than a
 * copy. The name changed on the way in because `_COST` is a single number everywhere else in
 * this entry point; `_BY_OWNED` says what the index is, as `UW_PLUS_UNLOCK_STONE_COSTS_BY_OWNED`
 * already does for the plus ladder.
 *
 * Checked against v29.2.2 on 2026-11-24: with 6 of 9 weapons owned the workshop showed
 * "New Ultimate Weapon 1750", the seventh entry (facts/v29.2.2/live-ui-check.json).
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    ULTIMATE_WEAPON_UNLOCK_STONE_COSTS_BY_OWNED, getNextUltimateWeaponStoneCost
 * depends    —
 * used by    src/data/ultimate-weapons/index, src/knowledge/compartments/ultimate-weapons
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */

/**
 * Power stones to unlock the next ultimate weapon, indexed by how many are already owned: the
 * first costs 5, the ninth 3000. Read off the wiki's "Ultimate Weapons" page on 2026-08-16.
 */
export const ULTIMATE_WEAPON_UNLOCK_STONE_COSTS_BY_OWNED = [5, 50, 150, 300, 800, 1250, 1750, 2400, 3000] as const

/**
 * Stones for the next ultimate weapon when `owned` are already unlocked.
 *
 * `null` once all nine are owned, and for a count that is not a whole number from 0 to 9 — a
 * negative or fractional count is a caller's mistake, and answering it with the nearest price
 * would hide that.
 */
export function getNextUltimateWeaponStoneCost(owned: number): number | null {
  if (!Number.isInteger(owned) || owned < 0) return null
  return ULTIMATE_WEAPON_UNLOCK_STONE_COSTS_BY_OWNED[owned] ?? null
}
