/**
 * Power stones to unlock the next ultimate weapon, indexed by how many are already owned: the
 * first costs 5, the ninth 3000. Read off the wiki's "Ultimate Weapons" page on 2026-08-16.
 */
export const ULTIMATE_WEAPON_UNLOCK_STONE_COSTS_BY_OWNED = [5, 50, 150, 300, 800, 1250, 1750, 2400, 3000] as const

/**
 * Stones for the next ultimate weapon when `owned` are already unlocked.
 *
 * `null` once all nine are owned, and for a count that is not a whole number from 0 to 9 — a
 * negative or fractional count is a caller's mistake, and answering it with the nearest price
 * would hide that.
 */
export function getNextUltimateWeaponStoneCost(owned: number): number | null {
  if (!Number.isInteger(owned) || owned < 0) return null
  return ULTIMATE_WEAPON_UNLOCK_STONE_COSTS_BY_OWNED[owned] ?? null
}

/**
 * Power stones to unlock the next ultimate weapon plus, indexed by how many pluses are already
 * owned: the first costs 500, the ninth 3800, 14,650 for all nine. Read off the wiki's
 * "Ultimate Weapons/Ultimate Weapon Plus" page (Unlocking) on 2026-11-24.
 *
 * The page also says pluses can be bought only once all nine weapons are owned. This array does
 * not encode that gate; it prices the purchase once it is open.
 */
export const UW_PLUS_UNLOCK_STONE_COSTS_BY_OWNED = [500, 625, 750, 975, 1250, 1650, 2200, 2900, 3800] as const

/**
 * Stones for the next ultimate weapon plus when `ownedPlusCount` pluses are already unlocked.
 *
 * `null` once all nine are owned, and for a count that is not a whole number from 0 to 9, for
 * the same reason as {@link getNextUltimateWeaponStoneCost}.
 */
export function getNextUltimateWeaponPlusStoneCost(ownedPlusCount: number): number | null {
  if (!Number.isInteger(ownedPlusCount) || ownedPlusCount < 0) return null
  return UW_PLUS_UNLOCK_STONE_COSTS_BY_OWNED[ownedPlusCount] ?? null
}

function sumUnlockLadder(
  priceAt: (owned: number) => number | null,
  ownedFrom: number,
  ownedTo: number,
): number | null {
  if (!Number.isInteger(ownedFrom) || !Number.isInteger(ownedTo)) return null
  if (ownedFrom < 0 || ownedTo < ownedFrom) return null

  let total = 0
  for (let owned = ownedFrom; owned < ownedTo; owned += 1) {
    const price = priceAt(owned)
    if (price === null) return null
    total += price
  }
  return total
}

/**
 * Stones to go from owning `ownedFrom` ultimate weapons to owning `ownedTo`.
 *
 * Each purchase is priced by how many are already owned, so this is the sum of the ladder's
 * entries `ownedFrom` up to, not including, `ownedTo`: `(0, 9)` is all nine, 9,705 stones.
 * `0` when the two are equal; `null` for a count that is not a whole number from 0 to 9, or
 * `ownedTo` below `ownedFrom`.
 */
export function sumUltimateWeaponUnlockStones(ownedFrom: number, ownedTo: number): number | null {
  return sumUnlockLadder(getNextUltimateWeaponStoneCost, ownedFrom, ownedTo)
}

/**
 * Stones to go from owning `ownedFrom` ultimate weapon pluses to owning `ownedTo`: `(0, 9)` is
 * all nine, 14,650 stones.
 *
 * Prices the purchases only. The game offers pluses once all nine weapons are owned, and this
 * does not check that.
 */
export function sumUltimateWeaponPlusUnlockStones(ownedFrom: number, ownedTo: number): number | null {
  return sumUnlockLadder(getNextUltimateWeaponPlusStoneCost, ownedFrom, ownedTo)
}
