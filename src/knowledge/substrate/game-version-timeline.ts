/**
 * Which build of the game was live when a claim was read.
 *
 * ## The gap this closes
 *
 * A game-sourced claim carries `sourceVersion: 'v28.3.0'`, so when a new
 * dump lands you can tell at a glance which claims were checked against the old
 * one. A wiki claim carried only `verifiedAt`, a calendar date — and a calendar
 * date says nothing about whether the developers have rebalanced since.
 *
 * That asymmetry meant the weakest claims were the ones you could not age. The
 * fix is not to hand-stamp 219 wiki sources, which would be transcription and
 * would drift the moment anyone added a claim. It is to record WHEN EACH BUILD
 * WAS LIVE, once, and derive every stamp from the date already on the claim.
 *
 * ## Reading this honestly
 *
 * A stamp says "this was read while build X was live". It does NOT say the
 * claim was true of build X, and it does not say a wiki page had caught up to
 * build X — pages lag patches by months, and `fandom:Rapid Fire` was last
 * edited in 2024. It tells you one thing precisely: whether the game has been
 * rebuilt since anybody looked.
 *
 * `until: null` means the build is current. Add the next entry when a dump
 * lands, and every claim read before it is instantly identifiable as older than
 * the game — which is the whole point.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    GAME_VERSION_TIMELINE, gameVersionOn, CURRENT_GAME_VERSION, readAgainstOlderBuild
 * depends    src/knowledge/substrate/types
 * used by    src/knowledge/substrate/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import type { GameVersionWindow } from './types'

/**
 * Known builds, oldest first, one window per minor version.
 *
 * Each window opens on the day the developers' own patch-notes channel says the build was out,
 * and closes the day before the next one. Hotfixes inside a minor version (29.1.1 .. 29.1.4) stay
 * in their minor's window: they fix bugs rather than rebalance, and a window per hotfix would
 * claim a precision the notes do not give.
 *
 * Dates before v28.3.0 are left out on purpose. Inventing earlier windows from notes nobody
 * checked would put unverified precision under every old claim, so a claim read before
 * 2026-06-30 still comes back `null` and is reported as unstampable.
 */
export const GAME_VERSION_TIMELINE: readonly GameVersionWindow[] = [
  {
    version: 'v28.3.0',
    from: '2026-06-30',
    until: '2026-08-26',
    basis:
      'The v28.3.0 build was captured 2026-06-30. v29 was announced 2026-08-25 to release after '
      + 'that week\'s tournament (patch note 1541918021939892245).',
  },
  {
    version: 'v29.0.0',
    from: '2026-08-27',
    until: '2026-10-14',
    basis:
      'v29.0.1 shipped 2026-08-27 (patch note 1542638399708594186), so v29 was live by then. Covers the '
      + '29.0.1 .. 29.0.6 hotfixes; facts/v29.0.0 was read from this build.',
  },
  {
    version: 'v29.1.0',
    from: '2026-10-15',
    until: '2026-11-15',
    basis:
      'v29.1 rolled out 2026-10-15 (patch note 1560299053789749419). Covers hotfixes 29.1.1 '
      + '(1560678214764994651), 29.1.2 (1561019100359032976), 29.1.3 (1562512032803201145) and '
      + '29.1.4 (1566858291710136333).',
  },
  {
    version: 'v29.2.0',
    from: '2026-11-16',
    until: null,
    basis:
      'v29.2 rolled out 2026-11-16 (patch note 1571908549376872459); build 1286 confirmed in an '
      + 'official export written 2026-11-18. Covers hotfix 29.2.1 (1572999340027420755, build 1294, '
      + '2026-11-19), which fixed ads and a tutorial soft-lock and changed no game data, hotfix '
      + '29.2.2 (1573850127008014367, build 1296, 2026-11-21), announced as a fix to tournament reward '
      + 'validation only; build 1296 confirmed in an official export written 2026-11-23, and hotfix '
      + '29.2.3 (1574821572844200137, build 1301, 2026-11-24), announced as a fix to new players being '
      + 'shown the login screen only; build 1301 confirmed in an official export written 2026-11-25.',
  },
]

/** The build live on a given day, or null if no window covers it. */
export function gameVersionOn(isoDate: string | undefined): string | null {
  if (!isoDate) return null
  const window = GAME_VERSION_TIMELINE.find(entry =>
    isoDate >= entry.from && (entry.until === null || isoDate <= entry.until))
  return window?.version ?? null
}

/** The newest build the timeline knows about. */
export const CURRENT_GAME_VERSION
  = GAME_VERSION_TIMELINE[GAME_VERSION_TIMELINE.length - 1].version

/**
 * Whether a claim was read against a build older than the current one.
 *
 * This is the question worth asking of a wiki claim, and it could not be asked
 * before: not "is this old?" — every claim is old — but "has the game been
 * rebuilt since anyone looked at this?"
 */
export function readAgainstOlderBuild(isoDate: string | undefined): boolean {
  const version = gameVersionOn(isoDate)
  return version !== null && version !== CURRENT_GAME_VERSION
}
