/** Rows of the research table that name a lab. */
const NAMED_RESEARCH = LAB_RESEARCH_BY_INDEX.filter(row => Boolean(row.displayName))

/**
 * Total research slots, including reserved gaps — counted from the table. It was the literal 250
 * twice over; v29 and v29.1 labs grew the table to 260, so it is no longer restated.
 */
export const LAB_RESEARCH_SLOT_COUNT = LAB_RESEARCH_BY_INDEX.length

/** Slots that actually name a lab — the number to use when counting labs. */
export const LAB_NAMED_RESEARCH_COUNT = NAMED_RESEARCH.length

/**
 * The slots with no name, as `[first, last]` runs, counted from the table. In the v29.1 table:
 * 7–9, 27–29, 42–49, 76–79, 89 and 249–250 sit on category boundaries (attack → defense,
 * utility → ultimate, ultimate → perks, fleet → Cells Mastery …); 257–259 trail the table.
 * So a contiguous index range does NOT stay inside one category, and an unnamed slot is
 * reserved space, not undiscovered content.
 */
export const LAB_UNNAMED_SLOT_RUNS: readonly (readonly [number, number])[] = (() => {
  const runs: [number, number][] = []
  for (const row of LAB_RESEARCH_BY_INDEX) {
    if (row.displayName) continue
    const last = runs.at(-1)
    if (last && last[1] === row.index - 1) last[1] = row.index
    else runs.push([row.index, row.index])
  }
  return runs
})()

/** Reserved slots after the last named lab: the trailing run, if the table ends with one. */
const TRAILING_RESERVED_SLOT_COUNT = (() => {
  const last = LAB_UNNAMED_SLOT_RUNS.at(-1)
  return last && last[1] === LAB_RESEARCH_SLOT_COUNT - 1 ? last[1] - last[0] + 1 : 0
})()

