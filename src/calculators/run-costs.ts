/**
 * The implementations behind `specs-costs.ts`, one direct import per handle.
 *
 * Kept beside `run.ts` rather than inside it for length alone; the rule is the same. Every entry
 * is a real import, so a handle pointing at a function that does not exist, or called with the
 * wrong arguments, fails to compile instead of failing when someone asks for it.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    COST_IMPLEMENTATIONS
 * depends    src/data/bots/cost-ranges, src/data/bots/data, src/data/guardians/definitions, src/data/modules/costs, src/data/ultimate-weapons/unlocks, src/data/workshop/cost-ranges (+8 more)
 * used by    src/calculators/run
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { botStatCostBetween } from '../data/bots/cost-ranges'
import { botStatValue } from '../data/bots/data'
import {
  guardianStatCost,
  sumGuardianAllStatCosts,
  sumGuardianStatCostsBetween,
} from '../data/guardians/definitions'
import { sumModuleCoinCostsBetween, sumModuleShardCostsBetween } from '../data/modules/costs'
import {
  sumUltimateWeaponPlusUnlockStones,
  sumUltimateWeaponUnlockStones,
} from '../data/ultimate-weapons/unlocks'
import { workshopCoinCostBetween } from '../data/workshop/cost-ranges'
import { cardLevelCopiesRequired, cardLevelUpgradeGemCost } from '../mechanics/cards/costs'
import {
  ultimateWeaponStoneCostBetween,
  vaultNodeKeysBetween,
  vaultNodeKeysCost,
  vaultTreeKeysRemaining,
} from '../mechanics/effective-paths/edamage-costs'
import { coinFarmDays } from '../mechanics/effective-paths/eecon-plan'
import { enhancementCoinCostBetween } from '../mechanics/effective-paths/enhancement-costs'
import { labCoinCostBetween, labDurationDaysBetween } from '../mechanics/effective-paths/lab-costs'
import { cumulativeAssistStoneCost } from '../mechanics/effective-paths/stone-costs'
import {
  vaultV29CategoryUnlockKeys,
  vaultV29TreeKeysRemaining,
  vaultV29UpgradeKeysBetween,
  vaultV29UpgradeKeysCost,
} from '../mechanics/vault/keys'
import { empiricalTierCoinMultiplier } from '../mechanics/waves/base-empirical-scaling'

export const COST_IMPLEMENTATIONS: Record<string, (args: Record<string, unknown>) => unknown> = {
  'guardian.statCost': a => guardianStatCost(a.guardianKey as string, a.statName as string, a.level as number),
  'guardian.statCostBetween': a => sumGuardianStatCostsBetween(
    a.guardianKey as string, a.statName as string, a.fromLevel as number, a.toLevel as number,
  ),
  'guardian.allStatCost': a => sumGuardianAllStatCosts(a.guardianKey as string, a.fromLevels as never),
  'vault.nodeKeysCost': a => vaultNodeKeysCost(a.nodeId as string, a.level as number),
  'vault.nodeKeysBetween': a => vaultNodeKeysBetween(a.nodeId as string, a.fromLevel as number, a.toLevel as number),
  'vault.treeKeysRemaining': a => vaultTreeKeysRemaining(a.tree as string, a.levels as never),
  'vault.v29.upgradeKeysCost': a => vaultV29UpgradeKeysCost(a.upgrade as string, a.level as number),
  'vault.v29.upgradeKeysBetween': a => vaultV29UpgradeKeysBetween(
    a.upgrade as string, a.fromLevel as number, a.toLevel as number,
  ),
  'vault.v29.categoryUnlockKeys': a => vaultV29CategoryUnlockKeys(a.tree as string, a.category as string),
  'vault.v29.treeKeysRemaining': a => vaultV29TreeKeysRemaining(a.tree as string, a.levels as never),
  'uw.unlockStonesBetween': a => sumUltimateWeaponUnlockStones(a.ownedFrom as number, a.ownedTo as number),
  'uw.plusUnlockStonesBetween': a => sumUltimateWeaponPlusUnlockStones(a.ownedFrom as number, a.ownedTo as number),
  'uw.stoneCostBetween': a => ultimateWeaponStoneCostBetween(
    a.weapon as string, a.stat as string, a.fromLevel as number, a.toLevel as number,
  ),
  'workshop.coinCostBetween': a => workshopCoinCostBetween(a.stat as string, a.fromLevel as number, a.toLevel as number),
  'workshop.enhancementCoinCostBetween': a => enhancementCoinCostBetween(
    a.stat as string, a.fromLevel as number, a.toLevel as number, a.discounts as never,
  ),
  'lab.coinCostBetween': a => labCoinCostBetween(
    a.labKey as string, a.fromLevel as number, a.toLevel as number, a.modifiers as never,
  ),
  'lab.durationDaysBetween': a => labDurationDaysBetween(
    a.labKey as string, a.fromLevel as number, a.toLevel as number, a.modifiers as never,
  ),
  'bot.statCostBetween': a => botStatCostBetween(
    a.botLabel as string, a.statName as string, a.fromLevel as number, a.toLevel as number,
  ),
  'bot.statValue': a => botStatValue(a.botLabel as string, a.statName as string, a.level as number),
  'module.coinCostBetween': a => sumModuleCoinCostsBetween(
    a.fromLevel as number, a.toLevel as number, a.discountPercent as number,
  ),
  'module.shardCostBetween': a => sumModuleShardCostsBetween(
    a.fromLevel as number, a.toLevel as number, a.discountPercent as number,
  ),
  'assist.stoneCostBetween': a => cumulativeAssistStoneCost(a.fromLevel as number, a.toLevel as number),
  'card.levelGemCost': a => cardLevelUpgradeGemCost(a.fromGameLevel as number, a.toGameLevel as number),
  'card.levelCopiesRequired': a => cardLevelCopiesRequired(a.gameLevel as number),
  'epaths.coinFarmDays': a => coinFarmDays(a.coins as number, a.coinsPerHour as number | undefined),
  'tier.coinMultiplier': a => empiricalTierCoinMultiplier(a.tier as number),
}
