/**
 * The implementations behind `specs-planning.ts`, one direct import per handle.
 *
 * Kept beside `run.ts` for length, under the same rule: every entry is a real import, so a handle
 * pointing at a function that does not exist fails to compile instead of failing when asked for.
 * The save-reading handles take `root` and an options bag, because `calc_run` fills a parameter
 * named `root` from `savePath`; the planning functions themselves take one options object.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    PLANNING_IMPLEMENTATIONS
 * depends    src/mechanics/coin-bonus/scenarios, src/mechanics/effective-paths/eecon-compute, src/mechanics/effective-paths/ehp-model, src/save/current-run/in-run-levels, src/save/current-run/progress, src/save/history/diff (+11 more)
 * used by    src/calculators/run
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { compareCoinBonusScenarios } from '../mechanics/coin-bonus/scenarios'
import { computeEffectiveEconomy } from '../mechanics/effective-paths/eecon-compute'
import { computeEffectiveHealth } from '../mechanics/effective-paths/ehp-model'
import { readInRunLevelsFromSaveRoot } from '../save/current-run/in-run-levels'
import { readCurrentRunProgressFromSaveRoot } from '../save/current-run/progress'
import { diffExportSnapshots } from '../save/history/diff'
import { buildExportSnapshot } from '../save/history/snapshot'
import { exportStateAt } from '../save/history/state-at'
import { buildExportTimeline } from '../save/history/timeline'
import { planCellBudgetFromSave } from '../save/planning/cells'
import { checkCoinModelFromSave } from '../save/planning/coin-check'
import { priceDissonancePaybackFromSave } from '../save/planning/dissonance'
import { affordableByFromSave, forecastIncomeFromSave } from '../save/planning/forecast'
import { scheduleLabsFromSave } from '../save/planning/lab-queue'
import { planSpendingFromSave } from '../save/planning/plan'
import { rankSpendsFromSave } from '../save/planning/rank'
import { readWorkshopCoinCostBetweenFromSaveRoot } from '../save/workshop/account-prices'

type Bag = Record<string, unknown>
const withSave = (a: Bag): never => ({ ...(a.options as Bag | undefined), save: a.root }) as never

export const PLANNING_IMPLEMENTATIONS: Record<string, (args: Bag) => unknown> = {
  'planning.forecastIncome': a => forecastIncomeFromSave(withSave(a)),
  'planning.affordableBy': a => affordableByFromSave({ ...(a.options as Bag | undefined), save: a.root, list: a.list } as never),
  'planning.checkCoinModel': a => checkCoinModelFromSave(withSave(a)),
  'planning.rankSpends': a => rankSpendsFromSave(withSave(a)),
  'planning.scheduleLabs': a => scheduleLabsFromSave(withSave(a)),
  'planning.cellBudget': a => planCellBudgetFromSave(withSave(a)),
  'planning.dissonancePayback': a => priceDissonancePaybackFromSave(withSave(a)),
  'planning.planSpending': a => planSpendingFromSave(withSave(a)),
  'currentRun.inRunLevels': a => readInRunLevelsFromSaveRoot(a.root as never, (a.earlier as never) ?? null),
  'currentRun.progress': a => readCurrentRunProgressFromSaveRoot(a.root as never, (a.beforeRun as never) ?? null),
  'history.snapshot': a => buildExportSnapshot(a.root),
  'history.diff': a => diffExportSnapshots(a.from, a.to, (a.options as never) ?? {}),
  'history.timeline': a => buildExportTimeline(a.snapshots as never, (a.options as never) ?? {}),
  'history.stateAt': a => exportStateAt(a.snapshots as never, a.at as string),
  'workshop.accountCoinCostBetween': a => readWorkshopCoinCostBetweenFromSaveRoot(
    a.root as never, a.stat as string, a.fromLevel as number, a.toLevel as number,
  ),
  'coinBonus.scenarios': a => compareCoinBonusScenarios(a.base as never, a.scenarios as never),
  'epaths.effectiveHealth': a => computeEffectiveHealth(a.config as never, a.levels as never),
  'epaths.effectiveEconomy': a => computeEffectiveEconomy(a.config as never, a.levels as never, (a.shadow as never) ?? {}),
}
