/**
 * The implementations behind `specs-survival.ts`, one direct import per handle.
 *
 * Kept beside `run.ts` for length, under the same rule: every entry is a real import, so a handle
 * pointing at a function that does not exist fails to compile instead of failing when asked for.
 * The three save-reading handles take `root` and an options bag, because `calc_run` fills a
 * parameter named `root` from `savePath`; the functions themselves take one options object.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    SURVIVAL_IMPLEMENTATIONS
 * depends    src/mechanics/survival/healing, src/mechanics/survival/incoming-damage, src/save/survival/from-save
 * used by    src/calculators/run
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { healingForWave } from '../mechanics/survival/healing'
import { incomingDamageForWave } from '../mechanics/survival/incoming-damage'
import {
  calibrateSurvivalFromHistory,
  rankSurvivalUpgradesFromSave,
  simulateSurvivalRunFromSave,
} from '../save/survival/from-save'

type Bag = Record<string, unknown>

export const SURVIVAL_IMPLEMENTATIONS: Record<string, (args: Bag) => unknown> = {
  'survival.healingForWave': a => healingForWave(a.state as never, a.wave as number, (a.options as never) ?? {}),
  'survival.incomingDamageForWave': a => incomingDamageForWave(
    a.state as never, a.wave as number, a.calibration as never, (a.context as never) ?? {},
  ),
  'survival.calibrateFromHistory': a => calibrateSurvivalFromHistory({ ...(a.options as Bag | undefined), save: a.root } as never),
  'survival.simulateRun': a => simulateSurvivalRunFromSave({ ...(a.options as Bag | undefined), save: a.root } as never),
  'survival.rankUpgrades': a => rankSurvivalUpgradesFromSave({
    ...(a.options as Bag | undefined), save: a.root, candidates: a.candidates,
  } as never),
}
