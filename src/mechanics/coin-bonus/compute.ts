/**
 * The Total Coin Bonus on the Battle tab, built the way the game's All Coins Bonuses panel lists it.
 *
 * Tapping Total Coin Bonus opens that panel: ten rows and their product. Every row multiplies —
 * the selected tier's coin bonus included — so the shown total moves with the tier picked.
 * Against game v29.2.2 on 2026-11-24 at tier 7 this reproduces every row the panel showed and
 * the x30.07 total exactly (`facts/v29.2.2/live-ui-check.json`, `totalCoinBonus`).
 *
 * Exact for the rows that account had active. Starter pack, Epic pack, the Coin Bonus
 * enhancement and the Coins+ mastery were Inactive there, so their values come from the oracle
 * and the wiki rather than from a screen.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    computeThemeAndSongCoinBonus, computeTotalCoinBonus
 * depends    src/data, src/mechanics/coin-bonus/types, src/mechanics/effective-paths/eecon-stats, src/mechanics/effective-paths/ehp-model, src/mechanics/resource-drops/coin-iap, src/mechanics/resource-drops/coin-multipliers
 * used by    src/calculators/run, src/mechanics/coin-bonus/index, src/save/coin-bonus/read
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import {
  computeModuleStat,
  computeThemePassiveCoinBonus,
  getCardTemplate,
  getTierData,
  THEME_CATEGORY_BONUS,
} from '../../data'
import { coinsCard } from '../effective-paths/eecon-stats'
import { dissonantBoostOfType } from '../effective-paths/ehp-model'
import { RESOURCE_DROPS_COIN_IAP_MULTIPLIERS } from '../resource-drops/coin-iap'
import { coinBonusEnhancementMult } from '../resource-drops/coin-multipliers'
import type {
  CoinsCardState,
  GeneratorModuleState,
  PaidCosmeticCounts,
  TotalCoinBonusBreakdown,
  TotalCoinBonusInput,
} from './types'

const COIN_BONUS_ENHANCEMENT_MAX_LEVEL = 200

function requireCount(value: number, what: string): number {
  if (!Number.isInteger(value) || value < 0) throw new RangeError(`${what} must be a whole number of at least 0`)
  return value
}

/** `'+0.6%'` → 0.6, so the catalog's stated rate is the one priced. */
function percentPoints(stated: string): number {
  const points = Number.parseFloat(stated.replace(/[+%]/g, ''))
  if (!Number.isFinite(points)) throw new RangeError(`Theme rate "${stated}" is not a percentage`)
  return points
}

/**
 * "Themes Bonus": one multiplier from every paying cosmetic, added together first.
 *
 * Tower, background, menu and guardian are priced by `computeThemePassiveCoinBonus`; profile
 * banners and songs by the catalog rate the stores print beside them (+0.6% each). The game's
 * theme screen calls the total "Theme & Song Coin Bonus".
 */
export function computeThemeAndSongCoinBonus(counts: PaidCosmeticCounts): number {
  const banner = requireCount(counts.profileBanner, 'Profile banner count')
  const song = requireCount(counts.song, 'Song count')
  return computeThemePassiveCoinBonus({
    tower: requireCount(counts.tower, 'Tower theme count'),
    background: requireCount(counts.background, 'Background theme count'),
    menu: requireCount(counts.menu, 'Menu theme count'),
    guardian: requireCount(counts.guardian, 'Guardian skin count'),
  }) + (banner * percentPoints(THEME_CATEGORY_BONUS.PROFILE_BANNER)
    + song * percentPoints(THEME_CATEGORY_BONUS.SONGS)) / 100
}

/** "Active cards": the Coins card, only while equipped, with its mastery. */
function activeCardsMultiplier(card: CoinsCardState): number {
  if (!card.equipped) return 1
  const template = getCardTemplate('coins')
  const value = Number.isInteger(card.level) ? template?.levelValues[card.level - 1] : undefined
  if (typeof value !== 'number') throw new RangeError('Coins card level must be a whole number from 1 to 7')
  const masteryLevels = template?.masteryValues?.length ?? 0
  if (card.masteryUnlocked && (!Number.isInteger(card.masteryLevel) || card.masteryLevel < 0
    || card.masteryLevel >= masteryLevels)) {
    throw new RangeError(`Coins Mastery level must be a whole number from 0 to ${masteryLevels - 1}`)
  }
  return coinsCard(true, value, card.masteryUnlocked, card.masteryLevel)
}

/** "Modules": the primary Generator's main stat. */
function modulesMultiplier(generator: GeneratorModuleState | null): number {
  if (!generator) return 1
  const stat = computeModuleStat({
    type: 'generator',
    rarityLabel: generator.rarityLabel,
    level: generator.level,
    primaryLabLevel: generator.primaryLabLevel,
  })
  // computeModuleStat answers 1 for a rarity it does not know; every real rarity pays above 1.
  if (stat === 1) throw new RangeError(`Generator rarity "${generator.rarityLabel}" is not one computeModuleStat knows`)
  return stat
}

/**
 * Every row of the All Coins Bonuses panel, and the Total Coin Bonus they multiply to.
 *
 * Throws `RangeError` for an input the game cannot hold — a tier with no coin bonus, a card level
 * outside 1-7, an unknown Generator rarity — rather than pricing it as 1.
 */
export function computeTotalCoinBonus(input: TotalCoinBonusInput): TotalCoinBonusBreakdown {
  const tierRow = getTierData(input.tier)
  if (!tierRow) throw new RangeError(`Tier ${input.tier} has no coin bonus`)
  if (!Number.isFinite(input.relicCoinBonus) || input.relicCoinBonus < 0) {
    throw new RangeError('Relic coin bonus must be a fraction of at least 0')
  }
  const enhancementLevel = requireCount(input.coinBonusEnhancementLevel, 'Coin Bonus enhancement level')
  if (enhancementLevel > COIN_BONUS_ENHANCEMENT_MAX_LEVEL) {
    throw new RangeError(`Coin Bonus enhancement level must be at most ${COIN_BONUS_ENHANCEMENT_MAX_LEVEL}`)
  }
  const waves = input.dissonance.coinBoostWaves

  const rows = {
    disableAds: input.purchases.hasDisableAds ? RESOURCE_DROPS_COIN_IAP_MULTIPLIERS.disableAds : 1,
    starterPack: input.purchases.hasStarterPack ? RESOURCE_DROPS_COIN_IAP_MULTIPLIERS.starterPack : 1,
    epicPack: input.purchases.hasEpicPack ? RESOURCE_DROPS_COIN_IAP_MULTIPLIERS.epicPack : 1,
    activeCards: activeCardsMultiplier(input.coinsCard),
    modules: modulesMultiplier(input.generator),
    difficultyTier: tierRow.coinBonus,
    themes: computeThemeAndSongCoinBonus(input.paidCosmetics),
    relics: 1 + input.relicCoinBonus,
    enhancement: coinBonusEnhancementMult(enhancementLevel),
    dissonance: dissonantBoostOfType(
      'utility',
      waves[input.tier] ?? 0,
      waves,
      requireCount(input.dissonance.echoLevel, 'Dissonant Echo level'),
    ),
  }
  const total = Object.values(rows).reduce((product, factor) => product * factor, 1)
  return { ...rows, total }
}
