/**
 * Prices several what-ifs for the Total Coin Bonus at once, each against the same starting point.
 *
 * The question a player asks is comparative — how much would a Dissonant run to wave 1,800 add,
 * against one to 2,000 — and answering it one what-if at a time means repeating the base and
 * rebuilding a 25-entry wave list with one number changed. A scenario names the change; this
 * applies each to the base input and reports the total, its ratio to today's and the rows moved.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    applyCoinBonusScenario, compareCoinBonusScenarios
 * depends    src/mechanics/coin-bonus/compute, src/mechanics/coin-bonus/types, src/support/own-lookup
 * used by    src/calculators/run-planning, src/calculators/specs.generated, src/mechanics/coin-bonus/index, src/mechanics/planning/dissonance-payback
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { hasOwnKey } from '../../support/own-lookup'
import { computeTotalCoinBonus } from './compute'
import type {
  CoinBonusRowChange,
  CoinBonusScenario,
  CoinBonusScenarioResult,
  TotalCoinBonusBreakdown,
  TotalCoinBonusInput,
} from './types'

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
}

/**
 * The base input with one scenario's changes applied. Throws `RangeError` naming a field the
 * input does not have: merged in silently, a misspelt field would be read by nothing and the
 * what-if would come back equal to the base.
 */
export function applyCoinBonusScenario(base: TotalCoinBonusInput, scenario: CoinBonusScenario): TotalCoinBonusInput {
  const merged: Record<string, unknown> = { ...base }
  if (scenario.tier !== undefined) merged.tier = scenario.tier
  for (const [key, value] of Object.entries(scenario.overrides ?? {})) {
    if (!hasOwnKey(base, key)) {
      throw new RangeError(`the coin bonus input has no field "${key}". It has: ${Object.keys(base).join(', ')}`)
    }
    const current = (base as unknown as Record<string, unknown>)[key]
    if (isRecord(current) && isRecord(value)) {
      const unknown = Object.keys(value).filter(field => !hasOwnKey(current, field))
      if (unknown.length > 0) {
        throw new RangeError(`"${key}" has no field ${unknown.map(field => `"${field}"`).join(', ')}. It has: ${Object.keys(current).join(', ')}`)
      }
      merged[key] = { ...current, ...value }
    }
    else {
      merged[key] = value
    }
  }
  if (scenario.dissonanceWave) {
    const { tier, wave } = scenario.dissonanceWave
    if (!Number.isInteger(tier) || tier < 1 || !Number.isFinite(wave) || wave < 0) {
      throw new RangeError('dissonanceWave needs a whole tier of at least 1 and a wave of at least 0')
    }
    const dissonance = merged.dissonance as TotalCoinBonusInput['dissonance']
    const waves = [...dissonance.coinBoostWaves]
    while (waves.length <= tier) waves.push(0)
    waves[tier] = Math.max(waves[tier] ?? 0, wave)
    merged.dissonance = { ...dissonance, coinBoostWaves: waves }
  }
  return merged as unknown as TotalCoinBonusInput
}

/**
 * Each scenario's Total Coin Bonus, its ratio to the base at the same tier, and the rows it
 * changed. A scenario that cannot be priced — an unknown field, a tier with no coin bonus —
 * comes back with `total: null` and the reason in `error`; the others are still answered.
 */
export function compareCoinBonusScenarios(
  base: TotalCoinBonusInput,
  scenarios: readonly CoinBonusScenario[],
): CoinBonusScenarioResult[] {
  const baseByTier = new Map<number, TotalCoinBonusBreakdown>()
  const baseAt = (tier: number): TotalCoinBonusBreakdown => {
    let rows = baseByTier.get(tier)
    if (!rows) {
      rows = computeTotalCoinBonus({ ...base, tier })
      baseByTier.set(tier, rows)
    }
    return rows
  }
  return scenarios.map((scenario) => {
    const tier = scenario.tier ?? base.tier
    try {
      const now = baseAt(tier)
      const rows = computeTotalCoinBonus(applyCoinBonusScenario(base, scenario))
      const changedRows: CoinBonusRowChange[] = []
      for (const row of Object.keys(rows) as (keyof TotalCoinBonusBreakdown)[]) {
        if (row !== 'total' && rows[row] !== now[row]) changedRows.push({ row, from: now[row], to: rows[row] })
      }
      return { name: scenario.name, tier, total: rows.total, ratioToNow: now.total > 0 ? rows.total / now.total : null, changedRows }
    }
    catch (error) {
      return { name: scenario.name, tier, total: null, ratioToNow: null, changedRows: [], error: error instanceof Error ? error.message : String(error) }
    }
  })
}
