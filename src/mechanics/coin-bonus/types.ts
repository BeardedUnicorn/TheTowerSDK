import type { ResourceDropsCoinIapToggles } from '../resource-drops/types'

/**
 * Owned cosmetics that pay the theme coin bonus, counted per kind.
 *
 * A count, not a list of what is owned: slot 0 of each kind is the default every account has
 * and pays nothing, and of the songs only the event-store tracks pay. The save reader applies
 * that rule; this is what is left after it.
 */
export interface PaidCosmeticCounts {
  tower: number
  background: number
  menu: number
  profileBanner: number
  guardian: number
  song: number
}

/** The Coins card as the cards screen holds it. */
export interface CoinsCardState {
  /** Equipped in the active card preset. An owned card that is not equipped pays nothing. */
  equipped: boolean
  /** Card level, 1 to 7. */
  level: number
  /** Whether the Coins+ mastery has been bought. */
  masteryUnlocked: boolean
  /** The Coins Mastery research level, 0 to 9. Read only when the mastery is unlocked. */
  masteryLevel: number
}

/** The equipped primary Generator module. */
export interface GeneratorModuleState {
  /** Rarity as `computeModuleStat` reads it: `Legendary`, `Mythic +`, `Ancestral 2`. */
  rarityLabel: string
  /** The slot level the module uses. */
  level: number
  /** Primary Module Bonus - Generator research level, 0 to 30. */
  primaryLabLevel: number
}

export interface TotalCoinBonusInput {
  /** The tier selected on the Battle tab. */
  tier: number
  purchases: ResourceDropsCoinIapToggles
  coinsCard: CoinsCardState
  /** Null when no Generator module is equipped. */
  generator: GeneratorModuleState | null
  paidCosmetics: PaidCosmeticCounts
  /** Coin Bonus relics, summed: 0.12 for +12%. */
  relicCoinBonus: number
  /** Coin Bonus workshop enhancement level, 0 to 200. */
  coinBonusEnhancementLevel: number
  /** Best utility (coin) dissonant wave per tier, index = tier, and the Dissonant Echo - Utility level. */
  dissonance: { coinBoostWaves: readonly number[], echoLevel: number }
}

/**
 * Every row of the game's All Coins Bonuses panel, as a multiplier, and their product.
 *
 * A row the game shows as `Inactive` is 1 here.
 */
export interface TotalCoinBonusBreakdown {
  /** "Disable ads" — the No Ads purchase. */
  disableAds: number
  /** "Starter pack". */
  starterPack: number
  /** "Epic pack". */
  epicPack: number
  /** "Active cards" — the equipped Coins card and its Coins+ mastery. */
  activeCards: number
  /** "Modules" — the primary Generator's main stat. */
  modules: number
  /** "Difficulty Tier" — the selected tier's coin bonus. */
  difficultyTier: number
  /** "Themes Bonus" — owned themes, banners, guardian skins and event songs. */
  themes: number
  /** "Relics Bonus". */
  relics: number
  /** "Enhancement Bonus" — the Coin Bonus workshop enhancement. */
  enhancement: number
  /** "Dissonant Coin Bonus" — the utility dissonant boost for the selected tier. */
  dissonance: number
  /** "Total bonus" — the product of every row above. */
  total: number
}

/** One what-if for the Total Coin Bonus: a named set of changes to the inputs. */
export interface CoinBonusScenario {
  /** What the scenario is called in the answer. */
  name: string
  /** The tier to price at. The base input's tier when omitted. */
  tier?: number
  /**
   * Fields of the input to change, merged one level deep: `{ coinsCard: { equipped: true } }`.
   * A field the input does not have is refused, not added.
   */
  overrides?: Readonly<Record<string, unknown>>
  /**
   * A Dissonant run reaching `wave` on `tier`, without resending the whole wave list. The game
   * keeps a tier's best wave, so a wave below the one already held changes nothing.
   */
  dissonanceWave?: { tier: number, wave: number }
}

/** One row of the coin bonus panel that a scenario changed. */
export interface CoinBonusRowChange {
  row: keyof TotalCoinBonusBreakdown
  from: number
  to: number
}

/** What one scenario does to the Total Coin Bonus. */
export interface CoinBonusScenarioResult {
  name: string
  /** The tier it was priced at. */
  tier: number
  /** The Total Coin Bonus under the scenario, or `null` when it could not be priced. */
  total: number | null
  /** `total` over the base input's total at the same tier: 1.085 for +8.5%. */
  ratioToNow: number | null
  /** The panel rows that differ from the base at the same tier, `total` left out. */
  changedRows: CoinBonusRowChange[]
  /** Why the scenario could not be priced, when it could not. */
  error?: string
}
