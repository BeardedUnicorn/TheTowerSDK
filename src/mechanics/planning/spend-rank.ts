/**
 * Ranks everything the next coins could buy on one scale: coins per day.
 *
 * Each kind of spend has had its own ranking — labs by lab time, health by effective health,
 * workshop buys by price — and nothing set a lab beside a workshop level. Coins per day is a
 * unit all of them can be priced in. Labs are limited by slot time and everything else by
 * coins, so there are two queues, each ranked by gain per unit of what limits it, and a
 * candidate behind a gate carries the gate's cost with it.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    rankSpends
 * depends    src/mechanics/planning/types
 * used by    src/calculators/specs.generated, src/mechanics/planning/index, src/save/planning/rank
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import type { RankedSpend, SpendCandidate, SpendRanking, UnrankedSpend } from './types'

function ranked(candidate: SpendCandidate): RankedSpend {
  const gates = candidate.gates ?? []
  const totalCoins = candidate.coins + gates.reduce((sum, gate) => sum + Math.max(0, gate.coins), 0)
  const totalSlotHours = (candidate.slotHours ?? 0) + gates.reduce((sum, gate) => sum + Math.max(0, gate.slotHours ?? 0), 0)
  const likely = candidate.gainPerDay.likely
  return {
    ...candidate,
    totalCoins,
    totalSlotHours,
    paybackDays: likely > 0 ? totalCoins / likely : null,
    gainPerSlotHour: candidate.kind === 'lab' && totalSlotHours > 0 ? likely / totalSlotHours : null,
    gainPerCoin: totalCoins > 0 ? likely / totalCoins : likely > 0 ? Number.POSITIVE_INFINITY : null,
    overlaps: [],
  }
}

/*
 * Two neighbours overlap when the better one's low figure does not clear the worse one's high
 * figure, each divided by what limits it. Where they do, the order between them is a coin toss
 * and the output says so instead of choosing.
 */
function markOverlaps(queue: RankedSpend[], per: (row: RankedSpend) => number): void {
  for (let index = 0; index + 1 < queue.length; index += 1) {
    const better = queue[index]
    const worse = queue[index + 1]
    const denominatorBetter = per(better)
    const denominatorWorse = per(worse)
    if (!(denominatorBetter > 0) || !(denominatorWorse > 0)) continue
    if (better.gainPerDay.low / denominatorBetter <= worse.gainPerDay.high / denominatorWorse) {
      better.overlaps.push(worse.candidate)
      worse.overlaps.push(better.candidate)
    }
  }
}

/**
 * The lab queue and the coin queue for a set of candidates.
 *
 * Labs are ranked by likely gain per slot-hour, everything else by likely gain per coin, and the
 * two are never merged. A gate's coins and slot-hours are added to its candidate's before
 * ranking, so a gated buy can never rank above the same buy with its gate already paid.
 * Candidates that add nothing go last. `notRanked` is passed through, so every candidate is
 * either ranked or explained.
 */
export function rankSpends(candidates: readonly SpendCandidate[], notRanked: readonly UnrankedSpend[] = []): SpendRanking {
  const warnings: string[] = []
  const rows = candidates.map(ranked)
  const by = (pick: (row: RankedSpend) => number | null) => (a: RankedSpend, b: RankedSpend) =>
    (pick(b) ?? -1) - (pick(a) ?? -1) || a.totalCoins - b.totalCoins
  const labQueue = rows.filter(row => row.kind === 'lab').sort(by(row => row.gainPerSlotHour))
  const coinQueue = rows.filter(row => row.kind !== 'lab').sort(by(row => row.gainPerCoin))
  markOverlaps(labQueue, row => row.totalSlotHours)
  markOverlaps(coinQueue, row => row.totalCoins)
  if (rows.some(row => row.overlaps.length > 0)) {
    warnings.push('some neighbours have overlapping gain bands: where `overlaps` names a candidate, the order between the two is not established')
  }
  return { labQueue, coinQueue, notRanked: [...notRanked], warnings }
}
