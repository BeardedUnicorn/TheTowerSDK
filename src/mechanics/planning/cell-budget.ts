/**
 * Picks a lab boost for each slot that the account's cell income can keep running.
 *
 * Boosts are paid in cells and cells come only from runs, so how hard to boost and how much to
 * run are one decision. A boost bought from the bank lasts until the bank is gone; one sized to
 * income lasts. This spends the forecast cells per day where a slot-hour is worth most, and says
 * what to drop first if the runs fall short.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    planCellBudget
 * depends    src/mechanics/planning/constants, src/mechanics/planning/types
 * used by    src/calculators/specs.generated, src/mechanics/planning/index, src/save/planning/cells
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { HOURS_PER_DAY } from './constants'
import type { CellBudget, CellBudgetInput, CellBudgetSlotPolicy } from './types'

interface Ladder { multiplier: number, cellsPerDay: number }

/*
 * Spend a daily allowance one step at a time: of every slot's next step up the price ladder,
 * take the one that adds the most value per cell, until none is affordable. Prices rise far
 * faster than multipliers, so each slot's steps get worse and the greedy choice is the best one.
 */
function allocate(
  slots: CellBudgetInput['slots'],
  ladder: readonly Ladder[],
  allowance: number,
  valueOf: (slot: number) => number,
): Map<number, Ladder> {
  const chosen = new Map<number, number>()
  let left = allowance
  for (;;) {
    let best: { slot: number, rung: number, perCell: number, cost: number } | null = null
    for (const slot of slots) {
      if (!slot.occupied) continue
      const rung = chosen.get(slot.slot) ?? -1
      const next = ladder[rung + 1]
      if (!next) continue
      const from = rung >= 0 ? ladder[rung] : { multiplier: 1, cellsPerDay: 0 }
      const cost = next.cellsPerDay - from.cellsPerDay
      if (cost > left) continue
      const perCell = (next.multiplier - from.multiplier) * valueOf(slot.slot) / Math.max(cost, 1e-9)
      if (!best || perCell > best.perCell) best = { slot: slot.slot, rung: rung + 1, perCell, cost }
    }
    if (!best) break
    chosen.set(best.slot, best.rung)
    left -= best.cost
  }
  const out = new Map<number, Ladder>()
  for (const [slot, rung] of chosen) out.set(slot, ladder[rung])
  return out
}

/**
 * A boost multiplier per slot whose daily cost the median cell income covers, favouring the slots
 * whose labs are worth most per slot-hour.
 *
 * An empty slot is never boosted. `daysToFloor` says how long the bank lasts at each income
 * figure; at the median it is `null`, since the policy is sized to that income. `fallback` is the
 * same allocation at the low income figure, stated as what changes.
 */
export function planCellBudget(input: CellBudgetInput): CellBudget {
  const warnings: string[] = []
  if (!input.pricesVerified) {
    warnings.push('boost prices are from the wiki and not confirmed in game: check one price on the Labs screen before relying on this budget')
  }
  const ladder: Ladder[] = Object.entries(input.cellsPerHourByMultiplier)
    .map(([multiplier, perHour]) => ({ multiplier: Number(multiplier), cellsPerDay: perHour * HOURS_PER_DAY }))
    .filter(rung => rung.multiplier > 1 && Number.isFinite(rung.cellsPerDay) && rung.cellsPerDay >= 0
      && (input.maxMultiplier == null || rung.multiplier <= input.maxMultiplier))
    .sort((a, b) => a.multiplier - b.multiplier)

  const anyValue = input.slots.some(slot => slot.occupied && (slot.value ?? 0) > 0)
  if (!anyValue && input.slots.some(slot => slot.occupied)) warnings.push('no slot has a value, so every slot is boosted alike')
  const valueOf = (slot: number) => (anyValue ? Math.max(0, input.slots.find(entry => entry.slot === slot)?.value ?? 0) : 1)

  const main = allocate(input.slots, ladder, Math.max(0, input.cellsPerDay.median), valueOf)
  const lean = allocate(input.slots, ladder, Math.max(0, input.cellsPerDay.p25), valueOf)
  const policy: CellBudgetSlotPolicy[] = [...input.slots].sort((a, b) => a.slot - b.slot).map(slot => ({
    slot: slot.slot,
    multiplier: main.get(slot.slot)?.multiplier ?? 1,
    cellsPerDay: main.get(slot.slot)?.cellsPerDay ?? 0,
  }))
  const cellsPerDay = policy.reduce((sum, slot) => sum + slot.cellsPerDay, 0)

  const fallback: string[] = []
  for (const slot of policy) {
    const lower = lean.get(slot.slot)?.multiplier ?? 1
    if (lower < slot.multiplier) fallback.push(`drop slot ${slot.slot + 1} to ${lower}x`)
  }

  const spare = input.bank - Math.max(0, input.floor ?? 0)
  const days = (income: number): number | null => {
    const net = income - cellsPerDay
    if (net >= 0) return null
    return spare <= 0 ? 0 : spare / -net
  }
  const nowMs = Date.parse(input.now)
  const renewAt = input.slots
    .filter(slot => (main.get(slot.slot)?.multiplier ?? 1) > 1)
    .map(slot => ({
      slot: slot.slot,
      at: new Date(nowMs + (slot.boost > 1 ? Math.max(0, slot.boostRemainingSeconds) * 1000 : 0)).toISOString(),
    }))
  for (const slot of input.slots) {
    if (!slot.occupied && slot.boost > 1 && slot.boostRemainingSeconds > 0) {
      warnings.push(`slot ${slot.slot + 1} is empty with a ${slot.boost}x boost still on it: start a lab there or the boost runs down unused`)
    }
    const planned = main.get(slot.slot)?.multiplier ?? 1
    if (slot.occupied && slot.boost > planned && slot.boostRemainingSeconds > 0) {
      warnings.push(`slot ${slot.slot + 1} is at ${slot.boost}x now; income sustains ${planned}x, so let it lapse to that after ${new Date(nowMs + slot.boostRemainingSeconds * 1000).toISOString()}`)
    }
  }
  if (spare < 0) warnings.push('the bank is already below the floor')
  return {
    policy,
    cellsPerDay,
    netCellsPerDay: {
      p25: input.cellsPerDay.p25 - cellsPerDay,
      median: input.cellsPerDay.median - cellsPerDay,
      p75: input.cellsPerDay.p75 - cellsPerDay,
    },
    daysToFloor: { p25: days(input.cellsPerDay.p25), median: days(input.cellsPerDay.median), p75: days(input.cellsPerDay.p75) },
    renewAt,
    fallback,
    warnings,
  }
}
