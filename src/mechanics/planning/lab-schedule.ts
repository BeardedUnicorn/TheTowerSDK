/**
 * Plays the lab slots forward in time: which lab runs in each slot, when each finishes, and how
 * many coins must be on hand at every start.
 *
 * Labs are limited by slot time, not by coins, so the question is never only "what next" but
 * "what next in which slot, and will the coins be there when it frees". This walks the slots
 * from the labs running now, starting the next waiting lab the moment a slot frees if the
 * forecast balance covers it, and saying how long the slot waits when it does not.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    scheduleLabs
 * depends    src/formatting/duration/compute, src/formatting/numbers/game-notation, src/mechanics/effective-paths/lab-costs, src/mechanics/planning/constants, src/mechanics/planning/types
 * used by    src/calculators/specs.generated, src/mechanics/planning/index, src/save/planning/lab-queue
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { formatInstantInTimeZone } from '../../formatting/duration/compute'
import { formatGameNumber } from '../../formatting/numbers/game-notation'
import { labCoinCostToReachLevel, labDurationDaysToReachLevel, labSpeedTotal } from '../effective-paths/lab-costs'
import { LAB_SCHEDULE_DEFAULT_HORIZON_DAYS, LAB_SWAP_GAIN_RATIO } from './constants'
import type { LabSchedule, LabScheduleInput, LabScheduleRow, LabSwapProposal, QueuedLab } from './types'

const MS_PER_DAY = 86_400_000
const MAX_STEPS = 20_000

/* Slugs and display names agree once reduced to letters and digits, which is how the lab catalog is keyed. */
const keyOf = (lab: string): string => lab.toLowerCase().replace(/[^a-z0-9]+/g, '')
const LABS_SPEED = keyOf('labs_speed')
const LABS_COIN_DISCOUNT = keyOf('labs_coin_discount')

interface Slot {
  slot: number
  /** The lab in the slot: its key, the level being researched and the work left, in seconds at speed 1. */
  lab: { key: string, name: string, toLevel: number, work: number, row: LabScheduleRow } | null
  boost: number
  boostRemaining: number
  policy: number
  lastFinished: { lab: string, name: string, level: number } | null
  waiting: { item: QueuedLab, cost: number, since: number, balance: number } | null
  idleWarned: boolean
}

/**
 * The lab schedule from `now` to the horizon: one row per lab, running ones first.
 *
 * The rules it follows:
 * - A lab starts only when the forecast balance covers its cost at that moment; otherwise the
 *   slot waits, and the row's `shortfall` says how long and why. A cheaper lab in another slot
 *   may start meanwhile.
 * - A finished Labs Speed level speeds up every slot from that moment, and a finished Labs Coin
 *   Discount level lowers every later price.
 * - A boost belongs to its slot and carries over to the next lab in it. Once it ends the slot
 *   runs at its `boostPolicy` multiplier, or unboosted with none.
 * - A waiting lab worth several times a running one per slot-hour is proposed as a swap, not
 *   made: stopping a lab refunds its coins and keeps its progress, but the choice is the player's.
 * - Every lab is permanent once researched, and every row says so.
 *
 * A queued level can start once the level below it is held and the lab is not already running.
 * Labs started before the horizon are followed to their finish; none is started after it.
 */
export function scheduleLabs(input: LabScheduleInput): LabSchedule {
  const warnings: string[] = []
  const timeZone = input.timeZone ?? 'UTC'
  const nowMs = Date.parse(input.now)
  const horizonMs = nowMs + Math.max(0, input.horizonDays ?? LAB_SCHEDULE_DEFAULT_HORIZON_DAYS) * MS_PER_DAY
  const coinsPerMs = Math.max(0, input.coinsPerDay) / MS_PER_DAY
  const local = (ms: number) => formatInstantInTimeZone(ms, timeZone)
  if (local(nowMs) == null) warnings.push(`time zone "${timeZone}" is not one this runtime knows, so local times are left out`)
  else if (!input.timeZone) warnings.push('no time zone was given, so local times are in UTC')

  let speedLevel = input.labSpeedLevel
  let discountLevel = input.coinDiscountLevel
  let spent = 0
  let now = nowMs
  const speed = () => labSpeedTotal(speedLevel, input.labSpeedRelicFraction)
  const balanceAt = (ms: number) => input.balance + coinsPerMs * (ms - nowMs) - spent

  const held = new Map<string, number>()
  for (const [lab, level] of Object.entries(input.labLevels)) held.set(keyOf(lab), level)
  const rows: LabScheduleRow[] = []
  const slots: Slot[] = [...input.slots].sort((a, b) => a.slot - b.slot).map((state) => {
    const policy = input.boostPolicy?.find(entry => entry.slot === state.slot)?.multiplier ?? 1
    const boost = state.boostRemainingSeconds > 0 && state.boost > 1 ? state.boost : 1
    const slot: Slot = {
      slot: state.slot, lab: null, boost, boostRemaining: boost > 1 ? state.boostRemainingSeconds : 0,
      policy: policy > 1 ? policy : 1, lastFinished: null, waiting: null, idleWarned: false,
    }
    if (state.running) {
      const key = keyOf(state.running.lab)
      held.set(key, state.running.toLevel - 1)
      const row: LabScheduleRow = {
        slot: state.slot, lab: state.running.name ?? state.running.lab, toLevel: state.running.toLevel,
        start: null, finish: '', startLocal: null, finishLocal: null, coinsNeeded: 0, balanceWhenSlotFreed: null,
        boost, permanent: true, warnings: [],
      }
      rows.push(row)
      slot.lab = { key, name: row.lab, toLevel: state.running.toLevel, work: Math.max(0, state.running.remainingSeconds) * speed(), row }
    }
    return slot
  })
  const boostNow = (slot: Slot) => (slot.boostRemaining > 0 ? slot.boost : slot.policy)

  const swaps: LabSwapProposal[] = []
  const startableNow = input.queue.filter(item => (held.get(keyOf(item.lab)) ?? 0) === item.toLevel - 1
    && !slots.some(slot => slot.lab?.key === keyOf(item.lab)))
  const offered = new Set<string>()
  for (const state of [...input.slots].sort((a, b) => (a.running?.gainPerSlotHour ?? Infinity) - (b.running?.gainPerSlotHour ?? Infinity))) {
    const running = state.running
    if (!running || running.gainPerSlotHour == null || slots.some(slot => !slot.lab)) continue
    const better = startableNow.find(item => !offered.has(keyOf(item.lab)) && item.gainPerSlotHour != null
      && item.gainPerSlotHour >= LAB_SWAP_GAIN_RATIO * Math.max(running.gainPerSlotHour as number, 0) && item.gainPerSlotHour > 0)
    if (!better) continue
    offered.add(keyOf(better.lab))
    swaps.push({
      slot: state.slot,
      stop: running.name ?? running.lab,
      start: better.name ?? better.lab,
      startLevel: better.toLevel,
      reason: `${better.name ?? better.lab} ${better.toLevel} is worth ${formatGameNumber(better.gainPerSlotHour as number)} a slot-hour against `
        + `${formatGameNumber(running.gainPerSlotHour)} for ${running.name ?? running.lab}; stopping refunds its coins and keeps its progress`,
    })
  }

  const claimed = new Set<string>()
  const nextFor = (slot: Slot): { item: QueuedLab, continued: boolean } | null => {
    for (const item of input.queue) {
      const key = keyOf(item.lab)
      const id = `${key}:${item.toLevel}`
      if (claimed.has(id) || (held.get(key) ?? 0) !== item.toLevel - 1) continue
      if (slots.some(other => other.lab?.key === key || (other.waiting && keyOf(other.waiting.item.lab) === key))) continue
      return { item, continued: false }
    }
    const last = slot.lastFinished
    if (last && input.continueFinishedLabs !== false && !slots.some(other => other.lab?.key === keyOf(last.lab))) {
      return { item: { lab: last.lab, name: last.name, toLevel: last.level + 1 }, continued: true }
    }
    return null
  }
  const start = (slot: Slot, item: QueuedLab, cost: number, waited: Slot['waiting']) => {
    const base = labDurationDaysToReachLevel(item.lab, item.toLevel, {})
    if (base == null) return
    spent += cost
    const row: LabScheduleRow = {
      slot: slot.slot, lab: item.name ?? item.lab, toLevel: item.toLevel,
      start: new Date(now).toISOString(), finish: '', startLocal: local(now), finishLocal: null,
      coinsNeeded: cost, balanceWhenSlotFreed: waited ? waited.balance : balanceAt(now) + cost,
      boost: boostNow(slot), permanent: true, warnings: [],
    }
    if (waited) {
      const short = cost - waited.balance
      row.shortfall = {
        coins: short,
        waitSeconds: (now - waited.since) / 1000,
        reason: `the slot freed with ${formatGameNumber(Math.max(0, waited.balance))} coins on hand against a cost of ${formatGameNumber(cost)}`,
      }
    }
    rows.push(row)
    slot.lab = { key: keyOf(item.lab), name: row.lab, toLevel: item.toLevel, work: base * 86_400, row }
    slot.waiting = null
    slot.idleWarned = false
  }

  for (let step = 0; step < MAX_STEPS; step += 1) {
    if (now < horizonMs) {
      for (const slot of slots) {
        if (slot.lab) continue
        if (slot.waiting) {
          if (balanceAt(now) >= slot.waiting.cost) start(slot, slot.waiting.item, slot.waiting.cost, slot.waiting)
          continue
        }
        const next = nextFor(slot)
        if (!next) {
          if (!slot.idleWarned) {
            slot.idleWarned = true
            const wasted = slot.boostRemaining > 0 ? `, with ${Math.round(slot.boostRemaining / 3600)} h of its ${slot.boost}x boost left to run down unused` : ''
            warnings.push(`slot ${slot.slot + 1} has nothing to research from ${local(now) ?? new Date(now).toISOString()}${wasted}`)
          }
          continue
        }
        const cost = labCoinCostToReachLevel(next.item.lab, next.item.toLevel, { coinDiscountLabLevel: discountLevel })
        if (cost == null) {
          claimed.add(`${keyOf(next.item.lab)}:${next.item.toLevel}`)
          if (next.continued) slot.lastFinished = null
          else warnings.push(`${next.item.name ?? next.item.lab} ${next.item.toLevel} is not a level the lab table has, so it was skipped`)
          continue
        }
        claimed.add(`${keyOf(next.item.lab)}:${next.item.toLevel}`)
        if (balanceAt(now) >= cost) {
          start(slot, next.item, cost, null)
        }
        else {
          slot.waiting = { item: next.item, cost, since: now, balance: balanceAt(now) }
          if (slot.boostRemaining > 0) {
            warnings.push(`slot ${slot.slot + 1} frees at ${local(now) ?? new Date(now).toISOString()} without the coins for ${next.item.name ?? next.item.lab} ${next.item.toLevel}: `
              + `its ${slot.boost}x boost has ${Math.round(slot.boostRemaining / 3600)} h left, which run down on an empty slot`)
          }
          if (coinsPerMs <= 0) warnings.push(`slot ${slot.slot + 1} cannot start ${next.item.name ?? next.item.lab} ${next.item.toLevel}: no income is forecast to cover it`)
        }
      }
    }

    let stepMs = Number.POSITIVE_INFINITY
    for (const slot of slots) {
      if (slot.lab) stepMs = Math.min(stepMs, (slot.lab.work / (speed() * boostNow(slot))) * 1000)
      if (slot.boostRemaining > 0) stepMs = Math.min(stepMs, slot.boostRemaining * 1000)
      if (slot.waiting && coinsPerMs > 0 && now < horizonMs) {
        stepMs = Math.min(stepMs, Math.max(1, (slot.waiting.cost - balanceAt(now)) / coinsPerMs))
      }
    }
    if (now < horizonMs && slots.some(slot => slot.lab || slot.waiting)) stepMs = Math.min(stepMs, horizonMs - now)
    if (!Number.isFinite(stepMs)) break
    stepMs = Math.max(stepMs, 1)

    for (const slot of slots) {
      if (slot.lab) slot.lab.work -= speed() * boostNow(slot) * (stepMs / 1000)
      if (slot.boostRemaining > 0) slot.boostRemaining = Math.max(0, slot.boostRemaining - stepMs / 1000)
    }
    now += stepMs
    for (const slot of slots) {
      if (!slot.lab || slot.lab.work > 1e-6) continue
      slot.lab.row.finish = new Date(now).toISOString()
      slot.lab.row.finishLocal = local(now)
      held.set(slot.lab.key, slot.lab.toLevel)
      if (slot.lab.key === LABS_SPEED) speedLevel = slot.lab.toLevel
      if (slot.lab.key === LABS_COIN_DISCOUNT) discountLevel = slot.lab.toLevel
      slot.lastFinished = { lab: slot.lab.key, name: slot.lab.name, level: slot.lab.toLevel }
      slot.lab = null
    }
    if (now >= horizonMs && !slots.some(slot => slot.lab)) break
  }

  for (const slot of slots) {
    if (slot.waiting) {
      warnings.push(`slot ${slot.slot + 1} is still waiting for the coins for ${slot.waiting.item.name ?? slot.waiting.item.lab} ${slot.waiting.item.toLevel} at the end of the schedule`)
    }
  }
  rows.sort((a, b) => (a.start ? Date.parse(a.start) : nowMs) - (b.start ? Date.parse(b.start) : nowMs) || a.slot - b.slot)
  return { rows: rows.filter(row => row.finish !== ''), swaps, timeZone, warnings }
}
