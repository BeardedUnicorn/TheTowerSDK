/**
 * Sets recorded coins against what the coin model predicts, and says how much of a predicted
 * gain arrives.
 *
 * A run's coins come in two parts. The wave payout is a flat sum the model computes exactly from
 * the coin bonus, so recorded over predicted wave coins is the run's own factor: what its perks
 * did, and nothing about ultimate weapons. Kill coins rest on inputs a stored export does not
 * carry, so they are brought to the account's level by a curve fitted to its runs. With both in place a
 * change in income can be read against how much runs differ when nothing has changed — which is
 * a lot, and is what makes two or three runs a poor measure of a pack.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    fitKillCoinCalibration, killCoinScaleAtWave, measureCoinDrift
 * depends    src/mechanics/planning/income, src/mechanics/planning/types
 * used by    src/calculators/specs.generated, src/mechanics/planning/index, src/save/planning/candidates, src/save/planning/coin-check
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { quantileBand } from './income'
import type {
  CoinDriftInput,
  CoinDriftPair,
  CoinModelCheck,
  CoinModelRun,
  CoinModelRunInput,
  CoinSourceDrift,
  KillCoinCalibration,
} from './types'

const DEFAULT_WAVE_TOLERANCE = 0.15
/** A kill-coin curve needs this many runs before its slope is fitted; below it the scale is flat. */
const MIN_RUNS_FOR_SLOPE = 6
/** A spread of run factors needs this many runs with nothing changed between them. */
const MIN_RUNS_FOR_SPREAD = 4

function median(values: readonly number[]): number | null {
  return quantileBand(values)?.median ?? null
}

function waveCoinRatio(run: CoinModelRunInput): number | null {
  return run.actualWaveCoins != null && run.predictedWaveCoins != null && run.predictedWaveCoins > 0 && run.actualWaveCoins > 0
    ? run.actualWaveCoins / run.predictedWaveCoins
    : null
}

/**
 * The kill-coin scale that makes the model's kill coins match an account's records, as a curve
 * in the wave a run reached.
 *
 * Each run gives one point: recorded kill coins over the model's, divided by the run's own
 * wave-coin factor so that perks drop out. The scale at the middle wave is the median of those
 * points; with six or more runs the slope against wave is fitted too, in logs, by least squares.
 * Every run counts, whatever is known of its state: a wrong coin bonus is in the run's kill coins
 * and its wave coins alike, and divides out. `null` with no usable run.
 */
export function fitKillCoinCalibration(runs: readonly CoinModelRunInput[]): KillCoinCalibration | null {
  const points: { x: number, y: number }[] = []
  for (const run of runs) {
    const factor = waveCoinRatio(run)
    const kill = run.actualWaveCoins == null ? null : run.actual - run.actualWaveCoins
    if (factor == null || kill == null || !(kill > 0) || !(run.wave > 0)) continue
    if (run.predictedKillCoins == null || !(run.predictedKillCoins > 0)) continue
    points.push({ x: Math.log(run.wave), y: Math.log(kill / run.predictedKillCoins / factor) })
  }
  if (points.length === 0) return null
  const meanX = points.reduce((sum, point) => sum + point.x, 0) / points.length
  const referenceWave = Math.exp(meanX)
  let slope = 0
  const spreadX = points.reduce((sum, point) => sum + (point.x - meanX) ** 2, 0)
  if (points.length >= MIN_RUNS_FOR_SLOPE && spreadX > 1e-6) {
    const meanY = points.reduce((sum, point) => sum + point.y, 0) / points.length
    slope = points.reduce((sum, point) => sum + (point.x - meanX) * (point.y - meanY), 0) / spreadX
  }
  /* The median of what is left after the slope: one perk-heavy run does not move it. */
  const scale = Math.exp(median(points.map(point => point.y - slope * (point.x - meanX))) as number)
  return { scale, referenceWave, waveExponent: -slope, runsFitted: points.length }
}

/** The fitted kill-coin scale for a run that reaches `wave`. */
export function killCoinScaleAtWave(calibration: KillCoinCalibration, wave: number): number {
  return calibration.scale * (Math.max(1, wave) / calibration.referenceWave) ** -calibration.waveExponent
}

/**
 * Predicted against recorded coins, run by run, and the drift across one change in income.
 *
 * `driftFactor` pairs each run after the change with the run before it nearest in wave, among
 * runs whose state is known, and divides the recorded ratio by the predicted one. `waveCoinDrift`
 * is the wider measure: the median run factor after the change over the median before, from wave
 * coins alone, over every run whose state is known or assumed. `runToRunSpread` is how much that
 * factor varies on the larger side with nothing changed. The pass-through is 1 unless the
 * wave-coin drift falls below one over that spread: a shortfall no bigger than the difference
 * between two ordinary runs is not evidence that a bonus failed to arrive.
 */
export function measureCoinDrift(input: CoinDriftInput): CoinModelCheck {
  const warnings: string[] = []
  const calibration = fitKillCoinCalibration(input.runs)
  const perRun: CoinModelRun[] = [...input.runs]
    .sort((a, b) => Date.parse(a.runDate) - Date.parse(b.runDate))
    .map((run) => {
      const kill = run.predictedKillCoins != null && calibration ? run.predictedKillCoins * killCoinScaleAtWave(calibration, run.wave) : null
      const predicted = run.predictedWaveCoins != null && kill != null ? run.predictedWaveCoins + kill : null
      return { ...run, predicted, ratio: predicted != null && predicted > 0 ? run.actual / predicted : null, waveCoinRatio: waveCoinRatio(run) }
    })
  if (calibration && Math.abs(calibration.scale - 1) > 0.5) {
    warnings.push(`kill coins are scaled by ${calibration.scale.toPrecision(2)} at wave ${Math.round(calibration.referenceWave)}, fitted to ${calibration.runsFitted} of this account's runs: the model's own kill coins are that far from the records`)
  }
  const empty = { perRun, calibration, pairs: [], driftFactor: null, waveCoinDrift: null, runToRunSpread: null, passThrough: 1, sources: [] }
  if (!input.changedBetween) {
    return { ...empty, warnings: [...warnings, 'no change in income to measure across, so the pass-through is left at 1'] }
  }

  const cut = Date.parse(input.changedBetween.after)
  const resumed = Date.parse(input.changedBetween.before)
  const isBefore = (run: CoinModelRun) => Date.parse(run.runDate) <= cut
  const isAfter = (run: CoinModelRun) => Date.parse(run.runDate) >= resumed

  /* Wave coins: every run on each side whose state is not in doubt. */
  const factors = (side: (run: CoinModelRun) => boolean) =>
    perRun.filter(run => side(run) && run.state !== 'unsettled' && run.waveCoinRatio != null).map(run => run.waveCoinRatio as number)
  const beforeFactors = factors(isBefore)
  const afterFactors = factors(isAfter)
  const waveCoinDrift = beforeFactors.length > 0 && afterFactors.length > 0
    ? (median(afterFactors) as number) / (median(beforeFactors) as number)
    : null
  const larger = beforeFactors.length >= afterFactors.length ? beforeFactors : afterFactors
  const band = larger.length >= MIN_RUNS_FOR_SPREAD ? quantileBand(larger) : null
  const runToRunSpread = band && band.p25 > 0 ? band.p75 / band.p25 : null

  /* Whole runs in pairs, where the state is known on both sides. */
  const usable = (run: CoinModelRun) => run.predicted != null && run.predicted > 0 && run.actual > 0 && run.state === 'known'
  const before = perRun.filter(run => isBefore(run) && usable(run))
  const tolerance = input.waveTolerance ?? DEFAULT_WAVE_TOLERANCE
  const pairs: CoinDriftPair[] = []
  const matched: [CoinModelRun, CoinModelRun][] = []
  for (const later of perRun.filter(run => isAfter(run) && usable(run))) {
    let nearest: CoinModelRun | null = null
    for (const earlier of before) {
      if (Math.abs(earlier.wave - later.wave) > later.wave * tolerance) continue
      if (!nearest || Math.abs(earlier.wave - later.wave) < Math.abs(nearest.wave - later.wave)) nearest = earlier
    }
    if (!nearest) continue
    const actualRatio = later.actual / nearest.actual
    const predictedRatio = (later.predicted as number) / (nearest.predicted as number)
    pairs.push({ before: nearest.runDate, after: later.runDate, actualRatio, predictedRatio, drift: actualRatio / predictedRatio })
    matched.push([nearest, later])
  }
  const driftFactor = pairs.length > 0 ? median(pairs.map(pair => pair.drift)) : null

  const sources: CoinSourceDrift[] = []
  if (pairs.length > 0) {
    const predicted = median(pairs.map(pair => pair.predictedRatio)) as number
    const names = new Set<string>()
    for (const [earlier, later] of matched) for (const name of Object.keys(later.sources)) if (name in earlier.sources) names.add(name)
    for (const source of names) {
      const ratios = matched
        .filter(([earlier, later]) => earlier.sources[source] > 0 && later.sources[source] > 0)
        .map(([earlier, later]) => later.sources[source] / earlier.sources[source])
      const ratio = median(ratios)
      if (ratio != null) sources.push({ source, ratio, drift: ratio / predicted })
    }
    sources.sort((a, b) => Math.abs(Math.log(b.drift)) - Math.abs(Math.log(a.drift)))
  }

  /* The verdict rests on the wider measure where there is one, and on the pairs where there is not. */
  const measured = waveCoinDrift ?? driftFactor
  let passThrough = 1
  if (measured == null) {
    warnings.push('no run on each side of the change could be compared, so the pass-through is left at 1')
  }
  else if (runToRunSpread == null) {
    passThrough = Math.min(1, Math.max(0, measured))
    warnings.push(`too few runs to say how much one differs from the next, so the measured drift of ${measured.toFixed(2)} is taken at face value`)
  }
  else if (measured < 1 / runToRunSpread) {
    passThrough = Math.max(0, measured)
    warnings.push(`run factors fell to ${measured.toFixed(2)} of what they were across the change, beyond the ${runToRunSpread.toFixed(2)}x by which runs differ on their own`)
  }
  else if (measured < 0.95 || (driftFactor != null && driftFactor < 0.95)) {
    warnings.push(`coins moved by ${measured.toFixed(2)} of the predicted change${driftFactor != null && waveCoinDrift != null ? ` (${driftFactor.toFixed(2)} on ${pairs.length} matched pair${pairs.length === 1 ? '' : 's'})` : ''}, within the ${runToRunSpread.toFixed(2)}x by which this account's runs differ with nothing changed: the perks taken in a run move its coins that much, so the pass-through is left at 1`)
  }
  return { perRun, calibration, pairs, driftFactor, waveCoinDrift, runToRunSpread, passThrough, sources, warnings }
}
