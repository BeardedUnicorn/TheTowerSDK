/**
 * The thresholds the planning models classify with, named so each can be found and questioned.
 *
 * None of these is a game value. Each is a judgement about where a line falls — how short a run
 * is a restart, how large a jump is a change of regime — and is stated here once.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    RESTART_MAX_REAL_SECONDS, PAUSED_SPAN_FACTOR, PAUSED_MIN_EXTRA_SECONDS, REGIME_COIN_BONUS_RATIO, REGIME_INCOME_STEP_RATIO, REGIME_MIN_RUNS_BEFORE, HOURS_PER_DAY, LAB_SCHEDULE_DEFAULT_HORIZON_DAYS (+3 more)
 * depends    —
 * used by    src/mechanics/planning/cell-budget, src/mechanics/planning/dissonance-payback, src/mechanics/planning/income, src/mechanics/planning/index, src/mechanics/planning/lab-schedule
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */

/** A run the player ended in less real time than this, in seconds, is a restart, not a farm run. */
export const RESTART_MAX_REAL_SECONDS = 3600

/**
 * A run is called paused when the wall-clock time it is known to span exceeds its real time by
 * this factor and by `PAUSED_MIN_EXTRA_SECONDS` as well.
 */
export const PAUSED_SPAN_FACTOR = 1.5

/** The extra wall-clock time, in seconds, a run must show before it is called paused. */
export const PAUSED_MIN_EXTRA_SECONDS = 1800

/** A Total Coin Bonus that grows by this factor between two exports starts a new regime. */
export const REGIME_COIN_BONUS_RATIO = 1.25

/**
 * Without exports, a step in coins per hour starts a new regime when the runs after it earn this
 * many times the runs before it, with no overlap between the two groups.
 */
export const REGIME_INCOME_STEP_RATIO = 2

/** A step needs at least this many farm runs before it to be told from noise. */
export const REGIME_MIN_RUNS_BEFORE = 3

/** Hours in a day, for turning a rate per hour into one per day. */
export const HOURS_PER_DAY = 24

/** How far ahead the lab scheduler plays when not told, in days. */
export const LAB_SCHEDULE_DEFAULT_HORIZON_DAYS = 3

/** The most lab slots an account can have. */
export const LAB_SLOT_LIMIT = 5

/**
 * A waiting lab is proposed in place of a running one when it is worth this many times as much
 * per slot-hour. Stopping is free in coins, so the bar is only that the difference be clear.
 */
export const LAB_SWAP_GAIN_RATIO = 3

/**
 * The wave past which a Dissonant boost stops growing. A game value, not a judgement: the boost
 * is `(min(5000, wave) / 5000) ^ 1.75` of its cap (wiki "Dissonance", Dissonant Boost).
 */
export const DISSONANT_BOOST_LAST_WAVE = 5000
