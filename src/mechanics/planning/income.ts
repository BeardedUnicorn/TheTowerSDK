/**
 * Forecasts an account's coins and cells per day from the runs it has actually played.
 *
 * The figures at hand overstate both: a best-three mean is a peak, and a 23-hour day is an
 * assumption few accounts meet. A plan needs what the account sustains — the median rate of its
 * full farm runs since income last changed, times the hours it really runs — and it needs the
 * spread, because a date promised from a single figure is wrong half the time.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    quantileBand, classifyPlanningRuns, findRegimeBreaks, forecastIncome, affordableBy
 * depends    src/mechanics/planning/constants, src/mechanics/planning/types
 * used by    src/calculators/specs.generated, src/mechanics/planning/coin-drift, src/mechanics/planning/index, src/save/planning/coin-inputs, src/save/planning/dissonance, src/save/planning/forecast
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import {
  HOURS_PER_DAY,
  PAUSED_MIN_EXTRA_SECONDS,
  PAUSED_SPAN_FACTOR,
  REGIME_COIN_BONUS_RATIO,
  REGIME_INCOME_STEP_RATIO,
  REGIME_MIN_RUNS_BEFORE,
  RESTART_MAX_REAL_SECONDS,
} from './constants'
import type {
  AffordableItem,
  ClassifiedRun,
  CoinBonusReading,
  IncomeForecast,
  IncomeForecastInput,
  PlanningRun,
  PlanningRunKind,
  QuantileBand,
  RegimeBreak,
  ShoppingItem,
  UptimeWindow,
} from './types'

const MS_PER_HOUR = 3_600_000
const MS_PER_DAY = 86_400_000

/** A value at a fraction of the way through a sorted list, interpolated between neighbours. */
function quantile(sorted: readonly number[], fraction: number): number {
  const position = (sorted.length - 1) * fraction
  const low = Math.floor(position)
  const high = Math.ceil(position)
  return sorted[low] + (sorted[high] - sorted[low]) * (position - low)
}

/** The 25th percentile, median and 75th of a list, or `null` for an empty one. */
export function quantileBand(values: readonly number[]): QuantileBand | null {
  const sorted = values.filter(Number.isFinite).sort((a, b) => a - b)
  if (sorted.length === 0) return null
  return { p25: quantile(sorted, 0.25), median: quantile(sorted, 0.5), p75: quantile(sorted, 0.75) }
}

function scaleBand(band: QuantileBand | null, factor: number): QuantileBand | null {
  return band ? { p25: band.p25 * factor, median: band.median * factor, p75: band.p75 * factor } : null
}

function kindOf(run: PlanningRun): PlanningRunKind {
  if (run.tournament) return 'tournament'
  if (run.dissonant) return 'dissonant'
  /* A run that died early is still a farm run; only one the player ended is a restart. */
  if (run.realSeconds < RESTART_MAX_REAL_SECONDS && run.endedByPlayer !== false) return 'restart'
  return 'farm'
}

/**
 * Each run with its kind, its rates per real hour and whether it sat paused, oldest first.
 *
 * A run is `paused` when an export taken during it shows it in progress far earlier than its
 * real time allows: the time between that export and the run's end exceeds the real time by
 * half again and by half an hour.
 */
export function classifyPlanningRuns(runs: readonly PlanningRun[]): ClassifiedRun[] {
  return runs
    .filter(run => Number.isFinite(Date.parse(run.endedAt)))
    .sort((a, b) => Date.parse(a.endedAt) - Date.parse(b.endedAt))
    .map((run) => {
      const hours = run.realSeconds / 3600
      const seen = run.firstSeenAt ? Date.parse(run.firstSeenAt) : Number.NaN
      const spanSeconds = Number.isFinite(seen) ? (Date.parse(run.endedAt) - seen) / 1000 : 0
      return {
        ...run,
        kind: kindOf(run),
        coinsPerHour: hours > 0 ? run.coins / hours : null,
        cellsPerHour: hours > 0 ? run.cells / hours : null,
        wavesPerHour: hours > 0 ? run.wave / hours : null,
        paused: spanSeconds > run.realSeconds * PAUSED_SPAN_FACTOR && spanSeconds - run.realSeconds > PAUSED_MIN_EXTRA_SECONDS,
        used: false,
      }
    })
}

/**
 * The moments income changed at once, oldest first.
 *
 * Exports give the surest sign: the Total Coin Bonus on one tier rising a quarter or more above
 * its highest reading so far, which a pack or a large upgrade does and ordinary progress does not. With
 * no such reading, the runs are searched for the latest step: a point where every farm run after
 * earns more per hour than every one before, by at least a factor of two, with three runs before.
 */
export function findRegimeBreaks(farmRuns: readonly ClassifiedRun[], readings: readonly CoinBonusReading[] = []): RegimeBreak[] {
  const breaks: RegimeBreak[] = []
  /*
   * Each reading is set against the highest since the last break, not the one before it: a
   * bonus that dips and recovers — a card unequipped for a tournament — is not a change of regime.
   */
  const stateByTier = new Map<number, { highest: number, last: CoinBonusReading }>()
  for (const reading of [...readings].sort((a, b) => Date.parse(a.at) - Date.parse(b.at))) {
    const state = stateByTier.get(reading.tier)
    if (!state) {
      stateByTier.set(reading.tier, { highest: reading.total, last: reading })
      continue
    }
    if (state.highest > 0 && reading.total / state.highest >= REGIME_COIN_BONUS_RATIO) {
      breaks.push({ after: state.last.at, before: reading.at, reason: 'coin-bonus', ratio: reading.total / state.highest })
      state.highest = reading.total
    }
    else {
      state.highest = Math.max(state.highest, reading.total)
    }
    state.last = reading
  }
  if (breaks.length > 0) return breaks

  const rated = farmRuns.filter(run => run.coinsPerHour != null)
  for (let split = rated.length - 1; split >= REGIME_MIN_RUNS_BEFORE; split -= 1) {
    const before = rated.slice(0, split).map(run => run.coinsPerHour as number)
    const after = rated.slice(split).map(run => run.coinsPerHour as number)
    const ratio = (quantileBand(after) as QuantileBand).median / (quantileBand(before) as QuantileBand).median
    if (ratio >= REGIME_INCOME_STEP_RATIO && Math.min(...after) > Math.max(...before)) {
      return [{ after: rated[split - 1].endedAt, before: rated[split].endedAt, reason: 'income-step', ratio }]
    }
  }
  return []
}

function uptimeOver(runs: readonly ClassifiedRun[], nowMs: number, days: number, currentRunSeconds: number): UptimeWindow {
  const from = nowMs - days * MS_PER_DAY
  let playedMs = Math.min(currentRunSeconds * 1000, nowMs - from)
  for (const run of runs) {
    const end = Date.parse(run.endedAt)
    /* A run is placed at the end of its span: its real time counted back from when it ended. */
    const start = end - run.realSeconds * 1000
    playedMs += Math.max(0, Math.min(end, nowMs) - Math.max(start, from))
  }
  const hours = playedMs / MS_PER_HOUR
  return { days, hoursPerDay: hours / days, share: hours / (days * HOURS_PER_DAY) }
}

/**
 * Coins and cells per day: the median rate of the full farm runs played since income last
 * changed, times the hours the account runs per day, with a 25th–75th percentile band.
 *
 * Only farm runs on the forecast's tier set the rate; restarts, tournaments and Dissonant runs
 * are classified and left out. A paused run still sets the rate, since rates are per real hour.
 * Hours per day count every run of every kind. With no farm run after the last break, the runs
 * before it are used and a warning says the figures predate the change.
 */
export function forecastIncome(input: IncomeForecastInput): IncomeForecast {
  const warnings: string[] = []
  const nowMs = Date.parse(input.now)
  const since = input.since ? Date.parse(input.since) : Number.NEGATIVE_INFINITY
  const runs = classifyPlanningRuns(input.runs).filter(run => Date.parse(run.endedAt) <= nowMs || !Number.isFinite(nowMs))

  const farmAll = runs.filter(run => run.kind === 'farm')
  let tier: number | null = input.tier ?? null
  if (tier == null && farmAll.length > 0) {
    const counts = new Map<number, number>()
    for (const run of farmAll) counts.set(run.tier, (counts.get(run.tier) ?? 0) + 1)
    tier = [...counts].sort((a, b) => b[1] - a[1] || b[0] - a[0])[0][0]
  }
  const farm = farmAll.filter(run => run.tier === tier)
  const regimeBreaks = findRegimeBreaks(farm, (input.coinBonusReadings ?? []).filter(reading => reading.tier === tier))
  const lastBreak = regimeBreaks.at(-1)

  let pool = farm.filter(run => Date.parse(run.endedAt) > since)
  if (lastBreak) {
    const cut = Date.parse(lastBreak.before)
    /* A run counts as after the break when it cannot have begun before it. */
    const after = pool.filter(run => lastBreak.reason === 'income-step'
      ? Date.parse(run.endedAt) >= cut
      : Date.parse(run.endedAt) - run.realSeconds * 1000 >= cut)
    if (after.length > 0) pool = after
    else warnings.push('no full farm run has finished since income last changed; the rates are from before the change')
  }
  for (const run of pool) run.used = true
  if (pool.length === 0) warnings.push(tier == null ? 'no full farm run to measure' : `no full farm run on tier ${tier} to measure`)
  else if (pool.length < 3) warnings.push(`only ${pool.length} farm run${pool.length === 1 ? '' : 's'} set the rates, so the band is narrow by accident, not by evidence`)

  const band = (pick: (run: ClassifiedRun) => number | null) => quantileBand(pool.map(pick).filter((value): value is number => value != null))
  const coinsPerHour = band(run => run.coinsPerHour)
  const cellsPerHour = band(run => run.cellsPerHour)

  const current = Math.max(0, input.currentRunRealSeconds ?? 0)
  const first = runs.length > 0 ? Date.parse(runs[0].endedAt) - runs[0].realSeconds * 1000 : nowMs
  const wholeDays = Math.max(1, (nowMs - first) / MS_PER_DAY)
  const uptime = Number.isFinite(nowMs)
    ? [uptimeOver(runs, nowMs, 1, current), uptimeOver(runs, nowMs, 7, current), uptimeOver(runs, nowMs, wholeDays, current)]
    : []
  const days = Math.max(1 / HOURS_PER_DAY, input.uptimeDays ?? 1)
  let hoursPerDay = input.hoursPerDay ?? (Number.isFinite(nowMs) ? uptimeOver(runs, nowMs, days, current).hoursPerDay : 0)
  if (!Number.isFinite(nowMs)) warnings.push('the forecast has no date to count hours back from, so hours per day is 0')
  hoursPerDay = Math.min(HOURS_PER_DAY, Math.max(0, hoursPerDay))

  return {
    tier,
    coinsPerRun: band(run => run.coins),
    coinsPerHour,
    cellsPerHour,
    wavesPerHour: band(run => run.wavesPerHour),
    hoursPerDay,
    coinsPerDay: scaleBand(coinsPerHour, hoursPerDay),
    cellsPerDay: scaleBand(cellsPerHour, hoursPerDay),
    runsUsed: pool.length,
    runs,
    regimeBreaks,
    pausedRuns: runs.filter(run => run.paused),
    uptime,
    warnings,
  }
}

/**
 * When each item on an ordered shopping list becomes affordable, buying in list order from a
 * starting balance at a forecast income.
 *
 * `coinsPerDay` is the forecast's band; `now` is an ISO date. An item the balance already covers
 * is affordable at `now`. With no income at a figure, an item the balance does not cover is
 * dated at the far end of time the date type can hold, never guessed.
 */
export function affordableBy(
  list: readonly ShoppingItem[],
  balance: number,
  coinsPerDay: QuantileBand,
  now: string,
): AffordableItem[] {
  const nowMs = Date.parse(now)
  const when = (short: number, rate: number): string => {
    if (short <= 0) return new Date(nowMs).toISOString()
    if (!(rate > 0)) return new Date(8.64e15).toISOString()
    return new Date(Math.min(8.64e15, nowMs + (short / rate) * MS_PER_DAY)).toISOString()
  }
  let cumulativeCoins = 0
  return list.map((item) => {
    cumulativeCoins += Math.max(0, item.coins)
    const short = cumulativeCoins - balance
    return {
      name: item.name,
      coins: item.coins,
      cumulativeCoins,
      affordableAt: { early: when(short, coinsPerDay.p75), likely: when(short, coinsPerDay.median), late: when(short, coinsPerDay.p25) },
    }
  })
}
