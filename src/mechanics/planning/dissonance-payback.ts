/**
 * Prices a Dissonant run: what it adds to every later run of its tier, and how long that takes
 * to repay the farm run given up for it.
 *
 * A Utility Dissonant run earns almost nothing itself and raises that tier's coin bonus for
 * good, by an amount that depends almost entirely on the wave it reaches. So the answer is not
 * one number but a table by wave, and the wave at which the run becomes worth playing.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    priceDissonancePayback
 * depends    src/mechanics/coin-bonus/scenarios, src/mechanics/planning/constants, src/mechanics/planning/types
 * used by    src/calculators/specs.generated, src/mechanics/planning/index, src/save/planning/dissonance
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { compareCoinBonusScenarios } from '../coin-bonus/scenarios'
import { DISSONANT_BOOST_LAST_WAVE } from './constants'
import type { DissonancePayback, DissonancePaybackInput, DissonancePaybackRow } from './types'

const BREAK_EVEN_STEP = 10

/**
 * Payback for a Dissonant run on `tier` at each of `waves`.
 *
 * Gain per day = coins per day × the gain in Total Coin Bonus × the pass-through. Cost = a farm
 * run's coins less what the Dissonant run earns. The gain applies to runs on that tier; an
 * account farming another tier gets only the echo, which this does not price. The break-even
 * wave is searched in steps of ten up to the wave the boost stops growing at.
 */
export function priceDissonancePayback(input: DissonancePaybackInput): DissonancePayback {
  const warnings: string[] = []
  const currentWave = input.coinBonus.dissonance.coinBoostWaves[input.tier] ?? 0
  const cost = Math.max(0, input.farmRunCoins - (input.dissonantRunCoins ?? 0))
  const cellsCost = Math.max(0, input.farmRunCells - (input.dissonantRunCells ?? 0))
  const base = compareCoinBonusScenarios(input.coinBonus, [{ name: 'now', tier: input.tier }])[0]
  if (base.total == null) throw new RangeError(base.error ?? `tier ${input.tier} has no coin bonus`)

  const priced = (wave: number): DissonancePaybackRow => {
    const result = compareCoinBonusScenarios(input.coinBonus, [{ name: String(wave), tier: input.tier, dissonanceWave: { tier: input.tier, wave } }])[0]
    const gain = Math.max(0, (result.ratioToNow ?? 1) - 1)
    const gainPerDay = Math.max(0, input.coinsPerDay) * gain * input.passThrough
    return {
      wave,
      totalBonus: result.total ?? base.total as number,
      gain,
      gainPerDay,
      cost,
      cellsCost,
      paybackDays: gainPerDay > 0 ? cost / gainPerDay : null,
    }
  }

  const rows = [...new Set(input.waves)].filter(wave => Number.isFinite(wave) && wave > 0).sort((a, b) => a - b).map(priced)
  if (rows.some(row => row.wave <= currentWave)) {
    warnings.push(`a run that ends at or below wave ${currentWave}, the best already held on tier ${input.tier}, adds nothing`)
  }
  let breakEvenWave: number | null = null
  if (input.paybackLimitDays != null && input.paybackLimitDays > 0) {
    const first = Math.ceil((currentWave + 1) / BREAK_EVEN_STEP) * BREAK_EVEN_STEP
    for (let wave = first; wave <= DISSONANT_BOOST_LAST_WAVE; wave += BREAK_EVEN_STEP) {
      const days = priced(wave).paybackDays
      if (days != null && days <= input.paybackLimitDays) { breakEvenWave = wave; break }
    }
  }
  if (input.passThrough < 1) {
    warnings.push(`gains are multiplied by a pass-through of ${input.passThrough.toFixed(2)}: recorded coins have risen by less than the coin bonus predicted`)
  }
  return { tier: input.tier, currentWave, currentBonus: base.total, rows, breakEvenWave, permanent: true, warnings }
}
