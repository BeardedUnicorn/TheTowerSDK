/**
 * Healing as a clamped rate per wave, not a bigger pool.
 *
 * The clamps are the point. A package that lands on a tower already at its overheal cap heals
 * nothing, so the same Recovery Amount heals very different totals in different runs; lifesteal
 * and regen stop at full health and never touch the overheal packages left. An effective-health
 * score cannot say any of that, which is why this is a model of its own.
 *
 * Exact for the rules the wiki states (package amount and cap, the full-health cap, the Death
 * Wave max-health bonus). How much lifesteal a wave offers is an estimate from expected kills.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    survivalHealthAfterPackage, survivalHealthAfterCappedHeal, survivalExpectedPackagesForWave, survivalProjectileDamageForWave, healingForWave
 * depends    src/mechanics/enemies/type-mults, src/mechanics/survival/constants, src/mechanics/survival/resolve, src/mechanics/survival/spawns, src/mechanics/survival/types, src/mechanics/uptime/compute
 * used by    src/calculators/specs.generated, src/mechanics/survival/index, src/mechanics/survival/simulate
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { ENEMY_MULT_BY_TYPE_TABLE } from '../enemies/type-mults'
import { computeWaveCombatDurationSeconds } from '../uptime/compute'
import { SURVIVAL_FULL_HEALTH_MULTIPLE } from './constants'
import { resolveSurvivalStats } from './resolve'
import { survivalEnemyBaseAtLevel, survivalIsBossWave, survivalSpawnCountsForWave } from './spawns'
import type { SurvivalHealingOptions, SurvivalState, SurvivalWaveHealing } from './types'

/**
 * Health after one recovery package: Recovery Amount × max health is added, up to Max Recovery ×
 * max health. Health already above the cap is left where it is.
 *
 * `share` scales the package, for the expected value of a package that only may arrive.
 *
 * @unit amount: health
 */
export function survivalHealthAfterPackage(
  health: number,
  maxHealth: number,
  recoveryAmount: number,
  maxRecovery: number,
  share = 1,
): number {
  const cap = Math.max(health, maxRecovery * maxHealth)
  return Math.min(health + Math.max(0, share) * recoveryAmount * maxHealth, cap)
}

/**
 * Health after a heal that stops at full health — lifesteal, health regen. It tops up to 100% and
 * never removes overheal a package already gave.
 *
 * @unit amount: health
 */
export function survivalHealthAfterCappedHeal(health: number, maxHealth: number, amount: number): number {
  const cap = Math.max(health, SURVIVAL_FULL_HEALTH_MULTIPLE * maxHealth)
  return Math.min(health + Math.max(0, amount), cap)
}

/**
 * Expected recovery packages in one played wave: the Package Chance roll, plus one after a boss
 * wave when the Package After Boss lab is owned.
 *
 * @unit packages
 */
export function survivalExpectedPackagesForWave(state: SurvivalState, wave: number, packageChance: number): number {
  const afterBoss = state.packageAfterBoss && survivalIsBossWave(state.tier, wave) ? 1 : 0
  return Math.min(1, Math.max(0, packageChance)) + afterBoss
}

/**
 * Projectile damage a wave offers lifesteal: the health of the enemies the tower's projectiles
 * kill. An estimate — it counts kills, not overkill or damage to survivors.
 *
 * @unit amount: damage
 */
export function survivalProjectileDamageForWave(state: SurvivalState, wave: number, healthSkips = 0): number {
  const w = Math.max(1, Math.floor(wave))
  const level = Math.max(1, w - Math.max(0, Math.floor(healthSkips)))
  const health = survivalEnemyBaseAtLevel(state.tier, level).hp
  const s = survivalSpawnCountsForWave(state, w)
  const m = ENEMY_MULT_BY_TYPE_TABLE
  const healthUnits = s.basic * m.Basic.hp + s.fast * m.Fast.hp + s.tank * m.Tank.hp + s.ranged * m.Ranged.hp
    + s.protector * m.Protector.hp + s.boss * m.Boss.hp + s.vampire * m.Vampire.hp + s.ray * m.Ray.hp
    + s.scatter * m.Scatter.hp
  return health * healthUnits * Math.min(1, Math.max(0, state.projectileKillShare))
}

/**
 * The four heals of one wave, each after its own clamp, and the health they leave.
 *
 * Applied in this order: the Death Wave bonus raises max health (and current health with it),
 * packages add up to the overheal cap, then lifesteal and regen top up to full health. `options`
 * says what happened in the wave; left out, it is an average played wave starting at full health.
 *
 * @unit amount: health
 */
export function healingForWave(
  state: SurvivalState,
  wave: number,
  options: SurvivalHealingOptions = {},
): SurvivalWaveHealing {
  const levels = options.levels ?? state.levels
  const held = Math.max(0, options.deathWaveFraction ?? 0)
  const before = resolveSurvivalStats(state, levels, held)

  const dw = state.deathWave
  const gained = Math.max(0, Math.min(dw.maxHealthFractionPerWave, dw.maxHealthFractionCap - held))
  const deathWave = gained * before.baseMaxHealth
  const maxHealth = before.maxHealth + deathWave
  let health = (options.health ?? before.maxHealth) + deathWave

  const packageCount = options.packages ?? survivalExpectedPackagesForWave(state, wave, before.packageChance)
  const afterDeathWave = health
  for (let left = Math.max(0, packageCount); left > 0; left -= 1) {
    health = survivalHealthAfterPackage(health, maxHealth, before.recoveryAmount, before.maxRecovery, Math.min(1, left))
  }
  const packages = health - afterDeathWave

  const blocked = options.healingBlocked === true
  const lifestealRaw = blocked || options.lifestealActive === false
    ? 0
    : before.lifesteal * (options.projectileDamage ?? survivalProjectileDamageForWave(state, wave))
  const afterPackages = health
  health = survivalHealthAfterCappedHeal(health, maxHealth, lifestealRaw)
  const lifesteal = health - afterPackages

  const regenRaw = blocked ? 0 : before.regenPerSecond * (options.seconds ?? computeWaveCombatDurationSeconds(false))
  const afterLifesteal = health
  health = survivalHealthAfterCappedHeal(health, maxHealth, regenRaw)
  const regen = health - afterLifesteal

  return { packages, lifesteal, regen, deathWave, healthAfter: health, maxHealth }
}
