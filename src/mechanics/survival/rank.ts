/**
 * Turns death waves into the answer the model exists for: how many waves each candidate upgrade
 * adds per coin.
 *
 * Each candidate is the same account with one workshop level raised, simulated on the same seeds
 * as the baseline so the comparison is between upgrades and not between dice. The coin column is
 * `computeWorkshopUpgradePrice`, so it matches the Workshop screen, discount included.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    rankSurvivalUpgrades
 * depends    src/data/workshop/upgrade-price, src/mechanics/survival/constants, src/mechanics/survival/simulate, src/mechanics/survival/types
 * used by    src/calculators/specs.generated, src/mechanics/survival/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { computeWorkshopUpgradePrice } from '../../data/workshop/upgrade-price'
import { SURVIVAL_STAT_TAB_BY_STAT } from './constants'
import { simulateSurvivalRun } from './simulate'
import type { SurvivalRankInput, SurvivalRankResult, SurvivalRankedUpgrade } from './types'

/**
 * Rank workshop purchases by median waves gained per billion coins.
 *
 * A candidate at or below the current level gains nothing and costs nothing. Unpriced candidates
 * sort last. The ranking inherits the calibration's uncertainty: report its leave-one-out error
 * beside it.
 */
export function rankSurvivalUpgrades(input: SurvivalRankInput): SurvivalRankResult {
  const shared = {
    mode: input.mode,
    calibration: input.calibration,
    seeds: input.seeds,
    baseSeed: input.baseSeed,
    subSteps: input.subSteps,
    cashPolicy: input.cashPolicy,
    assumptions: input.assumptions,
  }
  const baseline = simulateSurvivalRun({ ...shared, state: input.state })

  const ranked: SurvivalRankedUpgrade[] = input.candidates.map((candidate) => {
    const fromLevel = Math.floor(input.state.levels[candidate.stat])
    const toLevel = Math.max(fromLevel, Math.floor(candidate.toLevel))
    const discount = input.discountPercent?.[SURVIVAL_STAT_TAB_BY_STAT[candidate.stat]] ?? 0
    const price = toLevel > fromLevel
      ? computeWorkshopUpgradePrice(candidate.stat, fromLevel, toLevel - fromLevel, discount)
      : null
    /* The table may stop short of the level asked for; price and simulate what it can sell. */
    const reached = price ? price.toLevel : toLevel
    const result = reached > fromLevel
      ? simulateSurvivalRun({ ...shared, state: { ...input.state, levels: { ...input.state.levels, [candidate.stat]: reached } } })
      : baseline
    const medianWavesGained = result.deathWave.median - baseline.deathWave.median
    const coins = toLevel > fromLevel ? price?.coins ?? null : 0
    return {
      stat: candidate.stat,
      fromLevel,
      toLevel: reached,
      coins,
      medianWavesGained,
      wavesPerBillionCoins: coins != null && coins > 0 ? medianWavesGained / (coins / 1e9) : null,
      deathWave: result.deathWave,
    }
  })

  ranked.sort((a, b) => (b.wavesPerBillionCoins ?? Number.NEGATIVE_INFINITY) - (a.wavesPerBillionCoins ?? Number.NEGATIVE_INFINITY))
  return { baseline: baseline.deathWave, ranked, assumptions: baseline.assumptions }
}
