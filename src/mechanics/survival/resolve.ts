/**
 * Turns a state and a set of in-run levels into the numbers a wave is fought with.
 *
 * Every value comes from the workshop table through `workshopStatValue`, then takes the account's
 * resolved bonus. Nothing here is fitted. It exists as its own module because healing, incoming
 * damage and the simulator all need the same resolution and must not each do it differently.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    survivalStatLevelCap, resolveSurvivalStats, clampSurvivalLevels
 * depends    src/mechanics/effective-paths/hp, src/mechanics/effective-paths/workshop-values, src/mechanics/survival/constants, src/mechanics/survival/types
 * used by    src/calculators/specs.generated, src/mechanics/survival/healing, src/mechanics/survival/incoming-damage, src/mechanics/survival/index, src/mechanics/survival/simulate
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { DEFENSE_PERCENT_CAP } from '../effective-paths/hp'
import {
  inRunWorkshopStatValue,
  workshopStatMaxLevel,
  workshopStatValue,
} from '../effective-paths/workshop-values'
import { SURVIVAL_STATS } from './constants'
import type { SurvivalLevels, SurvivalResolvedStats, SurvivalStat, SurvivalState } from './types'

/**
 * The highest in-run level each modelled upgrade can reach.
 *
 * Health and Health Regen keep growing past the workshop table in a run, to the 10000 the in-run
 * curve covers. Every other upgrade stops at its last table row.
 *
 * @unit levels
 */
export function survivalStatLevelCap(stat: SurvivalStat): number {
  if (stat === 'Health' || stat === 'Health Regen') return 10_000
  return workshopStatMaxLevel(stat) ?? 0
}

/* The table is fixed, and a run reads it a few million times: remember each (upgrade, level). */
const VALUE_BY_STAT = new Map<SurvivalStat, number[]>()
const CAP_BY_STAT = new Map<SurvivalStat, number>()

function tableValue(stat: SurvivalStat, level: number): number {
  let cap = CAP_BY_STAT.get(stat)
  if (cap === undefined) {
    cap = survivalStatLevelCap(stat)
    CAP_BY_STAT.set(stat, cap)
  }
  const capped = Math.max(0, Math.min(Math.floor(level), cap))
  let values = VALUE_BY_STAT.get(stat)
  if (!values) {
    values = []
    VALUE_BY_STAT.set(stat, values)
  }
  const known = values[capped]
  if (known !== undefined) return known
  const value = stat === 'Health' || stat === 'Health Regen'
    ? inRunWorkshopStatValue(stat, capped) ?? 0
    : workshopStatValue(stat, capped)?.value ?? 0
  values[capped] = value
  return value
}

/**
 * What the state's upgrades are worth at the given in-run levels.
 *
 * Exact for the workshop's own contribution; the bonuses are whatever the state's builder resolved.
 * `deathWaveFraction` is the Death Wave health bonus held so far, as a share of base max health.
 */
export function resolveSurvivalStats(
  state: SurvivalState,
  levels: SurvivalLevels = state.levels,
  deathWaveFraction = 0,
): SurvivalResolvedStats {
  const b = state.bonuses
  const baseMaxHealth = tableValue('Health', levels['Health']) * b.healthMultiplier
  return {
    baseMaxHealth,
    maxHealth: baseMaxHealth * (1 + Math.max(0, deathWaveFraction)),
    regenPerSecond: tableValue('Health Regen', levels['Health Regen']) * b.healthRegenMultiplier,
    defensePercent: Math.min(
      DEFENSE_PERCENT_CAP,
      Math.max(0, tableValue('Defense Percent', levels['Defense Percent']) + b.defensePercentAdd),
    ),
    defenseAbsolute: tableValue('Defense Absolute', levels['Defense Absolute']) * b.defenseAbsoluteMultiplier,
    recoveryAmount: Math.max(0, tableValue('Recovery Amount', levels['Recovery Amount']) + b.recoveryAmountAdd),
    maxRecovery: Math.max(1, tableValue('Max Recovery', levels['Max Recovery']) + b.maxRecoveryAdd),
    packageChance: Math.max(0, tableValue('Package Chance', levels['Package Chance']) + b.packageChanceAdd),
    lifesteal: tableValue('Lifesteal', levels['Lifesteal']) * b.lifestealMultiplier,
    deathDefy: Math.min(1, Math.max(0, tableValue('Death Defy', levels['Death Defy']))),
    attackSkipChance: tableValue('Enemy Attack Level Skip', levels['Enemy Attack Level Skip']),
    healthSkipChance: tableValue('Enemy Health Level Skip', levels['Enemy Health Level Skip']),
  }
}

/** A copy of the levels, each held inside what its upgrade can reach. */
export function clampSurvivalLevels(levels: SurvivalLevels): SurvivalLevels {
  const out = { ...levels }
  for (const stat of SURVIVAL_STATS) {
    out[stat] = Math.max(0, Math.min(Math.floor(Number(levels[stat]) || 0), survivalStatLevelCap(stat)))
  }
  return out
}
