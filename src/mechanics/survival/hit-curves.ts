/**
 * How many hits one spawned enemy lands before it dies — the only term of incoming damage with no
 * game data behind it.
 *
 * **Fitted, not derived.** Deriving it needs enemy movement speed, range, knockback and attack
 * rate, which the SDK does not ship. So the model uses the one driver it does have: how long an
 * enemy outlives the tower's damage. Hits rise with that survival ratio along a power curve, one
 * curve per class group, and `fitSurvivalCalibration` finds the curve's two numbers from run
 * history. A damage upgrade lowers the ratio and so lowers incoming damage too; orb kills enter the
 * same way, through whatever kill speed the state's `effectiveDamage` reports.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    SURVIVAL_MAX_HITS_PER_ENEMY, survivalRatioAtWave, survivalStateForCalibration, survivalReferenceRatio, survivalHitsPerEnemy, survivalMeleeHeatUpFactor
 * depends    src/mechanics/survival/constants, src/mechanics/survival/spawns, src/mechanics/survival/types
 * used by    src/calculators/specs.generated, src/mechanics/survival/calibrate, src/mechanics/survival/incoming-damage, src/mechanics/survival/index, src/mechanics/survival/simulate
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { SURVIVAL_MELEE_HEAT_UP_PER_HIT } from './constants'
import { survivalEnemyBaseAtLevel } from './spawns'
import type { SurvivalCalibration, SurvivalHitCurve, SurvivalState } from './types'

/** Model guard: no curve reports more hits per enemy than this, however far it is extrapolated. */
export const SURVIVAL_MAX_HITS_PER_ENEMY = 500

/**
 * A basic enemy's health over the tower's effective damage at a wave: how long enemies outlive the
 * tower, in whatever unit `effectiveDamage` carries.
 *
 * `healthSkips` is the Enemy Health Level Skip count so far, which holds enemy health back.
 *
 * @unit ratio: enemy health per unit of effective damage
 */
export function survivalRatioAtWave(state: SurvivalState, wave: number, healthSkips = 0): number {
  const w = Math.max(1, Math.floor(wave))
  const level = Math.max(1, w - Math.max(0, Math.floor(healthSkips)))
  const health = survivalEnemyBaseAtLevel(state.tier, level).hp
  const damage = state.effectiveDamage * Math.pow(state.effectiveDamageGrowthPerWave, w - 1)
  return damage > 0 ? health / damage : Number.POSITIVE_INFINITY
}

/**
 * The state as a calibration sees it: max health scaled by the fitted `healthScale`.
 *
 * Every calculator that takes a calibration applies this first, so the scale cannot be applied
 * twice or forgotten.
 */
export function survivalStateForCalibration(state: SurvivalState, calibration: SurvivalCalibration): SurvivalState {
  const scale = calibration.healthScale
  if (!(scale > 0) || scale === 1) return state
  return { ...state, bonuses: { ...state.bonuses, healthMultiplier: state.bonuses.healthMultiplier * scale } }
}

/** The ratio a calibration measures its curves against: its own, or the state's at the reference wave. */
export function survivalReferenceRatio(state: SurvivalState, calibration: SurvivalCalibration): number {
  return calibration.referenceRatio ?? survivalRatioAtWave(state, calibration.referenceWave)
}

/**
 * Hits landed per spawned enemy on one curve. Fitted.
 *
 * `exp(logHits)` at the reference ratio, rising as `(ratio / referenceRatio) ^ exponent`, and held
 * between 0 and `SURVIVAL_MAX_HITS_PER_ENEMY`.
 *
 * @unit hits per enemy
 */
export function survivalHitsPerEnemy(curve: SurvivalHitCurve, ratio: number, referenceRatio: number): number {
  if (!(ratio > 0) || !(referenceRatio > 0)) return 0
  const hits = Math.exp(curve.logHits + curve.exponent * Math.log(ratio / referenceRatio))
  if (!Number.isFinite(hits)) return SURVIVAL_MAX_HITS_PER_ENEMY
  return Math.min(SURVIVAL_MAX_HITS_PER_ENEMY, Math.max(0, hits))
}

/**
 * The average strength of an enemy's melee hits when it lands `hits` of them, each 4% stronger
 * than the last. Exact for whole hits; 1 for a single hit or less.
 *
 * @unit multiplier
 */
export function survivalMeleeHeatUpFactor(hits: number): number {
  if (!(hits > 1)) return 1
  const step = SURVIVAL_MELEE_HEAT_UP_PER_HIT
  return (Math.pow(1 + step, hits) - 1) / (step * hits)
}
