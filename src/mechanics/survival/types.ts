/**
 * One group's hit curve: hits landed per spawned enemy.
 *
 * `hits = exp(logHits) × (survivalRatio / referenceRatio) ^ exponent`, where `survivalRatio` is
 * enemy health over the tower's effective damage. **Fitted, not derived** — see `hit-curves.ts`.
 */
export interface SurvivalHitCurve {
  /** Natural log of hits per enemy at the reference ratio. */
  logHits: number
  /** How steeply hits rise as enemies outlive the tower's damage. */
  exponent: number
}

/** The fitted part of the model: one curve per group, and the health scale. */
export interface SurvivalCalibration {
  curves: Record<SurvivalClassGroup, SurvivalHitCurve>
  /**
   * Multiplies the state's max health. **Fitted.** It stands in for the max-health multipliers a
   * state does not resolve — labs, perks, relics, modules, the Death Wave bonus — and the size of
   * a real package heal is what pins it. 1 for a state that resolves them all.
   */
  healthScale: number
  /**
   * The survival ratio at which `logHits` is read. `null` uses the state's own ratio at
   * `referenceWave`, which makes the curve blind to damage upgrades; a fit stores a number.
   */
  referenceRatio: number | null
  referenceWave: number
}

