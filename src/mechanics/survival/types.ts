/** The workshop upgrades the survival model reads, by their workshop table name. */
export type SurvivalStat =
  | 'Health'
  | 'Health Regen'
  | 'Defense Percent'
  | 'Defense Absolute'
  | 'Recovery Amount'
  | 'Max Recovery'
  | 'Package Chance'
  | 'Lifesteal'
  | 'Death Defy'
  | 'Enemy Attack Level Skip'
  | 'Enemy Health Level Skip'

/** A level for every modelled upgrade. Workshop levels at wave 1; in-run levels after it. */
export type SurvivalLevels = Record<SurvivalStat, number>

/** Which workshop tab a free upgrade belongs to. */
export type SurvivalFreeUpgradeTab = 'defense' | 'utility'

/**
 * What the account adds on top of the workshop ladder, already resolved to numbers.
 *
 * The simulator does not know about labs, cards, relics or modules. Whoever builds the state folds
 * them into these, so the same simulator serves a save, a snapshot and a hand-built test state.
 */
export interface SurvivalBonuses {
  /** Multiplies workshop Health into max health. */
  healthMultiplier: number
  /** Multiplies workshop Health Regen. */
  healthRegenMultiplier: number
  /** Multiplies workshop Defense Absolute. */
  defenseAbsoluteMultiplier: number
  /** Added to workshop Defense %, as a fraction. The total is still capped at 98%. */
  defensePercentAdd: number
  /** Added to workshop Recovery Amount, as a fraction of max health. */
  recoveryAmountAdd: number
  /** Added to the workshop Max Recovery multiplier. */
  maxRecoveryAdd: number
  /** Added to workshop Package Chance, as a fraction. */
  packageChanceAdd: number
  /** Multiplies workshop Lifesteal. */
  lifestealMultiplier: number
  /**
   * Share of a hit still taken after the layers that sit outside Defense % — Flame Bot, Chrono
   * Field, the trade-off perk. 1 means none of them.
   */
  otherDamageTakenMultiplier: number
}

/** How many enemies a wave holds and of which kinds. */
export interface SurvivalSpawnProfile {
  /** Multiplies the SDK's expected ordinary enemies per wave. Measured from history when known. */
  countScale: number
  /** Enemy Balance card multiplier on ordinary spawns. */
  enemyBalanceMultiplier: number
  /** Share of ordinary spawns by kind. Sums to 1. */
  shares: { basic: number, fast: number, tank: number, ranged: number, protector: number }
  /** Multiplies the SDK's expected elites per wave. */
  eliteScale: number
  /** Share of elites by kind. Sums to 1. */
  eliteShares: { vampire: number, ray: number, scatter: number }
}

/** Free upgrades: the chance per wave and what they can land on. */
export interface SurvivalFreeUpgradeProfile {
  /** Chance per wave, as a fraction. Above 1 the excess is the chance of a second. */
  defenseChance: number
  utilityChance: number
  /** Uncapped defense upgrades outside the model that also take free upgrades. */
  otherDefenseTargets: number
  /** Uncapped utility upgrades outside the model that also take free upgrades. */
  otherUtilityTargets: number
}

/** Death Wave's health bonus, which raises max health rather than healing. */
export interface SurvivalDeathWaveProfile {
  /** Max health gained per played wave, as a fraction of base max health. */
  maxHealthFractionPerWave: number
  /** Where the bonus stops, as a fraction of base max health. */
  maxHealthFractionCap: number
}

/**
 * Mechanics the wiki and the game data do not settle. Each is a switch with a default, and every
 * result echoes the ones it ran with.
 */
export interface SurvivalAssumptions {
  /** A run record's `damageTaken` is measured after mitigation. */
  damageTakenIsPostMitigation: boolean
  /** When max health rises mid-run, current health rises by the same amount. */
  maxHealthGrowthHealsCurrent: boolean
  /** Recovery packages are rolled on skipped waves too. */
  packagesOnSkippedWaves: boolean
  /** Lifesteal heals during the run. Some run records show none at all. */
  lifestealActive: boolean
}

/** Everything a run starts from. Plain numbers, so it serialises and a test can build one. */
export interface SurvivalState {
  tier: number
  /** Workshop levels: the in-run levels at wave 1. */
  levels: SurvivalLevels
  bonuses: SurvivalBonuses
  spawn: SurvivalSpawnProfile
  freeUpgrades: SurvivalFreeUpgradeProfile
  deathWave: SurvivalDeathWaveProfile
  /** The Package After Boss lab: one extra package after each boss wave. */
  packageAfterBoss: boolean
  /** Chance a wave is skipped by the Wave Skip card, as a fraction. */
  waveSkipChance: number
  /**
   * The tower's kill speed, as the eDamage model's index. Only its ratio to enemy health matters,
   * so the unit is free; the calibration is fitted against whatever the state supplies.
   */
  effectiveDamage: number
  /** Multiplies `effectiveDamage` each wave, for in-run attack upgrades. 1 is no growth. */
  effectiveDamageGrowthPerWave: number
  /** Share of kills made by tower projectiles, the only damage lifesteal reads. */
  projectileKillShare: number
}

