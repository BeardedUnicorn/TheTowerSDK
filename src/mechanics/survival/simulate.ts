/**
 * Plays a run forward wave by wave, the way `simulateWaveEconRows` does for coins, and stops when
 * health reaches zero.
 *
 * It steps inside each wave because runs end two ways: the pool is worn down over many waves
 * (attrition), or one stretch of a wave breaks a pool that was still healthy (burst). A per-wave
 * average cannot tell those apart. Spawns, packages, free upgrades, wave skips and Death Defy are
 * random, each on its own seeded stream so two states run on the same seed meet the same luck.
 *
 * A model, not a replay: incoming damage rests on the fitted hit curves.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    survivalRunSeed, survivalPercentiles, simulateSurvivalRunOnce, simulateSurvivalRunOutcomes, simulateSurvivalRun
 * depends    src/mechanics/primitives/unity-random, src/mechanics/survival/constants, src/mechanics/survival/healing, src/mechanics/survival/hit-curves, src/mechanics/survival/incoming-damage, src/mechanics/survival/resolve (+3 more)
 * used by    src/calculators/specs.generated, src/mechanics/survival/calibrate, src/mechanics/survival/index, src/mechanics/survival/rank, src/save/survival/from-save
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
