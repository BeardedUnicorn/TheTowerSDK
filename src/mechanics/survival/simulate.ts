/* One salt per random source, so each has its own stream under a single run seed. */
const STREAM_SALTS = { spawns: 0x1f83d9ab, packages: 0x5be0cd19, upgrades: 0x9e3779b9, skips: 0x3c6ef372, deathDefy: 0xa54ff53a, hits: 0x510e527f }

/* Above this many expected hits in a sub-step the count is taken as its expectation. */
const WHOLE_HIT_ROLL_BELOW = 20

interface RunSetup {
  state: SurvivalState
  calibration: SurvivalCalibration
  assumptions: SurvivalAssumptions
  subSteps: number
  maxWave: number
  active: boolean
  cashTargets: readonly { stat: SurvivalStat, target: number }[]
  cashByWave: number
  /** Expected spawns by wave, filled as runs reach each wave. */
  spawnsByWave: SurvivalSpawnCounts[]
  projectileDamageByWave: number[]
  targetsByTab: Record<SurvivalFreeUpgradeTab, readonly SurvivalStat[]>
  capByStat: Record<SurvivalStat, number>
  waveSeconds: number
}

/**
 * The seed run `index` uses under a base seed. Spread with the same multiplier the bot medal
 * simulation uses, so neighbouring base seeds do not share runs.
 */
export function survivalRunSeed(baseSeed: number, index: number): number {
  return ((baseSeed >>> 0) ^ Math.imul(index + 1, 2_654_435_761)) >>> 0
}

/** Nearest-rank 10th, 50th and 90th percentiles. An empty list reports zeros. */
export function survivalPercentiles(values: readonly number[]): SurvivalPercentiles {
  if (values.length === 0) return { p10: 0, median: 0, p90: 0 }
  const sorted = [...values].sort((a, b) => a - b)
  const at = (share: number) => sorted[Math.min(sorted.length - 1, Math.floor(share * (sorted.length - 1)))]
  return { p10: at(0.1), median: at(0.5), p90: at(0.9) }
}

function buildSetup(input: SurvivalSimulationInput): RunSetup {
  const calibration = input.calibration ?? SURVIVAL_DEFAULT_CALIBRATION
  /* Scaled once here; `survivalHitsForWave` is then handed a calibration with the scale spent. */
  const state = { ...survivalStateForCalibration(input.state, calibration), levels: clampSurvivalLevels(input.state.levels) }
  const active = input.mode === 'active' && input.cashPolicy != null
  const cashTargets: { stat: SurvivalStat, target: number }[] = []
  if (active && input.cashPolicy) {
    for (const stat of SURVIVAL_STATS) {
      const target = input.cashPolicy.targetLevels[stat]
      if (typeof target === 'number' && Number.isFinite(target)) cashTargets.push({ stat, target: Math.floor(target) })
    }
  }
  const capByStat = {} as Record<SurvivalStat, number>
  for (const stat of SURVIVAL_STATS) capByStat[stat] = survivalStatLevelCap(stat)
  return {
    state,
    calibration: { ...calibration, healthScale: 1 },
    assumptions: { ...SURVIVAL_DEFAULT_ASSUMPTIONS, ...input.assumptions },
    subSteps: Math.max(1, Math.floor(input.subSteps ?? SURVIVAL_DEFAULT_SUB_STEPS)),
    maxWave: Math.max(1, Math.floor(input.maxWave ?? SURVIVAL_DEFAULT_MAX_WAVE)),
    active,
    cashTargets,
    cashByWave: Math.max(1, Math.floor(input.cashPolicy?.byWave ?? 1)),
    spawnsByWave: [],
    projectileDamageByWave: [],
    targetsByTab: {
      defense: SURVIVAL_STATS.filter(stat => SURVIVAL_STAT_TAB_BY_STAT[stat] === 'defense'),
      utility: SURVIVAL_STATS.filter(stat => SURVIVAL_STAT_TAB_BY_STAT[stat] === 'utility'),
    },
    capByStat,
    waveSeconds: computeWaveCombatDurationSeconds(false),
  }
}

/* Whole events from a chance that may exceed 1: the whole part, plus one more by the remainder. */
function rollCount(rng: UnityRandom, expected: number): number {
  if (!(expected > 0)) return 0
  const whole = Math.floor(expected)
  return whole + (rng.value() < expected - whole ? 1 : 0)
}

/* Land free upgrades on the tab's uncapped upgrades, modelled or not. Returns whether a level moved. */
function landFreeUpgrades(
  setup: RunSetup,
  rng: UnityRandom,
  tab: SurvivalFreeUpgradeTab,
  count: number,
  levels: SurvivalLevels,
): boolean {
  const others = Math.max(0, Math.floor(
    tab === 'defense' ? setup.state.freeUpgrades.otherDefenseTargets : setup.state.freeUpgrades.otherUtilityTargets,
  ))
  let moved = false
  for (let i = 0; i < count; i += 1) {
    const open = setup.targetsByTab[tab].filter(stat => levels[stat] < setup.capByStat[stat])
    const slots = open.length + others
    if (slots === 0) return moved
    const pick = rng.rangeInt(0, slots)
    if (pick < open.length) {
      levels[open[pick]] += 1
      moved = true
    }
  }
  return moved
}

function simulateOne(setup: RunSetup, seed: number, wantRows: boolean): SurvivalRunOutcome {
  const { state, assumptions, subSteps } = setup
  const rng = {
    spawns: UnityRandom.fromSeed((seed ^ STREAM_SALTS.spawns) >>> 0),
    packages: UnityRandom.fromSeed((seed ^ STREAM_SALTS.packages) >>> 0),
    upgrades: UnityRandom.fromSeed((seed ^ STREAM_SALTS.upgrades) >>> 0),
    skips: UnityRandom.fromSeed((seed ^ STREAM_SALTS.skips) >>> 0),
    deathDefy: UnityRandom.fromSeed((seed ^ STREAM_SALTS.deathDefy) >>> 0),
    hits: UnityRandom.fromSeed((seed ^ STREAM_SALTS.hits) >>> 0),
  }
  const levels: SurvivalLevels = { ...state.levels }
  let deathWaveFraction = 0
  let stats = resolveSurvivalStats(state, levels, deathWaveFraction)
  let health = stats.maxHealth
  const out: SurvivalRunOutcome = {
    deathWave: setup.maxWave,
    endedBy: 'survived',
    damageTaken: 0,
    damageMitigated: 0,
    packages: 0,
    packageHeal: 0,
    lifestealHeal: 0,
    regenHeal: 0,
    maxHealthGrowth: 0,
    startingHealth: health,
    deathDefies: 0,
    attackSkips: 0,
    wavesSkipped: 0,
  }
  const rows: SurvivalRunRow[] = []
  let attackCounter = 0
  let healthCounter = 0
  let healthSkips = 0
  const elitePick = state.spawn.eliteShares

  for (let wave = 1; wave <= setup.maxWave; wave += 1) {
    const row: SurvivalRunRow = {
      wave, health: 0, maxHealth: 0, damageTaken: 0, damageMitigated: 0,
      packages: 0, packageHeal: 0, lifestealHeal: 0, regenHeal: 0, deathWaveHeal: 0,
    }

    /* 1. Enemies gain a level, less level skips: the game's counter, as `simulateEnemyLevelSkips`. */
    attackCounter += stats.attackSkipChance
    if (attackCounter > 1) { attackCounter -= 1; out.attackSkips += 1 }
    healthCounter += stats.healthSkipChance
    if (healthCounter > 1) { healthCounter -= 1; healthSkips += 1 }

    /* 2. Free upgrades from the wave before, then the cash policy. */
    let moved = false
    if (wave > 1) {
      moved = landFreeUpgrades(setup, rng.upgrades, 'defense', rollCount(rng.upgrades, state.freeUpgrades.defenseChance), levels) || moved
      moved = landFreeUpgrades(setup, rng.upgrades, 'utility', rollCount(rng.upgrades, state.freeUpgrades.utilityChance), levels) || moved
    }
    for (const { stat, target } of setup.cashTargets) {
      const base = state.levels[stat]
      const planned = Math.min(setup.capByStat[stat], base + Math.floor((target - base) * Math.min(1, wave / setup.cashByWave)))
      if (planned > levels[stat]) { levels[stat] = planned; moved = true }
    }

    const skipped = wave > 1 && rng.skips.value() < state.waveSkipChance
    if (skipped) out.wavesSkipped += 1

    /* 3. Max health from the in-run Health level and the Death Wave bonus. */
    const dw = state.deathWave
    const gained = skipped ? 0 : Math.max(0, Math.min(dw.maxHealthFractionPerWave, dw.maxHealthFractionCap - deathWaveFraction))
    if (moved || gained > 0) {
      const before = stats.maxHealth
      deathWaveFraction += gained
      stats = resolveSurvivalStats(state, levels, deathWaveFraction)
      const rise = stats.maxHealth - before
      if (rise > 0 && assumptions.maxHealthGrowthHealsCurrent) {
        health += rise
        out.maxHealthGrowth += rise
        row.deathWaveHeal = gained > 0 ? rise : 0
      }
    }
    const maxHealth = stats.maxHealth

    /* Packages this wave, each in a sub-step of its own; the after-boss one lands last. */
    const rollsPackage = !skipped || assumptions.packagesOnSkippedWaves
    const chancePackages = rollsPackage && rng.packages.value() < stats.packageChance ? 1 : 0
    const bossPackage = !skipped && state.packageAfterBoss && survivalIsBossWave(state.tier, wave) ? 1 : 0
    const chanceStep = chancePackages > 0 ? rng.packages.rangeInt(0, subSteps) : -1

    if (skipped) {
      if (chancePackages > 0) {
        const after = survivalHealthAfterPackage(health, maxHealth, stats.recoveryAmount, stats.maxRecovery)
        row.packages += 1
        row.packageHeal += after - health
        health = after
      }
    } else {
      let expected = setup.spawnsByWave[wave]
      if (!expected) {
        expected = survivalSpawnCountsForWave(state, wave)
        setup.spawnsByWave[wave] = expected
        setup.projectileDamageByWave[wave] = survivalProjectileDamageForWave(state, wave)
      }
      /* Elites arrive whole: roll how many, then which kind each is. */
      const spawns: SurvivalSpawnCounts = { ...expected, vampire: 0, ray: 0, scatter: 0 }
      const elites = rollCount(rng.spawns, expected.vampire + expected.ray + expected.scatter)
      for (let i = 0; i < elites; i += 1) {
        const u = rng.spawns.value()
        if (u < elitePick.vampire) spawns.vampire += 1
        else if (u < elitePick.vampire + elitePick.ray) spawns.ray += 1
        else spawns.scatter += 1
      }
      const hits = survivalHitsForWave(
        state, wave, setup.calibration,
        { levels, attackSkips: out.attackSkips, healthSkips, deathWaveFraction },
        spawns,
      )
      const healingBlocked = spawns.vampire > 0
      const lifestealPerStep = assumptions.lifestealActive && !healingBlocked
        ? stats.lifesteal * setup.projectileDamageByWave[wave] / subSteps
        : 0
      const regenPerStep = healingBlocked ? 0 : stats.regenPerSecond * setup.waveSeconds / subSteps
      const poolAtStart = health
      const burstLine = maxHealth * (1 + SURVIVAL_BURST_POOL_SHARE * (stats.maxRecovery - 1))

      /* 4. Sub-steps: that share of the hits, then any package, then lifesteal and regen. */
      for (let step = 0; step < subSteps; step += 1) {
        let damage = 0
        let mitigated = 0
        for (const entry of hits) {
          const share = entry.hits / subSteps
          const count = share >= WHOLE_HIT_ROLL_BELOW ? share : rollCount(rng.hits, share)
          if (count <= 0) continue
          damage += count * entry.damagePerHit
          mitigated += count * (entry.rawPerHit - entry.damagePerHit)
        }
        row.damageMitigated += mitigated

        /* 5. A killing sub-step rolls Death Defy, which ignores the hit; failing it ends the run. */
        if (damage >= health && damage > 0) {
          if (rng.deathDefy.value() < stats.deathDefy) {
            out.deathDefies += 1
          } else {
            row.damageTaken += health
            health = 0
            const endedBy: SurvivalEnding = poolAtStart >= burstLine ? 'burst' : 'attrition'
            out.endedBy = endedBy
            out.deathWave = wave
            break
          }
        } else {
          health -= damage
          row.damageTaken += damage
        }

        const stepPackages = (step === chanceStep ? 1 : 0) + (step === subSteps - 1 ? bossPackage : 0)
        for (let i = 0; i < stepPackages; i += 1) {
          const after = survivalHealthAfterPackage(health, maxHealth, stats.recoveryAmount, stats.maxRecovery)
          row.packages += 1
          row.packageHeal += after - health
          health = after
        }
        if (lifestealPerStep > 0) {
          const after = survivalHealthAfterCappedHeal(health, maxHealth, lifestealPerStep)
          row.lifestealHeal += after - health
          health = after
        }
        if (regenPerStep > 0) {
          const after = survivalHealthAfterCappedHeal(health, maxHealth, regenPerStep)
          row.regenHeal += after - health
          health = after
        }
      }
    }

    /* 6. One row per wave. */
    out.damageTaken += row.damageTaken
    out.damageMitigated += row.damageMitigated
    out.packages += row.packages
    out.packageHeal += row.packageHeal
    out.lifestealHeal += row.lifestealHeal
    out.regenHeal += row.regenHeal
    if (wantRows) {
      row.health = health
      row.maxHealth = maxHealth
      rows.push(row)
    }
    if (out.endedBy !== 'survived') break
  }
  if (wantRows) out.rows = rows
  return out
}

/**
 * One seeded run from wave 1 to death, with its totals.
 *
 * The same seed gives the same run. `rows` adds one row per wave.
 */
export function simulateSurvivalRunOnce(input: SurvivalSimulationInput, seed: number): SurvivalRunOutcome {
  return simulateOne(buildSetup(input), seed >>> 0, input.rows === true)
}

/** Every seeded run of a simulation, in seed order. The calibrator reads these directly. */
export function simulateSurvivalRunOutcomes(input: SurvivalSimulationInput): SurvivalRunOutcome[] {
  const setup = buildSetup(input)
  const seeds = Math.max(1, Math.floor(input.seeds ?? SURVIVAL_DEFAULT_SEEDS))
  const baseSeed = Math.floor(input.baseSeed ?? 1)
  const outcomes: SurvivalRunOutcome[] = []
  for (let i = 0; i < seeds; i += 1) outcomes.push(simulateOne(setup, survivalRunSeed(baseSeed, i), false))
  return outcomes
}

/**
 * Many seeded runs of one state: the median death wave with its 10th and 90th percentiles, how
 * the runs ended, and median totals.
 *
 * AFK mode uses workshop levels plus free upgrades. Active mode also follows the declared
 * `cashPolicy`. With `rows`, the run nearest the median death wave is returned wave by wave.
 * Predictions are only as good as the calibration: the default one is a placeholder.
 */
export function simulateSurvivalRun(input: SurvivalSimulationInput): SurvivalSimulationResult {
  const setup = buildSetup(input)
  const seeds = Math.max(1, Math.floor(input.seeds ?? SURVIVAL_DEFAULT_SEEDS))
  const baseSeed = Math.floor(input.baseSeed ?? 1)
  const outcomes: SurvivalRunOutcome[] = []
  for (let i = 0; i < seeds; i += 1) outcomes.push(simulateOne(setup, survivalRunSeed(baseSeed, i), false))

  const deathWave = survivalPercentiles(outcomes.map(o => o.deathWave))
  const share = (ending: SurvivalEnding) => outcomes.filter(o => o.endedBy === ending).length / seeds
  const result: SurvivalSimulationResult = {
    deathWave,
    endedBy: { attrition: share('attrition'), burst: share('burst'), survived: share('survived') },
    damageTaken: survivalPercentiles(outcomes.map(o => o.damageTaken)).median,
    packageHeal: survivalPercentiles(outcomes.map(o => o.packageHeal)).median,
    packages: survivalPercentiles(outcomes.map(o => o.packages)).median,
    seeds,
    assumptions: setup.assumptions,
  }
  if (input.rows) {
    const index = outcomes.findIndex(o => o.deathWave === deathWave.median)
    result.rows = simulateOne(setup, survivalRunSeed(baseSeed, Math.max(0, index)), true).rows
  }
  return result
}
