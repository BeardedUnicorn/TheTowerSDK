/**
 * Damage reaching the tower in one wave: for each kind of enemy, how many spawn, how many hits
 * each lands, how hard a hit is after level skips, and what mitigation leaves of it.
 *
 * Spawns, hit strength and mitigation come from existing calculators. Hits per enemy is the
 * fitted term, from `hit-curves.ts`.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    survivalDamageAfterMitigation, survivalHitsForWave, incomingDamageForWave
 * depends    src/mechanics/combat/damage-reduction, src/mechanics/enemies/type-mults, src/mechanics/survival/constants, src/mechanics/survival/hit-curves, src/mechanics/survival/resolve, src/mechanics/survival/spawns (+2 more)
 * used by    src/calculators/specs.generated, src/mechanics/survival/index, src/mechanics/survival/simulate
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { applyAbsoluteDefense, applyRelativeDefense } from '../combat/damage-reduction'
import { ENEMY_MULT_BY_TYPE_TABLE } from '../enemies/type-mults'
import { computeWaveCombatDurationSeconds } from '../uptime/compute'
import {
  SURVIVAL_DEFAULT_CALIBRATION,
  SURVIVAL_GROUP_BY_CLASS,
  SURVIVAL_VAMPIRE_DRAIN_PER_SECOND,
} from './constants'
import {
  survivalHitsPerEnemy,
  survivalMeleeHeatUpFactor,
  survivalRatioAtWave,
  survivalReferenceRatio,
} from './hit-curves'
import { resolveSurvivalStats } from './resolve'
import { survivalEnemyBaseAtLevel, survivalSpawnCountsForWave } from './spawns'
import type {
  SurvivalCalibration,
  SurvivalClassHits,
  SurvivalEnemyClass,
  SurvivalIncomingDamage,
  SurvivalResolvedStats,
  SurvivalSpawnCounts,
  SurvivalState,
  SurvivalWaveContext,
} from './types'

type SpawnKind = keyof SurvivalSpawnCounts

/** The class each kind is reported under, its enemy-type row, and whether its hits heat up. */
const KIND_ROWS: readonly { kind: SpawnKind, enemyClass: SurvivalEnemyClass, type: keyof typeof ENEMY_MULT_BY_TYPE_TABLE, melee: boolean }[] = [
  { kind: 'basic', enemyClass: 'basic', type: 'Basic', melee: true },
  { kind: 'protector', enemyClass: 'basic', type: 'Protector', melee: true },
  { kind: 'fast', enemyClass: 'fast', type: 'Fast', melee: true },
  { kind: 'tank', enemyClass: 'tank', type: 'Tank', melee: true },
  { kind: 'ranged', enemyClass: 'ranged', type: 'Ranged', melee: false },
  { kind: 'boss', enemyClass: 'boss', type: 'Boss', melee: true },
  { kind: 'scatter', enemyClass: 'elite', type: 'Scatter', melee: true },
  { kind: 'ray', enemyClass: 'elite', type: 'Ray', melee: false },
  { kind: 'vampire', enemyClass: 'elite', type: 'Vampire', melee: false },
]

/**
 * What one hit of `raw` damage takes from health: the layers outside Defense %, then Defense %,
 * then Defense Absolute, floored at zero. The order is the game's — percent before flat.
 *
 * @unit amount: health
 */
export function survivalDamageAfterMitigation(raw: number, stats: SurvivalResolvedStats, otherDamageTakenMultiplier = 1): number {
  const afterLayers = raw * Math.min(1, Math.max(0, otherDamageTakenMultiplier))
  return applyAbsoluteDefense(applyRelativeDefense(afterLayers, stats.defensePercent * 100), stats.defenseAbsolute)
}

/**
 * Every kind's expected hits in one wave, with what each hit carries before and after mitigation.
 *
 * `spawns` lets the simulator pass the wave it actually rolled; left out, the expected counts are
 * used. A Vampire's "hit" is one second of its drain — 2% of max health, which nothing mitigates.
 */
export function survivalHitsForWave(
  state: SurvivalState,
  wave: number,
  calibration: SurvivalCalibration = SURVIVAL_DEFAULT_CALIBRATION,
  context: SurvivalWaveContext = {},
  spawns: SurvivalSpawnCounts = survivalSpawnCountsForWave(state, wave),
): SurvivalClassHits[] {
  const w = Math.max(1, Math.floor(wave))
  const stats = resolveSurvivalStats(state, context.levels ?? state.levels, context.deathWaveFraction ?? 0)
  const attackLevel = Math.max(1, w - Math.max(0, Math.floor(context.attackSkips ?? 0)))
  const baseDamage = survivalEnemyBaseAtLevel(state.tier, attackLevel).damage
  const ratio = survivalRatioAtWave(state, w, context.healthSkips ?? 0)
  const referenceRatio = survivalReferenceRatio(state, calibration)
  const waveSeconds = computeWaveCombatDurationSeconds(false)

  const out: SurvivalClassHits[] = []
  for (const row of KIND_ROWS) {
    const spawned = spawns[row.kind]
    if (!(spawned > 0)) continue
    const type = ENEMY_MULT_BY_TYPE_TABLE[row.type]
    const curve = calibration.curves[SURVIVAL_GROUP_BY_CLASS[row.enemyClass]]
    /* A tougher kind outlives the tower's damage by its health multiple. */
    const perEnemy = survivalHitsPerEnemy(curve, ratio * type.hp, referenceRatio)
    if (row.kind === 'vampire') {
      const drain = SURVIVAL_VAMPIRE_DRAIN_PER_SECOND * stats.maxHealth
      out.push({ enemyClass: row.enemyClass, hits: spawned * Math.min(perEnemy, waveSeconds), damagePerHit: drain, rawPerHit: drain })
      continue
    }
    const raw = baseDamage * type.damage * (row.melee ? survivalMeleeHeatUpFactor(perEnemy) : 1)
    out.push({
      enemyClass: row.enemyClass,
      hits: spawned * perEnemy,
      damagePerHit: survivalDamageAfterMitigation(raw, stats, state.bonuses.otherDamageTakenMultiplier),
      rawPerHit: raw,
    })
  }
  return out
}

/**
 * Damage reaching the tower in one wave, by class, with what the defenses removed.
 *
 * An expectation over the wave's spawns. `context` places the wave in a run — in-run levels and
 * the level skips so far; left out, it is the wave as the workshop alone would meet it.
 *
 * @unit amount: health
 */
export function incomingDamageForWave(
  state: SurvivalState,
  wave: number,
  calibration: SurvivalCalibration = SURVIVAL_DEFAULT_CALIBRATION,
  context: SurvivalWaveContext = {},
): SurvivalIncomingDamage {
  const byClass: Record<SurvivalEnemyClass, number> = { basic: 0, fast: 0, tank: 0, ranged: 0, boss: 0, elite: 0 }
  let total = 0
  let mitigated = 0
  for (const entry of survivalHitsForWave(state, wave, calibration, context)) {
    const taken = entry.hits * entry.damagePerHit
    byClass[entry.enemyClass] += taken
    total += taken
    mitigated += entry.hits * (entry.rawPerHit - entry.damagePerHit)
  }
  return { byClass, mitigated, total }
}
