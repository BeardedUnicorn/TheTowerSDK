/**
 * Tunes the hit curves until simulated runs match real ones.
 *
 * Run records hold per-run totals, not per-wave rows, so the curves have to be smooth and few:
 * two numbers per class group. The fit targets are each run's death wave, total damage taken and
 * total package healing. The search is a seeded pattern search — no gradients, because the
 * simulator is a seeded random process — and leave-one-out says how far to trust the result.
 *
 * **Everything this returns is fitted.** With a handful of runs the curves are loosely pinned;
 * `leaveOneOutError` is the honest measure, not the in-sample loss.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    fitSurvivalCalibration
 * depends    src/mechanics/survival/constants, src/mechanics/survival/hit-curves, src/mechanics/survival/simulate, src/mechanics/survival/types
 * used by    src/calculators/specs.generated, src/mechanics/survival/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { SURVIVAL_DEFAULT_CALIBRATION, SURVIVAL_DEFAULT_SUB_STEPS } from './constants'
import { survivalRatioAtWave } from './hit-curves'
import { simulateSurvivalRunOutcomes, survivalPercentiles } from './simulate'
import type {
  SurvivalCalibration,
  SurvivalClassGroup,
  SurvivalFitOptions,
  SurvivalFitResult,
  SurvivalFitRun,
  SurvivalRunTarget,
} from './types'

const GROUPS: readonly SurvivalClassGroup[] = ['melee', 'ranged', 'bossElite']
const FIT_DEFAULT_SEEDS = 24
const FIT_DEFAULT_PASSES = 3
/* A missed death wave matters far more than a missed total: 10% of a wave against a factor of two. */
const WAVE_WEIGHT = 60
const TOTAL_WEIGHT = 1
const LOG_HITS_RANGE = [-30, 6] as const
const EXPONENT_RANGE = [0, 4] as const

interface Prediction {
  wave: number
  damageTaken: number
  packageHeal: number
  burstShare: number
}

function predict(run: SurvivalRunTarget, calibration: SurvivalCalibration, seeds: number, baseSeed: number, subSteps: number): Prediction {
  const outcomes = simulateSurvivalRunOutcomes({
    state: run.state,
    mode: run.mode,
    cashPolicy: run.cashPolicy,
    assumptions: run.assumptions,
    calibration,
    seeds,
    baseSeed,
    subSteps,
    /* A curve that never kills must not run to wave 10000 on every trial. */
    maxWave: Math.max(1000, Math.ceil(run.wave * 3)),
  })
  return {
    wave: survivalPercentiles(outcomes.map(o => o.deathWave)).median,
    damageTaken: survivalPercentiles(outcomes.map(o => o.damageTaken)).median,
    packageHeal: survivalPercentiles(outcomes.map(o => o.packageHeal)).median,
    burstShare: outcomes.filter(o => o.endedBy === 'burst').length / outcomes.length,
  }
}

function squaredLogRatio(predicted: number, observed: number): number {
  if (!(observed > 0)) return 0
  /* A prediction of nothing is as wrong as the search should ever see, not infinitely wrong. */
  const ratio = Math.max(predicted, observed * 1e-6) / observed
  return Math.log(ratio) ** 2
}

function lossOf(runs: readonly SurvivalRunTarget[], calibration: SurvivalCalibration, seeds: number, baseSeed: number, subSteps: number): number {
  let loss = 0
  for (const run of runs) {
    const p = predict(run, calibration, seeds, baseSeed, subSteps)
    loss += WAVE_WEIGHT * squaredLogRatio(p.wave, run.wave)
      + TOTAL_WEIGHT * squaredLogRatio(p.damageTaken, run.damageTaken)
      + TOTAL_WEIGHT * squaredLogRatio(p.packageHeal, run.packageHeal)
  }
  return runs.length > 0 ? loss / runs.length : 0
}

function withParameter(calibration: SurvivalCalibration, group: SurvivalClassGroup, key: 'logHits' | 'exponent', value: number): SurvivalCalibration {
  const range = key === 'logHits' ? LOG_HITS_RANGE : EXPONENT_RANGE
  return {
    ...calibration,
    curves: {
      ...calibration.curves,
      [group]: { ...calibration.curves[group], [key]: Math.min(range[1], Math.max(range[0], value)) },
    },
  }
}

function search(
  runs: readonly SurvivalRunTarget[],
  start: SurvivalCalibration,
  seeds: number,
  baseSeed: number,
  subSteps: number,
  passes: number,
): { calibration: SurvivalCalibration, loss: number } {
  let best = start
  let bestLoss = lossOf(runs, best, seeds, baseSeed, subSteps)
  let stepHits = 1.5
  let stepExponent = 0.4
  for (let pass = 0; pass < passes; pass += 1) {
    /* Sweep until a whole sweep changes nothing, then halve the steps. */
    for (let sweep = 0; sweep < 4; sweep += 1) {
      let improved = false
      for (const group of GROUPS) {
        for (const key of ['logHits', 'exponent'] as const) {
          const step = key === 'logHits' ? stepHits : stepExponent
          for (const direction of [1, -1]) {
            const candidate = withParameter(best, group, key, best.curves[group][key] + direction * step)
            if (candidate.curves[group][key] === best.curves[group][key]) continue
            const loss = lossOf(runs, candidate, seeds, baseSeed, subSteps)
            if (loss < bestLoss) {
              best = candidate
              bestLoss = loss
              improved = true
              break
            }
          }
        }
      }
      if (!improved) break
    }
    stepHits /= 2
    stepExponent /= 2
  }
  return { calibration: best, loss: bestLoss }
}

function median(values: readonly number[]): number {
  return survivalPercentiles(values).median
}

/**
 * The hit curves that best reproduce a set of real runs, with a leave-one-out check. Fitted.
 *
 * Each run brings the state it was played with. The curves are anchored at the median run's death
 * wave, where the data is, so the two numbers of a curve pull apart cleanly. `perRun` predicts
 * each run from a fit that did not see it; `leaveOneOutError` is the mean absolute relative miss.
 * With no runs the starting calibration comes back untouched.
 */
export function fitSurvivalCalibration(runs: readonly SurvivalRunTarget[], options: SurvivalFitOptions = {}): SurvivalFitResult {
  const seeds = Math.max(1, Math.floor(options.seeds ?? FIT_DEFAULT_SEEDS))
  const baseSeed = Math.floor(options.baseSeed ?? 1)
  const subSteps = Math.max(1, Math.floor(options.subSteps ?? SURVIVAL_DEFAULT_SUB_STEPS))
  const passes = Math.max(1, Math.floor(options.passes ?? FIT_DEFAULT_PASSES))
  const usable = runs.filter(run => run.wave > 0)
  const start = options.start ?? SURVIVAL_DEFAULT_CALIBRATION
  if (usable.length === 0) return { calibration: start, perRun: [], leaveOneOutError: null, loss: 0 }

  const referenceWave = Math.max(1, Math.round(median(usable.map(run => run.wave))))
  const anchored: SurvivalCalibration = {
    ...start,
    referenceWave,
    referenceRatio: options.start?.referenceRatio ?? survivalRatioAtWave(usable[0].state, referenceWave),
  }
  const full = search(usable, anchored, seeds, baseSeed, subSteps, passes)

  const perRun: SurvivalFitRun[] = []
  const holdOut = usable.length >= 2 && options.skipLeaveOneOut !== true
  for (let i = 0; i < usable.length; i += 1) {
    const run = usable[i]
    /* Refit without this run, starting from the full fit: one pass is enough to let it move away. */
    const calibration = holdOut
      ? search(usable.filter((_, j) => j !== i), full.calibration, seeds, baseSeed, subSteps, 1).calibration
      : full.calibration
    const p = predict(run, calibration, seeds, baseSeed + 1, subSteps)
    perRun.push({
      runDate: run.runDate,
      wave: run.wave,
      predictedWave: p.wave,
      error: (p.wave - run.wave) / run.wave,
      predictedDamageTaken: p.damageTaken,
      predictedPackageHeal: p.packageHeal,
      burstShare: p.burstShare,
    })
  }
  const leaveOneOutError = holdOut
    ? perRun.reduce((sum, run) => sum + Math.abs(run.error), 0) / perRun.length
    : null
  return { calibration: full.calibration, perRun, leaveOneOutError, loss: full.loss }
}
