/**
 * How many enemies of each kind one wave spawns — the count the SDK had in pieces and not in one
 * call.
 *
 * Ordinary enemies come from the spawn-yield model, elites from the Elite Spawn Chance chart and
 * bosses from the tier's boss interval. The split of ordinary enemies by kind is NOT derived: the
 * SDK's per-wave formula for Fast, Tank and Ranged is not modelled, so the state carries the
 * shares and a save reader measures them from run history.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    survivalEnemyBaseAtLevel, survivalIsBossWave, survivalSpawnCountsForWave
 * depends    src/data/enemies/data, src/mechanics/enemies/elite-spawn-chance, src/mechanics/enemies/wave-stats, src/mechanics/survival/types, src/mechanics/waves/resolve-wave-spawn-yield
 * used by    src/calculators/specs.generated, src/mechanics/survival/healing, src/mechanics/survival/hit-curves, src/mechanics/survival/incoming-damage, src/mechanics/survival/index, src/mechanics/survival/simulate
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { bossWaveIntervalForTier } from '../../data/enemies/data'
import { expectedEliteKillsPerWave, isBossSpawnWave } from '../enemies/elite-spawn-chance'
import { getBasicEnemyWaveStats } from '../enemies/wave-stats'
import { expectedEnemiesPerWaveFromAccount } from '../waves/resolve-wave-spawn-yield'
import type { SurvivalSpawnCounts, SurvivalState } from './types'

/* Enemy base stats depend only on tier and level, and a run asks for each level many times. */
const BASE_BY_TIER = new Map<number, { hp: number, damage: number }[]>()

/**
 * A basic enemy's health and damage at an enemy level on a tier, before type multipliers.
 *
 * The level is the wave less the level skips so far. `getBasicEnemyWaveStats`, remembered.
 *
 * @unit amount: health and damage
 */
export function survivalEnemyBaseAtLevel(tier: number, level: number): { hp: number, damage: number } {
  const l = Math.max(1, Math.floor(level))
  let rows = BASE_BY_TIER.get(tier)
  if (!rows) {
    rows = []
    BASE_BY_TIER.set(tier, rows)
  }
  let row = rows[l]
  if (!row) {
    const stats = getBasicEnemyWaveStats(tier, l, false)
    row = { hp: stats.hp, damage: stats.damage }
    rows[l] = row
  }
  return row
}

/** Whether the tier spawns a boss on this wave. */
export function survivalIsBossWave(tier: number, wave: number): boolean {
  return isBossSpawnWave(wave, bossWaveIntervalForTier(tier))
}

/**
 * Expected enemies spawned in one played wave, by kind.
 *
 * An expectation, so the counts are fractional: a wave with a 25% elite chance reports a quarter
 * of an elite. The simulator rolls whole elites itself and uses this for ordinary enemies. A
 * skipped wave spawns nothing and is not this function's concern.
 *
 * @unit enemies
 */
export function survivalSpawnCountsForWave(state: SurvivalState, wave: number): SurvivalSpawnCounts {
  const w = Math.max(1, Math.floor(wave))
  const spawn = state.spawn
  const ordinary = expectedEnemiesPerWaveFromAccount({
    wave: w,
    tier: state.tier,
    enemyBalanceMult: spawn.enemyBalanceMultiplier,
  }) * spawn.countScale
  const elites = expectedEliteKillsPerWave(state.tier, w) * spawn.eliteScale
  return {
    basic: ordinary * spawn.shares.basic,
    fast: ordinary * spawn.shares.fast,
    tank: ordinary * spawn.shares.tank,
    ranged: ordinary * spawn.shares.ranged,
    protector: ordinary * spawn.shares.protector,
    boss: survivalIsBossWave(state.tier, w) ? 1 : 0,
    vampire: elites * spawn.eliteShares.vampire,
    ray: elites * spawn.eliteShares.ray,
    scatter: elites * spawn.eliteShares.scatter,
  }
}
