/**
 * A workshop upgrade at a level: its value in the game's unit, the unit, and
 * what the next level costs.
 *
 * `value` is the workshop's own contribution, before labs, relics, cards and
 * modules. `unit` says how to read it: a `fraction` is a chance where 1 is
 * 100%, so Enemy Attack Level Skip at level 0 is 0.0005, the 0.05% the Workshop
 * screen shows, and Recovery Amount at level 35 is 0.28. The units are
 * `WORKSHOP_STAT_UNITS`.
 *
 * Returns `null` for an unknown upgrade or a level the table has no row for.
 */
export function workshopStatValue(stat: string, level: number): WorkshopStatLookup | null {
  const game = workshopGameValueAtLevel(stat, level)
  const row = game ? WORKSHOP_DATA[stat]?.[String(level)] : undefined
  if (!game || !row) return null

  return {
    value: game.value,
    unit: game.unit,
    coinCost: row.coins,
    cashCost: row.cash,
  }
}

/**
 * The highest level the table covers for a stat, or `null` if unknown.
 *
 * @unit levels
 */
export function workshopStatMaxLevel(stat: string): number | null {
  const rows = WORKSHOP_DATA[stat]
  if (!rows) return null
  let max = -1
  for (const key of Object.keys(rows)) {
    const level = Number(key)
    if (Number.isInteger(level) && level > max) max = level
  }
  return max < 0 ? null : max
}

/**
 * Actual in-run levels, separate from purchased workshop levels and their costs.
 *
 * @unit amount: damage, health, or health a second
 * @paramUnit level levels
 */
export function inRunWorkshopStatValue(stat: 'Damage' | 'Health' | 'Health Regen', level: number): number | null {
  if (!Number.isInteger(level) || level < 0 || level > 10000) return null
  if (stat === 'Damage') return workshopDamageAtLevel(level)
  const base = workshopStatValue(stat, Math.min(level, WORKSHOP_NORMAL_IN_RUN_CAP))
  return base ? applyWorkshopOvercapMultiplier(base.value, level) : null
}

/** Every stat the sheet's `DVT_WS_VALUE` can be lined up with. */
export function workshopStatsWithSheetMapping(): string[] {
  return Object.keys(WORKSHOP_STAT_MAPPINGS)
}

