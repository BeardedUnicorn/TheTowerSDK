/**
 * Effective Paths — workshop stat values, in the units the paths expect.
 *
 * The eHP model takes resolved workshop values, and this is where they come
 * from. `WORKSHOP_DATA` already carries all 48 stats at every level, verified
 * against the sheet's own `DVT_Workshop` tab, so nothing is recomputed here —
 * this is a units and naming layer, not a second copy of the curve.
 *
 * ## It answers in the game's units, not the sheet's
 *
 * `workshopStatValue` returns what the game gives for the upgrade, with the
 * unit named: a chance as a fraction, a multiplier as the number after the `x`.
 * It used to answer in the units of the sheet's `DVT_WS_VALUE`, and for most
 * upgrades those are the same thing, which is what made the rest dangerous.
 * The sheet has Enemy Attack and Health Level Skip at ten times the game's
 * chance (0.5% a level against the 0.05% the Workshop screen shows), Recovery
 * Amount at a hundredth of it, and Lifesteal, Land Mine Damage and Damage /
 * Meter in the table's raw storage unit. A number in the sheet's unit was read
 * as the game's and believed.
 *
 * The five upgrades the eHP model reads (Health, Defense Absolute, Defense %,
 * Wall Health, Max Recovery) are the same in both, so the port still reproduces
 * the sheet.
 *
 * ## What is kept about the sheet
 *
 * `WORKSHOP_STAT_MAPPINGS` records how each upgrade is spelled in the sheet and
 * the ratio between the table's number and the sheet's, derived by probing the
 * sheet at four levels. `WORKSHOP_STATS_DIVERGING_FROM_SHEET` lists the seven
 * whose sheet formula is a different curve from the game's, so no ratio exists.
 * Both describe the sheet. Neither decides what `workshopStatValue` returns.
 * See `docs/EFFECTIVE_PATHS_SHEET_FINDINGS.md`.
 */

