/**
 * Key prices of the v29 vault: one level of an upgrade, a range of levels, a category unlock, and
 * what is left of a whole tree.
 *
 * An upgrade is named by its row key, `v29:<tree>:<category>:<name>`, and a category unlock by
 * `v29:<tree>:<category>:__unlock__`. An Enemy row's name is `<enemy>:<stat>`. These are the keys
 * the save reader reports as `vault.v29.levels`, so a save's levels can be passed straight in.
 *
 * The pre-v29 trees are priced by `vaultNodeKeysCost` and its siblings; nothing here reads them.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    vaultV29KeyRows, vaultV29CategoryUnlockKey, vaultV29UpgradeKeysCost, vaultV29UpgradeMaxLevel, vaultV29UpgradeKeysBetween, vaultV29CategoryUnlockKeys, vaultV29TreeKeysRemaining
 * depends    src/data/generated/vault-v29.generated, src/mechanics/vault/types
 * used by    src/calculators/run-costs, src/calculators/specs.generated, src/charts/series/cost-families, src/charts/tables/lookup, src/mechanics/vault/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import {
  VAULT_V29_ENEMY,
  VAULT_V29_HARMONY,
  VAULT_V29_POWER,
} from '../../data/generated/vault-v29.generated'
import type { VaultV29Category } from '../../data/generated/vault-v29.generated'
import type { VaultV29KeyRow, VaultV29TreeKey } from './types'

const UNLOCK_NAME = '__unlock__'

function rowKey(tree: string, category: string, name: string): string {
  return `v29:${tree}:${category}:${name}`
}

function categoriesOf(tree: string): readonly VaultV29Category[] | null {
  if (tree === 'harmony') return VAULT_V29_HARMONY.categories
  if (tree === 'power') return VAULT_V29_POWER.categories
  if (tree === 'enemy') return VAULT_V29_ENEMY.categories
  return null
}

function buildRows(): readonly VaultV29KeyRow[] {
  const rows: VaultV29KeyRow[] = []
  const add = (tree: VaultV29TreeKey, category: string, name: string, levelCosts: readonly number[]) => {
    rows.push({ key: rowKey(tree, category, name), tree, category, name, levelCosts })
  }
  for (const upgrade of VAULT_V29_HARMONY.upgrades) add('harmony', upgrade.category, upgrade.name, upgrade.levelCosts)
  for (const upgrade of VAULT_V29_POWER.upgrades) add('power', upgrade.category, upgrade.name, upgrade.levelCosts)
  for (const upgrade of VAULT_V29_ENEMY.upgrades) {
    add('enemy', upgrade.category, `${upgrade.enemy}:${upgrade.stat}`, upgrade.levelCosts)
  }
  return rows
}

let cachedRows: readonly VaultV29KeyRow[] | null = null
let cachedByKey: ReadonlyMap<string, VaultV29KeyRow> | null = null

/** Every priced upgrade of the v29 vault, tree by tree in the game's order. */
export function vaultV29KeyRows(): readonly VaultV29KeyRow[] {
  if (!cachedRows) cachedRows = buildRows()
  return cachedRows
}

function rowOf(upgrade: string): VaultV29KeyRow | null {
  if (!cachedByKey) cachedByKey = new Map(vaultV29KeyRows().map(row => [row.key, row]))
  return cachedByKey.get(upgrade) ?? null
}

/** The row key of a category's unlock, as the save reader reports it. */
export function vaultV29CategoryUnlockKey(tree: string, category: string): string {
  return rowKey(tree, category, UNLOCK_NAME)
}

/**
 * Keys for one level of a v29 vault upgrade. `null` for an unknown row key, a level that is not a
 * whole number from 1, or a level past the upgrade's last.
 */
export function vaultV29UpgradeKeysCost(upgrade: string, level: number): number | null {
  const row = rowOf(upgrade)
  if (!row || !Number.isInteger(level) || level < 1) return null
  return row.levelCosts[level - 1] ?? null
}

/** The highest level a v29 vault upgrade can be taken to. `null` for an unknown row key. */
export function vaultV29UpgradeMaxLevel(upgrade: string): number | null {
  const row = rowOf(upgrade)
  return row ? row.levelCosts.length : null
}

/**
 * Keys to take a v29 vault upgrade from `fromLevel` to `toLevel`: {@link vaultV29UpgradeKeysCost}
 * summed over the levels bought. The category's unlock is not included.
 *
 * `0` when the two levels are equal; `null` for an unknown row key, a level that is not a whole
 * number, `toLevel` below `fromLevel`, or a level past the upgrade's last.
 */
export function vaultV29UpgradeKeysBetween(upgrade: string, fromLevel: number, toLevel: number): number | null {
  const row = rowOf(upgrade)
  if (!row || !Number.isInteger(fromLevel) || !Number.isInteger(toLevel)) return null
  if (fromLevel < 0 || toLevel < fromLevel || toLevel > row.levelCosts.length) return null

  let total = 0
  for (let level = fromLevel; level < toLevel; level += 1) total += row.levelCosts[level] ?? 0
  return total
}

/**
 * Keys to unlock a category of a v29 vault tree, paid once before any of its upgrades can be
 * bought. `0` for a category that is open from the start; `null` for an unknown tree or category.
 */
export function vaultV29CategoryUnlockKeys(tree: string, category: string): number | null {
  const found = categoriesOf(tree)?.find(entry => entry.name === category)
  if (!found) return null
  return found.unlockCost ?? 0
}

/**
 * Keys still to spend to finish a v29 vault tree: every category not yet unlocked, plus every
 * level not yet bought.
 *
 * `levels` maps a row key to its current level, and a category's unlock key to 1 once it is
 * unlocked; a key left out is at 0, so calling this with no levels gives the whole tree's price.
 * Keys of the other two trees are ignored, so one save's levels serve all three. `null` for a tree
 * other than `harmony`, `power` or `enemy`, a key of this tree that names no row, or a level a
 * row cannot be at — a misspelt key is refused rather than counted as nothing.
 */
export function vaultV29TreeKeysRemaining(
  tree: string,
  levels: Readonly<Record<string, number>> = {},
): number | null {
  const categories = categoriesOf(tree)
  if (!categories) return null

  const rows = vaultV29KeyRows().filter(row => row.tree === tree)
  const unlocks = new Map(categories.map(category => [vaultV29CategoryUnlockKey(tree, category.name), category.unlockCost ?? 0]))
  const known = new Set<string>([...rows.map(row => row.key), ...unlocks.keys()])
  const prefix = `v29:${tree}:`
  const levelOf = (key: string): number => (Object.prototype.hasOwnProperty.call(levels, key) ? levels[key] ?? 0 : 0)

  for (const key of Object.keys(levels)) {
    if (/^v29:(?:harmony|power|enemy):/.test(key) && !key.startsWith(prefix)) continue
    if (!known.has(key)) return null
  }

  let total = 0
  for (const [key, cost] of unlocks) {
    const state = levelOf(key)
    if (state !== 0 && state !== 1) return null
    if (state === 0) total += cost
  }
  for (const row of rows) {
    const part = vaultV29UpgradeKeysBetween(row.key, levelOf(row.key), row.levelCosts.length)
    if (part === null) return null
    total += part
  }
  return total
}
