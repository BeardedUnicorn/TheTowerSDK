/**
 * How many enemy level reductions still count once there are a lot of them.
 *
 * Below 101 raw reductions nothing is lost. Above that the curve is NOT smooth: the exponent
 * advances in whole steps of 1500 reductions, so the effective total is flat across each band and
 * then jumps. Modelling it as a continuous curve is close in the middle of a band and wrong at
 * both ends of one.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    LEVEL_REDUCTION_FREE_THRESHOLD, LEVEL_REDUCTION_STEP_SIZE, LEVEL_REDUCTION_ASYMPTOTE, LEVEL_REDUCTION_AMPLITUDE, diminishedLevelReductions
 * depends    —
 * used by    src/calculators/specs.generated, src/knowledge/compartments/enemies, src/mechanics/enemies/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */

/** Below this many raw reductions, none are lost. */
export const LEVEL_REDUCTION_FREE_THRESHOLD = 100

/** The exponent steps once per this many reductions above the threshold. */
export const LEVEL_REDUCTION_STEP_SIZE = 1500

/**
 * Effective reductions approach this, and DO reach it once the exponential underflows.
 *
 * "Approaches but never reaches" is the mathematical description and it is false in floating
 * point: once `300 * exp(-step)` falls below the precision of the subtraction, `400 - tiny` is
 * exactly 400. The game computes this in float32, which underflows sooner than the float64 here —
 * so if anything it reaches the cap earlier in game than this function does.
 */
export const LEVEL_REDUCTION_ASYMPTOTE = 400

/** Amplitude subtracted from the asymptote. */
export const LEVEL_REDUCTION_AMPLITUDE = 300

/** The curve itself: effective reductions for a raw count. */
export function diminishedLevelReductions(raw: number): number {
  if (raw <= LEVEL_REDUCTION_FREE_THRESHOLD) return raw
  const step = Math.floor((raw - LEVEL_REDUCTION_FREE_THRESHOLD) / LEVEL_REDUCTION_STEP_SIZE)
  return Math.trunc(
    LEVEL_REDUCTION_ASYMPTOTE - LEVEL_REDUCTION_AMPLITUDE * Math.exp(-step),
  )
}
