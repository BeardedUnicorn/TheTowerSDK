type DissonanceKind = 'attack' | 'defense'

/** What one formula may read. Every accessor returns the neutral value when the input is absent. */
interface Parts {
  table: number
  /** `computeLabValueAtLevel`: a multiplier lab is 1 at level 0, an additive lab 0. */
  lab: (slug: string) => number
  /** Summed relic benefit as stored: 0.18 for 18%. */
  relic: (stat: string) => number
  /** An active multiplier card's value, or 1. */
  cardMultiplier: (slug: string) => number
  /** An active additive card's value, or 0. */
  cardBonus: (slug: string) => number
  /** `computeModuleStat` for the equipped primary module of the type, or 1. */
  moduleMain: (type: ModuleCalcType) => number
  /** The summed benefit of that module's in-effect substats with this label, or 0. */
  substat: (type: ModuleCalcType, label: string) => number
  dissonant: (kind: DissonanceKind) => number
}

interface Recipe extends WorkshopScreenFormula {
  value: (parts: Parts) => number
}

const composed = (formula: string, value: (parts: Parts) => number): Recipe => ({ basis: 'composed', formula, value })
const tableOnly: Recipe = { basis: 'table', formula: 'table', value: parts => parts.table }

