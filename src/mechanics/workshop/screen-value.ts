const MODULE_CALC_TYPES: readonly ModuleCalcType[] = ['cannon', 'armor', 'generator', 'core']

const asModuleType = (category: string): ModuleCalcType | null => {
  const lower = category.trim().toLowerCase()
  return (MODULE_CALC_TYPES as readonly string[]).includes(lower) ? lower as ModuleCalcType : null
}

const ownValue = <T>(record: Readonly<Record<string, T>> | undefined, key: string): T | undefined =>
  record ? ownLookup(record, key) : undefined

const tableValueAt = (stat: string, level: number): number | null => {
  const rows = ownValue(WORKSHOP_DATA as unknown as Readonly<Record<string, Readonly<Record<string, { value: number }>>>>, stat)
  const value = ownValue(rows, String(level))?.value
  return typeof value === 'number' && Number.isFinite(value) ? value : null
}

/** In-effect substats of one module, as `[label, benefit]`. */
const substatsOf = (module: WorkshopScreenModule, type: ModuleCalcType): [string, number][] =>
  module.substatEffectIds.flatMap((id): [string, number][] => {
    const effect = id ? findModuleEffect(id) : null
    return effect?.category && asModuleType(effect.category) === type ? [[effect.label, effect.benefitValue]] : []
  })

/**
 * Total relic benefit per stat, as `RelicGameRow` stores it: 0.18 for 18%, seconds for WallRebuild.
 *
 * Pass the relics that count: a mailed relic adds nothing until it is claimed, so leave those out
 * (`readRelicsFromSaveRoot` marks them `state: 'mailed'`). An index with no table row is skipped.
 */
export function totalRelicBenefitByStat(relicIndices: Iterable<number>): Record<string, number> {
  const totals: Record<string, number> = {}
  for (const index of new Set(relicIndices)) {
    const row = RELIC_GAME_TABLE_BY_INDEX.get(index)
    if (row) totals[row.stat] = (totals[row.stat] ?? 0) + row.benefit
  }
  return totals
}

/**
 * The number the Workshop screen shows for an upgrade at a level, before the game formats it.
 *
 * Returns `null` when the upgrade has no verified formula (see `WORKSHOP_SCREEN_FORMULA_BY_STAT`)
 * or the table has no row at that level. A lab, card, module or boost that is not given is
 * neutral, so a bare `{ stat, level }` returns the value with nothing added.
 */
export function computeWorkshopScreenValue(input: WorkshopScreenInput): WorkshopScreenValue | null {
  const recipe = ownValue(RECIPE_BY_STAT, input.stat)
  const table = tableValueAt(input.stat, input.level)
  if (!recipe || table === null) return null

  const labLevelByName = new Map<string, number>()
  for (const [key, level] of Object.entries(input.labLevels ?? {})) {
    const lab = findToolLabBySlug(key)
    if (lab) labLevelByName.set(lab.name, level)
  }

  const activeCards = (input.cards ?? []).filter(card => card.active)
  const cardValue = (slug: string): number | null => {
    const card = activeCards.find(entry => entry.slug === slug)
    const value = card ? CARD_TEMPLATES.find(template => template.id === slug)?.levelValues[card.level - 1] : undefined
    return typeof value === 'number' ? value : null
  }

  const primaries = new Map<ModuleCalcType, WorkshopScreenModule>()
  const assists: WorkshopScreenModule[] = []
  for (const module of input.modules ?? []) {
    const type = asModuleType(module.category)
    if (!type) continue
    if (module.role === 'assist') assists.push(module)
    else if (!primaries.has(type)) primaries.set(type, module)
  }

  const readRelics = new Set<string>()
  const readSubstats = new Set<string>()
  const readTypes = new Set<ModuleCalcType>()
  const readCards = new Set<string>()

  const parts: Parts = {
    table,
    lab: (slug) => {
      const lab = findToolLabBySlug(slug)
      return lab ? computeLabValueAtLevel(lab, labLevelByName.get(lab.name) ?? 0) : Number.NaN
    },
    relic: (stat) => {
      readRelics.add(stat)
      return ownValue(input.relicBenefitByStat, stat) ?? 0
    },
    cardMultiplier: (slug) => {
      readCards.add(slug)
      return cardValue(slug) ?? 1
    },
    cardBonus: (slug) => {
      readCards.add(slug)
      return cardValue(slug) ?? 0
    },
    moduleMain: (type) => {
      readTypes.add(type)
      const module = primaries.get(type)
      return module ? computeModuleStat({ type, rarityLabel: module.rarityLabel, level: module.level }) : 1
    },
    substat: (type, label) => {
      readTypes.add(type)
      readSubstats.add(`${type}:${label}`)
      const module = primaries.get(type)
      return module ? substatsOf(module, type).reduce((sum, [name, benefit]) => sum + (name === label ? benefit : 0), 0) : 0
    },
    dissonant: kind => input.dissonantBoost?.[kind] ?? 1,
  }

  const value = recipe.value(parts)
  if (!Number.isFinite(value)) return null

  const names = (label: string) => (ownValue(WORKSHOP_STAT_BY_SUBSTAT_LABEL, label) ?? label) === input.stat
  const unread: string[] = []
  for (const [stat, benefit] of Object.entries(input.relicBenefitByStat ?? {})) {
    if (benefit !== 0 && ownValue(WORKSHOP_STAT_BY_RELIC_STAT, stat) === input.stat && !readRelics.has(stat)) {
      unread.push(`${stat} relics ${benefit}`)
    }
  }
  for (const [type, module] of primaries) {
    for (const [label, benefit] of substatsOf(module, type)) {
      if (names(label) && !readSubstats.has(`${type}:${label}`)) unread.push(`${module.category} substat ${label} ${benefit}`)
    }
  }
  for (const module of assists) {
    const type = asModuleType(module.category)!
    if (readTypes.has(type) || substatsOf(module, type).some(([label]) => names(label))) {
      unread.push(`assist ${module.category} module`)
    }
  }
  for (const card of activeCards) {
    const template = CARD_TEMPLATES.find(entry => entry.id === card.slug)
    if (template?.name === input.stat && !readCards.has(card.slug)) unread.push(`${template.name} card level ${card.level}`)
  }

  const gameUnit = ownValue(WORKSHOP_STAT_UNITS, input.stat)?.unit ?? 'amount'
  const unit = gameUnit === 'fraction' ? 'percent' : gameUnit
  return { stat: input.stat, level: input.level, value, unit, basis: recipe.basis, formula: recipe.formula, unread }
}
