// from screen-value.ts

/**
 * How a Workshop screen value is built. `composed` reproduced the game from the table plus labs,
 * relics, cards, modules and dissonance; `table` means the screen showed the table value alone.
 */
export type WorkshopScreenBasis = 'composed' | 'table'

/** One card, shaped like a row of `readCardsFromSaveRoot().equippedCards`. */
export interface WorkshopScreenCard {
  /** The `CARD_TEMPLATES` id, which the save reader calls `slug`: `as`, `hp`, `crit-chance`. */
  slug: string
  level: number
  /** Only an active card counts. */
  active: boolean
}

/** One equipped module, shaped like a row of `readModulesFromSaveRoot().equipped`. */
export interface WorkshopScreenModule {
  /** `Cannon`, `Armor`, `Generator` or `Core`, in either case. */
  category: string
  /** The rarity label `computeModuleStat` takes: `Legendary +`, `Mythic`, `Ancestral 3`. */
  rarityLabel: string
  level: number
  /**
   * The effect ids of the substats the module HAS IN EFFECT — the ones its screen lists. A save's
   * `effects` array also holds ids for slots the module's level has not opened yet, and those
   * must be left out: the SDK has no `data` export of the slot-opening levels to filter them by.
   */
  substatEffectIds: readonly number[]
  /** An assist module is not applied: none was on the account the screen was checked against. */
  role?: string
}

export interface WorkshopScreenInput {
  /** A `WORKSHOP_DATA` key: `Damage`, `Coins / Kill Bonus`. */
  stat: string
  /** The bought workshop level. */
  level: number
  /** Completed level per lab, keyed by any name `findToolLabBySlug` accepts. A missing lab is level 0. */
  labLevels?: Readonly<Record<string, number>>
  /** Summed relic `benefit` per `RelicGameRow.stat`, from `totalRelicBenefitByStat`. */
  relicBenefitByStat?: Readonly<Record<string, number>>
  cards?: readonly WorkshopScreenCard[]
  modules?: readonly WorkshopScreenModule[]
  /** `dissonantBoostOfType` for the tier selected. A missing boost is 1. */
  dissonantBoost?: Readonly<{ attack?: number, defense?: number }>
}

/** `WorkshopValueUnit` as the screen prints it: a fraction is shown as a percentage. */
export type WorkshopScreenUnit = Exclude<WorkshopValueUnit, 'fraction'> | 'percent'

export interface WorkshopScreenValue {
  stat: string
  level: number
  /** The number behind the screen's text, in the unit it prints: `30.24` for 30.24%, `8.2` for x8.2. */
  value: number
  /**
   * The unit `value` is in. `percent` is the number before a `%` sign, so 0.05 is 0.05%, which is a
   * hundred times the `fraction` that `workshopGameValueAtLevel` returns for the same upgrade.
   */
  unit: WorkshopScreenUnit
  basis: WorkshopScreenBasis
  /** What the value is built from, in the game's names. */
  formula: string
  /**
   * Inputs given that name this stat but that the formula does not read, because nothing on the
   * checked account showed whether the screen adds them. Empty when the value is fully verified.
   */
  unread: string[]
}

export interface WorkshopScreenFormula {
  basis: WorkshopScreenBasis
  formula: string
}
