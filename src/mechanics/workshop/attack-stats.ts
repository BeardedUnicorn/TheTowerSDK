/**
 * Workshop attack preview stats.
 *
 * ## Damage — `workshop preview damage`
 *
 * Workshop upgrade level `L` (attack damage slot):
 *
 *   core(L) = L × 2.8 + L² × 0.077 + 3
 *
 * For each tier threshold Tᵢ, when L > Tᵢ add:
 *
 *   (L − Tᵢ)^pᵢ × cᵢ
 *
 * | Threshold | Exponent p | Coeff c |
 * |-----------|------------|---------|
 * | 999       | 2.10       | 0.08    |
 * | 1499      | 2.12       | 0.09    |
 * | 1999      | 2.18       | 0.10    |
 * | 2499      | 2.25       | 0.10    |
 * | 2999      | 2.30       | 0.15    |
 * | 3499      | 2.33       | 0.20    |
 * | 3999      | 2.34       | 0.20    |
 *
 * Final getter multiplies `core + Σ tiers` by catalog table row, workshop
 * card mult, and relic chain.
 *
 * ## Critical multiplier (workshop preview)
 *
 *   levelTerm   = workshopLevel × 0.1 + 1.2
 *   moduleCrit  = module critical multiplier bonus
 *   upgradeCrit = workshop upgrade in the crit slot + 1.0
 *   cardMult    = card critical mult
 *   relicMult   = relic critical mult
 *
 *   critMult = (levelTerm × workshopStat28 + moduleCrit) × cardMult × upgradeCrit × relicMult
 *
 * Live probe anchor: CriticalMultiplier ≈ 969.95 at reference build.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    WORKSHOP_DAMAGE_TIERS, workshopDamageCurve, getOutOfRoundDamagePreview, getOutOfRoundCriticalMultiplier
 * depends    src/mechanics/primitives/constants, src/mechanics/workshop/types
 * used by    src/calculators/specs.generated, src/mechanics/workshop/index
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */

import {
  CRIT_MULT_LEVEL_BASE,
  CRIT_MULT_LEVEL_SCALE,
  WORKSHOP_DAMAGE_BASE_OFFSET,
  WORKSHOP_DAMAGE_LINEAR_COEFF,
  WORKSHOP_DAMAGE_QUAD_COEFF,
} from '../primitives/constants'
import type { CriticalMultiplierPreviewInput, WorkshopDamagePreviewInput, WorkshopDamageTier } from './types'

/** Tier pow terms above threshold levels. */
export const WORKSHOP_DAMAGE_TIERS: readonly WorkshopDamageTier[] = [
  { threshold: 999, exponent: 2.1, coefficient: 0.08 },
  { threshold: 1499, exponent: 2.12, coefficient: 0.09 },
  { threshold: 1999, exponent: 2.18, coefficient: 0.1 },
  { threshold: 2499, exponent: 2.25, coefficient: 0.1 },
  { threshold: 2999, exponent: 2.3, coefficient: 0.15 },
  { threshold: 3499, exponent: 2.33, coefficient: 0.2 },
  { threshold: 3999, exponent: 2.34, coefficient: 0.2 },
]

/**
 * Tower damage from the workshop level, before the catalog, card and relic multipliers.
 *
 * Gives every row of `WORKSHOP_DATA.Damage` to the table's own rounding, and is the same curve as
 * `workshopDamageAtLevel`. It carried `L² × 1e-6` and 0.10 on the 2999 band until it was checked
 * against the table; the game loads 0.077 for the first, and only 0.15 fits the rows past 2999.
 *
 * @unit amount: tower damage from the workshop alone
 * @paramUnit workshopLevel levels
 */
export function workshopDamageCurve(workshopLevel: number): number {
  const L = Math.max(0, workshopLevel)
  let sum = L * WORKSHOP_DAMAGE_LINEAR_COEFF + L * L * WORKSHOP_DAMAGE_QUAD_COEFF + WORKSHOP_DAMAGE_BASE_OFFSET
  for (const tier of WORKSHOP_DAMAGE_TIERS) {
    if (L > tier.threshold) {
      const excess = L - tier.threshold
      sum += excess ** tier.exponent * tier.coefficient
    }
  }
  return sum
}

/**
 * The Workshop preview of Damage: the curve times the catalog, card and relic multipliers.
 *
 * @unit amount: tower damage
 */
export function getOutOfRoundDamagePreview(input: WorkshopDamagePreviewInput): number {
  let raw = workshopDamageCurve(input.workshopLevel) * input.catalogMult
  if (input.cardMult != null) raw *= input.cardMult
  if (input.relicMult != null) raw *= input.relicMult
  return raw
}

/** workshop preview critical multiplier preview. */
export function getOutOfRoundCriticalMultiplier(input: CriticalMultiplierPreviewInput): number {
  const levelTerm = input.workshopLevel * CRIT_MULT_LEVEL_SCALE + CRIT_MULT_LEVEL_BASE
  let raw = levelTerm * input.workshopStat28 + input.moduleCriticalMultiplier
  if (input.cardMult != null) raw *= input.cardMult
  raw *= input.upgradeSlot18 + 1
  if (input.relicMult != null) raw *= input.relicMult
  return raw
}
