/**
 * The chance a card pull lands on each rarity and on each card.
 *
 * A pull picks a rarity first, Common 80% / Rare 17% / Epic 3% (`RARITY_CHANCES`), then a card of
 * that rarity at random. A card at level 7 can no longer be pulled, and a milestone card cannot be
 * pulled until its milestone is claimed, so both leave the pool and their rarity's share is split
 * among the cards left in it.
 *
 * When a whole rarity is out of cards, its share goes to another rarity. The game's Card Chances
 * panel on a v29.2.2 account with every Common maxed showed Common 0%, Rare 97% and Epic 3%
 * (2026-11-24): Common's 80% went entirely to Rare, and each of the nine Rares showed 10.78%.
 * That is the only move seen. The others follow the same rule — up to the next rarity that still
 * has cards, else down to the nearest — and are reported in `unverified` whenever they apply.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    computeCardDrawOdds
 * depends    src/data/cards/data, src/data/cards/types, src/mechanics/cards/types
 * used by    src/mechanics/cards/index, src/save/cards/draw-odds
 * ────────────────────────────────────────────────── generated by `pnpm map` ──
 */
import { RARITY_CHANCES } from '../../data/cards/data'
import type { CardTemplate } from '../../data/cards/types'
import type { CardDrawCandidate, CardDrawOdds } from './types'

type Rarity = CardTemplate['rarity']

/** Lowest to highest, the order an emptied rarity's share moves up through. */
const RARITY_ORDER: readonly Rarity[] = ['common', 'rare', 'epic']

const LABEL: Record<Rarity, string> = { common: 'Common', rare: 'Rare', epic: 'Epic' }

/** The only redistribution seen in the game so far. */
const SEEN_MOVES = new Set(['common>rare'])

/** Draw odds for a pool of cards. See the module comment for the rules and what is verified. */
export function computeCardDrawOdds(candidates: readonly CardDrawCandidate[]): CardDrawOdds {
  const drawableCount: Record<Rarity, number> = { common: 0, rare: 0, epic: 0 }
  for (const candidate of candidates) if (candidate.drawable) drawableCount[candidate.rarity] += 1

  const rarities: Record<Rarity, number> = { ...RARITY_CHANCES }
  const unverified: string[] = []
  RARITY_ORDER.forEach((rarity, position) => {
    if (drawableCount[rarity] > 0 || rarities[rarity] === 0) return
    const above = RARITY_ORDER.slice(position + 1).find(next => drawableCount[next] > 0)
    const below = RARITY_ORDER.slice(0, position).reverse().find(next => drawableCount[next] > 0)
    const target = above ?? below
    const share = rarities[rarity]
    rarities[rarity] = 0
    if (!target) return
    rarities[target] += share
    if (!SEEN_MOVES.has(`${rarity}>${target}`)) {
      unverified.push(
        `${LABEL[rarity]}'s ${(share * 100).toFixed(0)}% was moved to ${LABEL[target]}; the game has only been seen moving Common to Rare.`,
      )
    }
  })

  const cards = candidates.map(candidate => ({
    card: candidate.card,
    rarity: candidate.rarity,
    chance: candidate.drawable ? rarities[candidate.rarity] / drawableCount[candidate.rarity] : 0,
  }))
  return { rarities, cards, unverified }
}
